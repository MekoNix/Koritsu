"""
Граница ядра доски — проверяется, а не обещается.

Правило разреза: `kokuban` — чистые функции над JSON. Вход — сцена, выход —
текст и словари; ни диска, ни модели, ни хранилища, ни оркестратора. Нарушение
любого пункта означает, что в пакете завелось второе место, знающее про пути или
умеющее разговаривать с моделью, — и разойдётся оно с настоящим молча.

Отдельно и сильнее прочего проверяется то, на чём держится защита от инъекции:
**координат в тексте, который уезжает модели, нет ни одной**. Они потребляются
при разборе сцены ради порядка чтения — и там же кончаются. Обратная дорога
другая: модель называет короткий идентификатор, браузер находит по нему элемент
и берёт координаты у себя.

Читается это по исходникам без строк и комментариев: докстроки пакета называют
запрещённое поимённо («ни `import llm`, ни `os.path.join`»), и проверка по сырому
тексту запрещала бы объяснять правило там, где оно действует.
"""
from __future__ import annotations

import io
import re
import tokenize
from pathlib import Path

import kokuban

from .conftest import имена_образцов, образец

ПАКЕТ = Path(kokuban.__file__).parent
ФАЙЛЫ = sorted(ПАКЕТ.rglob("*.py"))

# Пакеты проекта, которых ядро доски не касается вовсе. `llm` — это сетевой код
# и сборка кусков промпта (их делает дверь `orchestrator/board.py`), `materials`
# и `orchestrator` — хранилище и диск, `api` — HTTP-служба.
СОСЕДИ = ("llm", "materials", "orchestrator", "api", "hokoku", "fragmos",
          "uml_generator", "zuhyo", "kadai")

# Дисковое. Пакет не знает ни одного пути: сцену ему передают словарём, а куда
# лечь снимку и файлу распознанного, решает тот, у кого есть хранилище.
ДИСКОВОЕ = ("os.path.join", "open(", "Path(", "pathlib", "shutil")


def код(path: Path) -> str:
    """Исходник без строк и комментариев."""
    out = []
    for tok in tokenize.generate_tokens(io.StringIO(path.read_text("utf-8")).readline):
        if tok.type in (tokenize.COMMENT, tokenize.STRING):
            continue
        out.append("\n" if tok.type in (tokenize.NL, tokenize.NEWLINE) else tok.string)
    return "\n".join(out)


def test_пакет_не_импортирует_соседей():
    """Импорт любого из них — это второй средний слой внутри чистого пакета."""
    for path in ФАЙЛЫ:
        текст = код(path)
        for имя in СОСЕДИ:
            найдено = re.search(rf"^\s*(?:import {имя}\b|from {имя}[.\s])", текст,
                                re.MULTILINE)
            assert найдено is None, f"{path.name}: import {имя}"


def test_пакет_не_знает_про_диск():
    """Ни пути, ни файла: вход — словарь сцены, выход — текст и словари."""
    for path in ФАЙЛЫ:
        текст = код(path)
        for что in ДИСКОВОЕ:
            assert что not in текст, f"{path.name}: {что}"


def test_пакет_не_собирает_куски_промпта():
    """`llm.Part` собирает оркестратор, и второго места для этого не заводится.

    Здесь это ловится не импортом (его запрещает тест выше), а словом: `Part`,
    появившийся в ядре, означал бы, что раскладка промпта разъехалась на два
    места — и рамка вокруг недоверенного текста ставилась бы в одном из них.
    """
    for path in ФАЙЛЫ:
        assert not re.search(r"\bPart\b", код(path)), path.name


def test_координат_в_шагах_и_выжимке_нет():
    """Самое дорогое правило пакета, проверенное на каждом образце.

    Числа координат образцов ищутся в том, что уезжает наружу: в тексте выжимки
    и в шагах. Ни одно из них там оказаться не может — и если однажды окажется,
    цена ошибки не в приватности, а в том, что модель начнёт рассуждать о
    расположении, которого не видит.
    """
    for имя in имена_образцов():
        сцена = образец(имя)
        выжимка = kokuban.digest(сцена, "000000")
        наружу = выжимка.text + repr(выжимка.steps)
        числа = {str(эл[поле]) for эл in сцена["elements"]
                 for поле in ("x", "y", "width", "height")
                 if isinstance(эл.get(поле), (int, float)) and эл[поле]}
        for число in числа:
            assert число not in наружу, f"{имя}: координата {число} уехала наружу"


def test_поверхность_объявлена_целиком():
    """Семь функций договора — и они же в `__all__`.

    Договор с соседними областями — это имена: служба и сайт написаны по ним
    раньше, чем ядро дописано. Пропавшее имя обязано ломать тест, а не чужой
    импорт.
    """
    for имя in ("steps", "digest", "schema", "rules", "request", "latex_file",
                "settle"):
        assert callable(getattr(kokuban, имя)), имя
        assert имя in kokuban.__all__, имя
