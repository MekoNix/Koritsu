"""
Сверка ответа со сценой: каждое правило закрывает свой способ ответить мимо.

Модель отвечает структурой, но структура по схеме — ещё не правда о доске.
Проверить её может только тот, у кого доска есть, и это сверка. Ниже — по тесту
на правило, и каждое из них появилось не из осторожности:

* «всё верно» — правдоподобный ответ, который ничего не стоит модели и который
  человек не перепроверит: он за этим и пришёл. Против него два заслона —
  обязанность перечислить сверенное и запрет подтверждать доску, часть которой
  репетитору не показали;
* выдуманный идентификатор, отброшенный молча, уносит с собой половину разбора,
  и заметить это можно только по счёту за токены;
* `ok` у строки, содержимого которой никто не видел, — ложное обвинение в одну
  сторону и пустое подтверждение в другую;
* строка, про которую модель промолчала, обязана быть видна человеку как «не
  сказано»: молчание иначе читается как согласие.

Ответ модели здесь подделывается словарём — настоящий вызов проверяется дверью
(`tests/orchestrator/test_board.py`).
"""
from __future__ import annotations

import kokuban
from kokuban import verdict as verdict_mod

from .conftest import МЕТКА, образец, росчерк, сцена


def доска_и_выжимка(*элементы):
    сц = сцена(*элементы)
    return сц, kokuban.digest(сц, МЕТКА)


def трёхстрочная():
    """Две подтверждённые строки и одна неподтверждённая посередине."""
    return доска_и_выжимка(
        росчерк("a", 10, группа="г1", latex="x^{2}+2x=8"),
        росчерк("b", 40, группа="г2", latex="D=-28", подтверждена=False),
        росчерк("c", 70, группа="г3", latex="x=2"),
    )


def test_запись_заводится_на_каждую_строку_доски():
    """Не названная моделью строка — `ok: null`, а не отсутствие строки."""
    _, выжимка = трёхстрочная()
    первый = выжимка.steps[0]["id"]
    ответ = kokuban.settle(
        {"verdict": "wrong", "checked": ["переход"], "remarks": [],
         "steps": [{"step": первый, "ok": True, "note": ""}]}, выжимка, "check")
    assert [ш["step"] for ш in ответ["steps"]] == [ш["id"] for ш in выжимка.steps]
    assert ответ["steps"][0]["ok"] is True
    assert ответ["steps"][2]["ok"] is None
    assert ответ["steps_total"] == 3


def test_приговор_строке_которую_не_показывали_гасится():
    """И обвинение, и подтверждение здесь одинаково неправдивы."""
    _, выжимка = трёхстрочная()
    неподтверждённая = выжимка.steps[1]["id"]
    ответ = kokuban.settle(
        {"verdict": "wrong", "checked": ["переход"], "remarks": [],
         "steps": [{"step": неподтверждённая, "ok": False, "note": "знак потерян"}]},
        выжимка, "check")
    строка = ответ["steps"][1]
    assert строка["ok"] is None
    assert строка["note"] == kokuban.UNCONFIRMED_NOTE
    assert ответ["unrecognized"] == 1


def test_выдуманная_строка_не_пропадает_молча():
    """Отброшенная без слов часть разбора видна только по счёту за токены."""
    _, выжимка = трёхстрочная()
    ответ = kokuban.settle(
        {"verdict": "wrong", "checked": ["переход"], "remarks": [],
         "steps": [{"step": "zzzzzz", "ok": False, "note": "тут ошибка"}]},
        выжимка, "check")
    assert len(ответ["steps"]) == 3
    assert any("zzzzzz" in з["text"] for з in ответ["remarks"])
    assert any("которых на доске нет" in n for n in ответ["notes"])


def test_вердикт_верно_без_перечня_сверенного_понижается():
    """Пустое подтверждение обязано выглядеть пустым — и объяснять себя."""
    _, выжимка = доска_и_выжимка(росчерк("a", 10, группа="г1", latex="x=7"))
    ответ = kokuban.settle({"verdict": "correct", "checked": [], "steps": [],
                            "remarks": []}, выжимка, "check")
    assert ответ["verdict"] == "unclear"
    assert any("не перечислила" in з["text"] for з in ответ["remarks"])


def test_вердикт_верно_при_нераспознанных_строках_понижается():
    """На доске есть запись, которой репетитор не видел: «верно» про неё нельзя."""
    _, выжимка = трёхстрочная()
    ответ = kokuban.settle({"verdict": "correct", "checked": ["переход сверен"],
                            "steps": [], "remarks": []}, выжимка, "check")
    assert ответ["verdict"] == "unclear"
    assert any("не показано" in з["text"] for з in ответ["remarks"])


def test_вердикт_верно_при_неверном_переходе_становится_wrong():
    """Ответ, противоречащий сам себе, разрешается в пользу подробностей."""
    _, выжимка = доска_и_выжимка(росчерк("a", 10, группа="г1", latex="x=7"),
                                 росчерк("b", 40, группа="г2", latex="x=8"))
    второй = выжимка.steps[1]["id"]
    ответ = kokuban.settle(
        {"verdict": "correct", "checked": ["переход сверен"], "remarks": [],
         "steps": [{"step": второй, "ok": False, "note": "не тождественно"}]},
        выжимка, "check")
    assert ответ["verdict"] == "wrong"


def test_незнакомый_вердикт_становится_unclear():
    _, выжимка = доска_и_выжимка(росчерк("a", 10, группа="г1", latex="x=7"))
    ответ = kokuban.settle({"verdict": "верно же", "checked": [], "steps": [],
                            "remarks": []}, выжимка, "check")
    assert ответ["verdict"] == "unclear"


def test_замечание_привязывается_к_настоящим_элементам():
    """Наружу едут `id` Excalidraw: по ним браузер ставит выноску.

    Соседний штрих группы разрешается в её якорь — тот же объект, о котором
    модель и говорила.
    """
    _, выжимка = доска_и_выжимка(росчерк("a1", 10, группа="г1", latex="x=7"),
                                 росчерк("a2", 12, группа="г1"))
    id6 = выжимка.steps[0]["id"]
    ответ = kokuban.settle(
        {"verdict": "wrong", "checked": ["переход"], "steps": [],
         "remarks": [{"kind": "error", "objects": [f"[{id6}]", "a2"],
                      "text": "знак"}]}, выжимка, "check")
    assert ответ["remarks"][0]["objects"] == ["a1"]


def test_выдуманный_объект_лишает_привязки_но_не_замечания():
    _, выжимка = доска_и_выжимка(росчерк("a", 10, группа="г1", latex="x=7"))
    ответ = kokuban.settle(
        {"verdict": "wrong", "checked": ["переход"], "steps": [],
         "remarks": [{"kind": "error", "objects": ["qqqqqq"], "text": "знак"}]},
        выжимка, "check")
    замечание = ответ["remarks"][0]
    assert замечание["objects"] == []
    assert "qqqqqq" in замечание["text"]


def test_пропуск_не_привязывается_к_соседу():
    """У отсутствующего шага объекта нет: привязка к случайному соседу хуже её
    отсутствия — человек пойдёт искать ошибку в верной строке."""
    _, выжимка = доска_и_выжимка(росчерк("a", 10, группа="г1", latex="x=7"))
    id6 = выжимка.steps[0]["id"]
    ответ = kokuban.settle(
        {"verdict": "wrong", "checked": ["переход"], "steps": [],
         "remarks": [{"kind": "missing", "objects": [id6],
                      "text": "нет проверки корней"}]}, выжимка, "check")
    assert ответ["remarks"][0]["objects"] == []
    assert "к объектам не привязывается" in ответ["remarks"][0]["text"]


def test_замечание_без_слов_не_выживает():
    """Выноска без слов на доске — это только испуг."""
    _, выжимка = доска_и_выжимка(росчерк("a", 10, группа="г1", latex="x=7"))
    ответ = kokuban.settle(
        {"verdict": "wrong", "checked": ["переход"], "steps": [],
         "remarks": [{"kind": "error", "objects": [], "text": "   "},
                     {"kind": "error", "objects": [], "text": "вот это дело"}]},
        выжимка, "check")
    assert [з["text"] for з in ответ["remarks"]] == ["вот это дело"]


def test_незнакомый_вид_замечания_становится_подсказкой():
    """Отбросить замечание целиком дороже, чем показать его осторожным видом."""
    _, выжимка = доска_и_выжимка(росчерк("a", 10, группа="г1", latex="x=7"))
    ответ = kokuban.settle(
        {"verdict": "wrong", "checked": ["переход"], "steps": [],
         "remarks": [{"kind": "катастрофа", "objects": [], "text": "что-то"}]},
        выжимка, "check")
    assert ответ["remarks"][0]["kind"] == "hint"


def test_подсказка_разрешается_в_строку():
    _, выжимка = трёхстрочная()
    последняя = выжимка.steps[2]["id"]
    ответ = kokuban.settle(
        {"verdict": "wrong", "checked": ["переход"], "steps": [], "remarks": [],
         "hint": {"step": f"[{последняя}]", "text": "посмотри на знак"}},
        выжимка, "hint")
    assert ответ["hint"] == {"step": последняя, "text": "посмотри на знак"}


def test_подсказка_без_слов_отбрасывается():
    """Пустая подсказка, показанная как подсказка, — обман за деньги человека."""
    _, выжимка = трёхстрочная()
    ответ = kokuban.settle(
        {"verdict": "wrong", "checked": [], "steps": [], "remarks": [],
         "hint": {"step": "", "text": ""}}, выжимка, "hint")
    assert ответ["hint"] is None
    assert any("без слов" in n for n in ответ["notes"])


def test_задача_приходит_без_вердикта_о_решении():
    """Пустой вердикт — «не выносился»; `unclear` означало бы «смотрел и не понял»."""
    _, выжимка = трёхстрочная()
    ответ = kokuban.settle(
        {"drill": {"topic": "дискриминант", "task": "Реши x^{2}-4=0",
                   "hint": "разложи на множители", "answer": "x=±2",
                   "why": "не сошёлся переход к дискриминанту"}}, выжимка, "drill")
    assert ответ["verdict"] == ""
    assert ответ["steps"] == [] and ответ["checked"] == []
    assert ответ["drill"]["why"].startswith("не сошёлся")


def test_задача_без_условия_не_задача():
    _, выжимка = трёхстрочная()
    ответ = kokuban.settle({"drill": {"topic": "", "task": "  ", "hint": "",
                                      "answer": "", "why": ""}}, выжимка, "drill")
    assert ответ["drill"] is None
    assert any("без условия" in n for n in ответ["notes"])


def test_задача_без_почему_остаётся_но_названа():
    """Без «почему именно эта задача» она неотличима от случайной."""
    _, выжимка = трёхстрочная()
    ответ = kokuban.settle({"drill": {"topic": "", "task": "Реши x=1", "hint": "",
                                      "answer": "", "why": ""}}, выжимка, "drill")
    assert ответ["drill"]["task"] == "Реши x=1"
    assert any("какой шаг не сошёлся" in n for n in ответ["notes"])


def test_ответ_не_объектом_не_роняет_разбор():
    """Вызова могло не быть вовсе: результат обязан остаться формой, а не бедой."""
    _, выжимка = трёхстрочная()
    ответ = kokuban.settle(None, выжимка, "check")
    assert ответ["verdict"] == "unclear"
    assert len(ответ["steps"]) == 3
    assert all(ш["ok"] is None for ш in ответ["steps"])


def test_длинное_замечание_обрезается():
    """Замечание на десять килобайт не читается, а выноску закрывает целиком."""
    _, выжимка = доска_и_выжимка(росчерк("a", 10, группа="г1", latex="x=7"))
    ответ = kokuban.settle(
        {"verdict": "wrong", "checked": ["и" * 5000], "steps": [],
         "remarks": [{"kind": "error", "objects": [], "text": "я" * 5000}]},
        выжимка, "check")
    assert len(ответ["remarks"][0]["text"]) <= verdict_mod.REMARK_LIMIT + 1
    assert len(ответ["checked"][0]) <= verdict_mod.REMARK_LIMIT + 1


def test_на_образце_проверка_доходит_целиком():
    """Сквозной случай: настоящая сцена, ответ по договору, все поля на месте."""
    выжимка = kokuban.digest(образец("квадратное_ошибка"), МЕТКА)
    шаги = выжимка.steps
    ответ = kokuban.settle(
        {"verdict": "wrong",
         "checked": [f"переход [{шаги[0]['id']}] → [{шаги[1]['id']}]: дискриминант"],
         "steps": [{"step": шаги[1]["id"], "ok": False, "note": "потерян знак"}],
         "remarks": [{"kind": "error", "objects": [шаги[1]["id"]],
                      "text": "-4·1·(-8) даёт +32"}]},
        выжимка, "check")
    assert ответ["verdict"] == "wrong"
    assert ответ["steps"][1]["ok"] is False
    assert ответ["remarks"][0]["objects"] == [шаги[1]["elements"][0]]
    assert ответ["notes"] == []


def test_замечание_по_элементу_записанной_строки_разрешается():
    """Строки живут рядом со сценой и знают про себя элементы, а не короткий id.

    Модель видит короткий, но заготовка и служба — элементы; разбирать их
    вторым путём значило бы завести второй разбор ответа.
    """
    доска = сцена(росчерк("a1", 10, группа="г1"), росчерк("a2", 12, группа="г1"))
    выжимка = kokuban.digest(доска, МЕТКА,
                             lines=[{"latex": "x=7", "elements": ["a1", "a2"]}])
    ответ = kokuban.settle(
        {"verdict": "wrong", "checked": ["переход"],
         "steps": [{"step": "a2", "ok": False, "note": "знак"}],
         "remarks": [{"kind": "error", "objects": ["a2"], "text": "знак"}]},
        выжимка, "check")
    assert ответ["steps"] == [{"step": выжимка.steps[0]["id"], "ok": False,
                               "note": "знак"}]
    assert ответ["remarks"][0]["objects"] == ["a1"]
    assert ответ["notes"] == []
