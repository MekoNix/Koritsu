"""
Шаги решения: что считается строкой, в каком порядке они читаются, что уезжает.

Проверяется не «список собрался», а решения, на которых стоит форма шага.

* **Шаг — строка, а не кадр.** Кадр («Шаг 1 — дискриминант») группирует строки,
  и шагов внутри него бывает два. Спутай их — и `ok` у «шага» перестанет
  означать переход между соседними строками, то есть единственное, ради чего
  разбор по шагам вообще нужен.
* **Нераспознанное не исчезает.** Росчерк без распознанной формулы и формула без
  подтверждения человека остаются строками с пустым `latex` и `confirmed: false`.
  Исчезни они — решение из пяти строк выглядело бы решением из трёх, и пропуск,
  о котором стоило сказать, стал бы нашим молчанием.
* **Порядок чтения — по кадрам.** Строки внутри кадра идут подряд, даже если
  геометрически между ними затесался чужой объект.
* **Наружу едут идентификаторы, внутрь — координаты.** В шаге нет ни одной
  координаты, но есть настоящие `id` элементов: по ним браузер ставит выноску.

Совпадение с образцами проверяется знак в знак: по ним написаны служба и сайт, и
молчаливая правка формы ломает чужой код, а не этот тест.
"""
from __future__ import annotations

import pytest

import kokuban

from .conftest import (имена_образцов, кадр, образец, ожидаемые_шаги, росчерк,
                       сцена, текст)


@pytest.mark.parametrize("имя", имена_образцов())
def test_шаги_образца_совпадают_знак_в_знак(имя):
    """Образец — договор между областями, а не снимок поведения на память."""
    assert kokuban.steps(образец(имя)) == ожидаемые_шаги(имя)


def test_кадр_группирует_шаги_и_сам_шагом_не_становится():
    """Два шага в одном кадре: имя кадра приезжает пометкой, а не строкой."""
    доска = сцена(
        кадр("к1", 0, "Шаг 1 — привести к каноническому виду"),
        росчерк("a", 10, группа="г1", latex="x^{2}+2x=8", кадр_id="к1"),
        росчерк("b", 40, группа="г2", latex="x^{2}+2x-8=0", кадр_id="к1"),
    )
    шаги = kokuban.steps(доска)
    assert [ш["latex"] for ш in шаги] == ["x^{2}+2x=8", "x^{2}+2x-8=0"]
    assert [ш["n"] for ш in шаги] == [1, 2]
    assert {ш["frame"] for ш in шаги} == {"к1"}
    assert {ш["frame_name"] for ш in шаги} == {"Шаг 1 — привести к каноническому виду"}


def test_нераспознанное_остаётся_строкой():
    """Три вида записи: подтверждённая, догадка машины, голый росчерк."""
    доска = сцена(
        росчерк("a", 10, группа="г1", latex="x=7"),
        росчерк("b", 40, группа="г2", latex="x=8", подтверждена=False),
        росчерк("c", 70),
    )
    шаги = kokuban.steps(доска)
    assert [(ш["latex"], ш["confirmed"]) for ш in шаги] == [
        ("x=7", True), ("", False), ("", False)]
    # Догадка машины не показывается никому: неверно распознанная формула
    # синтаксически безупречна, и ошибку распознавания ниже уже не поймать.
    assert kokuban.unrecognized_of(шаги) == 2


def test_росчерки_одной_формулы_это_одна_строка():
    """Группа росчерков — один шаг, и в нём перечислены все её элементы."""
    доска = сцена(
        росчерк("a1", 10, группа="г1", latex="x+1=2^{3}"),
        росчерк("a2", 12, группа="г1"),
        росчерк("a3", 14, группа="г1"),
    )
    шаги = kokuban.steps(доска)
    assert len(шаги) == 1
    assert шаги[0]["elements"] == ["a1", "a2", "a3"]
    assert шаги[0]["latex"] == "x+1=2^{3}"


def test_текст_и_фигуры_шагами_не_бывают():
    """Пояснение человека на доске — объект выжимки, но не строка решения."""
    доска = сцена(
        росчерк("a", 10, группа="г1", latex="D=36"),
        текст("t", 30, "проверка: 4 + 4 = 8"),
    )
    шаги = kokuban.steps(доска)
    assert len(шаги) == 1
    # В выжимке пояснение при этом есть: модель должна видеть, что человек
    # написал, а не только то, что распозналось формулой.
    assert "проверка: 4 + 4 = 8" in kokuban.digest(доска, "000000").text


def test_порядок_чтения_сверху_вниз_и_по_кадрам():
    """Кадр читается целиком: чужой объект между его строками их не разрывает."""
    доска = сцена(
        кадр("к2", 100, "второй"),
        кадр("к1", 0, "первый"),
        росчерк("b", 110, группа="г2", latex="во втором", кадр_id="к2"),
        росчерк("a", 10, группа="г1", latex="в первом", кадр_id="к1"),
        росчерк("c", 50, группа="г3", latex="вне кадров"),
    )
    assert [ш["latex"] for ш in kokuban.steps(доска)] == [
        "в первом", "во втором", "вне кадров"]


def test_удалённое_не_читается():
    """`isDeleted` — это стёрто человеком, а не спрятано от нас."""
    доска = сцена(
        росчерк("a", 10, группа="г1", latex="x=7"),
        dict(росчерк("b", 20, группа="г2", latex="x=8"), isDeleted=True),
    )
    assert [ш["latex"] for ш in kokuban.steps(доска)] == ["x=7"]


def test_идентификатор_шага_один_и_тот_же_везде():
    """Одна система идентификаторов на выжимку, шаги и файл распознанного.

    Иначе замечание, полученное от репетитора, не разрешается в объект доски:
    выноску ставить некуда, а человеку показывается «где-то ошибка».
    """
    доска = образец("квадратное_верно")
    выжимка = kokuban.digest(доска, "000000")
    for шаг in выжимка.steps:
        assert f"[{шаг['id']}]" in выжимка.text
        assert выжимка.resolve(шаг["id"]) == шаг["elements"][0]
    assert kokuban.steps(доска) == выжимка.steps


def test_идентификатор_не_зависит_от_порядка_элементов_в_файле():
    """Он функция от `id` элемента и только от него.

    Зависел бы от порядка обхода — и один и тот же объект в двух выжимках
    назывался бы по-разному, а замечание вчерашнего прогона указывало бы на
    сегодняшнюю соседнюю строку.
    """
    прямо = сцена(росчерк("a", 10, группа="г1", latex="раз"),
                  росчерк("b", 20, группа="г2", latex="два"))
    наоборот = сцена(росчерк("b", 20, группа="г2", latex="два"),
                     росчерк("a", 10, группа="г1", latex="раз"))
    assert [ш["id"] for ш in kokuban.steps(прямо)] == \
           [ш["id"] for ш in kokuban.steps(наоборот)]


def test_файл_распознанного_показывает_только_подтверждённое():
    """`<имя>.latex.md`: подтверждённые строки, номера чтения, счёт пропущенного.

    Номера идут по всей доске, а не по списку: нераспознанные строки в файл не
    попадают, и сквозная нумерация оставила бы их без следа. Пропуск в номерах —
    след, строка «не распознано» под списком — его объяснение.
    """
    доска = сцена(
        росчерк("a", 10, группа="г1", latex=r"\log_{2}(x+1)=3"),
        росчерк("b", 40, группа="г2"),
        росчерк("c", 70, группа="г3", latex="x=7"),
    )
    шаги = kokuban.steps(доска)
    текст_файла = kokuban.latex_file("Логарифм", шаги, "2026-09-10 14:02")
    строки = текст_файла.splitlines()
    assert строки[0] == "Доска «Логарифм», распознано 2026-09-10 14:02"
    assert строки[2].endswith(r"$\log_{2}(x+1)=3$")
    assert строки[2].startswith(f"1. [{шаги[0]['id']}]")
    assert строки[3].startswith(f"3. [{шаги[2]['id']}]")
    assert строки[-1] == "не распознано: 1 росчерк"
    assert "x=8" not in текст_файла


def test_файл_распознанного_говорит_о_пустой_доске_вслух():
    """Пустой файл читается как «распозналось ничего», и это разные вещи."""
    текст_файла = kokuban.latex_file("Пустая", [], "2026-09-10 14:02")
    assert "распознанных строк нет" in текст_файла


def test_имя_доски_не_ломает_первую_строку():
    """Имя пишет человек, а печатается оно в нашей строке: переносы схлопнуты."""
    текст_файла = kokuban.latex_file("Лог\nарифм", [], "2026-09-10 14:02")
    assert текст_файла.splitlines()[0] == "Доска «Лог арифм», распознано 2026-09-10 14:02"


# ── распознанное рядом со сценой ─────────────────────────────────────────────
# Сцена хранит нарисованное, прочитанное живёт рядом с ней, а строки решения
# записывает служба. Тогда у формулы один источник правды, и он не сцена:
# `customData` помнил бы вчерашнюю догадку там, где человек уже исправил строку.

ЗАПИСАННЫЕ = [
    {"n": 1, "latex": "x^{2}+2x=8", "source": "myscript", "elements": ["a1", "a2"]},
    {"n": 2, "latex": "x^{2}+2x-8=0", "source": "manual", "elements": ["b1"]},
    {"n": 3, "latex": "", "source": "", "elements": ["c1"]},
]


def доска_штрихов() -> dict:
    """Сцена из голых росчерков: `customData` нет ни у одного."""
    return сцена(
        кадр("к1", 0, "Шаг 1 — привести к каноническому виду"),
        росчерк("a1", 10, группа="г1", кадр_id="к1"),
        росчерк("a2", 12, группа="г1", кадр_id="к1"),
        росчерк("b1", 40, группа="г2", кадр_id="к1"),
        росчерк("c1", 90, группа="г3"),
    )


def test_записанные_строки_становятся_шагами():
    """Форма шага прежняя, а `latex` берётся из записи, а не со сцены."""
    шаги = kokuban.steps(доска_штрихов(), lines=ЗАПИСАННЫЕ)
    assert [(ш["n"], ш["latex"], ш["source"], ш["confirmed"]) for ш in шаги] == [
        (1, "x^{2}+2x=8", "myscript", True),
        (2, "x^{2}+2x-8=0", "manual", True),
        (3, "", "", False)]
    # Идентификатор и кадр приходят из сцены: по ним браузер ставит выноску, а
    # выжимка группирует строки подписью кадра.
    assert шаги[0]["elements"] == ["a1", "a2"]
    assert шаги[0]["frame_name"] == "Шаг 1 — привести к каноническому виду"
    assert шаги[2]["frame"] is None
    assert kokuban.unrecognized_of(шаги) == 1


def test_порядок_шагов_берётся_из_записи():
    """Порядок записи — то, в каком порядке человек подтверждал решение.

    Переставить его по геометрии значило бы спорить с ним о том, что он сделал.
    """
    наоборот = [ЗАПИСАННЫЕ[1], ЗАПИСАННЫЕ[0]]
    assert [ш["latex"] for ш in kokuban.steps(доска_штрихов(), lines=наоборот)] == [
        "x^{2}+2x-8=0", "x^{2}+2x=8"]


def test_записанное_сильнее_сцены_и_сцена_о_формулах_не_спрашивается():
    """Источник ровно один. Два разошлись бы молча и в разные стороны."""
    доска = сцена(росчерк("a1", 10, группа="г1", latex="вчерашняя догадка"))
    шаги = kokuban.steps(доска, lines=[{"latex": "сегодняшняя правка",
                                        "elements": ["a1"]}])
    assert [ш["latex"] for ш in шаги] == ["сегодняшняя правка"]
    assert "вчерашняя догадка" not in kokuban.digest(
        доска, "000000", lines=[{"latex": "сегодняшняя правка",
                                 "elements": ["a1"]}]).text


def test_пустой_список_строк_это_не_отсутствие_списка():
    """«Прочитанного нет» и «прочитанное хранится в сцене» — разные вещи."""
    доска = сцена(росчерк("a1", 10, группа="г1", latex="x=7"))
    assert [ш["latex"] for ш in kokuban.steps(доска, lines=[])] == []
    assert [ш["latex"] for ш in kokuban.steps(доска)] == ["x=7"]


def test_строка_без_нарисованного_не_исчезает():
    """Росчерки стёрли, запись ещё не пересобрали: решение не должно стать
    короче, чем его подтверждал человек."""
    шаги = kokuban.steps(доска_штрихов(),
                         lines=[{"id": "своё", "latex": "x=7", "elements": ["нет"]}])
    assert len(шаги) == 1
    assert (шаги[0]["id"], шаги[0]["elements"]) == ("своё", ["нет"])


def test_файл_распознанного_собирается_и_из_записанного():
    """Дорога до `<имя>.latex.md` одна, откуда бы ни пришли строки."""
    шаги = kokuban.steps(доска_штрихов(), lines=ЗАПИСАННЫЕ)
    файл = kokuban.latex_file("Квадратное", шаги, "2026-09-10 14:02")
    assert "$x^{2}+2x=8$" in файл and "$x^{2}+2x-8=0$" in файл
    assert файл.splitlines()[-1] == "не распознано: 1 росчерк"
