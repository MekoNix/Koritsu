"""
Блок-схемы через HTTP: из кода, из материала, с записью и без.

Пользователь, пространство и проект здесь настоящие (`c_fixtures`), подменён
один `current_user` — как и в тестах материалов, и по той же причине: проект,
подделанный строкой в базе, расходится с тем, как он заводится на самом деле,
а расхождение и есть то, что тесты обязаны ловить.

Что проверяется, кроме «схема построилась»:

* **предпросмотр не пишет на том ничего** — иначе левая половина экрана
  «Блок-схемы» засыпала бы том мусором, который никто не назвал;
* **XML доезжает до человека** — построенный артефакт скачивается по
  идентификатору и разбирается как XML, а не как «что-то бинарное»;
* **отказ ничего не рассказывает** — на кривом коде наружу уходит постоянный
  текст, а не трассировка tree-sitter'а с куском чужого исходника;
* **роли и чужие проекты** — те же два кода, что у материалов: `403`
  участнику без прав, `404` не участнику.
"""
