def test_артефакта_нет_404_а_кривой_идентификатор_400(клиент, проект):
    """Форма проверяется до тома: хранилище складывает из неё путь.

    Идентификатор с косой чертой до обработчика не доходит вовсе — его отсекает
    маршрутизация, — поэтому мерка здесь другая: чужая форма без разделителей
    («почти hex») обязана получить `400`, а не стать поиском на томе.
    """
    нет = клиент.get(АРТЕФАКТ.format(проект["id"], "0123456789abcdef"))
    assert нет.status_code == 404 and нет.json()["error"]["code"] == "not_found"
    кривой = клиент.get(АРТЕФАКТ.format(проект["id"], "0123456789abcdeZ"))
    assert кривой.status_code == 400
    assert кривой.json()["error"]["code"] == "invalid_id"
    # Путь в идентификаторе до тома не доезжает ни при каком повороте: его
    # сворачивает ещё клиент, а остаток не совпадает ни с одним маршрутом.
    подъём = клиент.get(АРТЕФАКТ.format(проект["id"], "../../etc"))
    assert подъём.status_code >= 400


