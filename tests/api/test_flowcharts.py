# ── скачивание построенного ──────────────────────────────────────────────────

def test_xml_скачивается_и_разбирается(клиент, проект):
    """Кнопка «скачать XML» из макета: то, что уехало, обязано быть XML.

    Разбирается настоящим разборщиком, а не поиском подстроки: битый XML с
    нужной подстрокой внутри прошёл бы проверку и не открылся бы в draw.io.
    """
    art = клиент.post(ПУТЬ.format(проект["id"]),
                      json={"source": ЦИКЛ, "lang": "py"}).json()["artifact"]
    ответ = клиент.get(АРТЕФАКТ.format(проект["id"], art))
    assert ответ.status_code == 200, ответ.text
    assert ответ.headers["content-type"].startswith("application/xml")
    assert ответ.headers["x-content-type-options"] == "nosniff"
    assert f'filename="{art}.xml"' in ответ.headers["content-disposition"]
    корень = ET.fromstring(ответ.content)
    assert корень.tag == "mxfile"


def test_inline_показывает_pdf_а_по_умолчанию_скачивает(клиент, проект, хозяин,
                                                       settings):
    """`?inline=1` меняет `Content-Disposition` на `inline` — и только его.

    Ради этого параметра сайт перестаёт выкачивать отчёт в `blob:`: встроенный
    просмотрщик рисует `<embed>` прямо по адресу артефакта. Проверяются оба
    ответа сразу, потому что важна именно разница: умолчание обязано остаться
    вложением — по нему работают кнопки «скачать Word» и «скачать архив».
    """
    каталог = dir_for(settings, хозяин.id, проект["id"])
    art = orchestrator.Project(каталог).put_artifact(b"%PDF-1.7\n1 0 obj\n")

    обычный = клиент.get(АРТЕФАКТ.format(проект["id"], art))
    assert обычный.status_code == 200, обычный.text
    assert обычный.headers["content-disposition"].startswith("attachment;")

    показ = клиент.get(АРТЕФАКТ.format(проект["id"], art) + "?inline=1")
    assert показ.status_code == 200, показ.text
    assert показ.headers["content-disposition"].startswith("inline;")
    # Имя в заголовке остаётся: из просмотрщика файл сохраняют той же кнопкой.
    assert f'filename="{art}.pdf"' in показ.headers["content-disposition"]
    assert показ.headers["content-type"].startswith("application/pdf")
    assert показ.headers["x-content-type-options"] == "nosniff"
    assert показ.content == обычный.content


