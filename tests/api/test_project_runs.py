"""
Модуль работы и журнал запусков: поле `module`, записи, порядок, удаление.

Проверяется то, что обещано в `api/projects/runs.py`, и в том же порядке. Три
утверждения стоят дороже прочих и потому идут первыми:

* **номер запуска даёт служба**: два браузера, открывшие проект разом,
  придумали бы одно и то же «Схема 2», поэтому `n` считается в базе;
* **порядок журнала не меняется между двумя запросами одной страницы**: у
  сортировки по имени и по модулю есть второй ключ;
* **удаление записи не трогает артефакт**: он адресуется содержимым и может
  стоять значением тега.

Пользователь настоящий (`c_fixtures`, живая регистрация); подменён, как и
всюду, только `current_user`.
"""
from __future__ import annotations

from .c_fixtures import (ПАРОЛЬ, docx_байты, войти, завести,  # noqa: F401
                         клиент, личное_id, создать_проект, сосед, хозяин)


def запуск(клиент, project_id: str, module: str = "reports", **поля):
    """Записать запуск, как это делает сайт."""
    тело = {"module": module, **поля}
    return клиент.post(f"/api/projects/{project_id}/runs", json=тело)


def журнал(клиент, project_id: str, **параметры):
    ответ = клиент.get(f"/api/projects/{project_id}/runs", params=параметры)
    assert ответ.status_code == 200, ответ.text
    return ответ.json()


