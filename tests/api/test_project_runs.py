    assert [з["name"] for з in новые] == ["А", "Б"]

    старые = журнал(клиент, проект["id"], sort="old")
    assert [з["name"] for з in старые] == ["Б", "А"]

    по_имени = журнал(клиент, проект["id"], sort="name")
    assert [з["name"] for з in по_имени] == ["А", "Б"]

    по_модулю = журнал(клиент, проект["id"], sort="module")
    assert [з["module"] for з in по_модулю] == ["flowcharts", "reports"]


