def test_запись_удаляется_и_артефакт_остаётся(клиент, хозяин):
    """Схема удаляется записью журнала; XML на томе не трогается.

    Артефакт может стоять значением тега, и снести его вслед за строкой значило
    бы выбить картинку из готового документа.
    """
    проект = создать_проект(клиент, личное_id(клиент), шаблон=docx_байты())
    # Настоящая схема: модуль схем сам пишет запись журнала, когда построил, —
    # отдельной кнопки «сохранить в проект» нет.
    схема = клиент.post(f"/api/projects/{проект['id']}/flowcharts",
                        json={"source": "def f():\n    return 1\n"})
    assert схема.status_code == 201, схема.text
    артефакт = схема.json()["artifact"]
    run_id = схема.json()["run_id"]

    записи = журнал(клиент, проект["id"])
    assert [(з["id"], з["module"], з["artifact_id"]) for з in записи] == [
        (run_id, "flowcharts", артефакт)]

    убрать = клиент.delete(f"/api/projects/{проект['id']}/runs/{run_id}")
    assert убрать.status_code == 204, убрать.text
    assert журнал(клиент, проект["id"]) == []

    остался = клиент.get(f"/api/projects/{проект['id']}/artifacts/{артефакт}")
    assert остался.status_code == 200, "артефакт удалением записи не трогается"


