def test_номер_запуска_считает_служба(клиент, хозяин):
    """`n` растёт по модулю в пределах работы, а не по всей работе сразу."""
    проект = создать_проект(клиент, личное_id(клиент))
    первая = запуск(клиент, проект["id"], "flowcharts")
    вторая = запуск(клиент, проект["id"], "flowcharts")
