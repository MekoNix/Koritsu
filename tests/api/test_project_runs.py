def переименовать(клиент, project_id: str, run_id: str, name: str):
    return клиент.patch(f"/api/projects/{project_id}/runs/{run_id}",
                        json={"name": name})


def test_запись_переименовывается(клиент, хозяин):
    """Имя запуска человек передумывает: «Схема 1» становится «Алгоритм»."""
    проект = создать_проект(клиент, личное_id(клиент))
    запись = запуск(клиент, проект["id"], "flowcharts").json()

    ответ = переименовать(клиент, проект["id"], запись["id"], "Алгоритм")
    assert ответ.status_code == 200, ответ.text
    assert ответ.json()["name"] == "Алгоритм"
    # Номер и модуль правкой имени не трогаются: они говорят о том, что
    # случилось, а случившееся не переписывают.
    assert ответ.json()["n"] == запись["n"]
    assert ответ.json()["module"] == "flowcharts"
    assert [з["name"] for з in журнал(клиент, проект["id"])] == ["Алгоритм"]


