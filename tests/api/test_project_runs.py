def test_журнал_новые_сверху_и_сортируется(клиент, хозяин):
    """Четыре порядка на один список: у клиента своего порядка не заводится."""
    проект = создать_проект(клиент, личное_id(клиент))
    запуск(клиент, проект["id"], "reports", name="Б")
    запуск(клиент, проект["id"], "flowcharts", name="А")

