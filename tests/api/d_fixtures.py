"""
Оснастка материалов: загрузка через очередь и выгрузка проекта.

Отдельным модулем, а не строками в `tests/api/conftest.py`, по той же причине,
что и `c_fixtures`: общий файл, который правят со всех сторон, — конфликты
слияния на ровном месте.

**Зачем это вообще нужно всем.** С 2.0.0a5.1 `POST …/materials` отвечает `202`
и материала в этот момент ещё нет: его делает задание `parse` («один путь,
через очередь»). Значит, каждый тест, которому нужен готовый материал, обязан
после загрузки прокрутить воркер, — и написанные по месту, эти три строки
разошлись бы на первом же тесте, где кто-нибудь забыл дождаться задания и
получил бы пустую опись вместо материала.

Воркер крутится **в этом же процессе** (`run_once(inline=True)`): подпроцесс на
каждую загрузку стоит секунду на импорт FastAPI и SQLAlchemy заново, а проверяют
через него не разбор, а сам подпроцесс — этим занят `test_worker`.
"""
from __future__ import annotations

from api.jobs.models import DONE, Job
from api.jobs.worker import Worker

# Поле multipart и тип содержимого. Тип всегда `octet-stream`: службу он не
# интересует — она смотрит на имя и на первые байты, а не на слово клиента.
ПОЛЕ = "file"
ТИП = "application/octet-stream"

# Поле формы «в папку какого решения этот файл». То же имя, что у службы
# (`api.materials.routes.ПОЛЕ_РЕШЕНИЯ`).
ПОЛЕ_РЕШЕНИЯ = "run_id"


def файл(имя: str, данные: bytes) -> dict:
    """Поле `file` для multipart."""
    return {ПОЛЕ: (имя, данные, ТИП)}


def путь_материалов(проект) -> str:
    ид = проект["id"] if isinstance(проект, dict) else проект
    return f"/api/projects/{ид}/materials"


def отдать(клиент, проект, имя: str, данные: bytes, *, run_id: str = ""):
    """Загрузить файл и вернуть ответ службы. Задание при этом **не** крутится.

    Нужна там, где проверяется сам отказ загрузки (размер, тип, квота, роль): у
    такого запроса задания нет вовсе, и крутить воркер после него незачем.

    `run_id` — в папку какого решения файл ложится. Пусто — файл общий для
    работы, как было до появления второго решения.
    """
    данные_формы = {ПОЛЕ_РЕШЕНИЯ: run_id} if run_id else None
    return клиент.post(путь_материалов(проект), files=файл(имя, данные),
                       data=данные_формы)


def докрутить(app, сколько: int = 8) -> None:
    """Прокрутить очередь, пока в ней есть что брать. Без подпроцесса.

    Потолок шагов есть намеренно: задание, которое ставит следующее задание,
    сегодня в службе одно (его нет), и цикл `while` на такой очереди однажды
    станет бесконечным молча.
    """
    w = Worker(app.state.settings, db=app.state.db)
    for _ in range(сколько):
        if w.run_once(inline=True) is None:
            return


def загрузить(app, клиент, проект, имя: str, данные: bytes, *,
              run_id: str = "") -> dict:
    """Загрузить файл и дождаться разбора. → карточка материала.

    Ровно то, что делал прежний синхронный `POST`, — но через очередь и без
    единого слова о ней в теле теста: тесту про опись материалов очередь не
    интересна, ему интересен материал.
    """
    ответ = отдать(клиент, проект, имя, данные, run_id=run_id)
    assert ответ.status_code == 202, ответ.text
    докрутить(app)
    карточка = клиент.get(f"{путь_материалов(проект)}/{ответ.json()['pending_id']}")
    assert карточка.status_code == 200, (
        f"{имя}: разбор не дошёл до материала — {итог_задания(app, ответ)}")
    return карточка.json()


def ид_материала(app, клиент, проект, имя: str, данные: bytes, *,
                 run_id: str = "") -> str:
    """То же, но нужен один идентификатор. Форма для соседних наборов."""
    return загрузить(app, клиент, проект, имя, данные, run_id=run_id)["id"]


def итог_задания(app, ответ) -> str:
    """Чем кончилось задание из ответа загрузки. Только для текста падения."""
    with app.state.db.session_scope() as s:
        строка = s.get(Job, ответ.json()["job"]["id"])
        return "задания нет" if строка is None else (
            f"{строка.status}: {строка.error or строка.result}")


def дождаться(app, ответ) -> Job:
    """Прокрутить очередь и вернуть строку задания из ответа `202`."""
    докрутить(app)
    with app.state.db.session_scope() as s:
        строка = s.get(Job, ответ.json()["job"]["id"])
        s.expunge(строка)
        return строка


def сделано(app, ответ) -> dict:
    """Результат задания, которое обязано было получиться. → `job.result`."""
    строка = дождаться(app, ответ)
    assert строка.status == DONE, f"{строка.status}: {строка.error}"
    return строка.result or {}


__all__ = ["файл", "путь_материалов", "отдать", "докрутить", "загрузить",
           "ид_материала", "дождаться", "сделано", "итог_задания", "ПОЛЕ",
           "ТИП"]
