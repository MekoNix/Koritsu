"""
Внешние ключи: выдаются один раз, хранятся хешем, отзываются, считают запросы.

Проверяется здесь то, что делает ключ ключом, а не строкой в базе:

* строка показана **один раз** и в базе её нет — ни в списке, ни в колонке;
* права из закрытого списка, опечатка отвергается на входе;
* отзыв не удаляет строку: отозванный ключ обязан отличаться от выдуманного;
* лимит запросов — скользящим окном, а не «сколько за календарную минуту».

Что ключ делает под `/api/v1` — в `test_v1`: там про вход, здесь про сам ключ.
"""
from __future__ import annotations

import pytest
from sqlalchemy import select

from api.tokens import service
from api.tokens.models import ApiToken, ПРИСТАВКА

from .c_fixtures import клиент, хозяин, сосед, войти  # noqa: F401


@pytest.fixture(autouse=True)
def _чистые_счётчики():
    """Окна лимита живут в памяти процесса, а тесты идут один за другим."""
    service.забыть_лимиты()
    yield
    service.забыть_лимиты()


def завести_ключ(клиент, *, name="ноутбук", scopes=None) -> dict:
    ответ = клиент.post("/api/tokens", json={
        "name": name, "scopes": scopes or [service.PROJECTS_READ]})
    assert ответ.status_code == 201, ответ.text
    return ответ.json()


# ── строка ключа ─────────────────────────────────────────────────────────────

def test_строка_ключа_показана_один_раз(клиент, хозяин):
    """Решение владельца §7 дословно: «показать один раз при создании»."""
    заведён = завести_ключ(клиент)
    строка = заведён["token"]
    assert строка.startswith(ПРИСТАВКА)
    assert заведён["prefix"] == строка[len(ПРИСТАВКА):][:8]

    список = клиент.get("/api/tokens")
    assert список.status_code == 200
    (карточка,) = список.json()
    assert "token" not in карточка
    assert строка not in список.text


def test_в_базе_хеш_а_не_строка(app, клиент, хозяин):
    """Снимок базы, попавший не туда, не должен раздавать доступ."""
    строка = завести_ключ(клиент)["token"]
    with app.state.db.session_scope() as s:
        (ключ,) = s.scalars(select(ApiToken)).all()
        assert ключ.token_hash == service.хеш(строка)
        assert строка not in ключ.token_hash
        # Ни одна колонка не содержит строки целиком — включая имя и приставку.
        for колонка in (ключ.name, ключ.prefix, ключ.token_hash):
            assert строка not in колонка


def test_две_выдачи_дают_разные_строки(клиент, хозяин):
    """Ключ — 32 случайных байта, а не счётчик."""
    первый = завести_ключ(клиент, name="первый")["token"]
    второй = завести_ключ(клиент, name="второй")["token"]
    assert первый != второй


# ── права ────────────────────────────────────────────────────────────────────

def test_неизвестное_право_отвергается(клиент, хозяин):
    """Опечатка `project:write` выглядит как право, но не проверяется нигде."""
    ответ = клиент.post("/api/tokens",
                        json={"name": "кривой", "scopes": ["project:write"]})
    assert ответ.status_code == 400
    assert ответ.json()["error"]["code"] == "unknown_scope"


def test_ключ_без_прав_не_заводится(клиент, хозяин):
    """Ключ, которым ничего нельзя, — это отозванный ключ, выданный сразу."""
    ответ = клиент.post("/api/tokens", json={"name": "пустой", "scopes": []})
    assert ответ.status_code == 400
    assert ответ.json()["error"]["code"] == "unknown_scope"


def test_права_нормализуются_по_порядку(клиент, хозяин):
    """Порядок в ответе — тот же, что в `ПРАВА`: два одинаковых по смыслу
    ключа не должны выглядеть разными."""
    заведён = завести_ключ(клиент, scopes=[service.RUNS_RUN,
                                           service.PROJECTS_READ,
                                           service.RUNS_RUN])
    assert заведён["scopes"] == [service.PROJECTS_READ, service.RUNS_RUN]


def test_запись_подразумевает_чтение():
    """`projects:write` без `projects:read` — это неработающий ключ, а не
    осторожность. Обратное неверно, и в этом весь смысл разделения."""
    assert service.даёт([service.PROJECTS_WRITE], service.PROJECTS_READ)
    assert not service.даёт([service.PROJECTS_READ], service.PROJECTS_WRITE)
    assert not service.даёт([service.PROJECTS_WRITE], service.RUNS_RUN)


# ── список и отзыв ───────────────────────────────────────────────────────────

def test_отозванный_остаётся_в_списке(клиент, хозяин):
    """Иначе человек не отличит «я его отозвал» от «он куда-то делся»."""
    ключ = завести_ключ(клиент)
    отзыв = клиент.delete(f"/api/tokens/{ключ['id']}")
    assert отзыв.status_code == 200
    assert отзыв.json()["revoked_at"] is not None

    (карточка,) = клиент.get("/api/tokens").json()
    assert карточка["id"] == ключ["id"]
    assert карточка["revoked_at"] is not None


def test_чужой_ключ_не_отзывается(app, клиент, хозяин, сосед):
    """Чужой и несуществующий отвечают одинаково (§3): `403` рассказал бы, что
    ключ с таким идентификатором существует."""
    чужой = завести_ключ(клиент)
    войти(app, сосед)
    ответ = клиент.delete(f"/api/tokens/{чужой['id']}")
    assert ответ.status_code == 404
    выдуманный = клиент.delete("/api/tokens/0f2a5f4e-0000-0000-0000-000000000000")
    assert выдуманный.status_code == 404
    assert ответ.json()["error"]["code"] == выдуманный.json()["error"]["code"]


def test_ключи_соседа_не_видны(app, клиент, хозяин, сосед):
    завести_ключ(клиент, name="мой")
    войти(app, сосед)
    assert клиент.get("/api/tokens").json() == []


# ── лимит запросов ───────────────────────────────────────────────────────────

def test_окно_пропускает_ровно_лимит():
    """Шестьдесят проходят, шестьдесят первый — нет (§11)."""
    ключ = "проба"
    assert all(service.в_пределах(ключ, сейчас=100.0)
               for _ in range(service.ЛИМИТ_В_МИНУТУ))
    assert not service.в_пределах(ключ, сейчас=100.0)


def test_окно_скользит_а_не_обнуляется_по_минутам():
    """Календарная минута позволила бы 120 запросов подряд на её границе."""
    ключ = "проба"
    for _ in range(service.ЛИМИТ_В_МИНУТУ):
        service.в_пределах(ключ, сейчас=100.0)
    assert not service.в_пределах(ключ, сейчас=159.0)      # окно ещё то же
    assert service.в_пределах(ключ, сейчас=161.0)          # старое выпало


def test_ключи_считаются_по_отдельности():
    for _ in range(service.ЛИМИТ_В_МИНУТУ):
        service.в_пределах("первый", сейчас=100.0)
    assert not service.в_пределах("первый", сейчас=100.0)
    assert service.в_пределах("второй", сейчас=100.0)
