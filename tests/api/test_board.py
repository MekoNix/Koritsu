def test_распознанное_едет_со_сценой_и_возвращается_как_есть(клиент, проект,
                                                             доска):
    """Кэш распознанного — не материал и не разбор: служба его хранит, не читая.

    Он описывает ровно те штрихи, что лежат рядом, и потому едет одной записью
    со сценой. Форма его — дело страницы: служба, начавшая в неё заглядывать,
    завела бы второе описание того же и разошлась бы с ним на первой правке.
    """
    кэш = {"строка-1": {"fingerprint": "a1", "latex": "x=1", "state": "draft"},
           "строка-2": {"fingerprint": "b2", "latex": "", "state": "manual",
                        "вложенное": {"чего": ["служба", "не", "знает"]}}}
    записанная = клиент.put(СЦЕНА.format(проект["id"]),
                            params={"run": доска["id"]},
                            json={"scene": образец("квадратное_верно"),
                                  "version": 0, "recognized": кэш})
    assert записанная.status_code == 200, записанная.text
    assert записанная.json()["recognized"] == кэш

    снова = клиент.get(СЦЕНА.format(проект["id"]),
                       params={"run": доска["id"]}).json()
    assert снова["recognized"] == кэш


def test_потерявшая_гонку_вкладка_получает_и_кэш(клиент, проект, доска):
    """Вкладка, потерявшая гонку, обязана увидеть и чужие штрихи, и чужой кэш:
    без него она распознала бы заново всё, что уже прочитано и оплачено."""
    клиент.put(СЦЕНА.format(проект["id"]), params={"run": доска["id"]},
               json={"scene": {"elements": []}, "version": 0,
                     "recognized": {"строка-1": {"latex": "x=1"}}})
    вторая = записать(клиент, проект, доска, {"elements": []}, 0)
    assert вторая.status_code == 409, вторая.text
    assert вторая.json()["recognized"] == {"строка-1": {"latex": "x=1"}}


def test_старая_версия_отвечает_409_и_текущей_сценой(клиент, проект, доска):
    """Две вкладки теряют правку шумно: в отказе приезжает то, что победило."""
