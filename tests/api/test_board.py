def test_строки_пишутся_телом_как_их_прочла_страница(клиент, проект, доска):
    """Строки от страницы записываются как есть: второй разбор той же сцены на
    стороне службы отвечал бы на тот же вопрос по-своему.

    Порядок чтения — порядок списка: какая строка выше какой, знает тот, кто
    смотрит на холст.
    """
    записать(клиент, проект, доска, образец("квадратное_верно"), 0)
    ответ = клиент.put(СТРОКИ.format(проект["id"]),
                       params={"run": доска["id"]},
                       json={"lines": [
                           {"id": "aaa111", "latex": "x^{2}=4",
                            "elements": ["э1", "э2"], "confirmed": True},
                           {"id": "bbb222", "latex": "", "elements": ["э3"],
                            "confirmed": False}]})
    assert ответ.status_code == 200, ответ.text
    тело = ответ.json()
    assert [ш["id"] for ш in тело["steps"]] == ["aaa111", "bbb222"]
    assert [ш["n"] for ш in тело["steps"]] == [1, 2]
    assert тело["steps"][0]["elements"] == ["э1", "э2"]
    assert тело["unrecognized"] == 1 and тело["stale"] is False

    # Тот же список приезжает и чтением: панель и файл строятся из одного.
    снова = клиент.get(СТРОКИ.format(проект["id"]),
                       params={"run": доска["id"]}).json()
    assert [ш["id"] for ш in снова["steps"]] == ["aaa111", "bbb222"]


