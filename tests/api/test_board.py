"""
Модуль доски через HTTP: доски работы, сцена, строки решения, условие.

Сам репетитор здесь не зовётся ни разу: его гоняет задание очереди
(`board_check`), и проверяет его `tests/api/test_board_check.py`. Мост
распознавания — `tests/api/test_board_ink.py`. Здесь то, без чего страница
доски не открывается и не сохраняется.

Что именно проверяется и почему это стоит теста:

* **карточка модуля есть в реестре.** Сайдбар строится по `GET /api/modules`, и
  модуля, которого там нет, на сайте нет вовсе. Забытая строка в `_наполнить()`
  не ломает ни одного запроса — она просто прячет модуль;
* **доска заводится без выбора работы.** Экран досок работ не показывает вовсе,
  и доска, для которой пришлось бы сперва назвать работу, начиналась бы с
  экрана, на котором нечего решать. Носитель при этом прежний — решение работы,
  — и лента пространства обязана называть ту работу в карточке;
* **доска переживает круг «нарисовал → перезагрузил страницу»**, и `customData`
  цел: связь «штрих ↔ формула ↔ LaTeX» живёт в нём, и потеря его превращает
  подтверждённое решение в набор линий;
* **`PUT …/scene` со старой версией отвечает `409` и текущей сценой.** Две
  вкладки одной доски обязаны терять правку шумно: молчаливая потеря
  обнаруживается через полчаса работы;
* **строки собираются по образцовой сцене знак в знак.** Идентификатор строки —
  договор трёх областей сразу: он печатается в выжимке, приезжает в ответе
  модели и разрешается браузером в объект холста;
* **распознанное перезаписывается, а не копится.** Опись работы уезжает в
  каждый промпт карточками, и тысяча версий одного файла в ней стоит денег;
* **без ключей распознавания доска отвечает состоянием, а не отказом.** Доска
  рисует и сохраняется всегда, и `ready: false` — это строка на экране, а не
  беда.
"""
