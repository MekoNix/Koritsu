def test_доска_заводится_без_выбора_работы(клиент, хозяин):
    """Работы в запросе нет вовсе: её находит служба, и вторая доска ляжет в ту же."""
    ws = личное_id(клиент)
    первая = клиент.post(ЛЕНТА, json={"workspace_id": ws, "name": "Логарифм"})
    assert первая.status_code == 201, первая.text
    вторая = клиент.post(ЛЕНТА, json={"workspace_id": ws})
    assert вторая.status_code == 201, вторая.text

    а, б = первая.json(), вторая.json()
    assert а["project_id"] == б["project_id"], "две доски — одна неявная работа"
    assert (а["n"], б["n"]) == (1, 2)
    assert а["project_name"] == "Доски"

    # Неявная работа — обычная работа модуля `board`: её видно списком работ, и
    # ни одного второго списка ради неё не заведено.
    работы = клиент.get("/api/projects", params={"workspace_id": ws}).json()
    свои = [р for р in работы["projects"] if р["id"] == а["project_id"]]
    assert len(свои) == 1 and свои[0]["module"] == "board"


def test_лента_пространства_несёт_работу_и_новые_сверху(клиент, хозяин):
    """Лента собирается по всем работам: доска живёт в решении любой из них."""
    ws = личное_id(клиент)
    чужая_работа = создать_проект(клиент, ws, name="Механика")
    в_работе = клиент.post(ДОСКИ.format(чужая_работа["id"]),
                           json={"name": "Наклонная"}).json()
    без_работы = клиент.post(ЛЕНТА,
                             json={"workspace_id": ws, "name": "Логарифм"}).json()

    лента = клиент.get(ЛЕНТА, params={"workspace_id": ws})
    assert лента.status_code == 200, лента.text
    карточки = {к["id"]: к for к in лента.json()}
    assert set(карточки) == {в_работе["id"], без_работы["id"]}
    assert карточки[в_работе["id"]]["project_name"] == "Механика"
    assert карточки[в_работе["id"]]["project_id"] == чужая_работа["id"]
    assert карточки[без_работы["id"]]["steps"] == 0
    # Новые сверху: лента без выбора работы читается как «что я решал последним».
    assert [к["id"] for к in лента.json()][0] == без_работы["id"]


