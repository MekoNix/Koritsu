def test_без_тела_строки_собираются_по_прочитанному(клиент, проект, доска):
    """Страница просит пересобрать строки, не пересказывая службе свой кэш.

    Порядок — сверху вниз по `box`, а не порядок словаря: какая строка выше
    какой, видно по сцене, и видно это одинаково странице и службе.
    """
    записать(клиент, проект, доска, сцена_штрихов(ЗАПИСЬ), 0, кэш(ЗАПИСЬ))
    ответ = клиент.put(СТРОКИ.format(проект["id"]), params={"run": доска["id"]})
    assert ответ.status_code == 200, ответ.text
    тело = ответ.json()
    assert [ш["id"] for ш in тело["steps"]] == [короткий("ш1"), короткий("ш3")]
    assert [ш["n"] for ш in тело["steps"]] == [1, 2]
    assert [ш["latex"] for ш in тело["steps"]] == ["x^{2}=4", ""]
    assert [ш["elements"] for ш in тело["steps"]] == [["ш1", "ш2"], ["ш3", "ш4"]]
    assert [ш["source"] for ш in тело["steps"]] == ["manual", "myscript"]
    # Непрочитанная строка не исчезает: она и есть «здесь написано то, чего я
    # не вижу», — но в файл контекста ей нечего положить.
    assert тело["unrecognized"] == 1 and тело["stale"] is False
    текст = клиент.get(f"/api/projects/{проект['id']}/materials/"
                       f"{тело['latex_material']}/text").json()["text"]
    assert f"[{короткий('ш1')}]" in текст and короткий("ш3") not in текст


def test_идентификатор_строки_один_у_службы_и_у_ядра(клиент, проект, доска):
    """Собрала ли строки служба по прочитанному или ядро по сцене, репетитор
    называет одну и ту же строку: иначе его замечание не разрешается в холст."""
    записать(клиент, проект, доска, сцена_штрихов(ЗАПИСЬ), 0, кэш(ЗАПИСЬ))
    по_кэшу = клиент.put(СТРОКИ.format(проект["id"]),
                         params={"run": доска["id"]}).json()
    # Та же сцена, но прочитанного с неё нет: строки собирает ядро.
    записать(клиент, проект, доска, сцена_штрихов(ЗАПИСЬ), 1)
    по_сцене = клиент.put(СТРОКИ.format(проект["id"]),
                          params={"run": доска["id"]}).json()
    assert ([ш["id"] for ш in по_кэшу["steps"]]
            == [ш["id"] for ш in по_сцене["steps"]])
    assert ([ш["elements"] for ш in по_кэшу["steps"]]
            == [ш["elements"] for ш in по_сцене["steps"]])


