def записать(клиент, проект, доска, сцена: dict, версия: int,
             распознанное: dict | None = None):
    return клиент.put(СЦЕНА.format(проект["id"]), params={"run": доска["id"]},
                      json={"scene": сцена, "version": версия,
                            "recognized": распознанное or {}})


# Запись на доске так, как её держит страница v2: росчерки на сцене, прочитанное
# рядом с ней. Порядок словаря обратный порядку чтения — строки обязаны встать
# по `box`, а не по тому, в каком порядке страница их перечислила.
ЗАПИСЬ = {"г2": (90.0, ["ш3", "ш4"], ""),
          "г1": (10.0, ["ш1", "ш2"], "x^{2}=4")}


def сцена_штрихов(запись: dict) -> dict:
    """Сцена из голых росчерков: v2 не пишет прочитанное в `customData`."""
    элементы = []
    for группа, (верх, росчерки, _latex) in запись.items():
        for k, ид in enumerate(росчерки):
            элементы.append({"id": ид, "type": "freedraw", "groupIds": [группа],
                             "x": 10.0 + 30 * k, "y": верх,
                             "width": 20.0, "height": 10.0, "isDeleted": False})
    return {"type": "excalidraw", "version": 2, "elements": элементы,
            "appState": {}}


def кэш(запись: dict) -> dict:
    """То, что страница уже прочла с этих росчерков."""
    return {группа: {"fingerprint": группа + "-1", "latex": latex,
                     "state": "manual" if latex else "recognized",
                     "elements": list(росчерки),
                     "box": {"x": 10.0, "y": верх, "width": 90.0,
                             "height": 20.0}}
            for группа, (верх, росчерки, latex) in запись.items()}


def короткий(ид: str) -> str:
    """Идентификатор строки по первому её росчерку — тот же, что у ядра."""
    return hashlib.sha256(ид.encode("utf-8")).hexdigest()[:6]


