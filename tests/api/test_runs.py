def test_отмена_посреди_отчёта_оставляет_закрытые_теги(app, клиент, хозяин,
                                                       модель):
    """Отмена — закрытые теги остаются. Проверяется на настоящем шве:
    подделка провода спрашивает `cancel()` перед каждым куском, как транспорт."""
    завести_ключ(клиент)
    p = проект(клиент)
    job_id = поставить(клиент, "fill_report", p["id"]).json()["id"]

    ответ = отчёт(цель=ЦЕЛЬ, выводы=ВЫВОДЫ)
    граница = ответ.index('"выводы"')

    def нажать_отменить():
        клиент.post(f"/api/jobs/{job_id}/cancel")

    def переждать_кэш():
        # Провод спрашивает базу не чаще, чем раз в `ПРОВЕРКА_ОТМЕНЫ_С`, иначе
        # сессия открывалась бы на каждый кусок ответа. Тест эту четверть
        # секунды честно ждёт, а не отменяет кэш: без него настоящий прогон
        # платил бы за отмену тысячей запросов в базу.
        time.sleep(ПРОВЕРКА_ОТМЕНЫ_С + 0.05)

    # Первая половина ответа кусками, потом человек жмёт «отменить», потом
    # вторая половина — которую поток уже не отдаст.
    модель([*куски(ответ[:граница], частей=8), нажать_отменить, переждать_кэш,
            *куски(ответ[граница:], частей=8)])

    assert прогнать(app) == job_id
    строка = задание(app, job_id)
    assert строка.status == CANCELLED
    # Закрытый тег на месте, недоделанный — нет.
    проект_на_томе = открыть(app, p["id"])
    assert проект_на_томе.value("цель") is not None
    assert проект_на_томе.value("выводы") is None
    assert "цель" in (строка.result or {}).get("filled", [])


