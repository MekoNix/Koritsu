def test_задача_агента_уезжает_в_промпт_недоверенным_куском(app, клиент, хозяин,
                                                            модель):
    """Задача для агента — из запроса. Проверяется по тому, что уехало по
    проводу: текст человека в промпте есть, и приехал он куском роли `files` с
    пометкой `untrusted` — то есть внутри рамки, отдельно от наших указаний."""
    завести_ключ(клиент)
    подделка = модель(сценарий("готово"))
    p = проект(клиент)
    задача = "Построй блок-схему по listing.py и вставь её в раздел «Ход работы»"
    job_id = поставить(клиент, "agent", p["id"], task=задача).json()["id"]

    прогнать(app)
    assert подделка.requests, "до модели дело не дошло — проверять нечего"
    куски_запроса = [ч for з in подделка.requests
                     for ч in (getattr(з, "parts", None) or ())]
    свой = [ч for ч in куски_запроса if задача in (getattr(ч, "text", "") or "")]
    assert свой, "задача человека до модели не доехала"
