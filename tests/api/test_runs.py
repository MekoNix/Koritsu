def test_текст_отчёта_уезжает_кусками_по_мере_генерации(app, клиент, хозяин,
                                                        модель):
    """Уровень 2 потоковый, и обещание «текст по мере генерации» держится
    именно на нём: кадров `text` больше одного, а склеены они по ~100 мс."""
