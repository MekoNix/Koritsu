"""
Прогоны модели заданиями: ключ, лимит, события, отмена, артефакты.

Сети нет: подменён провод модели и только он (`b_fixtures`). Проверяется не
«функция вернула словарь», а те четыре обещания, которые ломаются молча:

1. **нет ключа — нет вызова.** Отказ `no_key` приходит до модели, а не после;
2. **закрытое сохранено.** Отмена посреди отчёта не отбирает записанных тегов;
3. **лимит месячный и по нашим ценам**. Отказ на постановке (`402`),
   если на цену вида не хватает остатка, и отказ перед стартом обработчика,
   если остаток съели, пока задание ждало в очереди;
4. **секрет и ключ не уезжают никуда** — ни в ответ, ни в событие, ни в журнал.
"""
