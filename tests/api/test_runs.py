def test_лимит_кончился_пока_задание_ждало_и_закрытое_остаётся(app, клиент,
                                                               хозяин, модель):
    """Между постановкой и захватом остаток съели: задание падает до модели.

    Это вторая и последняя проверка месяца: первую прошла постановка, а
    пока задание лежало в очереди, остаток увёл сосед по аккаунту (или правка
    лимита владельцем). Записанное раньше при этом на месте — так и обещано:
    при исчерпании остановка, событие в поток, закрытое сохранено.
    """
    завести_ключ(клиент)
    p = проект(клиент)
    # Тег, поставленный человеком до прогона: он и есть «закрытое», которое
    # обязано пережить исчерпание лимита.
    клиент.put(f"/api/projects/{p['id']}/values/цель", json=ЦЕЛЬ)

    модель(сценарий(отчёт(выводы=ВЫВОДЫ)))
    ответ = поставить(клиент, "fill_report", p["id"])
    assert ответ.status_code == 202, ответ.text
    job_id = ответ.json()["id"]
    настроить(app, free_monthly_units=10)      # постановка прошла, а месяца нет

    assert прогнать(app) == job_id
    строка = задание(app, job_id)
    assert строка.status == FAILED
    assert строка.error["code"] == "limit_exhausted"
    assert "limit_exhausted" in виды_событий(app, job_id)
    # До модели дело не дошло вовсе: отказ стоит перед первым вызовом.
    assert открыть(app, p["id"]).value("выводы") is None
    # Закрытое сохранено: значение человека никуда не делось.
    assert открыть(app, p["id"]).value("цель")["text"] == ЦЕЛЬ["text"]


