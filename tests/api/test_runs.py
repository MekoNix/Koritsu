def проект(клиент) -> dict:
    return создать_проект(клиент, личное_id(клиент), шаблон=docx_байты())


def каталог(app, project_id: str) -> str:
    with app.state.db.session_scope() as s:
        return project_dir(s, app.state.settings, project_id)


def открыть(app, project_id: str):
    import orchestrator                                       # noqa: PLC0415

    return orchestrator.Project(каталог(app, project_id))


def настроить(app, **правки) -> None:
    """Поменять настройки собранного приложения. Настройки неизменяемы, поэтому
    заменяется весь объект — и маршруты, и воркер берут его через `app.state`."""
    app.state.settings = dataclasses.replace(app.state.settings, **правки)


