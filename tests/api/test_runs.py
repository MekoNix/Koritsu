def test_отмена_агента_осталась_отменой_а_не_провалом(app, клиент, хозяин,
                                                      модель):
    """Остановил прогон человек, и `cancelled` — его действие, а не беда.

    Проверка стоит рядом с предыдущей намеренно: `ok=false` бывает и у отмены
    (`outcome: interrupted`), и объявить её `failed` значило бы показать
    тревожный тост в ответ на нажатую человеком кнопку.
    """
    завести_ключ(клиент)
    p = проект(клиент)
    job_id = поставить(клиент, "agent", p["id"],
                       task="поставь цель").json()["id"]

    def нажать_отменить():
        клиент.post(f"/api/jobs/{job_id}/cancel")

    def переждать_кэш():
        # Провод спрашивает базу не чаще, чем раз в `ПРОВЕРКА_ОТМЕНЫ_С` — та же
        # четверть секунды, что и в проверке отмены уровня 2 выше.
        time.sleep(ПРОВЕРКА_ОТМЕНЫ_С + 0.05)

    модель([нажать_отменить, переждать_кэш, *куски("готово", частей=4)])

    assert прогнать(app) == job_id
    assert задание(app, job_id).status == CANCELLED


