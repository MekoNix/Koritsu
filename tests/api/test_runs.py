def test_исчерпанный_лимит_отказывает_на_постановке(app, клиент, хозяин):
    """402, а не 429: кончилась месячная квота, и ждать бесполезно.

    Расход набирается пробой очереди — тем же полем `spent_units`, по которому
    считается месяц, и потому проверка считает именно то, что считает служба.
    """
    настроить(app, free_monthly_units=500)
    клиент.post("/api/jobs", json={"kind": "probe", "payload": {"charge": 800}})
    прогнать(app)

    p = проект(клиент)
    ответ = поставить(клиент, "fill_tag", p["id"], key="цель")
    assert ответ.status_code == 402, ответ.text
    беда = ответ.json()["error"]
    assert беда["code"] == "limit_exhausted"
    # Отказ с цифрой: человек должен видеть, сколько потрачено и сколько было.
    assert "500" in беда["message"] and "800" in беда["message"]

    # А бесплатное задание ставится по-прежнему: лимит про деньги, а не про
    # очередь, и цена пробы — ноль.
    assert клиент.post("/api/jobs", json={"kind": "probe"}).status_code == 202


