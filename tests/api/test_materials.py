def test_удаление(app, клиент, проект):
    mid = загрузить(app, клиент, проект, "a.txt", "раз\n".encode())["id"]
    путь = ПУТЬ.format(проект["id"])
    ответ = клиент.delete(f"{путь}/{mid}")
    # Не `204`: в теле сказано, что именно ушло с тома, — у материала бывают
    # производные, и одного кода ответа для этого мало.
    assert ответ.status_code == 200, ответ.text
    assert ответ.json() == {"removed": [mid], "kept": []}
    assert клиент.get(f"{путь}/{mid}").status_code == 404
    assert клиент.get(путь).json() == []
    # Повторное удаление — 404, а не тихое «уже нет»: клиент, повторивший запрос,
    # обязан узнать, что второй раз он удалил не то, что думал.
    assert клиент.delete(f"{путь}/{mid}").status_code == 404


def test_удаление_уносит_картинки_страниц(app, клиент, проект):
    """Сироты PDF: картинка, вынутая со страницы, уходит вместе с методичкой.
    Иначе человек удалил один файл, а квота считает полсотни картинок, которых
    он в описи больше не видит."""
    путь = ПУТЬ.format(проект["id"])
    родитель = загрузить(app, клиент, проект, "методичка.pdf", pdf_с_картинкой())
    ребёнок = родитель["children"][0]
    assert len(клиент.get(путь).json()) == 2

    ответ = клиент.delete(f"{путь}/{родитель['id']}")
    assert ответ.status_code == 200, ответ.text
    assert set(ответ.json()["removed"]) == {родитель["id"], ребёнок}
    assert ответ.json()["kept"] == []
    assert клиент.get(путь).json() == []
    assert клиент.get(f"{путь}/{ребёнок}").status_code == 404


def test_картинка_остаётся_если_на_неё_ссылается_значение_тега(app, клиент,
                                                              проект):
    """Ссылка сильнее родства: картинка, поставленная в значение тега, уже стоит
    в отчёте, и унести её вместе с методичкой значило бы выбить рисунок из
    собранного документа. Оставленное названо в ответе — молчать об этом
    нельзя, иначе клиент считает материал удалённым."""
    путь = ПУТЬ.format(проект["id"])
    родитель = загрузить(app, клиент, проект, "методичка.pdf", pdf_с_картинкой())
    ребёнок = родитель["children"][0]
    поставлено = клиент.put(f"/api/projects/{проект['id']}/values/схема",
                            json={"v": 1, "type": "image", "artifact": ребёнок})
    assert поставлено.status_code == 200, поставлено.text

    ответ = клиент.delete(f"{путь}/{родитель['id']}")
    assert ответ.status_code == 200, ответ.text
    assert ответ.json() == {"removed": [родитель["id"]], "kept": [ребёнок]}
    # Картинка на месте и по-прежнему скачивается: ссылка на неё живая.
    assert клиент.get(f"{путь}/{ребёнок}").status_code == 200
    assert клиент.get(f"{путь}/{ребёнок}/blob").status_code == 200


