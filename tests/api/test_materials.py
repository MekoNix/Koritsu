def test_кривой_файл_не_оставляет_мусора_на_томе(app, клиент, проект,
                                                monkeypatch, settings):
    """Разборщик мог успеть положить исходник и умереть до `meta.json`.

    Такой полуматериал невидим для описи, но байты владельцу в квоту засчитал бы.
    Проверяем, что после беды нет ни его, ни принятых байтов в `incoming/`:
    второе так же занимает том, и убирается оно тем же `finally`.
    """
    def падает(склад, source, name=None, **kwargs):
        # Ведём себя как убитый разборщик: исходник лёг, `meta.json` — нет.
        with open(source, "rb") as f:
            mid = m_pkg.material_id(f.read())
        os.makedirs(os.path.join(склад.root, mid), exist_ok=True)
        with open(os.path.join(склад.root, mid, "source.txt"), "wb") as f:
            f.write("половина".encode())
        raise m_pkg.MaterialsError("убит по таймауту")

    monkeypatch.setattr(m_pkg.Store, "add", падает)
    ответ = отдать(клиент, проект, "a.txt", "раз\n".encode())
    assert дождаться(app, ответ).status == "failed"

    assert клиент.get(ПУТЬ.format(проект["id"])).json() == []
    assert клиент.get(ПУТЬ.format(проект["id"]) + "/pending").json() == []
