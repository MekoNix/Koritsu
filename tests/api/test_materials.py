def png_байты(w=160, h=90, color="orange") -> bytes:
    buf = io.BytesIO()
    PIL.new("RGB", (w, h), color).save(buf, format="PNG")
    return buf.getvalue()


def pdf_с_картинкой() -> bytes:
    """PDF, из которого разбор вынет отдельным материалом одну картинку."""
    doc = pymupdf.open()
    страница = doc.new_page()
    страница.insert_text((72, 100), "Hod raboty", fontsize=14)
    страница.insert_image(pymupdf.Rect(72, 150, 232, 240), stream=png_байты())
    данные = doc.tobytes()
    doc.close()
    return данные


def pdf_байты(страницы=("Pervaya stranica", "Vtoraya stranica")) -> bytes:
    doc = pymupdf.open()
    for текст in страницы:
        doc.new_page().insert_text((72, 100), текст, fontsize=14)
    данные = doc.tobytes()
    doc.close()
    return данные


