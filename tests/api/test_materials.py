def test_загрузка_отвечает_202_и_ставит_задание(app, клиент, проект):
    """Разбор — задание, а не работа запроса. В ответе — то и другое.

    `pending_id` известен уже в этот момент, потому что это sha256 содержимого,
    а не выданный кем-то номер: клиент может ждать материал по имени, которое
    ему уже назвали.
    """
    ответ = отдать(клиент, проект, "solver.py", b"def f():\n    return 1\n")
    assert ответ.status_code == 202, ответ.text
    тело = ответ.json()
    assert MATERIAL_ID_RE.match(тело["pending_id"])
    assert тело["job"]["kind"] == "parse"
    assert тело["job"]["status"] == "queued"
    assert тело["job"]["project_id"] == проект["id"]
    # Материала ещё нет: очередь не крутилась.
    assert клиент.get(ПУТЬ.format(проект["id"])).json() == []

    строка = дождаться(app, ответ)
    assert строка.status == "done", строка.error
    assert строка.result["material"] == тело["pending_id"]
    assert строка.result["card"]["name"] == "solver.py"


