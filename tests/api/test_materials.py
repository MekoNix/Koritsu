def test_тот_же_файл_второй_раз_не_разбирается(app, клиент, проект, monkeypatch):
    """Извлечённый текст хранится по хешу файла.

    Считаем разборы, а не время: «стало быстрее» — не утверждение, которое тест
    может проверить, а «разборщик не запускался» — да. Считается сам разбор
    (`materials.store.parse`), а не задание: задание ставится и на повторную
    загрузку: путь один, а не один путь для новых файлов.
    """
    запусков = []
    настоящий = m_pkg.store.parse

    def счётчик(*args, **kwargs):
        запусков.append(args[1] if len(args) > 1 else "")
        return настоящий(*args, **kwargs)

    monkeypatch.setattr(m_pkg.store, "parse", счётчик)

    # Байты одни и те же: `pdf_байты()` дважды даёт разные файлы (в PDF стоит
    # время создания), а проверяем мы именно «тот же файл».
    данные = pdf_байты()
    первый = загрузить(app, клиент, проект, "методичка.pdf", данные)
    второй = загрузить(app, клиент, проект, "она-же-под-другим-именем.pdf",
                       данные)

    assert первый["id"] == второй["id"]          # адрес — содержимое, не имя
    # Один разбор родителя (у этого PDF детей нет) на две загрузки.
    assert len(запусков) == 1
    # Имя остаётся от первой загрузки: материал один, и переименовывать его
    # второй загрузкой значило бы менять карточку у всех, кто на неё сослался.
    assert второй["name"] == "методичка.pdf"


