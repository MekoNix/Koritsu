@pytest.mark.parametrize("лимиты", [{"file_max_bytes": 4096}], indirect=True)
def test_поток_без_длины_рвётся_на_превышении(клиент, проект, лимиты):
    """Тела без `Content-Length` (chunked) ловит счётчик на потоке.

    Клиент шлёт тело кусками из генератора — httpx в этом случае не ставит
    длину, то есть первый заслон отключён и работает второй.
    """
    граница = "----koritsu"
    голова = (f"--{граница}\r\n"
              'Content-Disposition: form-data; name="file"; filename="big.txt"\r\n'
              "Content-Type: application/octet-stream\r\n\r\n").encode()
    хвост = f"\r\n--{граница}--\r\n".encode()

    def кусками():
        yield голова
        for _ in range(64):
            yield b"y" * 4096
        yield хвост

    ответ = клиент.post(
        ПУТЬ.format(проект["id"]), content=кусками(),
        headers={"Content-Type": f"multipart/form-data; boundary={граница}"})
    assert ответ.status_code == 413
    assert ответ.json()["error"]["code"] == "file_too_large"


