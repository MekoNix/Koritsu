def test_начать_заново_без_работы_это_внятный_отказ(клиент, проект):
    """Работы нет — переигрывать нечего, и это `422`, а не пятисотка."""
    отказ = клиент.post(ЗАНОВО.format(проект["id"]), json={})
    assert отказ.status_code == 422, отказ.text
    assert отказ.json()["error"]["code"] == "kadai_failed"


def test_вставшая_работа_возвращается_в_ход_без_модели(app, клиент, проект):
    """Главное обещание маршрута: `failed` → `running` и ни одного вызова модели.

    Ход работы кладётся на том руками — тем же способом, каким его пишет
    сценарий (`Project.put_state`): гонять ради этого семь стадий значило бы
    проверять модель, а проверяется возврат в ход.
    """
    _положить_вставшую(app, клиент, проект)

    ответ = клиент.post(ЗАНОВО.format(проект["id"]), json={})
    assert ответ.status_code == 200, ответ.text
    assert ответ.json()["restarted"] == "разбор задания"

    снимок = клиент.get(ХОД.format(проект["id"])).json()
    assert снимок["state"] == "running"
    состояния = {st["name"]: st["state"] for st in снимок["stages"]}
    # Сделанное до вставшей стадии остаётся сделанным: платили за него один раз.
    assert состояния["приём"] == "сделано"
    assert состояния["разбор задания"] == "ждёт"
    assert состояния["решение"] == "ждёт"


def test_заново_с_названной_стадии_сбрасывает_и_то_что_после_неё(app, клиент,
                                                                 проект):
    """Стадию можно назвать прямо: «переделай с приёма» — это тоже законно."""
    _положить_вставшую(app, клиент, проект)
    ответ = клиент.post(ЗАНОВО.format(проект["id"]), json={"stage": "приём"})
    assert ответ.status_code == 200, ответ.text
    состояния = {st["name"]: st["state"]
                 for st in клиент.get(ХОД.format(проект["id"])).json()["stages"]}
    assert состояния["приём"] == "ждёт"


