# ── архив артефактом ─────────────────────────────────────────────────────────

def test_архив_из_made_скачивается_маршрутом_артефактов(app, клиент, проект):
    """Архив kadai кладётся артефактом, а не только в `out/`.

    Проверяется то, ради чего это делалось: идентификатор из `made.archive`
    отдаётся снимком, и по нему архив скачивается тем же маршрутом, что DOCX и
    PDF. Байты кладутся здесь руками — их производит стадия «архив», а
    проверяется дорога от снимка до файла.
    """
    _положить_вставшую(app, клиент, проект)
    на_томе = _открыть(app, клиент, проект)
    art = на_томе.put_artifact(b"PK\x03\x04koritsu", name="работа.zip")
    задание = dict(на_томе.state("kadai-задание"))
    на_томе.put_state("kadai-задание", {**задание, "made": {"archive": art}})

    снимок = клиент.get(ХОД.format(проект["id"])).json()
    assert снимок["made"]["archive"] == art

    файл = клиент.get(f"/api/projects/{проект['id']}/artifacts/{art}")
    assert файл.status_code == 200, файл.text
    assert файл.content == b"PK\x03\x04koritsu"


def _открыть(app, клиент, проект):
    """Каталог проекта как `orchestrator.Project` — тем же путём, что служба."""
    import orchestrator

    from api.materials.deps import проект_и_роль

    with app.state.db.session_scope() as s:
        found = проект_и_роль(s, app.state.settings, _хозяин_id(app),
                              проект["id"])
    return orchestrator.Project(found.dir)


def _положить_вставшую(app, клиент, проект) -> None:
    """Работа, споткнувшаяся на «разборе задания», записью на томе.

    Пишутся обе записи, потому что читаются они порознь: `kadai-задание` знает
    профиль и пожелания (по ним строится план), `kadai` — ход стадий. Без
    первой сценарий отказал бы «в проекте нет работы», без второй — «сохранять
    было нечего».
    """
    from kadai.stages import STAGE_NAMES

    на_томе = _открыть(app, клиент, проект)
    на_томе.put_state("kadai-задание", {
        "work": "w-проба", "v": 1,
        "wishes": {"text": "", "show_task": False, "show_structure": False}})
    стадии = []
    for имя in STAGE_NAMES:
        if имя == "приём":
            стадии.append({"name": имя, "state": "сделано"})
        elif имя == "разбор задания":
            стадии.append({"name": имя, "state": "споткнулась",
                           "note": "условие не прочиталось"})
        else:
            стадии.append({"name": имя, "state": "ждёт"})
    на_томе.put_state("kadai", {
        "work": "w-проба", "profile": "", "state": "failed",
        "stage": "разбор задания", "stages": стадии, "current": "",
        "hold": None, "condition": {}, "condition_text": "",
        "problems": [], "outputs": {}, "pause_after": [], "seq": 4,
        "events": [{"n": 4, "at": "", "stage": "разбор задания",
                    "state": "споткнулась", "note": ""}]})


def _хозяин_id(app) -> str:
    """Идентификатор вошедшего — из той же подмены, которой он и вошёл."""
    from api.accounts import current_user

    return app.dependency_overrides[current_user]().id
