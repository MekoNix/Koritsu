"""
Модуль заданий через HTTP: стадии, условие и ход работы.

Три маршрута и ни одного прогона: сам сценарий гоняют задания очереди
(`kadai_run`, `kadai_rework`), и проверяет их `tests/api/test_runs.py`. Здесь —
то, чего у заданий нет и без чего страница заданий не запускается ни разу.

Что именно проверяется и почему это стоит теста:

* **карточка модуля есть в реестре.** Сайдбар строится по `GET /api/modules`, и
  модуля, которого там нет, на сайте нет вовсе (правило брифа). Забытая строка
  в `_наполнить()` не ломает ни одного запроса — она просто прячет модуль;
* **условие называется после приёма файла, а не при загрузке.** Человек
  подтверждает распознанное отдельным шагом (решение владельца 2026-08-31), и
  до подтверждения условие — обычный материал;
* **неразобранный и чужой материал условием не становятся.** Иначе прогон
  споткнулся бы на первой стадии, уже списав цену задания;
* **ход работы отдаётся до первого прогона.** Пустой снимок — это `200`, а не
  `404`: страница открывается раньше, чем заводится работа.
"""
from __future__ import annotations

import pytest

from api import Settings

from .c_fixtures import (docx_байты, войти, завести, клиент, личное_id,  # noqa: F401
                         создать_проект, сосед, хозяин)
from .d_fixtures import ид_материала, отдать

СТАДИИ = "/api/kadai/stages"
ХОД = "/api/projects/{}/kadai"
УСЛОВИЕ = "/api/projects/{}/kadai/condition"

УСЛОВИЕ_ТЕКСТОМ = ("Задача 1. Написать программу, считающую сумму чисел "
                   "от 1 до n, и построить блок-схему.\n").encode()


@pytest.fixture
def settings(tmp_path) -> Settings:
    return Settings.for_tests(tmp_path / "том")


@pytest.fixture
def проект(клиент, хозяин):
    """Проект без шаблона: у работы `kadai` шаблона нет вовсе, есть блоки."""
    return создать_проект(клиент, личное_id(клиент), name="задание")


# ── стадии ───────────────────────────────────────────────────────────────────

def test_стадии_отдаются_списком_по_порядку(клиент, хозяин):
    """Семь имён в том порядке, в котором сайт рисует шаги.

    Списком из службы, а не константой в браузере: восьмая стадия появилась бы
    в пакете и не появилась бы на экране, и заметили бы это по пропавшему шагу.
    """
    ответ = клиент.get(СТАДИИ)
    assert ответ.status_code == 200, ответ.text
    стадии = ответ.json()["stages"]
    assert стадии[0] == "приём" and стадии[-1] == "архив"
    assert len(стадии) == len(set(стадии)) == 7


def test_модуль_виден_в_реестре(клиент, хозяин):
    """Иначе пункта «Задания» в сайдбаре не будет, и ни один запрос не упадёт."""
    карточки = {m["id"]: m for m in клиент.get("/api/modules").json()}
    assert карточки["kadai"]["routes"] == "/api/projects"
    assert карточки["kadai"]["title"].isascii()


# ── условие ──────────────────────────────────────────────────────────────────

def test_условие_называется_после_приёма_файла(app, клиент, проект):
    """Загрузка условием не назначает: подтверждает человек, отдельным шагом."""
    ид = ид_материала(app, клиент, проект, "условие.txt", УСЛОВИЕ_ТЕКСТОМ)
    assert клиент.get(ХОД.format(проект["id"])).json()["condition"] == {}

    ответ = клиент.put(УСЛОВИЕ.format(проект["id"]), json={"material_id": ид})
    assert ответ.status_code == 200, ответ.text
    assert ответ.json()["condition"] == ид


def test_назвать_дважды_то_же_самое(app, клиент, проект):
    """`PUT`, а не `POST`: второе условие завести нельзя, можно назвать другое."""
    ид = ид_материала(app, клиент, проект, "условие.txt", УСЛОВИЕ_ТЕКСТОМ)
    первый = клиент.put(УСЛОВИЕ.format(проект["id"]), json={"material_id": ид})
    второй = клиент.put(УСЛОВИЕ.format(проект["id"]), json={"material_id": ид})
    assert первый.json() == второй.json()


def test_неразобранный_материал_условием_не_становится(клиент, проект):
    """Файл принят, задание разбора не крутилось: материала ещё нет.

    Пустить его условием значило бы дать прогону споткнуться на первой стадии —
    уже после того, как цена задания списана.
    """
    ответ = отдать(клиент, проект, "условие.txt", УСЛОВИЕ_ТЕКСТОМ)
    assert ответ.status_code == 202, ответ.text
    ид = ответ.json()["pending_id"]
    отказ = клиент.put(УСЛОВИЕ.format(проект["id"]), json={"material_id": ид})
    assert отказ.status_code == 404, отказ.text
    assert отказ.json()["error"]["code"] == "not_found"


def test_кривой_идентификатор_умирает_до_тома(клиент, проект):
    """`..` обязан умереть на входе: хранилище складывает из него путь."""
    отказ = клиент.put(УСЛОВИЕ.format(проект["id"]),
                       json={"material_id": "../../etc"})
    assert отказ.status_code == 400, отказ.text
    assert отказ.json()["error"]["code"] == "invalid_id"


def test_читателю_условие_назвать_нельзя(app, клиент, хозяин, сосед):
    """Тот же разрез, что у значений: смотреть — `viewer`, менять — `editor`."""
    ws = клиент.post("/api/workspaces", json={"name": "общее"})
    ws_id = ws.json()["id"]
    добавлен = клиент.post(f"/api/workspaces/{ws_id}/members",
                           json={"email": сосед.email, "role": "viewer"})
    assert добавлен.status_code == 201, добавлен.text
    общий = создать_проект(клиент, ws_id, name="общая работа")
    ид = ид_материала(app, клиент, общий, "условие.txt", УСЛОВИЕ_ТЕКСТОМ)

    войти(app, сосед)
    assert клиент.get(ХОД.format(общий["id"])).status_code == 200
    отказ = клиент.put(УСЛОВИЕ.format(общий["id"]), json={"material_id": ид})
    assert отказ.status_code == 403, отказ.text


# ── ход работы ───────────────────────────────────────────────────────────────

def test_ход_работы_до_первого_прогона_пуст_и_не_отказ(клиент, проект):
    """Страница заданий открывается раньше, чем заводится работа."""
    ответ = клиент.get(ХОД.format(проект["id"]))
    assert ответ.status_code == 200, ответ.text
    снимок = ответ.json()
    assert снимок["work"] is None and снимок["stages"] == []
    assert снимок["made"] == {} and снимок["condition_text"] == ""


def test_ход_работы_читает_запись_с_тома(app, клиент, проект):
    """Снимок собирается из того, что пишет сценарий, а не из карточки задания.

    Запись кладётся здесь руками — тем же способом, каким её кладёт сценарий
    (`Project.put_state`): гонять ради этого прогон значило бы проверять
    модель, а проверяется чтение.
    """
    import orchestrator

    from api.materials.deps import проект_и_роль

    with app.state.db.session_scope() as s:
        found = проект_и_роль(s, app.state.settings, _хозяин_id(app),
                              проект["id"])
    на_томе = orchestrator.Project(found.dir)
    на_томе.put_state("kadai", {
        "work": "w-проба", "state": "waiting_user", "stage": "приём",
        "condition": {"material": "abc", "name": "условие.txt", "ocr": True,
                      "text": "Задача 1. Сумма чисел."},
        "stages": [{"name": "приём", "state": "сделано"}],
        "current": "", "hold": {"stage": "приём", "show": "распознанное условие",
                                "note": "проверьте текст"},
        "problems": [], "outputs": {"docx": "отчёт.docx"},
        "events": [{"n": 3, "at": "", "stage": "приём", "state": "сделано"}]})
    на_томе.put_state("kadai-задание", {"made": {"docx": "0123456789abcdef"}})

    снимок = клиент.get(ХОД.format(проект["id"])).json()
    assert снимок["state"] == "waiting_user"
    assert снимок["hold"]["show"] == "распознанное условие"
    # Текст условия уезжает отдельным полем, а не внутри `condition`: показывают
    # его на своём шаге, и второй копии рядом быть не должно.
    assert снимок["condition_text"] == "Задача 1. Сумма чисел."
    assert "text" not in снимок["condition"]
    assert снимок["made"] == {"docx": "0123456789abcdef"}
    assert снимок["since"] == 3


def _хозяин_id(app) -> str:
    """Идентификатор вошедшего — из той же подмены, которой он и вошёл."""
    from api.accounts import current_user

    return app.dependency_overrides[current_user]().id
