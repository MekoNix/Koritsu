"""
Точка входа `python -m api`: справка, миграция, уборка.

Запускается **подпроцессом**, а не вызовом `__main__.main()`, и это не
формальность. Команда существует ради того, кто наберёт её в контейнере или
положит в cron, и ломается она ровно на том, чего вызов из теста не видит:
`python -m` не находит пакет без `PYTHONPATH`, `argparse` печатает справку и
выходит кодом, а `ConfigError` обязана превратиться в одну строку на stderr, а не
в сорок строк трассировки. Проверить это можно только снаружи процесса.

`serve` здесь не запускается намеренно: он открывает порт и не возвращается.
Проверяется его справка — то, что команда есть, объявлена и разбирает свои
параметры; сам подъём uvicorn — работа выката, а не набора тестов.

Каждый запуск получает свой временный том через окружение: у тома умолчания нет
(решение К.2), и тест, забывший его задать, честно падает вместо того, чтобы
писать в рабочий каталог.
"""
from __future__ import annotations

import os
import subprocess
import sys

import pytest

import api

# Корень `packages/` — тот же путь, что кладёт в `sys.path` `tests/conftest.py`.
# Берётся у пакета, а не собирается из `__file__` теста: пакеты в проекте не
# устанавливаются, и второе описание того, где они лежат, разошлось бы с первым
# при первом же переезде каталога.
ПАКЕТЫ = os.path.dirname(os.path.dirname(os.path.abspath(api.__file__)))

# Секрет для подпроцесса. Заведомо длиннее 32 байт и заведомо не настоящий.
СЕКРЕТ = "проба-командной-строки-проба-командной-строки"


def позвать(*аргументы, том=None, **правки) -> subprocess.CompletedProcess:
    """`python -m api …` в чистом окружении с временным томом.

    Окружение собирается с нуля (`env=`), а не наследуется: переменные
    `KORITSU_*` с машины разработчика увели бы команду на его настоящий том — и
    тест бы прошёл, а уборка снесла бы чужие каталоги.
    """
    env = {"PYTHONPATH": ПАКЕТЫ, "PATH": os.environ.get("PATH", ""),
           "PYTHONIOENCODING": "utf-8"}
    if том is not None:
        env["KORITSU_DATA_DIR"] = str(том)
        env["KORITSU_SECRET"] = СЕКРЕТ
    env.update({k: v for k, v in правки.items() if v is not None})
    return subprocess.run([sys.executable, "-m", "api", *аргументы],
                          env=env, capture_output=True, text=True, timeout=120)


# ── справка ──────────────────────────────────────────────────────────────────

def test_справка_называет_все_команды():
    """Справка — по-русски, как у `python -m llm` и `python -m hokoku.build`:
    её читает оператор, а не клиент API."""
    готово = позвать("--help")
    assert готово.returncode == 0, готово.stderr
    for команда in ("serve", "worker", "migrate", "purge"):
        assert команда in готово.stdout, готово.stdout


def test_без_команды_подсказка_и_код_два():
    """Пустой вызов — это ошибка в параметрах, а не «всё хорошо»: cron с
    опечаткой в строке обязан пожаловаться, а не молча ничего не делать."""
    готово = позвать()
    assert готово.returncode == 2
    assert "serve" in готово.stdout


def test_неизвестная_команда_не_проходит():
    готово = позвать("развернуть")
    assert готово.returncode != 0
    assert "развернуть" in (готово.stderr + готово.stdout)


def test_у_worker_есть_справка_и_он_не_крутится():
    """`worker --help` разбирает параметры и выходит, не начиная опрос очереди.

    Сам цикл здесь не запускается по той же причине, что и `serve`: он не
    возвращается, пока его не попросят остановиться. Живой цикл проверяет
    `test_worker.py`, изнутри процесса, где его есть чем остановить.
    """
    готово = позвать("worker", "--help")
    assert готово.returncode == 0, готово.stderr
    assert "очеред" in готово.stdout


def test_у_serve_есть_справка_и_он_не_поднимается():
    """`serve --help` разбирает параметры и выходит, не открывая порт."""
    готово = позвать("serve", "--help")
    assert готово.returncode == 0, готово.stderr
    assert "--host" in готово.stdout and "--port" in готово.stdout


# ── миграция ─────────────────────────────────────────────────────────────────

def test_migrate_поднимает_базу_на_чистом_томе(tmp_path):
    """Команда для выката: миграция один раз и до запуска процессов.

    Каталога тома ещё нет — его заводит сама команда; база после неё стоит на
    голове цепочки, и это напечатано, чтобы оператор видел, на какой именно.
    """
    том = tmp_path / "том"
    готово = позвать("migrate", том=том)
    assert готово.returncode == 0, готово.stderr
    assert (том / "koritsu.db").is_file()
    assert "koritsu:" in готово.stdout

    from api import Settings
    from api.db import current_revision
    from .test_migrations import ГОЛОВА
    assert current_revision(Settings.for_tests(том, secret=СЕКРЕТ)) == ГОЛОВА


def test_migrate_повторно_ничего_не_ломает(tmp_path):
    """Идемпотентность: выкат зовёт `migrate` каждый раз, а не «когда надо»."""
    том = tmp_path / "том"
    assert позвать("migrate", том=том).returncode == 0
    второй = позвать("migrate", том=том)
    assert второй.returncode == 0, второй.stderr


# ── уборка ───────────────────────────────────────────────────────────────────

def test_purge_на_пустой_базе_говорит_что_убирать_нечего(tmp_path):
    """«Сделано» без списка — сообщение, после которого никто не скажет, пропала
    ли чья-то работа по сроку или по ошибке."""
    том = tmp_path / "том"
    assert позвать("migrate", том=том).returncode == 0
    готово = позвать("purge", том=том)
    assert готово.returncode == 0, готово.stderr
    assert "нечего" in готово.stdout


# ── настройка ────────────────────────────────────────────────────────────────

@pytest.mark.parametrize("команда", ["migrate", "purge", "worker"])
def test_без_тома_одна_строка_а_не_трассировка(команда):
    """Оператор, поднявший контейнер без `KORITSU_DATA_DIR`, обязан прочитать
    одну понятную строку. Трассировка на её месте — это сорок строк, в которых
    нужная последняя."""
    готово = позвать(команда)
    assert готово.returncode == 1
    assert "KORITSU_DATA_DIR" in готово.stderr
    assert "Traceback" not in готово.stderr


def test_короткий_секрет_не_пропускается(tmp_path):
    """Тот же заслон, что и у службы: секретом шифруются ключи моделей."""
    готово = позвать("migrate", том=tmp_path / "том", KORITSU_SECRET="test")
    assert готово.returncode == 1
    assert "KORITSU_SECRET" in готово.stderr


def test_кривой_порт_это_беда_настройки(tmp_path):
    """`KORITSU_PORT=восемь тысяч`, понятый как 8000, означал бы службу,
    поднятую не там, где её ищет прокси, — и ни строки о том, почему.

    Проверяется на `serve`, но порт до `uvicorn` не доходит: разбор окружения
    падает раньше, чем открывается порт.
    """
    готово = позвать("serve", том=tmp_path / "том", KORITSU_PORT="восемь")
    assert готово.returncode == 1
    assert "KORITSU_PORT" in готово.stderr
