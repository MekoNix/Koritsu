"""
Своя картинка вместо генеративного аватара: загрузка, замена, снятие, отказы.

Проверяется здесь не «маршрут отвечает», а три обещания, каждое из которых
ломается тихо и дорого.

* **Из запроса берутся только байты.** Имя файла не участвует ни в пути, ни в
  решении о типе: `злое.png` с содержимым HTML — это HTML, а `картинка.exe` с
  байтами PNG — картинка. Отсюда две проверки на подделку расширения, в обе
  стороны.
* **Наружу уезжают наши байты.** Что бы ни принесли, на томе лежит PNG 256×256:
  ни EXIF, ни хвоста за концом картинки, ни исходного формата. Проверяется
  разбором того, что вернул `GET`, а не тем, что мы это задумали.
* **Путь строится из идентификатора аккаунта.** Файл ровно один, лежит в
  каталоге человека, и чужой идентификатор в адресе картинки не выдаёт ничего:
  и «нет такого человека», и «человек есть, картинки нет» отвечают `404`.

Пользователь настоящий (`c_fixtures`), вошедший подменён зависимостью — как во
всех тестах этого каталога.
"""
from __future__ import annotations

import io
import os

import pytest
from PIL import Image

from api.accounts import avatar as модуль_аватара

from .c_fixtures import войти, завести, клиент, сосед, хозяин  # noqa: F401

АДРЕС = "/api/auth/me/avatar"


def картинка(формат: str = "PNG", размер: tuple[int, int] = (300, 200),
             цвет: str = "#3355aa") -> bytes:
    """Настоящая картинка в памяти. Не квадратная: обрезку видно только на такой."""
    буфер = io.BytesIO()
    Image.new("RGB", размер, цвет).save(буфер, format=формат)
    return буфер.getvalue()


def форма(данные: bytes, имя: str = "фото.png", тип: str = "image/png") -> dict:
    return {"file": (имя, данные, тип)}


def профиль(клиент) -> dict:
    ответ = клиент.get("/api/auth/me")
    assert ответ.status_code == 200, ответ.text
    return ответ.json()["user"]


# ── загрузка ─────────────────────────────────────────────────────────────────

def test_у_нового_человека_картинки_нет(клиент, хозяин):
    """Умолчание — генеративный аватар, и служба говорит об этом нулём."""
    assert профиль(клиент)["avatar_version"] == 0
    ответ = клиент.get(f"/api/users/{хозяин.id}/avatar")
    assert ответ.status_code == 404, ответ.text


def test_загрузка_и_отдача(клиент, хозяин):
    """Загруженная картинка отдаётся PNG'ом 256×256, а версия становится единицей."""
    ответ = клиент.post(АДРЕС, files=форма(картинка()))
    assert ответ.status_code == 200, ответ.text
    assert ответ.json()["user"]["avatar_version"] == 1

    отдача = клиент.get(f"/api/users/{хозяин.id}/avatar")
    assert отдача.status_code == 200, отдача.text
    assert отдача.headers["content-type"] == "image/png"
    assert отдача.headers["x-content-type-options"] == "nosniff"
    with Image.open(io.BytesIO(отдача.content)) as им:
        assert им.format == "PNG"
        assert им.size == (модуль_аватара.СТОРОНА, модуль_аватара.СТОРОНА)


def test_версия_едет_и_в_сводку(клиент, хозяин):
    """`bootstrap` строит профиль той же функцией — значит, и поле там то же."""
    клиент.post(АДРЕС, files=форма(картинка()))
    сводка = клиент.get("/api/bootstrap")
    assert сводка.status_code == 200, сводка.text
    assert сводка.json()["me"]["avatar_version"] == 1


def test_замена_растит_версию_и_меняет_байты(клиент, хозяин):
    """Число в адресе меняется — иначе браузер показывал бы прежнюю картинку."""
    клиент.post(АДРЕС, files=форма(картинка(цвет="#3355aa")))
    было = клиент.get(f"/api/users/{хозяин.id}/avatar").content

    ответ = клиент.post(АДРЕС, files=форма(картинка(цвет="#aa3355")))
    assert ответ.status_code == 200, ответ.text
    assert ответ.json()["user"]["avatar_version"] == 2

    стало = клиент.get(f"/api/users/{хозяин.id}/avatar").content
    assert стало != было


def test_файл_на_томе_один_и_называется_нашим_именем(app, клиент, хозяин,
                                                     settings):
    """Имя от клиента до диска не доезжает: файл всегда `avatar.png`."""
    клиент.post(АДРЕС, files=форма(картинка(), имя="../../побег.jpg"))
    каталог = os.path.dirname(модуль_аватара.путь(settings, хозяин.id))
    assert sorted(os.listdir(каталог)) == [модуль_аватара.ФАЙЛ]


def test_картинка_пересохраняется_нами(клиент, хозяин):
    """Хвост за концом картинки на диск не доезжает: наружу — наши байты."""
    с_хвостом = картинка() + b"<script>alert(1)</script>" * 100
    assert клиент.post(АДРЕС, files=форма(с_хвостом)).status_code == 200
    отдача = клиент.get(f"/api/users/{хозяин.id}/avatar")
    assert b"<script>" not in отдача.content


# ── снятие ───────────────────────────────────────────────────────────────────

def test_снятие_возвращает_генеративный(клиент, хозяин):
    """После «убрать» картинки нет ни в профиле, ни на томе, ни в отдаче."""
    клиент.post(АДРЕС, files=форма(картинка()))
    ответ = клиент.delete(АДРЕС)
    assert ответ.status_code == 200, ответ.text
    assert ответ.json()["user"]["avatar_version"] == 0
    assert клиент.get(f"/api/users/{хозяин.id}/avatar").status_code == 404


def test_снятие_без_картинки_не_отказ(клиент, хозяин):
    """Человек просил, чтобы картинки не было; после вызова её нет — это удача."""
    assert клиент.delete(АДРЕС).status_code == 200


# ── отказы ───────────────────────────────────────────────────────────────────

def test_слишком_большой_файл(клиент, хозяин):
    """Предел — мегабайт. Больше — не аватар, а фотография, которую всё равно ужмут."""
    огромная = картинка(размер=(4000, 4000)) + b"\x00" * модуль_аватара.ПРЕДЕЛ
    ответ = клиент.post(АДРЕС, files=форма(огромная))
    assert ответ.status_code == 413, ответ.text
    assert ответ.json()["error"]["code"] == "file_too_large"
    assert профиль(клиент)["avatar_version"] == 0


@pytest.mark.parametrize("данные", [
    b"GIF89a" + b"\x00" * 64,                       # честный, но чужой формат
    b"<svg xmlns='http://www.w3.org/2000/svg'/>",   # картинка со скриптом внутри
    b"%PDF-1.7\n%\xe2\xe3\xcf\xd3\n",               # вообще не картинка
])
def test_чужой_формат(клиент, хозяин, данные):
    """Принимаются три формата, и решают это первые байты."""
    ответ = клиент.post(АДРЕС, files=форма(данные))
    assert ответ.status_code == 400, ответ.text
    assert ответ.json()["error"]["code"] == "unsupported_type"
    assert ответ.json()["error"]["where"] == "body.file"


def test_подделка_расширения_не_помогает(клиент, хозяин):
    """`.png` на HTML остаётся HTML: имя файла в решении не участвует."""
    ответ = клиент.post(АДРЕС,
                        files=форма("<html><body>не картинка</body></html>".encode(),
                                    имя="аватар.png", тип="image/png"))
    assert ответ.status_code == 400, ответ.text
    assert ответ.json()["error"]["code"] == "unsupported_type"


def test_расширение_мимо_содержимого_не_мешает(клиент, хозяин):
    """Обратная сторона того же правила: настоящий JPEG под именем `.exe` — картинка."""
    ответ = клиент.post(АДРЕС, files=форма(картинка("JPEG"), имя="файл.exe",
                                           тип="application/octet-stream"))
    assert ответ.status_code == 200, ответ.text
    assert ответ.json()["user"]["avatar_version"] == 1


def test_webp_принимается(клиент, хозяин):
    """Третий разрешённый формат — тем же путём, что и первые два."""
    assert клиент.post(АДРЕС,
                       files=форма(картинка("WEBP"), имя="ф.webp",
                                   тип="image/webp")).status_code == 200


def test_формы_без_файла_нет(клиент, хозяин):
    ответ = клиент.post(АДРЕС, data={"file": "строка, а не файл"})
    assert ответ.status_code == 400, ответ.text
    assert ответ.json()["error"]["code"] == "no_file"


# ── чужой аватар ─────────────────────────────────────────────────────────────

def test_чужой_идентификатор_не_нашей_формы(клиент, хозяин):
    """`..` в адресе не проходит форму uuid — обходу каталогов взяться неоткуда."""
    ответ = клиент.get("/api/users/..%2F..%2Fetc/avatar")
    assert ответ.status_code in (400, 404), ответ.text
    if ответ.status_code == 400:
        assert ответ.json()["error"]["code"] == "invalid_id"


def test_несуществующий_человек_и_человек_без_картинки_отвечают_одинаково(
        app, клиент, хозяин, сосед):
    """Разные ответы рассказывали бы, какие идентификаторы заведены."""
    нет_такого = "00000000-0000-4000-8000-000000000000"
    один = клиент.get(f"/api/users/{нет_такого}/avatar")
    другой = клиент.get(f"/api/users/{сосед.id}/avatar")
    assert один.status_code == 404 and другой.status_code == 404
    assert один.json() == другой.json()


def test_чужую_картинку_видно_вошедшему(app, клиент, хозяин, сосед):
    """Аватар стоит рядом с ником там, где ник и так виден."""
    клиент.post(АДРЕС, files=форма(картинка()))
    войти(app, сосед)
    ответ = клиент.get(f"/api/users/{хозяин.id}/avatar")
    assert ответ.status_code == 200, ответ.text


# ── кэш ──────────────────────────────────────────────────────────────────────

def test_кэш_зависит_от_версии_в_адресе(клиент, хозяин):
    """С версией ответ можно держать год; без неё браузер обязан переспрашивать."""
    клиент.post(АДРЕС, files=форма(картинка()))
    без = клиент.get(f"/api/users/{хозяин.id}/avatar")
    с_версией = клиент.get(f"/api/users/{хозяин.id}/avatar?v=1")
    assert "immutable" not in без.headers["cache-control"]
    assert "immutable" in с_версией.headers["cache-control"]
    assert "private" in с_версией.headers["cache-control"]
