# ── у каждого решения своё ───────────────────────────────────────────────────

def test_условие_и_пожелания_у_каждого_решения_свои(app, клиент, проект):
    """Та самая беда: вторая задача в работе затирала первую.

    Проверяется полным кругом — записали в одно решение, перечитали второе.
    """
    первое = завести_решение(клиент, проект)
    второе = завести_решение(клиент, проект)
    ид = ид_материала(app, клиент, проект, "задача1.txt", ЗАДАЧА_1,
                      run_id=первое["id"])

    назначено = клиент.put(УСЛОВИЕ.format(проект["id"]),
                           params={"run": первое["id"]},
                           json={"material_id": ид})
    assert назначено.status_code == 200, назначено.text
    клиент.put(ПОЖЕЛАНИЯ.format(проект["id"]), params={"run": первое["id"]},
               json={"text": "покороче", "show_task": True,
                     "show_structure": False})

    assert назначено.json()["condition"] == ид
    assert клиент.get(ПОЖЕЛАНИЯ.format(проект["id"]),
                      params={"run": первое["id"]}).json()["text"] == "покороче"

    # У второго решения не появилось ни условия, ни пожеланий: состояние решения
    # больше не одно на работу. Условие видно карточкой — снимок хода стадий до
    # первого прогона пуст по построению.
    карточки = {з["id"]: з for з in
                клиент.get(РЕШЕНИЯ.format(проект["id"])).json()}
    assert карточки[первое["id"]]["condition_name"] == "задача1.txt"
    assert карточки[второе["id"]]["condition_name"] == ""
    assert клиент.get(ПОЖЕЛАНИЯ.format(проект["id"]),
                      params={"run": второе["id"]}).json()["text"] == ""


def test_папка_контекста_у_каждого_решения_своя(app, клиент, проект):
    """Файл одного решения во втором не виден вовсе.

    В промпт решения уезжают только его файлы: чужая методичка сбивает модель
    ровно так же, как чужое условие, и платит за это человек.
    """
    первое = завести_решение(клиент, проект)
    второе = завести_решение(клиент, проект)
    свой = ид_материала(app, клиент, проект, "методичка1.txt", ЗАДАЧА_1,
                        run_id=первое["id"])
    чужой = ид_материала(app, клиент, проект, "методичка2.txt", ЗАДАЧА_2,
                         run_id=второе["id"])
    общий = ид_материала(app, клиент, проект, "устав.txt",
                         "Устав.\n".encode())

    моя = клиент.get(ОПИСЬ.format(проект["id"]), params={"run": первое["id"]})
    assert моя.status_code == 200, моя.text
    assert [m["id"] for m in моя.json()] == [свой]

    вторая = клиент.get(ОПИСЬ.format(проект["id"]), params={"run": второе["id"]})
    assert [m["id"] for m in вторая.json()] == [чужой]

    # Без `run` опись прежняя: все файлы работы, включая общий. Отчёты и схемы
    # видят их как раньше.
    вся = {m["id"] for m in клиент.get(ОПИСЬ.format(проект["id"])).json()}
    assert {свой, чужой, общий} <= вся


def test_карточка_решения_называет_его_условие(app, клиент, проект):
    """По списку видно, какую задачу решают: иначе карточки неразличимы."""
