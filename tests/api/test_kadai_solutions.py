"""
Много решений в одной работе: свои каталоги, свои файлы, удаление, переезд.

До этого состояние решения было одно на работу: ход стадий, условие, пожелания
и список блоков лежали в корне её каталога. Вторая задача в той же работе
читала их и затирала — молча. Здесь проверяется, что этого больше не бывает, и
что старая работа при этом ничего не теряет.

Что стоит теста и почему:

* **решение — запись журнала и каталог под ней.** Второй таблицы нет: имя,
  номер и время описаны журналом (`project_runs`), а всё остальное лежит на
  томе. Значит, `?run=` обязан спрашивать журнал: без этого он открывал бы
  каталог по любой строке, прошедшей проверку формы;
* **условие, пожелания и ход стадий — у каждого свои.** Это и есть та беда,
  ради которой всё затевалось, и проверяется она полным кругом: записали в одно
  — перечитали второе;
* **папка контекста своя.** Файл, положенный в одно решение, во втором не
  виден: в промпт решения уезжают только его файлы;
* **переезд старой работы.** Первое решение перебирается из корня в свой
  каталог со всем, что у него было, и делается это на первом же чтении списка;
* **удаление не задевает соседа и не уносит файлы работы.**
"""
from __future__ import annotations

import pytest

from api import Settings

from .c_fixtures import (войти, клиент, личное_id, позвать,  # noqa: F401
                         создать_проект, сосед, хозяин)
from .d_fixtures import ид_материала

РЕШЕНИЯ = "/api/projects/{}/kadai/runs"
ОДНО = "/api/projects/{}/kadai/runs/{}"
ХОД = "/api/projects/{}/kadai"
УСЛОВИЕ = "/api/projects/{}/kadai/condition"
ПОЖЕЛАНИЯ = "/api/projects/{}/kadai/wishes"
ОПИСЬ = "/api/projects/{}/materials"

ЗАДАЧА_1 = "Задача 1. Посчитать сумму чисел от 1 до n.\n".encode()
ЗАДАЧА_2 = "Задача 2. Посчитать количество слов в строке.\n".encode()


@pytest.fixture
def settings(tmp_path) -> Settings:
    return Settings.for_tests(tmp_path / "том")


@pytest.fixture
def проект(клиент, хозяин):
    """Работа без шаблона: у решения шаблона нет вовсе, есть список блоков."""
    return создать_проект(клиент, личное_id(клиент), name="две задачи")


def завести_решение(клиент, проект, name: str = "") -> dict:
    ответ = клиент.post(РЕШЕНИЯ.format(проект["id"]), json={"name": name})
    assert ответ.status_code == 201, ответ.text
    return ответ.json()


# ── журнал решений ───────────────────────────────────────────────────────────

def test_у_новой_работы_решений_нет(клиент, проект):
    """Пустой список — законное состояние, а не отказ: работу заводят раньше."""
    ответ = клиент.get(РЕШЕНИЯ.format(проект["id"]))
    assert ответ.status_code == 200, ответ.text
    assert ответ.json() == []


def test_решения_нумеруются_с_единицы(клиент, проект):
    """Номер считает служба: имя по умолчанию сайт рисует из него."""
    первое = завести_решение(клиент, проект)
