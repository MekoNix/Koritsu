# ── переезд старой работы ────────────────────────────────────────────────────

def test_решение_из_корня_переезжает_в_свой_каталог(app, клиент, проект):
    """Работа, заведённая до появления второго решения, ничего не теряет.

    Запись кладётся в корень руками — ровно там, где её оставил бы сценарий, —
    а забирает её самая старая запись журнала на первом же чтении списка.
    """
    на_томе = _на_томе(app, проект)
    на_томе.put_state("kadai", {"work": "w-старая", "state": "done",
                                "stage": "архив", "stages": [],
                                "current": "", "hold": None, "condition": {},
                                "problems": [], "outputs": {}, "events": []})
    первое = завести_решение(клиент, проект)
    второе = завести_решение(клиент, проект)

    список = клиент.get(РЕШЕНИЯ.format(проект["id"])).json()
    assert [з["id"] for з in список] == [первое["id"], второе["id"]]
    assert список[0]["state"] == "done" and список[0]["stage"] == "архив"
    # Второе решение чужого хода не видит: у него свой каталог и пустая запись.
    assert список[1]["state"] is None

    # Повторное чтение безобидно: перевозить уже нечего, каталоги на месте.
    ещё_раз = клиент.get(РЕШЕНИЯ.format(проект["id"])).json()
    assert ещё_раз[0]["state"] == "done"


# ── удаление ─────────────────────────────────────────────────────────────────

def test_удаление_решения_не_трогает_соседнее(app, клиент, проект):
    """Сносится ровно одно решение: у соседнего остаются условие и ход стадий."""
    первое = завести_решение(клиент, проект)
    второе = завести_решение(клиент, проект)
    ид = ид_материала(app, клиент, проект, "задача1.txt", ЗАДАЧА_1,
                      run_id=первое["id"])
    клиент.put(УСЛОВИЕ.format(проект["id"]), params={"run": первое["id"]},
               json={"material_id": ид})

    убрано = клиент.delete(ОДНО.format(проект["id"], второе["id"]))
    assert убрано.status_code == 204, убрано.text

    осталось = клиент.get(РЕШЕНИЯ.format(проект["id"])).json()
    assert [з["id"] for з in осталось] == [первое["id"]]
    assert осталось[0]["condition_name"] == "задача1.txt"
    # И файл остался в его папке контекста: сносили соседа, а не работу.
    моя = клиент.get(ОПИСЬ.format(проект["id"]), params={"run": первое["id"]})
    assert [m["id"] for m in моя.json()] == [ид]


def test_удаление_решения_не_уносит_файлы_работы(app, клиент, проект):
    """Приписка снимается, а сам материал остаётся: он принадлежит работе.

    На файл может ссылаться значение тега в соседнем документе, и уносить его
    вслед за решением значило бы выбить картинку из чужой готовой работы.
    """
    решение = завести_решение(клиент, проект)
    ид = ид_материала(app, клиент, проект, "методичка.txt", ЗАДАЧА_1,
                      run_id=решение["id"])

    убрано = клиент.delete(ОДНО.format(проект["id"], решение["id"]))
    assert убрано.status_code == 204, убрано.text
    вся = {m["id"] for m in клиент.get(ОПИСЬ.format(проект["id"])).json()}
    assert ид in вся


def test_читателю_решение_завести_нельзя(app, клиент, хозяин, сосед):
    """Тот же разрез, что у условия: смотреть — `viewer`, менять — `editor`."""
    ws = клиент.post("/api/workspaces", json={"name": "общее"})
    ws_id = ws.json()["id"]
    добавлен = позвать(app, клиент, ws_id, сосед, "viewer")
    assert добавлен.status_code == 201, добавлен.text
    общий = создать_проект(клиент, ws_id, name="общая работа")
    решение = завести_решение(клиент, общий)

    войти(app, сосед)
    assert клиент.get(РЕШЕНИЯ.format(общий["id"])).status_code == 200
    отказ = клиент.post(РЕШЕНИЯ.format(общий["id"]), json={"name": "своё"})
    assert отказ.status_code == 403, отказ.text
    снос = клиент.delete(ОДНО.format(общий["id"], решение["id"]))
    assert снос.status_code == 403, снос.text


def _на_томе(app, проект):
    """Каталог работы как `orchestrator.Project`. Общий вид, без решения."""
    import orchestrator

    from api.accounts import current_user
    from api.materials.deps import проект_и_роль

    хозяин_id = app.dependency_overrides[current_user]().id
    with app.state.db.session_scope() as s:
        found = проект_и_роль(s, app.state.settings, хозяин_id, проект["id"])
    return orchestrator.Project(found.dir)
