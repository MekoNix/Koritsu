def приложить(клиент, project_id: str, *, данные: bytes | None = None,
              template_id: str = "", имя: str = "бланк"):
    """Приложить шаблон к работе — файлом или идентификатором своего."""
    поля = {"name": имя}
    if template_id:
        поля["template_id"] = template_id
    files = ({"file": ("бланк.docx", данные, DOCX_ТИП)} if данные is not None
             else {"file": ("", b"", DOCX_ТИП)})
    return клиент.post(f"/api/projects/{project_id}/templates", data=поля,
                       files=files)


