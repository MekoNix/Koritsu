def test_проверка_доходит_до_done_и_разрешается_в_объекты(app, клиент, доска,
                                                          модель):
    """Идентификатор строки — договор выжимки, ответа модели и холста."""
    завести_ключ(клиент)
    модель(сценарий(ответ_проверки(доска["steps"])), step=STRICT)
    job_id = запустить(клиент, доска).json()["id"]

    assert прогнать(app) == job_id
    строка = задание(app, job_id)
    assert строка.status == DONE, строка.error
    итог = строка.result
    assert итог["mode"] == "check" and итог["verdict"] == "wrong"
    assert итог["steps_total"] == len(доска["steps"])
    assert [ш["step"] for ш in итог["steps"]] == [ш["id"] for ш in доска["steps"]]
    assert "key_source" not in итог, "чей ключ — вопрос без смысла: свой и только свой"

    # Замечание указывает на объекты той сцены, которую модель видела.
    на_холсте: set = set()
    for шаг in доска["steps"]:
        на_холсте.update(шаг["elements"])
    for замечание in итог["remarks"]:
        assert set(замечание["objects"]) <= на_холсте


def test_событие_на_каждую_строку_доски(app, клиент, доска, модель):
    """Молчание о половине строк человек читает как «остальные в порядке»."""
    завести_ключ(клиент)
    # Модель называет только две строки из шести — остальные обязаны доехать
    # до человека как «по этой строке не сказано», а не пропасть.
    урезанный = json.loads(ответ_проверки(доска["steps"]))
    урезанный["steps"] = урезанный["steps"][:2]
    модель(сценарий(json.dumps(урезанный, ensure_ascii=False)), step=STRICT)
    job_id = запустить(клиент, доска).json()["id"]

    assert прогнать(app) == job_id
    сказанное = [е for е in события(app, job_id) if е.kind == "step_checked"]
    assert len(сказанное) == len(доска["steps"])
    без_вердикта = [е for е in сказанное if е.data["ok"] is None]
    assert len(без_вердикта) == len(доска["steps"]) - 2
    assert задание(app, job_id).status == DONE


