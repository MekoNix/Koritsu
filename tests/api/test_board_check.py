"""
Задание очереди `board_check`: репетитор доски от постановки до результата.

Модель подменена на уровне провода: всё остальное — настоящее. Лестница
структурированного вывода, рамка вокруг недоверенного текста, месячный потолок,
списание цены при захвате и поток событий работают ровно так же, как на живом
поставщике.

Что именно проверяется и почему это стоит теста:

* **полный круг доходит до `done`**, и вердикты разрешаются в объекты сцены:
  идентификатор строки — договор трёх областей, и разошедшись, он превращает
  выноску на холсте в замечание в пустоту;
* **событий `step_checked` ровно столько, сколько строк на доске.** Молчание о
  трёх строках из шести человек читает как «остальные в порядке», а сказано
  этого не было;
* **проверка отказывается на доске, уехавшей вперёд.** И `409` по версии сцены,
  и `422` по отставшим строкам приходят **до** вызова модели, то есть до денег:
  вердикт о решении, которое человек уже исправил, хуже отсутствия вердикта;
* **три просьбы — одно задание.** `mode` это поле, а не три вида с тремя
  ценами, и слово не из списка отказывает на постановке;
* **ключ распознавания не годится в поставщики прогона.** Он заводится той же
  дверью, что ключ модели, и без разведённых списков прогон пошёл бы собирать
  пресет, которого нет, — уже потратив слот очереди и цену задания.
"""
