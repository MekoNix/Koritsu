def test_отставшие_строки_пересобираются_по_прочитанному(app, клиент, доска,
                                                         модель):
    """Дописанная строка — обычный ход работы, а не беда.

    Кэш рядом со сценой к нажатию описывает уже новые штрихи: строки
    собираются по нему на месте, и проверка идёт по той доске, которую человек
    видит, а не по вчерашнему тексту.
    """
    завести_ключ(клиент)
    pid = доска["project"]["id"]
    записана = клиент.put(СЦЕНА.format(pid), params={"run": доска["run"]},
                          json={"scene": сцена_штрихов(ЗАПИСЬ), "version": 1,
                                "recognized": кэш(ЗАПИСЬ)})
    assert записана.status_code == 200, записана.text
    ожидаемые = [{"id": короткий(росчерки[0]), "elements": list(росчерки)}
                 for _группа, _верх, росчерки, _latex in ЗАПИСЬ]
    модель(сценарий(ответ_проверки(ожидаемые)), step=STRICT)
    job_id = запустить(клиент, доска, scene_version=2).json()["id"]

    assert прогнать(app) == job_id
    строка = задание(app, job_id)
    assert строка.status == DONE, строка.error
    итог = строка.result
    assert [ш["step"] for ш in итог["steps"]] == [о["id"] for о in ожидаемые]
    assert итог["steps_total"] == 2 and итог["unrecognized"] == 0

    # Пересобранное осталось на томе: панель, файл контекста и следующая
    # проверка видят те же строки, а не собирают их заново каждая по-своему.
    строки = клиент.get(СТРОКИ.format(pid), params={"run": доска["run"]}).json()
    assert строки["stale"] is False and строки["scene_version"] == 2
    assert [ш["latex"] for ш in строки["steps"]] == ["x^{2}=4", "x=2"]
    assert строки["latex_material"]


