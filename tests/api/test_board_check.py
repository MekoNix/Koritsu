def test_задача_на_тренировку_не_ложится_на_доску_сама(app, клиент, доска,
                                                       модель):
    """Объектов от агента на холсте не бывает вовсе: кладёт их нажатие человека."""
    завести_ключ(клиент)
    модель(сценарий(json.dumps(
        {"drill": {"topic": "квадратные уравнения",
                   "task": "Решите x^2-5x+6=0",
                   "hint": "разложите на множители", "answer": "2 и 3",
                   "why": "не сошёлся переход к дискриминанту"}},
        ensure_ascii=False)), step=STRICT)
    pid = доска["project"]["id"]
    job_id = запустить(клиент, доска, mode="drill").json()["id"]

    assert прогнать(app) == job_id
    строка = задание(app, job_id)
    assert строка.status == DONE, строка.error
    assert строка.result["drill"]["why"]
    # Вердиктов при задаче нет: она карточка рядом с доской, а не разбор.
    assert строка.result["steps"] == []
    assert not [е for е in события(app, job_id) if е.kind == "step_checked"]
    # Сцена не тронута: точка мутации холста одна, и это `PUT …/scene`.
    сцена = клиент.get(СЦЕНА.format(pid), params={"run": доска["run"]}).json()
    assert сцена["version"] == доска["version"]


def test_репетитор_видит_формулы_доски_без_customData(app, клиент, доска, модель):
    """Распознанное живёт рядом со сценой, и выжимка собирается по нему.

    Росчерки на холсте — это только штрихи: что они значат, знает прочитанное
    рядом с доской и записанные по нему строки. Собери выжимку по одной сцене —
    и репетитор увидит доску, на которой «содержимое недоступно» у каждой
    строки, то есть заплаченный вызов, в котором нечего проверять.
    """
    завести_ключ(клиент)
    pid = доска["project"]["id"]
    записана = клиент.put(СЦЕНА.format(pid), params={"run": доска["run"]},
                          json={"scene": сцена_штрихов(ЗАПИСЬ), "version": 1,
                                "recognized": кэш(ЗАПИСЬ)})
    assert записана.status_code == 200, записана.text
    ожидаемые = [{"id": короткий(росчерки[0]), "elements": list(росчерки)}
                 for _группа, _верх, росчерки, _latex in ЗАПИСЬ]
    подделка = модель(сценарий(ответ_проверки(ожидаемые)), step=STRICT)
    job_id = запустить(клиент, доска, scene_version=2).json()["id"]

    assert прогнать(app) == job_id
    assert задание(app, job_id).status == DONE

    куски = [часть for часть in подделка.requests[-1].parts
             if часть.name == "выжимка доски"]
    assert len(куски) == 1
    выжимка = куски[0].text
    for _группа, _верх, росчерки, latex in ЗАПИСЬ:
        assert f"[{короткий(росчерки[0])}] формула:" in выжимка
        assert f"${latex}$" in выжимка
    assert "содержимое недоступно" not in выжимка
    # Чужой текст по-прежнему за забором: кусок недоверенный, и метка прогона
    # стоит в начале каждой нашей строки.
    assert куски[0].untrusted is True
    assert задание(app, job_id).result["unrecognized"] == 0
