"""
Выгрузка файлов проекта: маршрут, задание, содержимое архива, доступ.

Не проект целиком, а только файлы пользователя: архив материалов и артефактов;
код проекта — в git. Отсюда и проверки: в архиве
обязаны быть оригиналы и артефакты, и не обязан быть разбор — он производная,
которая восстанавливается из оригинала.

Пользователь, пространство и проект здесь настоящие (`c_fixtures`), архив
складывается настоящим обработчиком в настоящем задании — только без
подпроцесса (`d_fixtures.докрутить`, `run_once(inline=True)`): подпроцесс
проверяет `test_worker`, а здесь проверяется, что внутри архива.
"""
