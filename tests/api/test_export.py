# ── потолок ──────────────────────────────────────────────────────────────────

def test_архив_больше_квоты_отказывает(app, клиент, проект):
    """Потолок архива — квота владельца. Отказ внятный, а не обрезанный
    архив: молча выгруженная половина работы хуже честного отказа.

    Потолок урезается **воркеру**, а не службе, и это не хитрость теста. Архив
    складывается из того, что и так лежит на томе, то есть из того же, что уже
    посчитано в квоту, — при обычных настройках он в неё влезает всегда, и
    сработать этот потолок может только на разошедшихся числах (квоту убавили
    после того, как файлы легли). Ровно этот случай здесь и разыгран, а читает
    число тот, кто архив собирает.
    """
    загрузить(app, клиент, проект, "методичка.txt", b"z" * 4096)
    ответ = выгрузить(клиент, проект)
    assert ответ.status_code == 202, ответ.text

    скупой = dataclasses.replace(app.state.settings, user_quota_bytes=1024)
    Worker(скупой, db=app.state.db).run_once(inline=True)

    with app.state.db.session_scope() as сессия:
        строка = сессия.get(Job, ответ.json()["job"]["id"])
        assert строка.status == "failed"
        assert строка.error["code"] == выгрузка.EXPORT_TOO_LARGE


