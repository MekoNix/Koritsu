# ── сборка архива отдельно от службы ─────────────────────────────────────────

def test_безопасное_имя():
    """Приведение имени — одно место на весь архив, и проверяется оно здесь:
    через службу такое имя не всегда и составишь."""
    assert выгрузка.безопасное_имя("../../etc/passwd") == "etc/passwd"
    assert выгрузка.безопасное_имя("/абсолютный") == "абсолютный"
    assert выгрузка.безопасное_имя("C:\\Windows\\cmd.exe") == "C:/Windows/cmd.exe"
    assert выгрузка.безопасное_имя("..") == "file"


def test_архив_читается_обычным_zip():
    """Сборка не зовёт `Project.pack`: тот кладёт файл в `out/` и отдаёт имя, а
    артефакту нужны байты. Значит своя сборка — и её договор проверяется здесь."""
    текст = "раз".encode("utf-8")
    данные = выгрузка.собрать_архив([("a/b.txt", текст), ("c.bin", b"\x00\xff")])
    zf = zipfile.ZipFile(io.BytesIO(данные))
    assert zf.namelist() == ["a/b.txt", "c.bin"]
    assert zf.read("a/b.txt") == текст
