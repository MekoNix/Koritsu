def test_в_архиве_оригиналы_материалов(app, клиент, проект):
    """Оригинал байт в байт и под своим именем — то, что человек принёс."""
    данные = "раз\nдва\nтри\n".encode()
    загрузить(app, клиент, проект, "методичка.txt", данные)

    art = сделано(app, выгрузить(клиент, проект))["artifact"]
    zf = архив(клиент, проект, art)
    assert f"{выгрузка.ПАПКА_МАТЕРИАЛОВ}/методичка.txt" in zf.namelist()
    assert zf.read(f"{выгрузка.ПАПКА_МАТЕРИАЛОВ}/методичка.txt") == данные


def test_разбора_в_архиве_нет(app, клиент, проект):
    """Извлечённый текст — производная: она восстанавливается из оригинала и
    меняется с каждой версией разборщика. Человеку принадлежит оригинал."""
    загрузить(app, клиент, проект, "методичка.txt", b"tekst\n")
    art = сделано(app, выгрузить(клиент, проект))["artifact"]
    имена = архив(клиент, проект, art).namelist()
    assert not [и for и in имена if и.endswith(("units.json", "meta.json"))]


def test_в_архиве_артефакты_проекта(app, клиент, проект):
    """Шаблон проекта — артефакт, и он в архиве: «файлы пользователя» — это и
    то, что он принёс, и то, что служба ему построила."""
    итог = сделано(app, выгрузить(клиент, проект))
    zf = архив(клиент, проект, итог["artifact"])
    из_артефактов = [и for и in zf.namelist()
                     if и.startswith(выгрузка.ПАПКА_АРТЕФАКТОВ + "/")]
    assert len(из_артефактов) == итог["artifacts"] >= 1
    # Расширение по содержимому: шаблон — DOCX, и в архиве он `.docx`.
    assert [и for и in из_артефактов if и.endswith(".docx")]


def test_значения_блоки_и_опись(app, клиент, проект):
    """Три файла рядом с папками: текущие значения, блоки и README для глаз."""
    поставлено = клиент.put(f"/api/projects/{проект['id']}/values/цель",
                            json={"v": 1, "type": "text", "text": "проверка"})
    assert поставлено.status_code == 200, поставлено.text
    загрузить(app, клиент, проект, "исходник.py", b"print(1)\n")

    art = сделано(app, выгрузить(клиент, проект))["artifact"]
    zf = архив(клиент, проект, art)

    значения = json.loads(zf.read(выгрузка.ЗНАЧЕНИЯ))
    assert значения["цель"]["text"] == "проверка"
    assert json.loads(zf.read(выгрузка.БЛОКИ)) == []

    опись = zf.read(выгрузка.ОПИСЬ).decode("utf-8")
    # Слова описи английские (наружу — по-английски); имена файлов в ней
    # какие есть — их сочинил человек, и переводить их некому и незачем.
    assert "Koritsu project export" in опись
    assert "materials/" in опись and "artifacts/" in опись
    assert "исходник.py" in опись and проект["id"] in опись


def test_имена_в_архиве_без_путей(app, клиент, проект):
    """Имя файла сочиняет человек, и `..` в нём — это запись мимо каталога
    распаковки на его же машине (zip-slip). В архиве таких имён не бывает."""
    загрузить(app, клиент, проект, "../../etc/passwd", b"raz\n")
    art = сделано(app, выгрузить(клиент, проект))["artifact"]
    for имя in архив(клиент, проект, art).namelist():
        assert not имя.startswith("/") and ".." not in имя.split("/")


def test_прошлая_выгрузка_в_новую_не_попадает(app, клиент, проект):
    """Иначе каждый следующий архив больше предыдущего на весь предыдущий.

    Проверяется не размером, а содержимым: в архиве нет артефакта с
    идентификатором первой выгрузки.
    """
    загрузить(app, клиент, проект, "методичка.txt", b"z" * 4096)
    первый = сделано(app, выгрузить(клиент, проект))["artifact"]
    второй = сделано(app, выгрузить(клиент, проект))
    имена = архив(клиент, проект, второй["artifact"]).namelist()
    assert not [и for и in имена if первый in и]


