def test_заметки_трассировки_ложатся_рядом_с_артефактом(клиент, проект):
    """Заметка описывает схему, а не тег: одну схему можно поставить в два тега,
    и правда о ней одна. Смотреть отчёт человек будет позже и другим глазом.

    Тут же проверяется и общая форма замечания: `kyotsu.Notice`, а не строка,
    — иначе интерфейс разбирал бы замечания схемы одним кодом, а замечания
    сборки другим.
    """
    ответ = клиент.post(
        ОБЪЕКТЫ_ПУТЬ.format(проект["id"]),
        json={"sources": [кусок("счёт.py", С_ЗАМЕТКОЙ)], "lang": "py"})
    assert ответ.status_code == 201, ответ.text
    assert ответ.json()["notices"], "трассировка сказала «не понял» — это в ответе"
    art = ответ.json()["artifact"]
    рядом = клиент.get(АРТЕФАКТ.format(проект["id"], art) + "/notices")
    assert рядом.status_code == 200
    assert рядом.json() == ответ.json()["notices"]
    for заметка in рядом.json():
        assert {"module", "level", "code", "message"} <= set(заметка)


