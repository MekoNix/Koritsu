def test_xml_диаграммы_скачивается_и_разбирается(клиент, проект):
    art = клиент.post(КЛАССЫ_ПУТЬ.format(проект["id"]),
                      json={"sources": [кусок("a.py", КЛАССЫ)],
                            "lang": "py"}).json()["artifact"]
    ответ = клиент.get(АРТЕФАКТ.format(проект["id"], art))
    assert ответ.status_code == 200
    assert ответ.headers["content-type"].startswith("application/xml")
    # Разбирается настоящим разборщиком, а не поиском подстроки: битый XML с
    # нужным словом внутри прошёл бы проверку и не открылся бы в draw.io.
    assert ET.fromstring(ответ.content).tag in ("mxfile", "mxGraphModel")


