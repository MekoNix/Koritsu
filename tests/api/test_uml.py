def файлы_тома(settings) -> set[str]:
    найдено = set()
    for корень, _каталоги, файлы in os.walk(settings.data_dir):
        for имя in файлы:
            найдено.add(os.path.join(корень, имя))
    return найдено


def материал(app, клиент, проект, имя: str, текст: str) -> str:
    """Загрузить исходник в проект и дождаться разбора. → идентификатор.

    С 2.0.0a5.1 загрузка отвечает `202` и ставит задание `parse` (§11), поэтому
    материала сразу после запроса нет; оборот воркера делает `d_fixtures`.
    """
    return ид_материала(app, клиент, проект, имя, текст.encode("utf-8"))


def кусок(имя: str, код: str) -> dict:
    return {"name": имя, "source": код}


