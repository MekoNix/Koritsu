"""
Сводка первого экрана: `GET /api/bootstrap`.

Предмет проверки — не «маршрут ответил», а то единственное, что ломается
молча: **вложенные объекты обязаны совпадать с ответами отдельных маршрутов
знак в знак**. Разойдясь, они дадут сайт, которому одно и то же поле приходит
по-разному в зависимости от того, каким запросом он спросил, — и заметно это
станет через экран, а не здесь.

Отсюда способ проверки: каждый кусок сводки сравнивается с ответом своего
маршрута целиком, а не по нескольким полям. Поле, добавленное в карточку
пространства завтра, сравнение проходит само; поле, описанное в сводке заново
и разошедшееся с оригиналом, роняет прогон.
"""
from __future__ import annotations

from .c_fixtures import клиент, сосед, хозяин  # noqa: F401


def сводка(клиент, **params) -> dict:
    ответ = клиент.get("/api/bootstrap", params=params or None)
    assert ответ.status_code == 200, ответ.text
    return ответ.json()


def test_сводка_отдаёт_все_пять_кусков(клиент, хозяин):
    """Пять частей, ради которых сводка и заведена, приезжают все разом.

    Проверка на присутствие, а не на равенство множеств: в сводку кладут и то,
    что первому экрану нужно знать про саму службу (например, на каком имени
    живёт админка). Требовать «ни одного лишнего поля» значило бы ронять
    прогон на каждом таком добавлении, ничего этим не защищая.
    """
    тело = сводка(клиент)
    assert {"me", "modules", "usage", "workspaces", "notifications"} <= set(тело)


def test_профиль_тот_же_что_у_своего_маршрута(клиент, хозяин):
    """`me` — ровно то, что лежит внутри обёртки `{"user": …}` у `/api/auth/me`."""
    отдельно = клиент.get("/api/auth/me")
    assert отдельно.status_code == 200
    assert сводка(клиент)["me"] == отдельно.json()["user"]


def test_модули_те_же_что_у_своего_маршрута(клиент, хозяин):
    """Список модулей — тот же и в том же порядке: из него строится сайдбар."""
    отдельно = клиент.get("/api/modules")
    assert отдельно.status_code == 200
    assert сводка(клиент)["modules"] == отдельно.json()


def test_расход_тот_же_что_у_своего_маршрута(клиент, хозяин):
    """Остаток месяца и цены видов — вместе, как их отдаёт `/api/usage`."""
    отдельно = клиент.get("/api/usage")
    assert отдельно.status_code == 200
    тело = сводка(клиент)["usage"]
    assert тело == отдельно.json()
    # Цены приезжают той же строкой, что и остаток: экран показывает их до
    # нажатия, и второго запроса за ними быть не должно.
    assert "prices" in тело and "remaining_units" in тело


def test_пространства_те_же_что_у_своего_маршрута(клиент, хозяин):
    """`workspaces` — массив тех же карточек, что отдаёт `/api/workspaces`.

    Массивом, а не объектом с полем `workspaces`: корень у сводки уже есть.
    """
    отдельно = клиент.get("/api/workspaces")
    assert отдельно.status_code == 200
    тело = сводка(клиент)["workspaces"]
    assert тело == отдельно.json()["workspaces"]
    # Личное у человека одно и стоит первым — на нём начинается любой сеанс.
    assert тело and тело[0]["personal"] is True
    assert тело[0]["role"] == "owner"


def test_уведомления_с_числом_непрочитанных(клиент, хозяин):
    """Колокольчик рисуется из сводки: список и число непрочитанных вместе."""
    отдельно = клиент.get("/api/notifications", params={"limit": 20})
    assert отдельно.status_code == 200
    assert сводка(клиент)["notifications"] == отдельно.json()


def test_длина_списка_уведомлений_задаётся_запросом(клиент, хозяин):
    """Сколько уведомлений класть — решает тот, кто рисует колокольчик."""
    assert сводка(клиент, notifications=1)["notifications"]["unread_count"] == 0
    ответ = клиент.get("/api/bootstrap", params={"notifications": 0})
    assert ответ.status_code == 422, ответ.text


def test_чужого_в_сводке_нет(app, клиент, хозяин, сосед):
    """Сводка — про того, кто пришёл. Чужое личное пространство в ней не лежит.

    Проверка не про вежливость: сводка собирается из пяти обработчиков, и
    самая дешёвая ошибка при этом — потерять «чей» у одного из них.
    """
    from .c_fixtures import войти                             # noqa: PLC0415

    чужое = сводка(клиент)["workspaces"][0]["id"]

    войти(app, сосед)
    тело = сводка(клиент)
    assert тело["me"]["id"] == сосед.id
    свои = {ws["id"] for ws in тело["workspaces"]}
    assert чужое not in свои
    assert клиент.get("/api/workspaces/personal").json()["id"] in свои


def test_без_входа_отказ(app):
    """Не вошёл — 401, а не пустая сводка: «кто вошёл» решает одно место."""
    from fastapi.testclient import TestClient                 # noqa: PLC0415

    with TestClient(app, raise_server_exceptions=False) as c:
        ответ = c.get("/api/bootstrap")
    assert ответ.status_code == 401
    assert ответ.json()["error"]["code"] == "unauthenticated"


def test_наружу_не_выставлена(app):
    """Под `/api/v1` сводки нет: она собрана под первый экран сайта.

    Смотрим в документ, а не в `app.routes`: включения роутеров ленивы, и
    настоящие маршруты собираются как раз при сборке документа.
    """
    пути = set(app.openapi()["paths"])
    assert "/api/bootstrap" in пути
    assert "/api/v1/bootstrap" not in пути
