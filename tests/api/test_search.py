"""
Поиск по именам работ и файлов: `GET /api/search`.

Четыре обещания, и все четыре ломаются тихо:

* **регистр не считается.** Имена работ русские, а `lower()` в SQLite знает
  только латиницу — поиск, написанный на `ILIKE`, не нашёл бы «сортировки» по
  запросу «Сортировки» ровно на той базе, на которой служба и запускается;
* **чужое не находится.** Поиск ходит по всем пространствам сразу, и это
  единственное место службы, где отбор доступа делается не маршрутом, а
  запросом. Ошибка здесь показывает человеку имя чужой работы — то есть ровно
  то, что запрещено;
* **корзина не находится.** Каталоги удалённых работ ещё на диске, но человек
  их выбросил, и предлагать открыть их поиском нечестно;
* **материалы находятся вместе с работой,** в которой лежат: файл без имени
  работы — это строка, по которой некуда идти.
"""
from __future__ import annotations

from .c_fixtures import (docx_байты, войти, завести, клиент, личное_id,  # noqa: F401
                         создать_проект, сосед, хозяин)
from .d_fixtures import ид_материала

ПОИСК = "/api/search"

ТЕКСТ = "Задача 1. Сравнить сортировки на массиве из миллиона чисел.\n".encode()


def найти(клиент, q: str, **params) -> dict:
    ответ = клиент.get(ПОИСК, params={"q": q, **params})
    assert ответ.status_code == 200, ответ.text
    return ответ.json()


def имена(строки) -> list[str]:
    return [с["name"] for с in строки]


