def test_работа_находится_по_куску_имени_без_учёта_регистра(клиент, хозяин):
    """Работу зовут «Лабораторная 4 — сортировки», а набирают «СОРТИ»."""
    создать_проект(клиент, личное_id(клиент), name="Лабораторная 4 — сортировки")
    создать_проект(клиент, личное_id(клиент), name="Курсовая по графам")

    найдено = найти(клиент, "СОРТИ")
    assert имена(найдено["projects"]) == ["Лабораторная 4 — сортировки"]
    assert найти(клиент, "граф")["projects"][0]["name"] == "Курсовая по графам"


def test_пустой_запрос_отдаёт_пустоту_а_не_всю_опись(клиент, хозяин):
    """`q=` без текста означает «человек ещё ничего не набрал»."""
    создать_проект(клиент, личное_id(клиент), name="работа")
    assert найти(клиент, "   ") == {"projects": [], "materials": []}


def test_ничего_не_совпало_это_пустой_список_а_не_отказ(клиент, хозяин):
    создать_проект(клиент, личное_id(клиент), name="работа")
    assert найти(клиент, "щщщ")["projects"] == []


def test_чужая_работа_не_находится(app, клиент, хозяин, сосед):
    """Отбор доступа здесь делает запрос, а не маршрут: ошибка в нём показала бы
    человеку имя работы, к которой его не звали."""
    создать_проект(клиент, личное_id(клиент), name="Тайная работа")

    войти(app, сосед)
    assert найти(клиент, "Тайная")["projects"] == []


def test_работа_общего_пространства_находится_участником(app, клиент, хозяин,
                                                         сосед):
    """Приглашённый ищет по тем же пространствам, что и владелец."""
    ws_id = клиент.post("/api/workspaces", json={"name": "общее"}).json()["id"]
    клиент.post(f"/api/workspaces/{ws_id}/members",
                json={"email": сосед.email, "role": "viewer"})
    создать_проект(клиент, ws_id, name="Общая работа")

    войти(app, сосед)
    найдено = найти(клиент, "общая")["projects"]
    assert имена(найдено) == ["Общая работа"]
    assert найдено[0]["workspace_name"] == "общее"


def test_корзина_не_находится(клиент, хозяин):
    """Каталог ещё на диске, но человек работу выбросил."""
    p = создать_проект(клиент, личное_id(клиент), name="Выброшенная")
    assert клиент.delete(f"/api/projects/{p['id']}").status_code in (200, 204)
    assert найти(клиент, "выброш")["projects"] == []


def test_модуль_называется_чтобы_знать_какой_экран_открыть(app, клиент, хозяин):
    """Модуль — не колонка в базе, а то, чем в работе работали: запись `kadai`
    на томе есть только у заданий, и по ней же строится ссылка на сайте."""
    обычный = создать_проект(клиент, личное_id(клиент), name="Отчёт про сорти")
    задание = создать_проект(клиент, личное_id(клиент), name="Задание про сорти")
    _открыть(app, задание).put_state("kadai", {"work": "w-1",
                                               "state": "running",
                                               "stages": []})

    по_имени = {p["id"]: p["module"] for p in найти(клиент, "сорти")["projects"]}
    assert по_имени[обычный["id"]] == "reports"
    assert по_имени[задание["id"]] == "kadai"


def test_потолок_у_каждого_списка_свой(клиент, хозяин):
    """Двадцать — потолок подсказки: двадцать первая строка означает не «мало
    нашли», а «плохо спросили»."""
    for n in range(23):
        создать_проект(клиент, личное_id(клиент), name=f"работа {n}")
    assert len(найти(клиент, "работа")["projects"]) == 20
    assert len(найти(клиент, "работа", limit=5)["projects"]) == 5


