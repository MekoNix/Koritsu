def test_файл_находится_вместе_с_работой_в_которой_лежит(app, клиент, хозяин):
    """Файл без имени работы — строка, по которой некуда идти."""
    p = создать_проект(клиент, личное_id(клиент), name="Работа с файлом")
    ид = ид_материала(app, клиент, p, "Условие-сортировки.txt", ТЕКСТ)

    найдено = найти(клиент, "УСЛОВИЕ")["materials"]
    assert найдено == [{"id": ид, "name": "Условие-сортировки.txt",
                        "project_id": p["id"],
                        "project_name": "Работа с файлом"}]


def test_чужой_файл_не_находится(app, клиент, хозяин, сосед):
    p = создать_проект(клиент, личное_id(клиент), name="Работа")
    ид_материала(app, клиент, p, "секрет.txt", ТЕКСТ)

    войти(app, сосед)
    assert найти(клиент, "секрет")["materials"] == []


def _открыть(app, проект):
    """Каталог проекта как `orchestrator.Project`. Путь складывает служба, не тест."""
    import orchestrator

    from api.projects.service import dir_for

    return orchestrator.Project(
        dir_for(app.state.settings, проект["owner_id"], проект["id"]))
