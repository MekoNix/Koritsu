class Собеседник:
    """Тот, кто стоит вместо облака: здоровается вызовом подписи и возвращает всё.

    Синхронный сервер в своём потоке: мост — асинхронный клиент в цикле событий
    приложения, и поднимать собеседника в том же цикле значило бы проверять
    мост на самом себе.
    """

    def __init__(self):
        self.путь = ""
        self.принятое: list = []
        self.подпись = ""

    def __enter__(self) -> "Собеседник":
        from websockets.sync.server import serve

        # Библиотека на уровне DEBUG печатает строку рукопожатия с ключом в
        # адресе; тест про то, что ключа нет в журнале службы, а не в журнале
        # подделки, — ей даётся свой тихий журнал, как и мосту.
        тихий = logging.getLogger("tests.board.ink.upstream")
        тихий.setLevel(logging.WARNING)
        self._сервер = serve(self._вести, "127.0.0.1", 0, logger=тихий)
        self._поток = threading.Thread(target=self._сервер.serve_forever,
                                       daemon=True)
        self._поток.start()
        return self

    def __exit__(self, *беда) -> bool:
        self._сервер.shutdown()
        self._поток.join(timeout=5)
        return False

    @property
    def адрес(self) -> str:
        хост, порт = self._сервер.socket.getsockname()[:2]
        return f"{хост}:{порт}"

    def _вести(self, соединение) -> None:
        self.путь = соединение.request.path
        соединение.send(json.dumps({"type": "hmacChallenge",
                                    "hmacChallenge": ВЫЗОВ}))
        for сообщение in соединение:
            тело = _разобрать(сообщение)
            if тело.get("type") == "hmac":
                # Ответ на вызов подписи вниз не уходит и в эхо не попадает:
                # это разговор моста с собеседником, а не с браузером.
                self.подпись = str(тело.get("hmac") or "")
                continue
            self.принятое.append(сообщение)
            соединение.send(сообщение)


def _разобрать(сообщение) -> dict:
    if not isinstance(сообщение, str):
        return {}
    try:
        тело = json.loads(сообщение)
    except ValueError:
        return {}
    return тело if isinstance(тело, dict) else {}


