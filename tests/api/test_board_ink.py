def test_подпись_ответа_едет_запасной_строкой(с_ключами, пачка):
    """Подпись всего ответа годится строке, только когда строка одна: иначе она
    описывала бы соседей вместе с нею."""
    def с_подписью(группы):
        ответ = жиикс(группы)
        for выражение in ответ["expressions"]:
            выражение.pop("latex")
            выражение["operands"] = [лист("1"), лист("2")]
            выражение["type"] = "+"
        ответ["label"] = "1+2"
        return ответ

    пачка.ответ = с_подписью
    одна = позвать(с_ключами, [СТРОКИ_ОБРАЗЕЦ[0]]).json()["lines"][0]
    assert одна["latex"] == "1+2" and одна["text"] == "1+2"

    пачкой = позвать(с_ключами).json()["lines"]
    assert all(с["latex"] == "1+2" for с in пачкой)
    assert all(с["text"] == "" for с in пачкой)
