#
# В облако не ходит ни один тест и здесь: пакетный запрос там оплачен так же,
# как открытие сокета. Вместо облака поднимается обычный HTTP-собеседник на
# локальной петле — тот же приём, что у моста, и по той же причине.

РАСПОЗНАТЬ = "/api/board/recognize"

# Строки-образцы: три записи одна под другой, в пикселях холста. Координаты
# выбраны так, чтобы полосы не пересекались по вертикали, — иначе разложение по
# рамкам проверяло бы удачу, а не правило.
СТРОКИ_ОБРАЗЕЦ = [
    {"id": "строка-1", "strokes": [{"x": [10.0, 20.0], "y": [10.0, 30.0],
                                    "t": [0.0, 10.0]}]},
    {"id": "строка-2", "strokes": [{"x": [10.0, 30.0], "y": [100.0, 130.0],
                                    "t": [0.0, 10.0]}]},
    {"id": "строка-3", "strokes": [{"x": [12.0, 40.0], "y": [200.0, 240.0],
                                    "t": [0.0, 10.0]}]},
]


def в_мм(пиксели: float, dpi: int = 96) -> float:
    """Пиксели холста → миллиметры ответа. Обратное тому, что делает служба."""
    return пиксели * 25.4 / float(dpi)


def жиикс(группы, латексы=None) -> dict:
    """Ответ распознавания: по выражению на присланную группу штрихов.

    Ровно так отвечает сервис, когда границы групп он удержал: у каждого
    выражения своя рамка в миллиметрах и свой LaTeX.
    """
    выражения = []
    for i, группа in enumerate(группы):
        xs = [з for ш in группа["strokes"] for з in ш["x"]]
        ys = [з for ш in группа["strokes"] for з in ш["y"]]
        выражения.append({
            "type": "expression",
            "latex": (латексы or [])[i] if латексы else f"x_{{{i}}}=1",
            "bounding-box": {"x": в_мм(min(xs)), "y": в_мм(min(ys)),
                             "width": в_мм(max(xs) - min(xs)),
                             "height": в_мм(max(ys) - min(ys))}})
    return {"type": "Math", "version": "3", "expressions": выражения}


class СобеседникHTTP:
    """Тот, кто стоит вместо пакетного входа облака.

    Обычный HTTP-сервер в своём потоке: маршрут службы синхронный и исполняется
    в отдельном потоке пула, и поднимать собеседника в цикле событий значило бы
    проверять службу на самой себе.
    """

    def __init__(self):
        self.запросы: list = []
        self.код = 200
        self.ответ = жиикс          # тело(группы) → словарь; можно подменить

    def __enter__(self) -> "СобеседникHTTP":
        import http.server

        собеседник = self

        class Ручка(http.server.BaseHTTPRequestHandler):
            protocol_version = "HTTP/1.1"

            def do_POST(self) -> None:                       # noqa: N802
                длина = int(self.headers.get("content-length") or 0)
                сырое = self.rfile.read(длина)
                тело = json.loads(сырое.decode("utf-8"))
                собеседник.запросы.append(
                    {"path": self.path, "headers": dict(self.headers),
                     "body": тело, "raw": сырое})
                ответ = собеседник.ответ(тело.get("strokeGroups") or [])
                данные = json.dumps(ответ).encode("utf-8")
                self.send_response(собеседник.код)
                self.send_header("content-type", "application/json")
                self.send_header("content-length", str(len(данные)))
                self.end_headers()
                self.wfile.write(данные)

            def log_message(self, *что) -> None:             # noqa: A003
                """Молча: журнал подделки в выводе проверок не нужен никому."""

        self._сервер = http.server.ThreadingHTTPServer(("127.0.0.1", 0), Ручка)
        self._поток = threading.Thread(target=self._сервер.serve_forever,
                                       daemon=True)
        self._поток.start()
        return self

    def __exit__(self, *беда) -> bool:
        self._сервер.shutdown()
        self._сервер.server_close()
        self._поток.join(timeout=5)
        return False

    @property
    def адрес(self) -> str:
        хост, порт = self._сервер.socket.getsockname()[:2]
        return f"{хост}:{порт}"


def только_петля(self, запрос):
    """Пропустить запрос на локальную петлю, всё прочее — падение проверки.

    Общая оснастка запрещает проверкам сеть целиком, и запрет этот правильный:
    тихий запрос наружу — это оплаченное распознавание в чужом счёте. Но
    собеседник, поднятый вместо облака, живёт на петле, и дойти до него надо.
    Поэтому запрет здесь не снимается, а сужается до одного адреса.
    """
    if запрос.url.host in ("127.0.0.1", "localhost", "::1"):
        return ТРАНСПОРТ(self, запрос)
    raise AssertionError(f"тест попытался пойти в сеть: {запрос.url}")


