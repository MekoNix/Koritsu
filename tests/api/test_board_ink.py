"""
Мост распознавания рукописи: подпись считает служба, ключи наружу не уезжают.

**В облако распознавания не ходит ни один тест.** Каждое открытие сокета там —
оплаченный запрос, и проверка, которая тратит деньги, — это проверка, которую
перестают гонять. Вместо облака поднимается собеседник на локальной петле: он
здоровается, шлёт вызов подписи и возвращает всё, что получил. Этого хватает,
чтобы проверить всё, ради чего мост написан, кроме самого распознавания почерка
— его проверяет человек своими ключами.

Что именно проверяется и почему это стоит теста:

* **без ключей сокет закрывается кодом `4401`.** Это не беда, а состояние:
  доска рисует и сохраняется всегда, и страница обязана получить код, по
  которому напишет «распознавание выключено», а не «связь пропала»;
* **настоящий ключ подставляется и в адрес, и в тело.** Он едет в двух местах
  сразу, и подмена в одном означала бы отказ в доступе там, где ключ есть;
* **на вызов подписи отвечает мост, а вниз вызов не уходит.** Браузер подписать
  не может: ключей у него нет и не будет — в этом весь смысл моста;
* **кадры гоняются в обе стороны без изменений**: мост не разбирает почерк и не
  хранит штрихов;
* **частота открытий ограничена, и потолок считается по журналу.** Тариф
  считает открытия, а не росчерки, и вкладка, переоткрывающая сокет в цикле,
  тратит чужие деньги молча;
* **ключ не встречается ни в одном журнале и ни в одном ответе** — та же
  проверка, что у ключей моделей, и по той же причине.
"""
