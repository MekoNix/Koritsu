"""
Заслон CSRF: изменяющий запрос с cookie-сессией без заголовка не проходит.

Проверяется здесь и то, что заслон стоит, и то, что он стоит **не везде**:
запрет, срабатывающий на входе или на ключе, сломал бы вход и внешний API, а
обнаружилось бы это у первого клиента, а не тут.

    вход, регистрация, подтверждение, сброс пароля  — мимо (сессии ещё нет)
    `Authorization: Bearer`                         — мимо (cookie нет вовсе)
    `GET`                                           — мимо (нечего подделывать)
    всё остальное с cookie-сессией                  — только с заголовком

Отдельно проверяется порядок middleware: отказ по CSRF обязан унести
`X-Request-Id` и попасть в журнал безопасности — иначе жалобу «у меня не
сохраняется» не с чем связать.

**Про клиента без подстановки.** `tests/api/conftest.py` дописывает заголовок в
каждый изменяющий запрос сам — иначе его пришлось бы дописать в сотню чужих
тестов. Здесь эта подстановка мешает: тесту про заслон нужен клиент, который
ведёт себя как чужая страница. Отключается она флагом `без_csrf`.
"""
from __future__ import annotations

import pytest
from sqlalchemy import select

from api import csrf
from api.accounts.service import COOKIE as СЕССИЯ
from api.admin.models import SecurityEvent
from api.tokens import service as ключи

from .c_fixtures import (войти_по_настоящему, клиент, личное_id,  # noqa: F401
                         создать_проект, хозяин)

ПОЧТА = "csrf@пример.рф"


@pytest.fixture
def чужая_страница(клиент):
    """Клиент, который заголовок сам не подставляет, — как сторонний сайт."""
    клиент.без_csrf = True
    return клиент


# ── cookie ───────────────────────────────────────────────────────────────────

def test_cookie_ставится_при_входе(клиент, caplog):
    """Заслон работает двойной отправкой: значение обязано быть у страницы."""
    вход = войти_по_настоящему(клиент, caplog, ПОЧТА)
    assert csrf.COOKIE in вход.cookies
    assert клиент.cookies.get(csrf.COOKIE)


def test_cookie_видна_скрипту_страницы(клиент, caplog):
    """`HttpOnly` тут нельзя: сайт обязан её прочитать и положить в заголовок.

    У cookie сессии всё наоборот — она `HttpOnly`, и одно другому не мешает:
    значение CSRF не даёт входа, оно лишь доказывает, что запрос послан нашей
    страницей.
    """
    вход = войти_по_настоящему(клиент, caplog, ПОЧТА)
    свои = [с for с in вход.headers.get_list("set-cookie")
            if с.startswith(csrf.COOKIE + "=")]
    assert свои, вход.headers.get_list("set-cookie")
    for строка in свои:
        assert "httponly" not in строка.lower()


def test_значение_не_перевыпускается_на_каждом_ответе(клиент, caplog):
    """Иначе давно открытая вкладка кладёт в заголовок уже не то значение."""
    войти_по_настоящему(клиент, caplog, ПОЧТА)
    было = клиент.cookies.get(csrf.COOKIE)
    клиент.get("/api/auth/me")
    клиент.get("/api/auth/me")
    assert клиент.cookies.get(csrf.COOKIE) == было


# ── сам заслон ───────────────────────────────────────────────────────────────

def test_без_заголовка_403(чужая_страница, caplog):
    """То, ради чего всё: чужая страница послать за человека `POST` не может."""
    войти_по_настоящему(чужая_страница, caplog, ПОЧТА)
    ответ = чужая_страница.post("/api/auth/logout")
    assert ответ.status_code == 403
    assert ответ.json()["error"]["code"] == "csrf_failed"


def test_с_заголовком_проходит(чужая_страница, caplog):
    войти_по_настоящему(чужая_страница, caplog, ПОЧТА)
    значение = чужая_страница.cookies.get(csrf.COOKIE)
    ответ = чужая_страница.post("/api/auth/logout",
                                headers={csrf.ЗАГОЛОВОК: значение})
    assert ответ.status_code == 200, ответ.text


def test_чужое_значение_в_заголовке_не_годится(чужая_страница, caplog):
    """Двойная отправка держится на том, что чужая страница нашей cookie не
    видит; заголовок «какой-нибудь» её не заменяет."""
    войти_по_настоящему(чужая_страница, caplog, ПОЧТА)
    ответ = чужая_страница.post("/api/auth/logout",
                                headers={csrf.ЗАГОЛОВОК: "wrong-value"})
    assert ответ.status_code == 403
    assert ответ.json()["error"]["code"] == "csrf_failed"


def test_чтение_не_трогается(чужая_страница, caplog):
    """`GET` не проверяется: маршрута, меняющего что-то по `GET`, у службы нет."""
    войти_по_настоящему(чужая_страница, caplog, ПОЧТА)
    assert чужая_страница.get("/api/auth/me").status_code == 200


def test_вход_и_регистрация_мимо_заслона(чужая_страница, caplog):
    """До входа сессии нет, и подделывать нечего: у чужой страницы получился бы
    вход в аккаунт, пароль от которого она уже знает."""
    вход = войти_по_настоящему(чужая_страница, caplog, ПОЧТА)
    assert вход.status_code == 200


def test_ключ_мимо_заслона(app, клиент, хозяин):
    """CSRF — про cookie, которую браузер прикладывает сам. Ключ чужая страница
    подставить не может: она его не знает."""
    ws = личное_id(клиент)
    строка = клиент.post("/api/tokens",
                         json={"name": "скрипт",
                               "scopes": list(ключи.ПРАВА)}).json()["token"]
    app.dependency_overrides.clear()
    клиент.без_csrf = True
    клиент.headers["Authorization"] = f"Bearer {строка}"

    ответ = клиент.post("/api/v1/projects",
                        data={"workspace_id": ws, "name": "ключом"})
    assert ответ.status_code == 201, ответ.text


def test_без_сессии_заслона_нет(чужая_страница):
    """Проверять нечего, пока никто не вошёл: такой запрос всё равно отвечает
    `401`, и подменять этот отказ на `403` значило бы врать про причину."""
    ответ = чужая_страница.post("/api/auth/logout-all")
    assert ответ.status_code == 401
    assert ответ.json()["error"]["code"] == "unauthenticated"


# ── отказ виден ──────────────────────────────────────────────────────────────

def test_отказ_несёт_метку_запроса(чужая_страница, caplog):
    """Порядок middleware: заслон стоит внутри журнала, а не снаружи.

    Снаружи он отвечал бы клиенту без `X-Request-Id` и без строки в журнале, и
    жалобу «у меня не сохраняется» было бы не с чем связать.
    """
    войти_по_настоящему(чужая_страница, caplog, ПОЧТА)
    ответ = чужая_страница.post("/api/auth/logout")
    assert ответ.status_code == 403
    assert ответ.headers.get("X-Request-Id")


def test_отказ_попадает_в_журнал_безопасности(app, чужая_страница, caplog):
    """Отказ CSRF — событие безопасности, а не просто код ответа."""
    войти_по_настоящему(чужая_страница, caplog, ПОЧТА)
    assert чужая_страница.post("/api/auth/logout").status_code == 403

    with app.state.db.session_scope() as s:
        виды = [e.kind for e in s.scalars(select(SecurityEvent))]
    assert "csrf_failed" in виды


def test_сессия_остаётся_живой_после_отказа(чужая_страница, caplog):
    """Отказ — про один запрос, а не про человека: заслон не выкидывает."""
    войти_по_настоящему(чужая_страница, caplog, ПОЧТА)
    assert чужая_страница.post("/api/auth/logout").status_code == 403
    assert чужая_страница.cookies.get(СЕССИЯ)
    assert чужая_страница.get("/api/auth/me").status_code == 200
