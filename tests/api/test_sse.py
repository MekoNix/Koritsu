"""
Потоки `text/event-stream`: кадры задания и кадры человека.

Читаются они настоящим потоковым клиентом (`client.stream`), а не разбором
готового тела: у `text/event-stream` нет «готового тела», и тест, который его
дожидается, проверял бы обычный `GET`, а не поток.

Четыре вещи, которые здесь закрепляются:

1. **форма кадра.** `id:` — курсор, `event:` — вид, `data:` — одна строка JSON.
   Перенос строки внутри `data` разрезал бы кадр надвое, и клиент получил бы
   обрывки — поэтому JSON пишется без отступов, и это проверяется;
2. **поток задания закрывается сам** по терминальному статусу. Не закройся он —
   вкладка держала бы соединение и его сессию базы до таймаута прокси;
3. **`Last-Event-ID` сильнее параметра.** Заголовок ставит браузер при
   переподключении, и это как раз тот случай, когда клиент знает лучше;
4. **поток начинается с пульса.** Пока из генератора не вышло ни байта, ответ
   висит без заголовков, и клиент не знает, открылся ли поток вообще.
"""
from __future__ import annotations

import dataclasses
import datetime
import json
import urllib.parse

from .b_fixtures import прогнать, _чистый_реестр  # noqa: F401
from .c_fixtures import войти, клиент, сосед, хозяин  # noqa: F401


def быстрый_опрос(app, *, жизнь: float = 60.0) -> None:
    """Поток спрашивает базу часто и живёт недолго.

    `жизнь` — тот самый `sse_max_s`, потолок жизни соединения. Он нужен тесту
    не для скорости, а по существу: `TestClient` собирает ответ целиком, прежде
    чем отдать его (`starlette/testclient.py`, `raw_kwargs["stream"]` —
    `BytesIO`), поэтому поток, который не кончается сам, в тесте не кончится
    никогда. Потоку человека конца по смыслу нет, и единственная его граница —
    как раз этот потолок; на живом сайте после него браузер переподключается с
    `Last-Event-ID` и продолжает с того же места.
    """
    app.state.settings = dataclasses.replace(app.state.settings,
                                             sse_poll_s=0.01, sse_max_s=жизнь)


def сейчас() -> str:
    """Момент «прямо сейчас» в том виде, в каком он ложится в адрес запроса.

    Знак `+` в смещении обязан быть закодирован: в строке запроса `+` означает
    пробел, и незакодированное `+00:00` доезжает до службы как ` 00:00` —
    время не разбирается, курсор молча становится «сейчас», и поток не
    показывает ничего. Браузер этой беды не знает: он присылает курсор
    заголовком `Last-Event-ID`, где кодировать нечего.
    """
    момент = datetime.datetime.now(datetime.timezone.utc).isoformat()
    return urllib.parse.quote(момент, safe="")


def разобрать(строки) -> list[dict]:
    """Кадры SSE из строк ответа. Разбор нарочно наивный и свой.

    Своим разбором, а не библиотечным: проверяется именно то, что мы написали
    в провод, — а библиотека простила бы нам и лишний перенос строки, и
    пропущенный `id`.
    """
    кадры: list[dict] = []
    текущий: dict = {}
    for строка in строки:
        if строка.startswith(":"):
            текущий["comment"] = строка[1:].strip()
            continue
        if not строка:
            if текущий:
                кадры.append(текущий)
                текущий = {}
            continue
        поле, _, значение = строка.partition(":")
        текущий[поле.strip()] = значение.strip()
    if текущий:
        кадры.append(текущий)
    return кадры


def прочитать(клиент, путь: str, *, headers=None) -> list[dict]:
    """Прочитать поток до конца. → разобранные кадры.

    До конца, а не «пока не увижу нужное»: `TestClient` собирает ответ целиком,
    и оборвать поток на середине тест всё равно не может (см. `быстрый_опрос`).
    Поэтому конец у каждого потока в тесте есть: у задания — терминальный
    статус, у человека — потолок жизни соединения.
    """
    строки: list[str] = []
    with клиент.stream("GET", путь, headers=headers or {}) as ответ:
        assert ответ.status_code == 200
        assert ответ.headers["content-type"].startswith("text/event-stream")
        for строка in ответ.iter_lines():
            строки.append(строка)
    return разобрать(строки)


def события(кадры) -> list[dict]:
    """Только настоящие кадры: пульс — комментарий, а не событие."""
    return [к for к in кадры if "event" in к]


# ── поток одного задания ─────────────────────────────────────────────────────

def test_поток_задания_отдаёт_кадры_и_закрывается_сам(app, клиент, хозяин):
    """Задание кончилось — значит поток обязан кончиться вместе с ним.

    Иначе клиент остался бы ждать продолжения, которого не будет, а служба
    держала бы соединение и сессию базы до таймаута прокси.
    """
    быстрый_опрос(app)
    job_id = клиент.post("/api/jobs", json={
        "kind": "probe", "payload": {"steps": 2}}).json()["id"]
    прогнать(app)

    кадры = прочитать(клиент, f"/api/jobs/{job_id}/stream")

    assert кадры[0].get("comment") == "keep-alive", "поток не поздоровался"
    настоящие = события(кадры)
    виды = [к["event"] for к in настоящие]
    assert виды[0] == "progress" and виды[-1] == "done"
    assert "text" in виды
    # `id:` — курсор, и он растёт: по нему клиент дочитывает поток с обрыва.
    номера = [int(к["id"]) for к in настоящие]
    assert номера == sorted(номера) and номера[0] == 1
    # `data:` — одна строка JSON, разбираемая как есть.
    первый = json.loads(настоящие[0]["data"])
    assert первый["seq"] == 1 and первый["kind"] == "progress"
    assert первый["data"]["note"] == "step 1"


def test_данные_кадра_не_разрезаются_переносом_строки(app, клиент, хозяин):
    """Многострочный текст внутри события обязан уехать одним кадром: перенос
    строки в `data:` — это граница поля, и клиент получил бы половину."""
    быстрый_опрос(app)
    job_id = клиент.post("/api/jobs", json={"kind": "probe"}).json()["id"]
    with app.state.db.session_scope() as s:
        from api.jobs.models import JobEvent                  # noqa: PLC0415

        s.add(JobEvent(job_id=job_id, seq=1, kind="text",
                       data={"text": "первая строка\nвторая строка"}))
    прогнать(app)

    кадры = прочитать(клиент, f"/api/jobs/{job_id}/stream")
    текст = next(к for к in события(кадры) if к["event"] == "text")
    assert json.loads(текст["data"])["data"]["text"] == \
        "первая строка\nвторая строка"


def test_last_event_id_сильнее_параметра(app, клиент, хозяин):
    """Заголовок ставит браузер при переподключении — он и знает лучше."""
    быстрый_опрос(app)
    job_id = клиент.post("/api/jobs", json={
        "kind": "probe", "payload": {"steps": 3}}).json()["id"]
    прогнать(app)

    все = события(прочитать(клиент, f"/api/jobs/{job_id}/stream"))
    последний = max(int(к["id"]) for к in все)

    хвост = прочитать(клиент, f"/api/jobs/{job_id}/stream?after=0",
                      headers={"Last-Event-ID": str(последний - 1)})
    assert [int(к["id"]) for к in события(хвост)] == [последний]


def test_чужой_поток_это_404_до_того_как_он_начался(app, клиент, хозяин, сосед):
    """Отказ приходит ответом, а не серединой потока: `404` внутри
    `text/event-stream` клиент разобрать не сумеет — там нет места для кода."""
    job_id = клиент.post("/api/jobs", json={"kind": "probe"}).json()["id"]
    войти(app, сосед)
    ответ = клиент.get(f"/api/jobs/{job_id}/stream")
    assert ответ.status_code == 404
    assert ответ.json()["error"]["code"] == "not_found"


# ── поток человека ───────────────────────────────────────────────────────────

def test_поток_человека_получает_уведомление_о_задании(app, клиент, хозяин):
    """Один поток на человека: колокольчик узнаёт о конце работы отсюда, а не
    из письма (писем нет).

    Курсор задаётся явно (`after`), потому что умолчание у потока — «сейчас»:
    поток показывает происходящее, а не историю, и историю читают списком.
    """
    быстрый_опрос(app, жизнь=1.0)
    до = сейчас()
    job_id = клиент.post("/api/jobs", json={"kind": "probe"}).json()["id"]
    прогнать(app)

    кадры = прочитать(клиент, f"/api/events?after={до}")
    кадр = next(к for к in события(кадры) if к["event"] == "job_finished")
    тело = json.loads(кадр["data"])
    assert тело["kind"] == "job_done" and тело["job_id"] == job_id
    # `id:` потока человека — время создания: браузер вернёт его заголовком.
    assert кадр["id"].startswith("20")


def test_поток_человека_не_показывает_чужих_уведомлений(app, клиент, хозяин,
                                                        сосед):
    """Чужое уведомление не показывается никому: в `data` лежит идентификатор
    чужого проекта. Поток соседа молчит — и это видно по тому, что первым
    и единственным приходит пульс."""
    быстрый_опрос(app, жизнь=1.0)
    до = сейчас()
    клиент.post("/api/jobs", json={"kind": "probe"})
    прогнать(app)

    войти(app, сосед)
    кадры = прочитать(клиент, f"/api/events?after={до}")
    assert события(кадры) == []
    assert кадры and кадры[0].get("comment") == "keep-alive"
