def test_serve_принимает_нулевой_хост():
    """`--host 0.0.0.0` обязан работать: этим аргументом служба поднимается в
    контейнере. Умолчание при этом остаётся петлёй — открытый порт без прокси
    должен быть решением, а не забывчивостью."""
    from api.__main__ import ХОСТ_УМОЛЧАНИЕ, _parser

    args = _parser().parse_args(["serve", "--host", "0.0.0.0"])
    assert args.host == "0.0.0.0"
    assert ХОСТ_УМОЛЧАНИЕ == "127.0.0.1"
    assert _parser().parse_args(["serve"]).host is None
