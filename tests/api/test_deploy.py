def test_robots_запрещает_всё_и_живёт_в_корне():
    """Робот читает `/robots.txt` у origin и ни про какой префикс не знает,
    поэтому правило стоит **до** снятия префикса. Под префиксом тот же адрес
    отдаётся тоже — чтобы «открыть robots руками» работало оттуда, откуда
    открывают сайт."""
    текст = файл("Caddyfile")
    assert "@robots path /robots.txt {$KORITSU_BASE_PATH}/robots.txt" in текст
    assert "User-agent: *" in текст and "Disallow: /" in текст
    # И до снятия префикса: `import robots` стоит раньше `handle_path` —
    # сравниваются директивы, а не слова из комментариев выше.
    assert (текст.index("\timport robots")
            < текст.index("\thandle_path {$KORITSU_BASE_PATH}/* {"))


