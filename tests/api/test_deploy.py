"""
Выкат: `.env.example`, Dockerfile, compose, Caddyfile — то, что читает не Python.

Тесты здесь текстовые и простые намеренно: собрать образ на прогоне нельзя (сети
в лаборатории нет и не должно быть), поднять compose — тем более. Значит
проверяется то, что проверяемо без Docker, и оно же — то, что ломается чаще
всего: **расхождение между кодом и файлами выката**.

Главный из них — первый: каждое поле `Settings` названо в `.env.example`. Новая
настройка, заведённая в коде и не попавшая в образец, обнаруживается иначе
только на живой машине, где она молча работает с умолчанием, — и хуже всего это
там, где умолчание безопасное (`KORITSU_TRUST_PROXY`), потому что тогда не
ломается ничего, просто перестаёт работать защита.

Чего эти тесты **не** проверяют и проверить не могут: что образ собирается, что
LibreOffice в нём запускается, что Anubis понимает переданные ему переменные.
Первые два проверяются сборкой на машине с сетью, третье — по документации
Anubis (в `docker-compose.yml` про это стоит пометка «проверить по docs»).
"""
from __future__ import annotations

import dataclasses
import os
import re

import pytest

from api.settings import ПРЕФИКС, Settings

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))))

# Секрет для проверки разбора: в образце он пуст намеренно (пустой секрет в
# файле, который копируют, — это общий секрет на всех, кто его скопировал).
СЕКРЕТ = "проба" * 8


def файл(имя: str) -> str:
    путь = os.path.join(КОРЕНЬ, имя)
    assert os.path.isfile(путь), f"нет файла выката: {имя}"
    with open(путь, encoding="utf-8") as f:
        return f.read()


def разобрать_env(текст: str) -> dict[str, str]:
    """`.env` как словарь. Закомментированные строки — не значения.

    Разбор нарочно свой и грубый: `.env` разворачивает docker compose, и
    сложный разбор здесь означал бы третье описание формата (наше, compose'а и
    того, кто правит файл руками).
    """
    значения = {}
    for строка in текст.splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("#") or "=" not in строка:
            continue
        имя, _, значение = строка.partition("=")
        значения[имя.strip()] = значение.strip()
    return значения


def имена_env(текст: str) -> set[str]:
    """Все `KORITSU_*`, названные в файле, — и в значениях, и в комментариях.

    В комментариях тоже: настройка, которую в образце оставили закомментированной
    (`KORITSU_HOST`), названа человеку и это главное. Пропуск же — это когда о
    ней не сказано вовсе.
    """
    return set(re.findall(r"KORITSU_[A-Z0-9_]+", текст))


# ── `.env.example` ───────────────────────────────────────────────────────────

def test_каждое_поле_настроек_названо_в_образце():
    """Поле `Settings` есть — строка в `.env.example` есть. Без исключений.

    Тест намеренно жёсткий: он падает у того, кто завёл настройку и не дописал
    образец, — то есть в правильный момент, а не через месяц на живой машине.
    """
    текст = файл(".env.example")
    названы = имена_env(текст)
    пропущены = sorted(ПРЕФИКС + поле.name.upper()
                       for поле in dataclasses.fields(Settings)
                       if ПРЕФИКС + поле.name.upper() not in названы)
    assert not пропущены, f"нет в .env.example: {', '.join(пропущены)}"


def test_образец_разбирается_настройками():
    """`.env.example` — не просто текст: служба обязана подняться на нём.

    Секрет подставляется тестом: в образце он пуст, и это правильно — образец
    копируют, а скопированный секрет перестаёт быть секретом.
    """
    окружение = разобрать_env(файл(".env.example"))
    окружение[ПРЕФИКС + "SECRET"] = СЕКРЕТ
    настройки = Settings.from_env(окружение)

    assert настройки.data_dir == "/data"
    assert настройки.env == "prod"
    # За Caddy это обязательно: иначе лимит регистраций по IP станет лимитом на
    # весь сайт разом (за прокси все запросы приходят с одного адреса).
    assert настройки.trust_proxy is True
    assert настройки.base_url.startswith("https://")


def test_в_образце_нет_настоящего_секрета():
    """Заполненный секрет в файле, который копируют, — общий секрет на всех."""
    окружение = разобрать_env(файл(".env.example"))
    assert окружение.get(ПРЕФИКС + "SECRET", "") == ""


def test_значения_образца_совпадают_с_умолчаниями_кода():
    """Числа в образце — те же, что в `Settings`. Разошедшись, они врут.

    Образец читают как документацию («сколько слотов у воркера?»), и число в нём,
    отставшее от кода, — это ответ, который никто не проверяет.
    """
    окружение = разобрать_env(файл(".env.example"))
    из_образца = Settings.from_env({**окружение, ПРЕФИКС + "SECRET": СЕКРЕТ})
    умолчания = Settings(data_dir="/data", secret=СЕКРЕТ, env="prod")
    # Список полей не пишется руками: он устарел бы ровно на ту настройку,
    # которую завели последней, — то есть на ту, где расхождение всего вероятнее.
    for поле in dataclasses.fields(Settings):
        if not isinstance(поле.default, (int, float)) or isinstance(
                поле.default, bool):
            continue
        assert getattr(из_образца, поле.name) == getattr(умолчания, поле.name), \
            поле.name


def test_trust_proxy_объяснён_как_обязательный_за_прокси():
    """Настройка, чьё умолчание безопасно, а неверное значение молча снимает
    защиту, обязана быть объяснена там, где её ставят."""
    текст = файл(".env.example")
    строка = ПРЕФИКС + "TRUST_PROXY=yes"
    assert строка in текст
    # Именно перед самой строкой, а не где-нибудь в файле: объяснение, до
    # которого надо доскроллить, объяснением не работает.
    рядом = текст[max(0, текст.index(строка) - 700):текст.index(строка)]
    assert "Caddy" in рядом and "IP" in рядом


