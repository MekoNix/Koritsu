def test_v1_идёт_мимо_anubis():
    """§11 дословно: «`/api/v1/` с токеном идёт мимо Anubis».

    Проверяется порядком: блок `/api/v1/*` объявлен раньше того, который шлёт
    остальное в Anubis, — а в Caddy блоки `handle` разбираются в порядке
    объявления.
    """
    текст = файл("Caddyfile")
    v1 = текст.index("@v1 path /api/v1/*")
    в_anubis = текст.index("reverse_proxy anubis:8923")
    assert v1 < в_anubis
    # И сам внешний вход идёт в службу, а не в проверку работой.
    кусок = текст[v1:в_anubis]
    assert "reverse_proxy api:8000" in кусок


