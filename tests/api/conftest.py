"""
Оснастка тестов службы.

Два правила обеспечиваются структурно, а не договорённостью.

1. **Том — всегда временный.** Настройки собираются `Settings.for_tests(tmp_path)`,
   и обязательное поле `data_dir` не даёт забыть: приложение без тома не
   соберётся вовсе. Тест, случайно писавший бы в рабочий том, здесь не пишется —
   для этого пришлось бы явно указать путь.
2. **Сети нет.** Каркас никуда не ходит (ни модели, ни почты в нём ещё нет), но
   запрет стоит с первого дня: подтверждение почты и вызов поставщика
   появляются позже, и запрет должен встретить их уже готовым, а не заводиться
   после первого случайного письма из тестов.

`client` строится с `raise_server_exceptions=False` намеренно. По умолчанию
`TestClient` перебрасывает необработанное исключение в тест — удобно, пока не
проверяешь ровно то, что служба обязана делать с необработанным исключением:
отдать пятисотку без подробностей. С перебросом такой тест проверял бы
`TestClient`, а не службу.

Тестовые маршруты (`/_test/...`) вешаются на приложение здесь, а не в пакете:
маршрут, заведённый ради теста и живущий в пакете, однажды окажется на живом
сайте — а `/_test/boom` на живом сайте это отказ обслуживания в одну строку.

**Про фильтр предупреждений** (см. `ЧУЖОЕ_ПРЕДУПРЕЖДЕНИЕ` ниже). Набор службы
гоняется ещё и с `-W error::UserWarning`: `UserWarning` — то, чем FastAPI
сообщает о столкновении имён схем в OpenAPI, и такое предупреждение обязано
ронять прогон, а не теряться в хвосте вывода. Чужое предупреждение при этом
ровно одно и приходит не от службы: Starlette просит ставить `httpx2` вместо
`httpx`. Оно наследует `UserWarning`, поэтому под `-W error` уронило бы прогон
на импорте — и уронило бы его молча для того, кто ищет предупреждения **своего**
кода. Гасится оно поимённо, по классу, а не «все UserWarning»: заглушить весь
вид значило бы отменить ровно ту проверку, ради которой прогон и заведён.
"""
from __future__ import annotations

import warnings

from starlette.exceptions import StarletteDeprecationWarning

# Гасится ДО импорта `fastapi.testclient`: предупреждение выдаётся при импорте
# модуля, то есть здесь и один раз на процесс, а не внутри теста. Метка
# `filterwarnings` до этой точки не доживает — её ставят на тест, а тестов в
# момент импорта conftest ещё нет.
ЧУЖОЕ_ПРЕДУПРЕЖДЕНИЕ = StarletteDeprecationWarning
warnings.filterwarnings("ignore", category=ЧУЖОЕ_ПРЕДУПРЕЖДЕНИЕ)

import httpx                                                        # noqa: E402
import pytest                                                       # noqa: E402
from fastapi.testclient import TestClient                            # noqa: E402

from api import Settings, create_app                           # noqa: E402
from api.errors import ApiError                                # noqa: E402

# Та же беда, но для предупреждений, выданных во время самого теста: pytest
# восстанавливает список фильтров вокруг каждого теста, и поставленный выше
# `ignore` до тела теста не доживает.
ФИЛЬТР = (f"ignore::{ЧУЖОЕ_ПРЕДУПРЕЖДЕНИЕ.__module__}."
          f"{ЧУЖОЕ_ПРЕДУПРЕЖДЕНИЕ.__qualname__}")


def pytest_collection_modifyitems(items) -> None:
    """Повесить фильтр на каждый тест этого каталога.

    Через хук, а не `pytestmark` в каждом файле: восемь файлов с одинаковой
    строкой наверху — это восемь мест, где однажды окажется восемь разных
    строк. Каталог у хука свой: conftest действует только на своё поддерево.
    """
    метка = pytest.mark.filterwarnings(ФИЛЬТР)
    for item in items:
        item.add_marker(метка)

# Секретный текст исключения: тест проверяет, что наружу он не уезжает. Слово
# осмысленное, чтобы падение теста читалось глазами, а не как «строка не равна».
СЕКРЕТ_В_ИСКЛЮЧЕНИИ = "путь-к-тому-и-кусок-запроса"


@pytest.fixture(autouse=True)
def _csrf_заголовок(monkeypatch):
    """Клиент сам подставляет `X-CSRF-Token` — как это делает сайт.

    Заслон CSRF требует на каждом изменяющем запросе
    **с cookie-сессией** заголовок, равный cookie `koritsu_csrf`. В браузере
    это делает один раз код сайта; в тестах пришлось бы дописать заголовок в
    каждый `client.post` — то есть в сотню мест, где о CSRF речи нет вовсе.

    Поэтому не фикстура-клиент, а подмена метода `TestClient.request`:
    фикстура-клиент помогла бы только тем тестам, которые её берут, а свои
    `TestClient(app)` заводят и `test_accounts`, и наборы соседей. Подмена же
    действует на всё поддерево `tests/api` и ничего не требует от теста.

    Заголовок дописывается ровно тогда, когда cookie есть и заголовка ещё нет,
    — то есть только там, где человек и правда вошёл. Тестам про сам заслон
    подмена не мешает: у клиента с `без_csrf = True` она молчит.
    """
    from api import csrf

    исходный = TestClient.request

    def запрос(self, method, url, *args, **kwargs):
        значение = self.cookies.get(csrf.COOKIE)
        нужен = (str(method).upper() in csrf.ИЗМЕНЯЮЩИЕ and значение
                 and not getattr(self, "без_csrf", False))
        if нужен:
            заголовки = dict(kwargs.get("headers") or {})
            if not any(k.lower() == csrf.ЗАГОЛОВОК.lower() for k in заголовки):
                заголовки[csrf.ЗАГОЛОВОК] = значение
                kwargs["headers"] = заголовки
        return исходный(self, method, url, *args, **kwargs)

    monkeypatch.setattr(TestClient, "request", запрос)


@pytest.fixture(autouse=True)
def _без_сети(monkeypatch):
    """Любая попытка пойти в сеть — падение теста, а не тихий запрос наружу."""
    def отказ(self, request):        # noqa: ANN001
        raise AssertionError(
            f"тест попытался пойти в сеть: {request.method} {request.url}. "
            "Служба в тестах работает только на временном томе.")

    monkeypatch.setattr(httpx.HTTPTransport, "handle_request", отказ)


