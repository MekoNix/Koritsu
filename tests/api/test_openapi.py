"""
OpenAPI: из этого документа генерируется клиент сайта, и врать он не должен.

Схема — не побочный продукт, а второй, машиночитаемый экземпляр договора.
Из неё берётся TypeScript-клиент, поэтому проверяется здесь не «документ
собрался», а шесть вещей, каждая из которых иначе всплывает у того, кто пишет
сайт, а не у того, кто писал маршрут.

* **Собирается молча.** `UserWarning` при сборке — это FastAPI, сообщающий, что
  два разных объекта претендуют на одно имя схемы. Клиент в этом случае
  собирается, но один из типов оказывается чужим.
* **Описания — английские и свои.** `description` умолчанием берётся из
  докстроки обработчика, а докстроки здесь русские и написаны внутрь кода: с
  доводами и оговорками. В документе, который уезжает на сайт, это и нечитаемая
  подсказка метода, и рассказ о внутренностях.
* **Имена — ASCII.** Когда формы запроса назывались по-русски, генератор
  выписывал из них `____` и `api__projects__routes_____` — имена,
  которые ни набрать, ни отличить друг от друга. Кириллица в имени схемы не
  ломает генерацию, она делает её бесполезной, и заметно это только на той
  стороне.
* **`operationId` уникальны.** Дубль — это два метода клиента с одним именем;
  генератор оставит один, и какой именно, зависит от порядка обхода.
* **Путей на диске в документе нет.** Наружу — идентификаторы. Документ
  уезжает на сайт целиком, вместе с описаниями, и `/data/users/...`, попавший в
  докстроку обработчика, — это раскладка тома, опубликованная в интернете.
* **Ошибка описана одной формой.** У службы один формат отказа
  (`{"error": {code, message}}`), и в схеме он обязан быть один: второе описание
  означает второй разбор в интерфейсе, а он разойдётся с первым молча.
  Исключение ровно одно и названо здесь по имени — `/health`: он отвечает
  прокси, а не клиенту, и его 503 несёт то же тело, что и 200.

Приложение здесь строится обычной фикстурой `app` — на временном томе, как и
везде в этих тестах: `openapi()` обходит все маршруты, а маршруты знают про
настройки.
"""
from __future__ import annotations

import json
import re
import warnings

import pytest

from api.errors import ErrorOut

# Что считаем «путём на диске» в тексте документа. `/data` — том по решению
# владельца, остальное — обычные корни, откуда служба могла бы
# проговориться о машине.
ПУТИ_НА_ДИСКЕ = ("/data", "/home/", "/tmp/", "/var/", "/root/", "/mnt/")

# Имя схемы, годное для генератора: буква, дальше буквы, цифры и подчёркивание.
ИМЯ_СХЕМЫ_RE = re.compile(r"\A[A-Za-z][A-Za-z0-9_]*\Z")

# Единственный маршрут, чей отказ не `ErrorOut`. Список закрыт и лежит здесь, а
# не в пакете: пополнить его — значит завести второй формат отказа, и такое
# решение принимается глазами человека, а не правкой строки в маршруте.
ОТВЕЧАЕТ_ПРОКСИ = "/health"


@pytest.fixture
def схема(app) -> dict:
    """Документ OpenAPI этого приложения."""
    return app.openapi()


def тексты(узел, путь=()):
    """Все строки документа с адресом, по которому они лежат.

    Обход, а не `json.dumps` целиком: сообщение «где-то в схеме есть /data»
    искать глазами дольше, чем править.
    """
    if isinstance(узел, dict):
        for ключ, значение in узел.items():
            yield from тексты(значение, путь + (str(ключ),))
    elif isinstance(узел, list):
        for i, значение in enumerate(узел):
            yield from тексты(значение, путь + (str(i),))
    elif isinstance(узел, str):
        yield ".".join(путь), узел


def операции(схема: dict):
    """`(путь, метод, описание операции)` для каждого маршрута."""
    методы = ("get", "post", "put", "patch", "delete", "head", "options")
    for путь, узел in схема["paths"].items():
        for метод, операция in узел.items():
            if метод in методы:
                yield путь, метод, операция


# ── сборка ───────────────────────────────────────────────────────────────────

def test_собирается_без_предупреждений(app):
    """`UserWarning` от FastAPI при сборке схемы — это столкновение имён.

    Кэш схемы сбрасывается перед сборкой: `app.openapi()` считает документ один
    раз и запоминает, а предупреждения выдаются только при настоящей сборке.
    """
    app.openapi_schema = None
    with warnings.catch_warnings(record=True) as поймано:
        warnings.simplefilter("always")
        app.openapi()
    свои = [w for w in поймано if issubclass(w.category, UserWarning)]
    assert not свои, [str(w.message) for w in свои]


# ── имена ────────────────────────────────────────────────────────────────────

def test_имена_схем_ascii(схема):
    """Кириллица в имени класса превращается в `____` — имя, бесполезное на той
    стороне. Формы запроса поэтому названы по-английски (`WorkspaceNameIn`)."""
    for имя in схема["components"]["schemas"]:
        assert имя.isascii(), имя
        assert ИМЯ_СХЕМЫ_RE.match(имя), имя
        # `____` и `api__projects__routes_____` формально ASCII, но это и
        # есть след кириллического имени: подряд идущие подчёркивания.
        assert "__" not in имя.strip("_") or имя.startswith("Body_"), имя


def test_operation_id_уникальны_и_читаемы(схема):
    """Дубль `operationId` — два метода клиента с одним именем, и какой из них
    останется, решает порядок обхода генератора."""
    все = [операция.get("operationId") for _, _, операция in операции(схема)]
    assert all(все), "у маршрута нет operationId"
    assert len(все) == len(set(все)), \
        f"дубли: {sorted({i for i in все if все.count(i) > 1})}"
    for имя in все:
        assert имя.isascii() and re.match(r"\A[a-z][a-z0-9_]*\Z", имя), имя


def test_у_каждого_маршрута_есть_summary(схема):
    """Короткая английская строка — то, что генератор кладёт в подсказку метода.
    Её отсутствие не ломает клиент, но делает его нечитаемым (наружу —
    по-английски)."""
    for путь, метод, операция in операции(схема):
        summary = операция.get("summary", "")
        assert summary, f"{метод.upper()} {путь}"
        assert summary.isascii(), f"{метод.upper()} {путь}: {summary}"


def test_описания_операций_английские(схема):
    """`description` пишется в декораторе, а не берётся из докстроки.

    Умолчание FastAPI — докстрока обработчика, а докстроки в этом проекте
    русские и написаны для того, кто правит код: там довод и оговорка. В
    документе, из которого генерируется клиент сайта, это сразу две беды.
    Кириллица в `description` уезжает в подсказку метода на стороне, где её
    никто не читает (наружу — по-английски), а вместе с докстрокой наружу
    уезжает и то, что писалось внутрь: раскладка тома и имена соседних модулей.

    Отсюда правило: у каждой операции есть своё английское `description`. Тест
    смотрит на всё, что видит генератор, — `summary`, `description` и `tags`.
    """
    for путь, метод, операция in операции(схема):
        где = f"{метод.upper()} {путь}"
        описание = операция.get("description", "")
        assert описание, f"{где}: описания нет"
        assert описание.isascii(), f"{где}: {описание}"
        for тег in операция.get("tags", ()):
            assert тег.isascii(), f"{где}: тег {тег}"


# ── ничего лишнего наружу ────────────────────────────────────────────────────

def test_ни_путей_ни_тома_в_документе(схема):
    """Наружу — идентификаторы. Документ публикуется целиком, вместе с
    описаниями, и раскладка тома в докстроке обработчика — это раскладка тома в
    интернете."""
    for адрес, строка in тексты(схема):
        for кусок in ПУТИ_НА_ДИСКЕ:
            assert кусок not in строка, f"{адрес}: {строка!r}"


def test_секретов_в_документе_нет(схема, settings):
    """Секрет службы и путь её тома не уезжают в схему даже случайно —
    например, через `description`, собранный из настроек."""
    целиком = json.dumps(схема, ensure_ascii=False)
    assert settings.secret not in целиком
    assert settings.data_dir not in целиком


# ── что выставлено наружу ────────────────────────────────────────────────────

# Что обязано быть под `/api/v1`, по областям. Список пишется руками намеренно:
# он и есть утверждение — «наружу выставлено вот это», — а не пересказ того, что
# сейчас лежит в `routes.ПОД_V1`. Пропавшая строка в том списке ломает внешний
# клиент молча: маршрут остаётся у сайта, у скрипта его больше нет.
#
# Проверяется наличие, а не полнота: маршрут, добавленный к уже выставленному
# роутеру, попадает под второй вход сам, и требовать его перечисления здесь
# значило бы править тест на каждую строку у соседей.
НАРУЖУ = {
    "projects": ("list_projects", "create_project", "get_project",
                 "rename_project", "trash_project", "restore_project"),
    "values": ("get_project_values", "set_project_value"),
    "materials": ("list_materials", "upload_material", "get_material",
                  "get_material_text", "download_material", "delete_material",
                  "list_pending_materials"),
    "jobs": ("jobs_list", "jobs_create", "jobs_get", "jobs_cancel"),
    "events": ("jobs_events",),
    "streams": ("jobs_stream", "user_events"),
    "artifacts": ("download_artifact", "artifact_notices"),
    "modules": ("list_modules", "flowcharts_modes", "flowcharts_create",
                "flowcharts_preview", "uml_themes", "uml_classes",
                "uml_objects"),
    "export": ("export_project",),
}


def имена_v1(схема: dict) -> set[str]:
    """`operation_id` под вторым входом, без суффикса. `ping` — свой, он не
    зеркало и суффикса не носит."""
    return {о["operationId"][:-len("_v1")]
            for путь, _, о in операции(схема)
            if путь.startswith("/api/v1")
            and о["operationId"].endswith("_v1")}


def test_всё_обещанное_наружу_есть_под_v1(схема):
    """Внешнему клиенту даётся: проекты, значения, материалы, задания,
    события, потоки, схемы и выгрузка.

    Обещание это держится одной строкой в `routes.ПОД_V1`, и потеря её ничего
    не ломает у сайта — ломается ровно у того, кто службу не правит и заметит
    это первым в своём скрипте.
    """
    есть = имена_v1(схема)
    for область, имена in sorted(НАРУЖУ.items()):
        не_хватает = [и for и in имена if и not in есть]
        assert not не_хватает, f"{область}: под /api/v1 нет {не_хватает}"


def test_под_v1_нет_ничего_закрытого(схема):
    """Обратная сторона того же списка: аккаунты, ключи моделей, сами ключи,
    админка и платёжка наружу не выставлены вовсе, а не закрыты правом.

    По путям, а не по именам операций: путь — это то, что видит человек с
    ключом, и «его там нет» надёжнее, чем «на него не пустят».
    """
    пути = [p for p in схема["paths"] if p.startswith("/api/v1")]
    assert пути
    for кусок in ("/auth", "/keys", "/tokens", "/admin", "/billing",
                  "/workspaces", "/usage", "/notifications"):
        assert not [p for p in пути if кусок in p], кусок


def test_у_зеркала_то_же_описание_что_у_оригинала(схема):
    """Зеркало — тот же маршрут, а не второй: `summary` и `description` у него
    те же самые.

    Разойтись они могут только одним способом — если кто-нибудь заведёт под
    второй вход отдельный обработчик, — и ровно это правило файла `routes`
    запрещает («обработчик пишется один раз»).
    """
    по_имени = {о["operationId"]: о for _, _, о in операции(схема)}
    for имя, операция in по_имени.items():
        if not имя.endswith("_v1"):
            continue
        свой = по_имени.get(имя[:-len("_v1")])
        assert свой is not None, имя
        assert операция["summary"] == свой["summary"], имя
        assert операция["description"] == свой["description"], имя


# ── одна форма отказа ────────────────────────────────────────────────────────

def test_ошибка_описана_одной_формой(схема):
    """Все отказы — `ErrorOut`, и другой формы в документе нет.

    Отдельно проверяется, что чужого `HTTPValidationError` не осталось: FastAPI
    дописывает его сам, а наш `422` выглядит не так, и оставленная чужая форма
    соврала бы про самый частый отказ.
    """
    имена = схема["components"]["schemas"]
    assert "ErrorOut" in имена and "ErrorBody" in имена
    assert "HTTPValidationError" not in имена and "ValidationError" not in имена

    for путь, метод, операция in операции(схема):
        if путь == ОТВЕЧАЕТ_ПРОКСИ:
            continue
        отказы = {код: тело for код, тело in операция["responses"].items()
                  if код == "default" or (код.isdigit() and int(код) >= 400)}
        assert отказы, f"{метод.upper()} {путь}: отказ не описан вовсе"
        for код, тело in отказы.items():
            ссылка = (тело.get("content", {}).get("application/json", {})
                      .get("schema", {}).get("$ref"))
            assert ссылка == "#/components/schemas/ErrorOut", \
                f"{метод.upper()} {путь} [{код}]: {ссылка}"


def test_у_health_своё_тело_и_оно_описано(схема):
    """Единственное исключение — и оно описано, а не забыто.

    Прокси читает статус, а не `code`, поэтому 503 у `/health` несёт то же тело,
    что и 200 (`HealthOut`). Тест держит это исключение поимённо: незамеченным
    вторым форматом отказа оно стать не может.
    """
    отказ = схема["paths"][ОТВЕЧАЕТ_ПРОКСИ]["get"]["responses"]["503"]
    ссылка = отказ["content"]["application/json"]["schema"]["$ref"]
    assert ссылка == "#/components/schemas/HealthOut"


def test_форма_отказа_совпадает_с_настоящей(client):
    """Схема описывает то, что служба и правда отдаёт.

    Проверяется настоящим отказом, а не чтением схемы: описание, разошедшееся с
    поведением, — это и есть та беда, ради которой схема генерируется, а не
    пишется руками.
    """
    ответ = client.get("/api/workspaces/не-uuid")
    assert ответ.status_code >= 400
    ErrorOut.model_validate(ответ.json())


def test_форма_отказа_совпадает_и_на_проверке_формы(client):
    """422 от pydantic — тот же `ErrorOut`, а не `HTTPValidationError`."""
    ответ = client.post("/api/auth/register",
                        json={"email": "не почта", "nickname": "кто"})
    assert ответ.status_code == 422
    разобрано = ErrorOut.model_validate(ответ.json())
    assert разобрано.error.code == "validation_failed"
    assert разобрано.error.where is not None
