"""
Пространство у работы: видно у карточки и обязательно у списков.

Пространство заводят ради разделения — своё отдельно, кафедра отдельно, — и
разделение это держится на двух вещах, обе из которых ломаются тихо:

1. **работа называет своё пространство словом.** Карточка отдаёт и
   `workspace_id`, и `workspace_name`: человек, у которого пространств три,
   иначе читает на экране идентификатор вместо имени и не знает, куда положил
   работу;
2. **список без пространства не отвечает.** `GET /api/projects` требует
   `workspace_id`, и это правило, а не умолчание: список «всех работ человека»
   на экране означает, что в одном пространстве видно работы другого.

Задания отобраны иначе, и это не непоследовательность: задание принадлежит
человеку, а не пространству, и у задания без проекта пространства нет вовсе.
Поэтому `workspace_id` у `GET /api/jobs` — отбор, а не обязательный параметр.
"""
from __future__ import annotations

from .c_fixtures import (docx_байты, войти, клиент, личное_id,  # noqa: F401
                         позвать, создать_проект, сосед, хозяин)


def кафедра(клиент, name: str = "кафедра") -> str:
    """Второе пространство того же человека."""
    ответ = клиент.post("/api/workspaces", json={"name": name})
    assert ответ.status_code == 201, ответ.text
    return ответ.json()["id"]


# ── имя пространства в карточке ──────────────────────────────────────────────

def test_карточка_называет_пространство_словом(клиент, хозяин):
    ws = кафедра(клиент)
    проект = создать_проект(клиент, ws, name="Работа кафедры")

    assert проект["workspace_id"] == ws
    assert проект["workspace_name"] == "кафедра"

    карточка = клиент.get(f"/api/projects/{проект['id']}").json()
    assert карточка["workspace_id"] == ws
    assert карточка["workspace_name"] == "кафедра"


def test_список_называет_пространство_у_каждой_строки(клиент, хозяин):
    ws = кафедра(клиент)
    создать_проект(клиент, ws, name="Раз")
    создать_проект(клиент, ws, name="Два")

    строки = клиент.get("/api/projects", params={"workspace_id": ws}).json()["projects"]
    assert [с["workspace_name"] for с in строки] == ["кафедра", "кафедра"]


def test_переименованное_пространство_видно_в_карточке(клиент, хозяин):
    """Имя читается у пространства, а не запоминается в работе: иначе
    переименование пространства оставило бы у работ прежнее слово."""
    ws = кафедра(клиент)
    проект = создать_проект(клиент, ws, name="Работа")
    assert клиент.patch(f"/api/workspaces/{ws}",
                        json={"name": "новая кафедра"}).status_code == 200

    карточка = клиент.get(f"/api/projects/{проект['id']}").json()
    assert карточка["workspace_name"] == "новая кафедра"


def test_имя_пространства_есть_и_у_работы_в_корзине(клиент, хозяин):
    """Корзина — тот же список, только другого содержания."""
    ws = кафедра(клиент)
    проект = создать_проект(клиент, ws, name="Выброшенная")
    assert клиент.delete(f"/api/projects/{проект['id']}").status_code == 200

    строки = клиент.get("/api/projects",
                        params={"workspace_id": ws, "trash": True}).json()["projects"]
    assert [с["workspace_name"] for с in строки] == ["кафедра"]


# ── список без пространства ──────────────────────────────────────────────────

def test_список_без_пространства_отказ(клиент, хозяин):
    """Пропущенный `workspace_id` — `422`, а не «отдам всё, что вижу»."""
    создать_проект(клиент, личное_id(клиент), name="Работа")
    ответ = клиент.get("/api/projects")
    assert ответ.status_code == 422, ответ.text
    тело = ответ.json()["error"]
    assert тело["code"] == "validation_failed"
    assert тело["where"] == "query.workspace_id"


def test_в_списке_пространства_только_его_работы(клиент, хозяин):
    """Обе работы свои, но список у каждого пространства свой."""
    ws = кафедра(клиент)
    создать_проект(клиент, ws, name="Работа кафедры")
    создать_проект(клиент, личное_id(клиент), name="Работа личная")

    личные = клиент.get("/api/projects",
                        params={"workspace_id": личное_id(клиент)}).json()["projects"]
    чужие = клиент.get("/api/projects", params={"workspace_id": ws}).json()["projects"]
    assert [p["name"] for p in личные] == ["Работа личная"]
    assert [p["name"] for p in чужие] == ["Работа кафедры"]


def test_список_чужого_пространства_это_404(app, клиент, хозяин, сосед):
    моё = личное_id(клиент)
    войти(app, сосед)
    ответ = клиент.get("/api/projects", params={"workspace_id": моё})
    assert ответ.status_code == 404
    assert ответ.json()["error"]["code"] == "not_found"


# ── задания одного пространства ──────────────────────────────────────────────

def test_задания_отбираются_по_пространству(клиент, хозяин):
    """Задание работы из соседнего пространства в список не попадает."""
    ws = кафедра(клиент)
    свой = создать_проект(клиент, личное_id(клиент), name="Личная")
    чужой = создать_проект(клиент, ws, name="Кафедральная")
    for проект in (свой, чужой):
        ответ = клиент.post("/api/jobs", json={"kind": "probe",
                                               "project_id": проект["id"]})
        assert ответ.status_code == 202, ответ.text

    в_личном = клиент.get("/api/jobs",
                          params={"workspace_id": личное_id(клиент)}).json()["jobs"]
    assert [з["project_id"] for з in в_личном] == [свой["id"]]

    без_отбора = клиент.get("/api/jobs").json()["jobs"]
    assert len(без_отбора) == 2


def test_задание_без_проекта_видно_в_любом_пространстве(клиент, хозяин):
    """Оно ничьего пространства не касается — спрятать его значило бы потерять."""
    assert клиент.post("/api/jobs", json={"kind": "probe"}).status_code == 202

    задания = клиент.get("/api/jobs",
                         params={"workspace_id": кафедра(клиент)}).json()["jobs"]
    assert [з["project_id"] for з in задания] == [None]
