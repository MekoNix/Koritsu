def test_viewer_видит_список_но_не_строит(app, клиент, хозяин, сосед):
    """Смотреть чужие схемы можно; занимать место на чужом томе — нет."""
    ws = клиент.post("/api/workspaces", json={"name": "общее"}).json()["id"]
    assert позвать(app, клиент, ws, сосед, "viewer").status_code == 201
    общая = создать_проект(клиент, ws, name="общая работа")
    схема = построить(клиент, общая)

    войти(app, сосед)
    видно = клиент.get(СХЕМЫ.format(общая["id"]))
    assert видно.status_code == 200
    assert [с["run_id"] for с in видно.json()] == [схема["run_id"]]

    строить = клиент.post(СХЕМЫ.format(общая["id"]),
                          json={"source": ЦИКЛ, "lang": "py"})
    assert строить.status_code == 403
