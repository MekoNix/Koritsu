# ── два модуля, два списка ───────────────────────────────────────────────────

def test_у_uml_свой_список(клиент, проект):
    """Диаграмма классов не попадает к блок-схемам, и наоборот."""
    схема = построить(клиент, проект)
    диаграмма = клиент.post(КЛАССЫ.format(проект["id"]),
                            json={"sources": [{"name": "a.py",
                                               "source": КЛАСС}],
                                  "lang": "py"})
    assert диаграмма.status_code == 201, диаграмма.text
    диаграмма = диаграмма.json()

    assert [с["run_id"] for с in список(клиент, проект)] == [схема["run_id"]]
    assert [с["run_id"] for с in список(клиент, проект, ДИАГРАММЫ)] == [
        диаграмма["run_id"]]
    # Номер считается по модулю, а не по работе: первая диаграмма — первая.
    assert диаграмма["n"] == 1 and диаграмма["kind"] == "classes"
    assert диаграмма["theme"] == "dark"


def test_схему_чужого_модуля_не_открыть_своим_маршрутом(клиент, проект):
    """Иначе блок-схема перестроилась бы как диаграмма классов."""
    схема = построить(клиент, проект)
    ответ = клиент.get(f"{ДИАГРАММЫ.format(проект['id'])}/{схема['run_id']}")
    assert ответ.status_code == 404, ответ.text


# ── удаление ─────────────────────────────────────────────────────────────────

def test_удаление_записи_журнала_убирает_схему_а_артефакт_остаётся(клиент,
                                                                   проект):
    """Удаление одно — записью журнала; артефакт может стоять значением тега."""
    схема = построить(клиент, проект)
    убрать = клиент.delete(
        f"{ЖУРНАЛ.format(проект['id'])}/{схема['run_id']}")
    assert убрать.status_code == 204, убрать.text

    assert список(клиент, проект) == []
    пропала = клиент.get(f"{СХЕМЫ.format(проект['id'])}/{схема['run_id']}")
    assert пропала.status_code == 404

    остался = клиент.get(АРТЕФАКТ.format(проект["id"], схема["artifact"]))
    assert остался.status_code == 200, "XML удалением записи не трогается"


