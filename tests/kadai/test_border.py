"""
Граница с соседями — проверяется, а не обещается.

Правило разреза: `kadai` держит сценарий и не заводит второго экземпляра
среднего слоя. Проверяется оно так же, как соседнее правило про пути, — чтением
исходников: в `packages/kadai/` не должно быть ни импорта пакетов проекта, ни
работы с путями. Нарушение любого пункта означает, что в `kadai` завелось
второе место, которое хранит состояние или разговаривает с моделью, — и
разойдётся оно с настоящим молча.

Отдельно и сильнее прежнего проверяется другое: **слова про вид работы
в пакете нет вовсе**, и это решение несущее. Раньше «курсовая» была
именем файла-профиля и умолчанием; теперь строение сочиняет модель по условию, а
работой бывает что угодно — хоть учёт продажи носков. Значит ни одно из этих слов
не вправе встретиться в пакете даже прозой: докстрока, объясняющая правило
словами одного вида работы, завтра станет объяснением, почему код знает про
второй.
"""
from __future__ import annotations

import io
import re
import tokenize
from pathlib import Path

import kadai

ПАКЕТ = Path(kadai.__file__).parent
ФАЙЛЫ = sorted(ПАКЕТ.rglob("*.py"))


def код(path: Path) -> str:
    """Исходник без строк и комментариев.

    Смотреть надо на код, а не на прозу: докстроки этого пакета называют
    запрещённое поимённо («ни `import hokoku`, ни `os.path.join`»), и проверка
    по сырому тексту запрещала бы объяснять правило там, где оно действует.
    """
    out = []
    for tok in tokenize.generate_tokens(io.StringIO(path.read_text("utf-8")).readline):
        if tok.type in (tokenize.COMMENT, tokenize.STRING):
            continue
        out.append("\n" if tok.type in (tokenize.NL, tokenize.NEWLINE) else tok.string)
    return "\n".join(out)

# Пакеты проекта, которых `kadai` не касается вовсе. Импорт любого из них — это
# либо второй средний слой (`materials`), либо сетевой код в сценарии (`llm`),
# либо нарушение действующего правила импорта (`orchestrator`, поправка Л.9 не
# принята), либо знание о языках и об OOXML, которое сценарию не принадлежит.
СОСЕДИ = ("llm", "materials", "fragmos", "uml_generator", "orchestrator", "docx", "kyotsu")

# `hokoku` — исключение правила разреза 2.0.0a4.3: его можно звать **как чистый
# инструмент** (байты и значения, без диска и проекта). Разрешение узкое, и
# держится оно тем, что живёт в одном файле: разойдись оно по восьми, проверять
# «а это точно чистая функция?» пришлось бы чтением всего пакета.
ГДЕ_МОЖНО_HOKOKU = "blocks.py"

# Дисковое и проектное у `hokoku`: путь на входе, готовый файл на выходе, чужой
# ZIP. Всё это знает `orchestrator`, и второго знающего в проекте не заводится.
ДИСКОВОЕ_У_HOKOKU = ("open_document", "build_report", "docx_to_pdf", "validate_docx",
                     "manifest_from_template", "build_template")


def test_файлы_пакета_на_месте():
    имена = {p.name for p in ФАЙЛЫ}
    assert имена == {"__init__.py", "__main__.py", "errors.py", "seams.py", "blocks.py",
                     "profile.py", "plan.py", "stages.py", "run.py", "status.py",
                     "archive.py", "rework.py"}


def test_ни_одного_импорта_соседа():
    for path in ФАЙЛЫ:
        текст = код(path)
        for сосед in СОСЕДИ:
            found = re.search(rf"^\s*(?:import {сосед}\b|from {сосед}[.\s])",
                              текст, re.MULTILINE)
            assert not found, f"{path.name}: импорт {сосед} — это второй средний слой"


def test_hokoku_зовётся_из_одного_файла_и_только_чистым():
    """Движок отчётов можно звать чистыми функциями и только из `blocks.py`.

    Два утверждения, и оба проверяются, потому что каждое поодиночке ничего не
    стоит. «Только чистыми» без «из одного файла» пришлось бы проверять чтением
    всего пакета; «из одного файла» без «только чистыми» разрешило бы туда
    `build_report` — то есть путь и готовый файл, то есть второе место, которое
    знает диск.
    """
    for path in ФАЙЛЫ:
        текст = код(path)
        есть = re.search(r"^\s*(?:import hokoku\b|from hokoku[.\s])", текст, re.MULTILINE)
        assert not есть or path.name == ГДЕ_МОЖНО_HOKOKU, \
            f"{path.name}: hokoku зовётся мимо {ГДЕ_МОЖНО_HOKOKU}"
        for дисковое in ДИСКОВОЕ_У_HOKOKU:
            assert дисковое not in текст, f"{path.name}: {дисковое} — это диск и пути"


def test_путей_в_пакете_нет():
    """`os.path.join` в kadai означает, что рядом с Project завелось второе
    хранилище, и переезд на SQLite перестал быть заменой одного класса.
    Данные профиля читаются через importlib.resources — это ресурс пакета,
    а не состояние работы.

    `from os import environ` в `__main__.py` — единственная уступка, и она не
    про пути: так процесс узнаёт, кто соберёт ему двери. Всё остальное из `os`
    запрещено ровно потому, что почти всё остальное в `os` — это путь.
    """
    for path in ФАЙЛЫ:
        текст = код(path)
        assert "os.path" not in текст, path.name
        assert not re.search(r"^\s*import os\b", текст, re.MULTILINE), path.name
        for найдено in re.findall(r"^\s*from os import (.+)$", текст, re.MULTILINE):
            assert найдено.strip() == "environ" and path.name == "__main__.py", \
                f"{path.name}: from os import {найдено}"
        assert not re.search(r"\bopen\s*\(", текст), path.name


def test_кода_никто_не_исполняет():
    """Запрет исполнения пользовательского кода цел: ни exec, ни subprocess,
    ни eval — их отсутствие проверяется, а не подразумевается."""
    for path in ФАЙЛЫ:
        текст = код(path)
        for опасное in ("subprocess", "exec(", "eval(", "__import__"):
            assert опасное not in текст, f"{path.name}: {опасное}"


# Слова, которых в пакете нет и быть не может: вид работы не фиксирован, и
# всякое такое слово — утверждение о том, чего мы не знаем. Проверяется по
# СЫРОМУ тексту, а не по коду: прозе здесь запрещено ровно то же самое.
СЛОВА_ПРО_ВИД_РАБОТЫ = ("курсов", "лаборатор", "реферат", "кафедр", "студент",
                        "kursov", "диплом", "методичк")


def test_слова_про_вид_работы_в_пакете_нет():
    """Несущее решение: Koritsu обрабатывает любой документ.

    Одно такое слово в докстроке — и через полгода рядом появится ветка `if`,
    объясняющая, чем «этот вид работы» отличается от «того».
    """
    for path in ФАЙЛЫ:
        текст = path.read_text("utf-8").lower()
        for слово in СЛОВА_ПРО_ВИД_РАБОТЫ:
            assert слово not in текст, f"{path.name}: слово про вид работы «{слово}»"


def test_умолчания_у_вида_работы_нет():
    """Ни папки профилей, ни загрузчика, ни имени умолчания: строение работы
    приходит только из ответа модели по условию."""
    assert not (ПАКЕТ / "profiles").exists()
    for имя in ("DEFAULT_PROFILE", "load", "available", "base_template"):
        assert not hasattr(kadai.profile, имя), f"{имя} — это умолчание вида работы"
    пустое = kadai.run.BLANK
    assert пустое.name == "" and пустое.kinds == {} and пустое.needs == {}


def test_замечания_едут_в_общей_форме():
    """Четвёртого канала предупреждений в проекте не заводится."""
    p = kadai.problem("нет_кода", "нет листингов", key="реализация")
    assert set(p) == {"module", "level", "code", "key", "message"}
    assert p["module"] == "kadai" and p["level"] == "error"
