/**
 * useUsage — остаток месяца и цены видов заданий.
 *
 * Расход и цены показываются одним местом — разделом «Расход и лимиты» в
 * настройках. Рядом с кнопками их нет: цена прогона динамическая, и названное
 * до нажатия число было бы обещанием, которого никто не давал. Цена и остаток
 * при этом приезжают одним ответом (`prices`), поэтому разойтись они не могут.
 *
 * Ключ сбрасывается после каждого поставленного задания — цифра «осталось»,
 * не меняющаяся после запуска, читается как поломка.
 */
import { useQuery, type UseQueryResult } from '@tanstack/react-query'

import { api, unwrap } from '../client'
import { keys } from '../queryKeys'
import type { Usage } from '../types'

export function useUsage(): UseQueryResult<Usage> {
  return useQuery({
    queryKey: keys.usage,
    queryFn: () => unwrap<Usage>(api.GET('/api/usage')),
    // Остаток меняется только концом задания, и ключ гасит поток человека
    // (`useUserEvents`). Короткая свежесть означала бы перезапрос на каждом
    // переходе ради цифры, которая не могла измениться.
    staleTime: 5 * 60_000,
  })
}
