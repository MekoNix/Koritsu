/**
 * useWidePage — экран во всю ширину окна, без обычного потолка колонки текста.
 *
 * Оболочка держит содержимое в колонке шириной `--content-max` с полями
 * `--space-5`: так читается текст, списки и формы, то есть почти всё
 * приложение. Рабочим экранам это мешает: у отчёта три колонки — теги,
 * заполнение и превью страницы, — и полтора сантиметра пустоты по краям
 * забирают их у самого узкого, превью, где каждая точка это буква вёрстки.
 *
 * Потолок и поля объявлены переменными на `main`, а меняются здесь — на
 * корневом элементе. Иначе никак: переменная наследуется вниз, и экран,
 * лежащий внутри `main`, повлиять на его собственную ширину не может.
 * Возврат к обычной колонке — снятием переменных при уходе с экрана, а не
 * записью прежних значений: прежнее значение это их отсутствие.
 */
import { useEffect } from 'react'

const МАКС = '--page-max'
const ПОЛЯ = '--page-pad'

export function useWidePage(): void {
  useEffect(() => {
    const корень = document.documentElement
    корень.style.setProperty(МАКС, '100%')
    корень.style.setProperty(ПОЛЯ, 'var(--space-3)')
    return () => {
      корень.style.removeProperty(МАКС)
      корень.style.removeProperty(ПОЛЯ)
    }
  }, [])
}
