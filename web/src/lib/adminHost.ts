/**
 * adminHost — на каком имени живёт админка.
 *
 * Админка вынесена на домен третьего уровня: у неё свой блок на прокси, свой
 * белый список адресов и свой origin, то есть своя cookie сессии. Отсюда
 * следствие для сайта: страницы `/admin*` открываются **только** с этого
 * имени, а с основного их нет — там служба и прокси отвечают 404, и сайт
 * обязан показывать то же самое, а не пустой экран или «нет доступа».
 *
 * **Откуда берётся имя.** Из службы, полем `admin_domain` первого запроса
 * загрузки страницы (`GET /api/bootstrap`, он же `GET /api/auth/me`). Не из
 * сборки: имя живёт в `.env` на машине, в репозиторий не попадает, и вписать
 * его в статику значило бы пересобирать сайт ради строки настройки.
 *
 * **Почему обычная переменная, а не состояние React.** Значение приезжает
 * раньше, чем рисуется хоть один защищённый экран: и оболочка, и охрана
 * маршрутов ждут ответа с профилем, а он и приносит имя. Перерисовывать по
 * нему нечего, а хук на одну строку настройки протянул бы её через каждый
 * компонент, которому она не нужна.
 *
 * Пусто — «домена нет»: так работают машина разработчика и стенд, где имени у
 * сайта нет вовсе. Тогда `/admin` открывается там же, где весь сайт, и решает
 * по-прежнему один `is_admin`.
 */
import { BASE_PATH } from './basePath'

let домен = ''

/** Запомнить имя из ответа службы. `undefined` — поля не было, значит домена нет. */
export function запомнитьДоменАдминки(значение: string | undefined | null): void {
  домен = (значение ?? '').trim().toLowerCase()
}

/** Имя домена админки или пустая строка. */
export function доменАдминки(): string {
  return домен
}

/**
 * Открывается ли админка на том имени, где сейчас страница.
 *
 * Порт не сравнивается: 80 и 443 — это один и тот же домен, а на машине
 * разработчика имени нет вовсе и сравнивать нечего. Так же считает и служба
 * (`settings.имя_хоста`), и разойтись эти два счёта не должны — иначе сайт
 * покажет админку, которой служба ответит 404.
 */
export function админкаНаЭтомИмени(): boolean {
  if (!домен) return true
  return window.location.hostname.toLowerCase() === домен
}

/**
 * Полный адрес страницы админки на её домене.
 *
 * Ссылка абсолютная и с именем: переход между origin'ами роутер сделать не
 * может, это обычный переход браузера. Схема и порт берутся у текущей
 * страницы — админка живёт на той же машине и за тем же прокси, а разные схемы
 * у соседних имён означали бы ссылку, ведущую в предупреждение браузера.
 */
export function адресАдминки(путь = '/admin'): string {
  const { protocol, port } = window.location
  const хвост = port ? `:${port}` : ''
  return `${protocol}//${домен}${хвост}${BASE_PATH}${путь}`
}
