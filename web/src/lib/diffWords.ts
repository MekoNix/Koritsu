/**
 * diffWords — сравнение двух текстов по словам. Чистая функция, без React.
 *
 * **Своё, а не библиотека `diff` из npm.** Довод не в гордости, а в трёх
 * вещах, которых у пакета нет и которые нужны именно нам:
 *
 * 1. **Потолок работы.** Значение тега — это абзац или страница, но однажды
 *    туда ляжет распознанный PDF на сотню тысяч слов, и сравнение двух таких
 *    версий подвесило бы вкладку молча. Здесь потолок объявлен числом
 *    (`ПОТОЛОК`), и за ним ответ честный: «текст заменён целиком», а не
 *    зависание.
 * 2. **Разбиение — наше.** Слово с пунктуацией, перенос строки как отдельная
 *    единица, схлопнутые пробелы — от этого зависит, покажется ли правка
 *    «слово» или «весь абзац», и решать это должен экран, а не умолчание
 *    чужого пакета.
 * 3. **Зависимость на сорок строк кода.** Пакет пришлось бы обновлять,
 *    проверять и объяснять; здесь всё поведение видно глазами и покрыто
 *    проверками.
 *
 * Алгоритм — наибольшая общая подпоследовательность (LCS) динамикой по
 * типизированному массиву, с двумя обычными приёмами: сначала срезается общее
 * начало и общий конец (в двух версиях одного абзаца совпадает почти всё), и
 * только остаток считается матрицей. `Uint32Array` вместо массива массивов —
 * это одно выделение памяти вместо тысячи.
 */

/** Что случилось с куском текста. */
export type DiffKind = 'same' | 'add' | 'del'

/** Кусок сравнения: подряд идущие слова одной судьбы. */
export type DiffPart = { kind: DiffKind; text: string }

/**
 * Потолок площади матрицы (слов слева × слов справа) после срезки общих краёв.
 *
 * 4 000 000 клеток — это 16 МБ `Uint32Array` и доли секунды счёта; больше —
 * уже заметная пауза в браузере, ради которой никто не смотрел бы на разницу.
 */
export const ПОТОЛОК = 4_000_000

/**
 * Разбить текст на единицы сравнения. → массив слов и пробельных кусков.
 *
 * Пробелы остаются отдельными единицами, а не приклеиваются к словам: иначе
 * замена одного пробела на перенос строки красила бы соседнее слово как
 * изменённое. Склейка кусков обратно даёт исходный текст знак в знак — это и
 * проверяется тестом.
 */
export function splitWords(text: string): string[] {
  return text.match(/\s+|[^\s]+/g) ?? []
}

/**
 * Сравнить два текста по словам. → куски в порядке чтения.
 *
 * Порядок внутри одной правки — сначала удалённое, потом добавленное: так
 * читается «было → стало», и так же расположены цвета в столбик на экране.
 */
export function diffWords(before: string, after: string): DiffPart[] {
  return diffTokens(splitWords(before), splitWords(after))
}

/** То же по готовым единицам — для тех, у кого своё разбиение (строки, блоки). */
export function diffTokens(a: string[], b: string[]): DiffPart[] {
  // Общее начало и общий конец. У двух версий одного абзаца это почти весь
  // текст, и матрица после срезки получается размером с саму правку.
  let начало = 0
  while (начало < a.length && начало < b.length && a[начало] === b[начало]) начало++
  let конец = 0
  while (
    конец < a.length - начало &&
    конец < b.length - начало &&
    a[a.length - 1 - конец] === b[b.length - 1 - конец]
  )
    конец++

  const левое = a.slice(начало, a.length - конец)
  const правое = b.slice(начало, b.length - конец)

  const куски: DiffPart[] = []
  добавить(куски, 'same', a.slice(0, начало))

  if (левое.length === 0 || правое.length === 0) {
    // Чистая вставка или чистое удаление — матрица не нужна.
    добавить(куски, 'del', левое)
    добавить(куски, 'add', правое)
  } else if (левое.length * правое.length > ПОТОЛОК) {
    // Слишком много, чтобы считать (см. докстроку модуля): показываем правду
    // грубее — старое целиком убрано, новое целиком добавлено.
    добавить(куски, 'del', левое)
    добавить(куски, 'add', правое)
  } else {
    середина(куски, левое, правое)
  }

  добавить(куски, 'same', a.slice(a.length - конец))
  return куски
}

/** Сколько слов добавлено, убрано и оставлено — подпись над сравнением. */
export function diffStats(parts: DiffPart[]): { added: number; removed: number; same: number } {
  let added = 0
  let removed = 0
  let same = 0
  for (const кусок of parts) {
    // Пробельные куски не считаются словами: «изменено 12 слов» не должно
    // расти от переносов строк.
    const слов = (кусок.text.match(/[^\s]+/g) ?? []).length
    if (кусок.kind === 'add') added += слов
    else if (кусок.kind === 'del') removed += слов
    else same += слов
  }
  return { added, removed, same }
}

// ── внутреннее ───────────────────────────────────────────────────────────────

/**
 * Середина сравнения: LCS динамикой и обратный ход по матрице.
 *
 * Матрица размером `(n+1) × (m+1)` хранит длину общей подпоследовательности
 * хвостов. Обратный ход по ней и даёт куски: равные слова идут по диагонали,
 * шаг вправо — вставка, шаг вниз — удаление.
 */
function середина(куски: DiffPart[], a: string[], b: string[]): void {
  const n = a.length
  const m = b.length
  const таблица = new Uint32Array((n + 1) * (m + 1))
  const шаг = m + 1

  // `!` здесь и ниже — не небрежность: индексы держатся длинами `n` и `m`
  // самих массивов, и `noUncheckedIndexedAccess` иначе потребовал бы проверки
  // на `undefined` в самом горячем цикле сравнения.
  for (let i = n - 1; i >= 0; i--) {
    for (let j = m - 1; j >= 0; j--) {
      таблица[i * шаг + j] =
        a[i] === b[j]
          ? таблица[(i + 1) * шаг + j + 1]! + 1
          : Math.max(таблица[(i + 1) * шаг + j]!, таблица[i * шаг + j + 1]!)
    }
  }

  let i = 0
  let j = 0
  while (i < n && j < m) {
    if (a[i] === b[j]) {
      добавить(куски, 'same', [a[i]!])
      i++
      j++
    } else if (таблица[(i + 1) * шаг + j]! >= таблица[i * шаг + j + 1]!) {
      добавить(куски, 'del', [a[i]!])
      i++
    } else {
      добавить(куски, 'add', [b[j]!])
      j++
    }
  }
  добавить(куски, 'del', a.slice(i))
  добавить(куски, 'add', b.slice(j))
}

/**
 * Дописать слова одной судьбы, склеивая с последним куском, если судьба та же.
 *
 * Склейка — не украшение: без неё каждое слово стало бы своим `<span>`, и
 * абзац на тысячу слов превратился бы в тысячу узлов DOM с рамками по краям
 * каждого.
 */
function добавить(куски: DiffPart[], kind: DiffKind, слова: string[]): void {
  if (слова.length === 0) return
  const текст = слова.join('')
  const последний = куски[куски.length - 1]
  if (последний && последний.kind === kind) последний.text += текст
  else куски.push({ kind, text: текст })
}
