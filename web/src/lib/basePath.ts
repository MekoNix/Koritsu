/**
 * basePath — префикс пути, под которым живёт сайт.
 *
 * Домена у сайта пока нет, поэтому адрес — IP машины
 * плюс случайная строка в пути: `http://203.0.113.7/k7f3x9/`. Строка эта в
 * репозиторий не попадает; она задаётся один раз на сборке переменной
 * `VITE_BASE_PATH` (`vite.config.ts` кладёт её в `base`), а сюда приходит
 * готовой — `import.meta.env.BASE_URL`.
 *
 * Почему `import.meta.env.BASE_URL`, а не своя переменная: Vite сам подставляет
 * в него значение `base` и сам же переписывает по нему ссылки в `index.html` и
 * на файлы `assets/`. Второе имя того же значения однажды разошлось бы с
 * первым — и страница грузилась бы, а скрипты к ней нет.
 *
 * Два вида значения, и путать их нельзя:
 *
 *   BASE_URL (Vite)  всегда с косой на конце: `/` или `/k7f3x9/`
 *   BASE_PATH (тут)  всегда без косой на конце: `` или `/k7f3x9`
 *
 * Второе удобнее для склейки: `BASE_PATH + '/api/jobs'` — и в корне, и под
 * префиксом получается ровно один разделитель.
 *
 * В `pnpm dev` и в проверках `VITE_BASE_PATH` никто не задаёт, `BASE_URL`
 * равен `/`, `BASE_PATH` пуст — то есть всё работает ровно как раньше.
 */

/** Префикс без косой на конце: `` (корень) или `/k7f3x9`. */
export const BASE_PATH: string = (import.meta.env.BASE_URL || '/').replace(/\/+$/, '')

/**
 * `basename` для роутера. React Router просит `/` для корня, а не пустую
 * строку, — отсюда отдельная константа, а не `BASE_PATH` по месту.
 */
export const ROUTER_BASENAME: string = BASE_PATH || '/'

/**
 * Собственный путь сайта → полный путь от корня сервера.
 *
 *     withBase('/api/jobs')  →  '/api/jobs'          в корне
 *     withBase('/api/jobs')  →  '/k7f3x9/api/jobs'   под префиксом
 *
 * Нужен всюду, где адрес не проходит через клиент API: потоки SSE, ссылки на
 * артефакты и материалы, `href` у скачивания. Клиент API префикс ставит сам
 * (`api/client.ts`), и его вызовы через эту функцию **не** гоняют — вышло бы
 * два префикса подряд.
 */
export function withBase(path: string): string {
  return BASE_PATH + path
}
