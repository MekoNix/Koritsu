/**
 * maskEmail — почта, показанная не целиком: `ivan@mail.ru` → `i***@mail.ru`.
 *
 * На дашборде и в профиле имя человека — ник, а почта прячется частично. Смысл
 * прятки не в тайне от хозяина экрана (свою почту он знает), а в том, что экран
 * открывают при других людях, показывают на защите и снимают на видео. Домен
 * при этом остаётся: по нему человек узнаёт **свой** адрес, если их у него
 * несколько, — а именно за этим он на почту и смотрит.
 *
 * Одним помощником на весь сайт, а не тремя одинаковыми строчками по экранам:
 * три разойдутся — где-то останется две буквы, где-то весь адрес, — и разница
 * будет выглядеть как утечка, а не как небрежность.
 *
 * Строка без `@` — не почта; возвращается как есть, звёздочками из неё сделать
 * нечего.
 */

/** Сколько звёздочек ставить вместо скрытой части. Всегда три, а не по числу
 *  скрытых знаков: длина адреса — тоже сведение, и подсказывать её незачем. */
const ЗВЁЗДОЧКИ = '***'

export function maskEmail(email: string | null | undefined): string {
  const адрес = (email ?? '').trim()
  const собака = адрес.lastIndexOf('@')
  if (собака <= 0) return адрес

  const имя = адрес.slice(0, собака)
  const домен = адрес.slice(собака)
  // Однобуквенное имя показывается целиком: спрятать в нём нечего, а пустое
  // место перед звёздочками читается как обрезанный адрес.
  return `${[...имя][0] ?? ''}${ЗВЁЗДОЧКИ}${домен}`
}
