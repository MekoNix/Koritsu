/**
 * Куда ведёт найденное и когда палитра спрашивает службу.
 *
 * Два правила, и оба ломаются молча:
 *
 * 1. **найденная работа открывается своим модулем.** Служба называет модуль
 *    (`kadai` | `reports`), а адрес экрана знает сайт. Ошибка здесь даёт ссылку
 *    в никуда — ровно то, что запрещено;
 * 2. **запрос откладывается.** Без задержки «сортировки» стоит службе десяти
 *    обходов тома ради одного ответа, и заметить это по экрану нельзя вовсе:
 *    выдача-то правильная.
 */
import { act, renderHook } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

import { ЗАДЕРЖКА_МС, useDebounced, адрес } from './data'

describe('адрес найденной работы', () => {
  it('ведёт прямо в модуль там, где служба его знает', () => {
    // Запись о работе `kadai` на томе либо есть, либо нет — это знание, а не
    // догадка, и вести по нему прямо на экран работы можно.
    expect(адрес('kadai', 'p-1')).toBe('/kadai/p-1')
  })

  it('предположение и незнакомый модуль ведут на карточку проекта', () => {
    // `reports` служба не знает, а выводит из отсутствия записи `kadai`. У
    // проекта без шаблона на экране отчёта показывать нечего, а карточка есть у
    // любой работы: она и есть честный адрес.
    expect(адрес('reports', 'p-1')).toBe('/projects/p-1')
    expect(адрес('карточки', 'p-1')).toBe('/projects/p-1')
    expect(адрес(undefined, 'p-1')).toBe('/projects/p-1')
  })
})

describe('задержка ввода', () => {
  beforeEach(() => vi.useFakeTimers())
  afterEach(() => vi.useRealTimers())

  it('отдаёт набранное не раньше, чем через задержку', () => {
    const { result, rerender } = renderHook(({ q }) => useDebounced(q, ЗАДЕРЖКА_МС), {
      initialProps: { q: 'с' },
    })
    expect(result.current).toBe('с')

    rerender({ q: 'со' })
    rerender({ q: 'сор' })
    // Пока пауза не выдержана, отложенное значение прежнее: запроса за «со» и
    // «сор» служба не увидит вовсе.
    act(() => void vi.advanceTimersByTime(ЗАДЕРЖКА_МС - 1))
    expect(result.current).toBe('с')

    act(() => void vi.advanceTimersByTime(1))
    expect(result.current).toBe('сор')
  })
})
