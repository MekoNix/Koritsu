/**
 * Маршруты области «Отчёты».
 *
 *     /reports                      выбор работы
 *     /reports?project=<работа>     отчёты этой работы карточками
 *     /reports/<работа>/<отчёт>     экран отчёта: теги, заполнение, превью PDF
 *     /reports/<работа>             тот же экран без названного отчёта
 *
 * Отчётов в работе несколько — у каждого свой бланк и свои значения, — поэтому
 * адрес экрана называет открытый отчёт: иначе ссылку на готовый отчёт нельзя ни
 * сохранить, ни послать.
 *
 * Адрес без отчёта остаётся законным и открывает **собственный документ
 * работы** — тот, который был у неё, пока отчёт в ней был один, и который
 * достаётся первому отчёту (`packages/api/projects/reports.py`). По нему
 * приходят ссылки из уведомлений о заданиях, где известна только работа, и по
 * нему же открывается работа, отчётов в которой ещё нет вовсе.
 *
 * Список отчётов стоит на главной модуля, а не отдельной страницей, потому что
 * выбор здесь один и делается он в два шага: сначала работа, потом отчёт в ней.
 * Разрывать эти два шага на два адреса значило бы заставлять возвращаться назад
 * ради второго.
 *
 * `/reports/:projectId` — тот же адрес, что в карте модулей
 * (`features/projects/moduleRoutes.ts`): кнопка «открыть в модуле» со страницы
 * работы ведёт сюда, а строка журнала запусков — сразу к своему отчёту.
 */
import type { RouteObject } from 'react-router-dom'

import { ReportWorkPage } from './ReportWorkPage'
import { ReportsHomePage } from './ReportsHomePage'

export const reportsRoutes: RouteObject[] = [
  { path: 'reports', element: <ReportsHomePage /> },
  { path: 'reports/:projectId', element: <ReportWorkPage /> },
  { path: 'reports/:projectId/:runId', element: <ReportWorkPage /> },
]
