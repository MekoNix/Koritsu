/**
 * context — над какой работой панель агента стоит прямо сейчас.
 *
 * Панель открывается поверх любого экрана и своего адреса не имеет, поэтому
 * контекст она берёт **из адреса того экрана, что под ней**: агент работает в
 * проекте, и проект — это тот, который человек сейчас видит. Разделов, где
 * проект есть, пять; их список — здесь, одной таблицей, а не разбросан
 * условиями по компоненту.
 *
 *     /reports/<id>      экран отчёта
 *     /projects/<id>     карточка работы
 *     /flowcharts/<id>   блок-схема
 *     /uml/<id>          UML
 *     /kadai/<id>        задание
 *
 * `/kadai` стоит в списке намеренно: панель обязана узнавать проект и на этой
 * странице — иначе на самом «агентском» экране агент окажется без контекста.
 *
 * Вне этих адресов проекта нет, и панель спрашивает его сама (выбор в панели):
 * запускать прогон «куда-нибудь» нельзя, а гадать «последний открытый» —
 * значит однажды переписать чужую работу.
 */

/** Разделы, у которых второй кусок адреса — идентификатор проекта. */
const РАЗДЕЛЫ = new Set(['reports', 'projects', 'flowcharts', 'uml', 'kadai'])

/**
 * Идентификатор проекта из адреса или `null`.
 *
 * Берётся ровно второй кусок пути: `/reports/p-1/versions` — тот же проект, а
 * `/reports` — никакой. Проверять форму идентификатора здесь незачем: чужую
 * строку отвергнет служба (`400 invalid_id`), а сайт, знающий формат чужих
 * ключей, обязан меняться вместе с ним.
 */
export function projectFromPath(pathname: string): string | null {
  const [раздел, идентификатор] = pathname.split('/').filter(Boolean)
  if (!раздел || !идентификатор) return null
  if (!РАЗДЕЛЫ.has(раздел)) return null
  return идентификатор
}

/**
 * Идентификатор отчёта из адреса `/reports/<работа>/<отчёт>`; иначе пусто.
 *
 * Отчётов в работе несколько, у каждого свои значения тегов, и агент обязан
 * писать в тот, который человек сейчас видит. Взять его больше неоткуда:
 * панель открывается поверх экрана и своего адреса не имеет — тот же довод,
 * что и у `projectFromPath`. Пусто — панель стоит не над отчётом, и тогда
 * прогон идёт по документу работы, как было, пока отчёт в ней был один.
 */
export function reportFromPath(pathname: string): string {
  const [раздел, , отчёт] = pathname.split('/').filter(Boolean)
  return раздел === 'reports' && отчёт ? отчёт : ''
}

/**
 * Ссылка на тег, который изменил прогон: экран отчёта с выбранным тегом.
 *
 * Без отчёта ссылка ведёт к списку отчётов работы: назвать тег, не назвав
 * документ, в котором он лежит, нельзя — в соседнем отчёте тег с тем же ключом
 * означает другой текст.
 */
export function tagHref(projectId: string, key: string, report = ''): string {
  const экран = report ? `/reports/${projectId}/${report}` : `/reports/${projectId}`
  return `${экран}?tag=${encodeURIComponent(key)}`
}
