/**
 * bell — как открыть колокольчик снаружи.
 *
 * Страницы уведомлений нет, а ссылка «все» у виджета
 * дашборда вести куда-то обязана. Вести ей некуда, кроме самого колокольчика,
 * — значит виджету нужен способ его открыть.
 *
 * Способ — крошечная подписка на модуле, а не контекст: контекст потребовал бы
 * провайдера в `app/` (чужая область) ради одного булева состояния, которое
 * живёт в единственном экземпляре на всё приложение — колокольчик в шапке один.
 */
const слушатели = new Set<() => void>()

/** Подписаться (колокольчик). Возвращает отписку. */
export function onOpenBell(слушатель: () => void): () => void {
  слушатели.add(слушатель)
  return () => слушатели.delete(слушатель)
}

/** Открыть колокольчик (виджет дашборда). */
export function openBell(): void {
  for (const слушатель of слушатели) слушатель()
}
