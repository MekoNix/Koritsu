/**
 * order — порядок клеток дашборда и его память.
 *
 * Клетки переставляются рукой, поэтому порядок стал состоянием. Живёт он **в
 * браузере**, а не в профиле, и это решение, а не отсрочка: раскладка ленты —
 * свойство экрана, за которым человек сидит (на ноутбуке в один столбец, на
 * мониторе в три), а не свойство аккаунта. Хранилища для неё в службе нет и
 * заводить его незачем.
 *
 * Список клеток закрыт и лежит здесь же: «какие клетки бывают» и «в каком они
 * порядке» — одно знание, и разъехавшись, они дали бы сохранённый порядок,
 * который ссылается на клетку, которой уже нет.
 *
 * Правило склейки, из которого всё и следует: сохранённый порядок — это
 * **подсказка, а не договор**. Незнакомые имена из него выбрасываются
 * (клетку убрали выкатом), недостающие дописываются в конец на своё место по
 * умолчанию (клетку добавили). Поэтому обновление сайта не оставляет человека
 * ни с пустым дашбордом, ни без новой клетки.
 */

/** Имена клеток ленты в порядке по умолчанию. */
export const КЛЕТКИ = [
  'clock',
  'wordToPdf',
  'usage',
  'modules',
  'stats',
  'works',
  'notifications',
] as const

export type CellId = (typeof КЛЕТКИ)[number]

/**
 * Ширина клетки в сетке дашборда — двенадцать колонок на широком экране, шесть
 * на среднем, одна на узком. Ширина живёт здесь, а не внутри клетки: раскладка
 * ленты читается одним списком, и переставленная клетка обязана унести свою
 * ширину с собой.
 */
export const ШИРИНА: Record<CellId, string> = {
  clock: 'lg:col-span-3',
  wordToPdf: 'lg:col-span-3',
  usage: 'sm:col-span-6 lg:col-span-6',
  modules: 'sm:col-span-6 lg:col-span-12',
  stats: 'sm:col-span-6 lg:col-span-12',
  works: 'sm:col-span-6 lg:col-span-12',
  notifications: 'sm:col-span-6 lg:col-span-6',
}

/** Где помнится порядок. Ключ с приставкой: `localStorage` один на весь домен. */
const КЛЮЧ = 'koritsu.dashboard.order'

/** Склеить сохранённое с нынешним списком клеток. См. правило в шапке файла. */
export function склеить(сохранённое: readonly string[]): CellId[] {
  const известные = new Set<string>(КЛЕТКИ)
  const порядок: CellId[] = []
  for (const имя of сохранённое) {
    if (известные.has(имя) && !порядок.includes(имя as CellId)) порядок.push(имя as CellId)
  }
  for (const имя of КЛЕТКИ) if (!порядок.includes(имя)) порядок.push(имя)
  return порядок
}

export function прочитать(): CellId[] {
  try {
    const сырое = window.localStorage.getItem(КЛЮЧ)
    if (!сырое) return [...КЛЕТКИ]
    const разобранное: unknown = JSON.parse(сырое)
    if (!Array.isArray(разобранное)) return [...КЛЕТКИ]
    return склеить(разобранное.filter((x): x is string => typeof x === 'string'))
  } catch {
    // Приватный режим, запрет на хранилище, испорченная строка — не повод
    // показывать пустой дашборд. Без памяти он работает, просто раскладка
    // возвращается к умолчанию.
    return [...КЛЕТКИ]
  }
}

export function записать(порядок: readonly CellId[]): void {
  try {
    window.localStorage.setItem(КЛЮЧ, JSON.stringify(порядок))
  } catch {
    // См. `прочитать`: без хранилища порядок живёт до перезагрузки.
  }
}

/** Переставить клетку с места `откуда` на место `куда`. */
export function переставить(порядок: readonly CellId[], откуда: number, куда: number): CellId[] {
  const цель = Math.max(0, Math.min(порядок.length - 1, куда))
  if (откуда === цель || откуда < 0 || откуда >= порядок.length) return [...порядок]
  const новый = [...порядок]
  const клетка = новый.splice(откуда, 1)[0]
  if (!клетка) return [...порядок]
  новый.splice(цель, 0, клетка)
  return новый
}
