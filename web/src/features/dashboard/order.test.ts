/**
 * Порядок клеток дашборда: склейка сохранённого с нынешним списком.
 *
 * Проверяется ровно то, что ломается тихо и у человека, а не в сборке: старая
 * запись в браузере переживает выкат, в котором клетку добавили или убрали.
 * Ошибка здесь выглядит как «дашборд стал пустой» или «новой клетки нет», и
 * ни одна из них не оставляет следа в консоли.
 */
import { describe, expect, it } from 'vitest'

import { КЛЕТКИ, переставить, склеить, type CellId } from './order'

describe('склеить', () => {
  it('пустая память — порядок по умолчанию', () => {
    expect(склеить([])).toEqual([...КЛЕТКИ])
  })

  it('сохранённый порядок сохраняется', () => {
    const свой = [...КЛЕТКИ].reverse()
    expect(склеить(свой)).toEqual(свой)
  })

  it('незнакомое имя выбрасывается — клетку убрали выкатом', () => {
    expect(склеить(['такой-клетки-нет', ...КЛЕТКИ])).toEqual([...КЛЕТКИ])
  })

  it('повтор не удваивает клетку', () => {
    const склеенное = склеить(['clock', 'clock', 'usage'])
    expect(склеенное.filter((id) => id === 'clock')).toHaveLength(1)
    expect(склеенное).toHaveLength(КЛЕТКИ.length)
  })

  it('недостающая клетка дописывается — её добавили выкатом', () => {
    const старое = КЛЕТКИ.slice(0, 2)
    const склеенное = склеить(старое)
    expect(склеенное.slice(0, 2)).toEqual([...старое])
    expect(new Set(склеенное)).toEqual(new Set(КЛЕТКИ))
  })
})

describe('переставить', () => {
  const порядок = ['a', 'b', 'c', 'd'] as unknown as CellId[]

  it('двигает клетку на новое место', () => {
    expect(переставить(порядок, 0, 2)).toEqual(['b', 'c', 'a', 'd'])
    expect(переставить(порядок, 3, 0)).toEqual(['d', 'a', 'b', 'c'])
  })

  it('за край не уводит: цель прижимается к списку', () => {
    expect(переставить(порядок, 1, -5)).toEqual(['b', 'a', 'c', 'd'])
    expect(переставить(порядок, 1, 99)).toEqual(['a', 'c', 'd', 'b'])
  })

  it('на своё же место — список тот же', () => {
    expect(переставить(порядок, 2, 2)).toEqual([...порядок])
  })
})
