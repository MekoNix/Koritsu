/**
 * preset — какой моделью решают эту задачу, пока вкладка жива.
 *
 * Пресет выбирают при заведении решения, а прогон начинается позже — после
 * того, как человек подтвердит распознанное условие. Между этими двумя
 * событиями выбору надо где-то лежать, и лежит он в `sessionStorage`: службе он
 * не нужен (задание называет endpoint само), а переживать вкладку ему незачем.
 *
 * Помнится по **решению**, а не по работе: решений в ней несколько, и второе
 * заводят другой моделью не реже, чем той же.
 *
 * Отдельным файлом, а не строчкой в странице: страницы этим пользуются две, а
 * `sessionStorage` в приватном окне бросает — оборачивать его в двух местах
 * значило бы однажды забыть про одно из них.
 */
const КЛЮЧ = 'kadai.endpoint.'

export function запомнить(runId: string, endpoint: string): void {
  try {
    sessionStorage.setItem(КЛЮЧ + runId, endpoint)
  } catch {
    /* приватное окно: пресет просто не запомнится */
  }
}

export function запомненный(runId: string): string | null {
  try {
    return sessionStorage.getItem(КЛЮЧ + runId)
  } catch {
    return null
  }
}
