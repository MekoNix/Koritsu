/**
 * pdfBlocks — счётная часть просмотрщика с областями блоков.
 *
 * Собранный документ несёт адреса блоков: при сборке на первый абзац каждого
 * блока ставится закладка `blk-<ключ>`, и в PDF она выходит именованным
 * назначением. Назначение — это точка, а не прямоугольник: страница и высота на
 * ней. Где блок кончается, в документе не записано нигде, и узнать это можно
 * единственным способом — по началу следующего блока.
 *
 * Отдельным файлом без React и без pdf.js: здесь только счёт, и ошибается он
 * молча — область, съехавшая на полстраницы, выглядит как обычная область, а
 * замечание уезжает не к тому блоку.
 *
 * Доли, а не пиксели. Масштаб просмотрщика меняется сколько угодно раз, а
 * область блока считается один раз: доля высоты страницы переживает и масштаб,
 * и разворот колонки, и другой экран.
 */

/**
 * Приставка имени закладки блока в собранном документе.
 *
 * Своя приставка нужна затем, что в документе есть и другие закладки — подписи
 * рисунков и таблиц ставят свои, — и отличать блоки от них по чему-то, кроме
 * имени, негде.
 */
const ПРИСТАВКА = 'blk'

/**
 * Имя закладки блока: `blk` плюс ключ, где всё, кроме латинских букв и цифр,
 * закодировано.
 *
 * Дефиса и подчёркивания в имени быть не может, хотя ключи блоков ими полны
 * (`b-01`): Word выбрасывает из имени закладки дефис молча, а LibreOffice при
 * выкладке в PDF кодирует всё, кроме букв и цифр, и никакого знака, по которому
 * кодировку видно, не ставит. Имя, собранное «как есть», доехало бы до
 * просмотрщика чужим — и без пары к ключу блока.
 *
 * Поэтому кодировка своя и обратимая: латинская буква или цифра идёт как есть,
 * любой другой знак — по байтам UTF-8, каждый байт `X` и две шестнадцатеричные
 * заглавные. Заглавная `X` кодируется тоже (`X58`), иначе её нельзя было бы
 * отличить от начала кода.
 *
 * Форму задаёт сборка документа (`hokoku.live.bookmark_name`); здесь её вторая
 * половина, и обе должны читать одно и то же.
 */
export function bookmarkName(key: string): string {
  let имя = ПРИСТАВКА
  for (const знак of key) {
    if (знак !== 'X' && /^[0-9A-Za-z]$/.test(знак)) {
      имя += знак
      continue
    }
    for (const байт of new TextEncoder().encode(знак)) {
      имя += `X${байт.toString(16).toUpperCase().padStart(2, '0')}`
    }
  }
  return имя
}

/**
 * Ключ блока по имени закладки; не закладка блока — `null`.
 *
 * Разбор живёт одной функцией намеренно: форму имени задаёт сборка документа, и
 * когда она станет другой, поправить придётся здесь и больше нигде.
 *
 * Отказ обязателен и важнее разбора: в документе полно чужих назначений —
 * закладки подписей, оглавление, ссылки Word, — и имя, разобранное «как
 * получится», дало бы область блока, которого нет.
 */
export function keyOfBookmark(name: string): string | null {
  if (!name.startsWith(ПРИСТАВКА)) return null
  const байты: number[] = []
  let i = ПРИСТАВКА.length
  while (i < name.length) {
    const знак = name[i] as string
    if (знак === 'X') {
      // Заглавные шестнадцатеричные и строчные: пишет их сборка заглавными, но
      // имя проходит через Word и LibreOffice, и регистр в коде знака — не то,
      // на чём стоит терять блок.
      const код = name.slice(i + 1, i + 3)
      if (!/^[0-9A-Fa-f]{2}$/.test(код)) return null
      байты.push(parseInt(код, 16))
      i += 3
      continue
    }
    if (!/^[0-9A-Za-z]$/.test(знак)) return null
    байты.push(знак.charCodeAt(0))
    i += 1
  }
  if (байты.length === 0) return null
  try {
    return new TextDecoder('utf-8', { fatal: true }).decode(new Uint8Array(байты)) || null
  } catch {
    return null
  }
}

/** Якорь блока: страница (с нуля) и доля высоты страницы сверху. */
export type Anchor = { key: string; page: number; top: number }

/** Область блока на одной странице: доли высоты страницы сверху. */
export type Area = { key: string; page: number; top: number; bottom: number }

/**
 * Координата `y` назначения в единицах PDF; `null` — точки нет.
 *
 * Видов назначений в PDF несколько, и высота у каждого лежит в своём месте:
 * `/XYZ` — левый верхний угол с приближением, `/FitH` — только высота, `/FitR` —
 * прямоугольник. Виды без точки (`/Fit`, «вся страница») дают `null`: якорь
 * такого блока встаёт на верх страницы, и это правда, а не заглушка.
 *
 * У `/XYZ` высота бывает пустой — это «оставить как есть», и точки в ней тоже
 * нет.
 */
export function destY(dest: unknown): number | null {
  if (!Array.isArray(dest)) return null
  const вид = (dest[1] as { name?: unknown } | null | undefined)?.name
  if (вид === 'XYZ') return число(dest[3])
  if (вид === 'FitH' || вид === 'FitBH') return число(dest[2])
  if (вид === 'FitR') return число(dest[5])
  return null
}

function число(это: unknown): number | null {
  return typeof это === 'number' && Number.isFinite(это) ? это : null
}

/**
 * Области блоков по их якорям.
 *
 * Блок тянется от своего якоря до якоря следующего блока по порядку документа;
 * последний — до конца документа. Порядок берётся из самих якорей (страница,
 * потом высота), а не из списка блоков: список на экране бывает новее собранного
 * PDF, и порядок из него расставил бы границы по документу, которого ещё нет.
 *
 * Блок, начавшийся на одной странице и кончившийся на другой, даёт несколько
 * областей — по одной на страницу. Одним прямоугольником через разрыв страницы
 * его нарисовать нельзя: между страницами лежат поля, колонтитул и край
 * соседней, и рамка поверх них означала бы, что блок занимает и их.
 *
 * Пустые области (следующий блок начинается там же, где кончился этот)
 * отбрасываются: невидимая рамка в ноль пикселей ловит клики соседей.
 */
export function blockAreas(anchors: Anchor[], pages: number): Area[] {
  if (pages <= 0) return []
  const порядок = [...anchors]
    .filter((я) => я.page >= 0 && я.page < pages)
    .sort((а, б) => а.page - б.page || а.top - б.top)
  const области: Area[] = []
  порядок.forEach((якорь, i) => {
    const следом = порядок[i + 1]
    const край = следом ?? { page: pages - 1, top: 1 }
    const последняя = Math.min(край.page, pages - 1)
    for (let стр = якорь.page; стр <= последняя; стр++) {
      const верх = стр === якорь.page ? доля(якорь.top) : 0
      const низ = стр === край.page ? доля(край.top) : 1
      if (низ - верх > 0.002) области.push({ key: якорь.key, page: стр, top: верх, bottom: низ })
    }
  })
  return области
}

function доля(это: number): number {
  if (!Number.isFinite(это)) return 0
  return Math.min(1, Math.max(0, это))
}
