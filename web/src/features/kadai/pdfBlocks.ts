/**
 * pdfBlocks — имя закладки блока в собранном документе.
 *
 * Собранный документ несёт адреса блоков: при сборке на первый абзац каждого
 * блока ставится закладка `blk-<ключ>`, и в PDF она выходит именованным
 * назначением. По этому имени встроенный просмотрщик браузера и переходит к
 * блоку — `…?inline=1#nameddest=<имя>`.
 *
 * Отдельным файлом без React: здесь только счёт по строке, и ошибается он
 * молча — имя, собранное чужой формой, просто не находит назначения, и переход
 * к блоку выглядит как «ничего не произошло».
 */

/**
 * Приставка имени закладки блока в собранном документе.
 *
 * Своя приставка нужна затем, что в документе есть и другие закладки — подписи
 * рисунков и таблиц ставят свои, — и отличать блоки от них по чему-то, кроме
 * имени, негде.
 */
const ПРИСТАВКА = 'blk'

/**
 * Имя закладки блока: `blk` плюс ключ, где всё, кроме латинских букв и цифр,
 * закодировано.
 *
 * Дефиса и подчёркивания в имени быть не может, хотя ключи блоков ими полны
 * (`b-01`): Word выбрасывает из имени закладки дефис молча, а LibreOffice при
 * выкладке в PDF кодирует всё, кроме букв и цифр, и никакого знака, по которому
 * кодировку видно, не ставит. Имя, собранное «как есть», доехало бы до
 * просмотрщика чужим — и без пары к ключу блока.
 *
 * Поэтому кодировка своя и обратимая: латинская буква или цифра идёт как есть,
 * любой другой знак — по байтам UTF-8, каждый байт `X` и две шестнадцатеричные
 * заглавные. Заглавная `X` кодируется тоже (`X58`), иначе её нельзя было бы
 * отличить от начала кода.
 *
 * Форму задаёт сборка документа (`hokoku.live.bookmark_name`); здесь её вторая
 * половина, и обе должны читать одно и то же.
 */
export function bookmarkName(key: string): string {
  let имя = ПРИСТАВКА
  for (const знак of key) {
    if (знак !== 'X' && /^[0-9A-Za-z]$/.test(знак)) {
      имя += знак
      continue
    }
    for (const байт of new TextEncoder().encode(знак)) {
      имя += `X${байт.toString(16).toUpperCase().padStart(2, '0')}`
    }
  }
  return имя
}
