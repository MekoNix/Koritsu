/** Флаги в порядке строки `DocEntry.flags`. */
export const FLAG_NAMES = ['OF', 'DF', 'IF', 'SF', 'ZF', 'AF', 'PF', 'CF'] as const

const list: DocEntry[] = []

function add(e: Omit<DocEntry, 'errs' | 'see' | 'kw'> & Partial<Pick<DocEntry, 'errs' | 'see' | 'kw'>>) {
  list.push({
    ...e,
    // Пустой пример и пустой синтаксис — это «нет», а не блок без строк.
    ex: e.ex || undefined,
    syntax: e.syntax || undefined,
    errs: e.errs ?? [],
    see: e.see ?? [],
    kw: e.kw ?? '',
  })
}

/* ── инструкции ───────────────────────────────────────────── */

function C(
  names: string,
  short: string,
  syntax: string,
  flags: string,
  desc: string,
  ex: string,
  errs: string[],
  see: string[],
  kw: string,
) {
  const a = names.split(' ')
  add({ id: `cmd-${a[0]}`, sec: 'cmd', name: a.join(' / '), alias: a, short, syntax, flags, desc, ex, errs, see, kw })
}

