/**
 * entries — записи справки режима TASM: инструкции 8086, функции DOS и BIOS,
 * регистры и флаги, директивы TASM, адресация, команды DebugX. Здесь же тип
 * записи и разделы, общие для всех наборов: справка режима MinGW x64 лежит в
 * `entries64.ts`, окно получает набор из описателя режима (`toolchain.docs()`).
 *
 * Тексты записей — содержимое, а не подписи интерфейса, поэтому живут здесь, а
 * не в словаре i18n: у записи десяток связанных полей, и разнесённые по ключам
 * они расходились бы между собой при первой правке.
 *
 * Записи собираются короткими построителями по разделам (`cmd`, `dos`, …): у
 * всех условных переходов одна и та же частая ошибка, у всех функций DOS —
 * одинаковый синтаксис вызова, и повторять их руками значит однажды поправить
 * в одном месте из двадцати.
 *
 * Порядок записей важен: он же порядок в списке, и по нему же решается, чей
 * псевдоним главнее (`lookup.ts` берёт первую запись с таким именем — `di`
 * остаётся регистром, а не мнемоникой флага IF).
 */

/**
 * Раздел записи. TASM: `cmd dos bios reg dir addr dbg`; MinGW x64: `cmd reg addr
 * gas conv api build pitfall att`. Окно показывает только разделы, в которых у
 * набора есть записи.
 */
export type DocSection =
  | 'cmd'
  | 'dos'
  | 'bios'
  | 'reg'
  | 'dir'
  | 'addr'
  | 'gas'
  | 'conv'
  | 'api'
  | 'build'
  | 'pitfall'
  | 'att'
  | 'dbg'

/** Регистр или ячейка и что в ней: строка таблицы «Вход» / «Выход». */
export type DocIoRow = readonly [where: string, what: string]

export interface DocEntry {
  /** Постоянный идентификатор: `cmd-mov`, `dos-09`, `flag-zf`. Его ждёт якорь `{kind:'doc', id}`. */
  id: string
  sec: DocSection
  /** Заголовок карточки: `je / jz`, `int 21h · 09h`. */
  name: string
  /** Имена, по которым запись находится из кода: мнемоники, регистры, `21h/09h`. */
  alias: string[]
  /** Строка под заголовком. */
  short: string
  syntax?: string
  /**
   * Действие на флаги в порядке `OF DF IF SF ZF AF PF CF`, по знаку на флаг:
   * `-` не меняется, `*` по результату, `0`/`1` всегда это значение, `?` не определён.
   */
  flags?: string
  /** Описание; `код` в обратных кавычках показывается моноширинным. */
  desc: string
  /** Вход и выход функции прерывания. */
  io?: { in: DocIoRow[]; out: DocIoRow[] }
  ex?: string
  /** Частые ошибки. */
  errs: string[]
  /** «См. также»: id записи или любой токен, понятный `lookup`. */
  see: string[]
  /** Слова для поиска, которых нет в тексте. */
  kw: string
}

