/**
 * AuthBackdrop — фон левой половины страниц входа: изолинии, как горизонтали
 * на топографической карте, медленно перетекающие друг в друга.
 *
 * Почему изолинии. Фон входа не должен ничего обещать и ни с чем спорить:
 * человек пришёл к форме, а не к картинке. Замкнутые плавные контуры
 * читаются как рельеф — спокойный, без предмета, — и не тянут взгляд от
 * полей. Скриншот экрана устарел бы к следующей версии, а сетка узлов
 * рассказывала про схемы то, чего страница входа рассказывать не обязана.
 *
 * **Как построено.** Два «холма»: у каждого свой центр и набор вложенных
 * контуров с растущим радиусом. Контур — окружность, радиус которой по углу
 * качается суммой трёх синусоид; вложенные контуры одного холма делят одни
 * и те же синусоиды, поэтому не пересекаются — качание растёт вместе с
 * радиусом, а не обгоняет его. Холмы расставлены так, чтобы их крайние
 * контуры не доставали друг до друга: горизонтали на карте не пересекаются
 * никогда. Точки соединены кубическими Безье через Catmull-Rom, так что
 * углов нет и при трёх десятках опорных точек.
 *
 * **Без зависимостей.** Один `<svg>`, пути считаются один раз при загрузке
 * модуля, движение — правила `@keyframes` в `styles/index.css`: анимация
 * библиотекой стоила бы сотню килобайт на странице, которую видят один раз.
 *
 * **Цвет — из темы.** Линии рисуются `currentColor` от `text-accent`,
 * прозрачность держит их позади формы, а не поверх неё; в каждой теме и в
 * светлом с тёмным фон свой.
 *
 * **Движение уважает «поменьше движения».** Каждый контур медленно
 * поворачивается и чуть смещается вокруг центра своего холма, соседние — с
 * разным периодом, фазой и направлением, отчего линии текут одна
 * относительно другой. Остановленный рисунок закончен: правило
 * `prefers-reduced-motion` (`styles/index.css`) гасит анимацию, и остаётся
 * просто карта.
 *
 * **Форме не мешает.** Лежит `absolute inset-0` за содержимым, помечен
 * `aria-hidden`: для скринридера картинки здесь нет.
 */

type Точка = { x: number; y: number }

/** Холм: центр в системе координат 0..100, радиусы контуров и три качания
 *  радиуса — (частота, амплитуда в долях радиуса, фаза). */
type Холм = {
  cx: number
  cy: number
  радиусы: readonly number[]
  волны: readonly (readonly [number, number, number])[]
}

const ХОЛМЫ: readonly Холм[] = [
  {
    cx: 30,
    cy: 72,
    радиусы: [5, 10, 15.5, 21, 27, 33, 39.5],
    волны: [
      [2, 0.11, 0.6],
      [3, 0.07, 2.1],
      [5, 0.035, 4.0],
    ],
  },
  {
    cx: 82,
    cy: 16,
    радиусы: [4, 8.5, 13.5, 19, 24.5],
    волны: [
      [2, 0.09, 3.3],
      [3, 0.06, 0.9],
      [4, 0.04, 5.2],
    ],
  },
]

/** Опорных точек на контуре: хватает, чтобы волна пятой частоты не срезалась. */
const ТОЧЕК = 36

function радиус(холм: Холм, базовый: number, угол: number): number {
  let r = базовый
  for (const [частота, амплитуда, фаза] of холм.волны) {
    r += базовый * амплитуда * Math.sin(частота * угол + фаза)
  }
  // Контуры чуть вытянуты по диагонали — склон, а не круг.
  return r * (1 + 0.08 * Math.cos(угол - 0.7))
}

function опорные(холм: Холм, базовый: number): Точка[] {
  const точки: Точка[] = []
  for (let i = 0; i < ТОЧЕК; i++) {
    const угол = (i / ТОЧЕК) * Math.PI * 2
    const r = радиус(холм, базовый, угол)
    точки.push({ x: холм.cx + r * Math.cos(угол), y: холм.cy + r * Math.sin(угол) })
  }
  return точки
}

/** Замкнутый путь по точкам: Catmull-Rom → кубические Безье. */
function путь(точки: Точка[]): string {
  const n = точки.length
  const f = (v: number) => v.toFixed(2)
  const первая = точки[0]!
  let d = `M${f(первая.x)} ${f(первая.y)}`
  for (let i = 0; i < n; i++) {
    const p0 = точки[(i - 1 + n) % n]!
    const p1 = точки[i]!
    const p2 = точки[(i + 1) % n]!
    const p3 = точки[(i + 2) % n]!
    const c1 = { x: p1.x + (p2.x - p0.x) / 6, y: p1.y + (p2.y - p0.y) / 6 }
    const c2 = { x: p2.x - (p3.x - p1.x) / 6, y: p2.y - (p3.y - p1.y) / 6 }
    d += ` C${f(c1.x)} ${f(c1.y)} ${f(c2.x)} ${f(c2.y)} ${f(p2.x)} ${f(p2.y)}`
  }
  return `${d} Z`
}

const КОНТУРЫ = ХОЛМЫ.flatMap((холм, номерХолма) =>
  холм.радиусы.map((базовый, номер) => ({
    key: `${номерХолма}-${номер}`,
    d: путь(опорные(холм, базовый)),
    cx: холм.cx,
    cy: холм.cy,
    // Внутренние линии чуть заметнее: вершина холма читается первой.
    opacity: 0.32 - номер * 0.03,
    // Период, фаза и направление свои у каждой линии — соседние текут вразнобой.
    длительность: 38 + номер * 7 + номерХолма * 5,
    задержка: -(номер * 9 + номерХолма * 13),
    направление: номер % 2 === 0 ? 'normal' : 'reverse',
  })),
)

export function AuthBackdrop() {
  return (
    <svg
      aria-hidden="true"
      className="pointer-events-none absolute inset-0 h-full w-full text-accent"
      viewBox="0 0 100 100"
      preserveAspectRatio="xMidYMid slice"
      fill="none"
      stroke="currentColor"
      strokeWidth="0.32"
      strokeLinejoin="round"
    >
      {КОНТУРЫ.map((к) => (
        <path
          key={к.key}
          className="auth-contour"
          d={к.d}
          opacity={к.opacity}
          style={{
            transformOrigin: `${к.cx}px ${к.cy}px`,
            animationDuration: `${к.длительность}s`,
            animationDelay: `${к.задержка}s`,
            animationDirection: к.направление,
          }}
        />
      ))}
    </svg>
  )
}
