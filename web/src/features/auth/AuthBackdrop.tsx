/**
 * AuthBackdrop — фон левой половины страниц входа: медленно плывущая сетка
 * узлов со связями.
 *
 * Что нарисовано и почему именно это. Всё, что делает служба, — это узлы и
 * связи между ними: блок-схема из кода, диаграмма классов, дерево разделов
 * документа. Рисунок на входе показывает ровно это и ничего не обещает сверх:
 * ни скриншота экрана, который завтра поменяется, ни абстрактных пятен.
 *
 * **Без зависимостей.** Один `<svg>` и несколько правил `@keyframes`
 * (`styles/index.css`): анимация библиотекой стоила бы сотню килобайт на
 * странице, которую человек видит один раз и с неё уходит.
 *
 * **Цвет — из темы.** Ни одного своего значения: линии рисуются
 * `currentColor` от `text-accent`, поэтому в каждой теме и в светлом с тёмным
 * фон свой, а прозрачность держит его позади формы, а не поверх неё.
 *
 * **Движение уважает «поменьше движения».** Правило `prefers-reduced-motion`
 * гасит анимации во всём сайте (`styles/index.css`), и рисунок сделан так,
 * чтобы остановленным он выглядел законченным: движение — это медленное
 * дыхание уже собранной сетки, а не сборка её из ничего.
 *
 * **Форме он не мешает.** Лежит `absolute inset-0` в левой половине, за
 * содержимым, и помечен `aria-hidden`: для скринридера картинки здесь нет.
 */

/** Узлы сетки в системе координат 0..100 по обеим осям. */
const УЗЛЫ = [
  { x: 18, y: 14 },
  { x: 52, y: 8 },
  { x: 84, y: 20 },
  { x: 12, y: 44 },
  { x: 46, y: 38 },
  { x: 78, y: 52 },
  { x: 26, y: 70 },
  { x: 60, y: 66 },
  { x: 88, y: 84 },
  { x: 38, y: 92 },
] as const

/** Связи парами номеров узлов. Дерево с парой возвратов — как в разборе кода. */
const СВЯЗИ = [
  [0, 1],
  [1, 2],
  [0, 3],
  [1, 4],
  [2, 5],
  [3, 4],
  [4, 5],
  [3, 6],
  [4, 7],
  [5, 8],
  [6, 7],
  [7, 9],
  [7, 8],
  [6, 9],
] as const

export function AuthBackdrop() {
  return (
    <svg
      aria-hidden="true"
      className="pointer-events-none absolute inset-0 h-full w-full text-accent"
      viewBox="0 0 100 100"
      preserveAspectRatio="xMidYMid slice"
    >
      {/* Три слоя с разной скоростью: ближний движется заметнее дальнего, и
          сетка перестаёт читаться как одна плоская картинка. */}
      <g className="auth-drift auth-drift-slow" opacity="0.14">
        {СВЯЗИ.map(([от, до]) => {
          const a = УЗЛЫ[от] as { x: number; y: number }
          const b = УЗЛЫ[до] as { x: number; y: number }
          return (
            <line
              key={`${от}-${до}`}
              x1={a.x}
              y1={a.y}
              x2={b.x}
              y2={b.y}
              stroke="currentColor"
              strokeWidth="0.35"
            />
          )
        })}
      </g>

      <g className="auth-drift" opacity="0.22">
        {УЗЛЫ.map((узел, номер) => (
          <circle
            key={номер}
            cx={узел.x}
            cy={узел.y}
            r={номер % 3 === 0 ? 1.6 : 1.05}
            fill="currentColor"
          />
        ))}
      </g>

      {/* Контур блок-схемы поверх сетки: прямоугольник, ромб и связь между
          ними — то, что служба и рисует. Штрих бежит по контуру, поэтому
          движение видно даже там, где узлы почти неподвижны. */}
      <g className="auth-trace" opacity="0.3" stroke="currentColor" fill="none">
        <rect x="30" y="26" width="26" height="11" rx="1.5" strokeWidth="0.4" />
        <path d="M43 37 L43 48" strokeWidth="0.4" />
        <path d="M43 48 L54 56 L43 64 L32 56 Z" strokeWidth="0.4" />
        <path d="M54 56 L70 56 L70 44" strokeWidth="0.4" />
      </g>
    </svg>
  )
}
