/**
 * Запас координат слева и сверху от левого верхнего угла пачки.
 *
 * Точки уезжают не абсолютными: координаты сцены бывают и отрицательными, и
 * шестизначными, а распознавателю нужна страница. Сдвиг при этом **один на всю
 * пачку**, а не свой у каждой строки: вся пачка уезжает одним вызовом сервиса,
 * и строки, сдвинутые каждая в свой угол, легли бы там одна на другую — сервис
 * склеил бы их в одну запись и вернул кашу.
 */
const ЗАПАС = 20

/** Точность координат в теле запроса. Дальше — шум пера, а вес тела растёт. */
const ЗНАКОВ = 2

/* ── группировка ─────────────────────────────────────────────────────────── */

/**
 * Доля меньшей высоты, на которую полосы должны перекрываться по вертикали,
 * чтобы росчерки считались одной строкой.
 *
 * Меньшей, а не большей: точка над «i», запятая и знак минус — росчерки почти
 * нулевой высоты, и по большей высоте они не попадали бы в свою строку никогда.
 */
const ПЕРЕКРЫТИЕ = 0.4

/** Во сколько высот строки укладывается зазор между соседями по горизонтали. */
const ЗАЗОР = 1.5

/** Росчерк, разобранный до точек и габарита. */
type Росчерк = {
  id: string
  /** Место в массиве элементов: им же определяется якорь строки. */
  индекс: number
  точки: [number, number][]
  box: Box
}

/**
 * Росчерки, которые идут в распознавание.
 *
 * Только `freedraw` и только не удалённые: текст, рамки и картинки на доске —
 * не рукопись. Помеченное `customData.agent` пропускается на будущее: то, что
 * на доску кладёт репетитор, распознавать незачем — он это и написал.
 */
export function inkElements(elements: readonly SceneElement[]): SceneElement[] {
  return elements.filter(
    (э) => э?.type === 'freedraw' && !э.isDeleted && !(э.customData as { agent?: unknown })?.agent,
  )
}

/** Габарит по точкам, а не по `x/width` элемента: у `freedraw` они расходятся. */
function габарит(точки: readonly [number, number][]): Box {
  let слева = Infinity
  let сверху = Infinity
  let справа = -Infinity
  let снизу = -Infinity
  for (const [x, y] of точки) {
    if (x < слева) слева = x
    if (x > справа) справа = x
    if (y < сверху) сверху = y
    if (y > снизу) снизу = y
  }
  if (!Number.isFinite(слева)) return { x: 0, y: 0, width: 0, height: 0 }
  return { x: слева, y: сверху, width: справа - слева, height: снизу - сверху }
}

/** Габарит двух габаритов. */
function объединить(а: Box, б: Box): Box {
  const слева = Math.min(а.x, б.x)
  const сверху = Math.min(а.y, б.y)
  const справа = Math.max(а.x + а.width, б.x + б.width)
  const снизу = Math.max(а.y + а.height, б.y + б.height)
  return { x: слева, y: сверху, width: справа - слева, height: снизу - сверху }
}

/**
 * Одна ли это строка: правило целиком.
 *
 * Перекрытие по вертикали — не меньше 40 % меньшей высоты; зазор по горизонтали
 * — не больше полутора **бо́льших** высот. Большая высота потому, что зазор
 * меряется в строках, а строка — это высота письма, а не высота запятой.
 */
export function sameLine(а: Box, б: Box): boolean {
  const перекрытие = Math.min(а.y + а.height, б.y + б.height) - Math.max(а.y, б.y)
  if (перекрытие < ПЕРЕКРЫТИЕ * Math.min(а.height, б.height)) return false
  const зазор = Math.max(а.x, б.x) - Math.min(а.x + а.width, б.x + б.width)
  return зазор <= ЗАЗОР * Math.max(а.height, б.height)
}

/**
 * Строки сцены: росчерки, сведённые в группы, сверху вниз.
 *
 * Сведение идёт в два захода, и это не перестраховка. Первый — по парам
 * росчерков: он даёт связность (два конца длинной строки не соседи друг другу,
 * но связаны цепочкой через середину). Второй — по уже сложившимся группам:
 * после первого захода их единицы, а зазор, который у двух запятых меряется
 * высотой запятой, у сложившейся строки меряется высотой строки — и хвост,
 * отколовшийся на первом заходе, прирастает на втором.
 */
export function sceneLines(elements: readonly SceneElement[]): SceneLine[] {
  const росчерки: Росчерк[] = []
  inkElements(elements).forEach((э) => {
    const точки = absolutePoints(э)
    if (точки.length === 0) return
    росчерки.push({ id: э.id, индекс: росчерки.length, точки, box: габарит(точки) })
  })
  if (росчерки.length === 0) return []

  // Заход первый: система непересекающихся множеств по парам росчерков.
  const корень = росчерки.map((_, и) => и)
  const найти = (и: number): number => {
    let к = и
    while (корень[к] !== к) к = корень[к] as number
    // Сжатие пути: без него цепочка из сотни росчерков одной строки
    // превращается в сотню шагов на каждом обращении.
    let шаг = и
    while (корень[шаг] !== к) {
      const дальше = корень[шаг] as number
      корень[шаг] = к
      шаг = дальше
    }
    return к
  }
  for (let и = 0; и < росчерки.length; и++) {
    for (let ж = и + 1; ж < росчерки.length; ж++) {
      const а = росчерки[и] as Росчерк
      const б = росчерки[ж] as Росчерк
      if (!sameLine(а.box, б.box)) continue
      const ка = найти(и)
      const кб = найти(ж)
      if (ка !== кб) корень[кб] = ка
    }
  }

  const поКорню = new Map<number, Росчерк[]>()
  росчерки.forEach((р, и) => {
    const к = найти(и)
    const свои = поКорню.get(к)
    if (свои) свои.push(р)
    else поКорню.set(к, [р])
  })

  // Заход второй: те же правила, но уже между группами, до неподвижности.
  let группы = [...поКорню.values()].map((свои) => ({
    свои,
    box: свои.map((р) => р.box).reduce(объединить),
  }))
  for (let слито = true; слито;) {
    слито = false
    поиск: for (let и = 0; и < группы.length; и++) {
      for (let ж = и + 1; ж < группы.length; ж++) {
        const а = группы[и] as (typeof группы)[number]
        const б = группы[ж] as (typeof группы)[number]
        if (!sameLine(а.box, б.box)) continue
        а.свои = [...а.свои, ...б.свои]
        а.box = объединить(а.box, б.box)
        группы = группы.filter((_, к) => к !== ж)
        слито = true
        break поиск
      }
    }
  }

  const строки = группы.map(({ свои, box }) => {
    const порядок = [...свои].sort((а, б) => а.индекс - б.индекс)
    return {
      // Якорь — самый ранний росчерк группы: он переживает и дорисовывание, и
      // перенос строки, и потому годится идентификатором на всю её жизнь.
      id: (порядок[0] as Росчерк).id,
      strokes: порядок.map((р) => р.id),
      box,
      fingerprint: fingerprint(порядок, box),
    }
  })
  // Порядок чтения — сверху вниз, при равной высоте слева направо. Он же
  // порядок, в котором строки уезжают агенту: дописанная сверху строка встаёт
  // на своё место, а не в конец, как было бы по времени письма.
  строки.sort((а, б) => (Math.abs(а.box.y - б.box.y) > 1 ? а.box.y - б.box.y : а.box.x - б.box.x))
  // Короткие имена раздаются в порядке чтения — это и делает их устойчивыми:
  // при столкновении имя удлиняется, и от того, кого встретили первым, зависит,
  // кому достанется короткое.
  const занятые = new Map<string, string>()
  return строки.map((с) => ({ ...с, step: shortId(с.id, занятые) }))
}

/* ── отпечаток ───────────────────────────────────────────────────────────── */

/** Точность округления точек в отпечатке: десятая пикселя. */
const ШАГ = 10

/**
 * Отпечаток группы: свёртка точек относительно габарита плюс список росчерков.
 *
 * Точки берутся **относительно** левого верхнего угла габарита группы — оттого
 * перенос строки целиком отпечатка не меняет, и подвинутая на полях формула не
 * распознаётся заново. Округление до десятой пикселя убирает дрожь двоичной
 * арифметики после вычитания; для рукописи это заведомо мельче пера.
 *
 * Идентификаторы росчерков входят в отпечаток наравне с точками: стёртый и тут
 * же нарисованный в том же месте росчерк — это другая строка, и распознать её
 * надо заново.
 */
export function fingerprint(
  штрихи: readonly { id: string; точки: readonly [number, number][] }[],
  box: Box,
): string {
  const части: string[] = []
  for (const штрих of штрихи) {
    const точки: string[] = []
    for (const [x, y] of штрих.точки) {
      точки.push(`${Math.round((x - box.x) * ШАГ) / ШАГ},${Math.round((y - box.y) * ШАГ) / ШАГ}`)
    }
    части.push(`${штрих.id}:${точки.join(';')}`)
  }
  return свёртка(части.join('|'))
}

/**
 * FNV-1a двумя разными началами — шестнадцать шестнадцатеричных знаков.
 *
 * Два прохода, а не один: у 32 бит на доске в сотню строк совпадения пришлось
 * бы ждать всерьёз, а два независимых начала дают 64 бита при той же цене.
 */
function свёртка(текст: string): string {
  let а = 0x811c9dc5
  let б = 0x01000193
  for (let и = 0; и < текст.length; и++) {
    const код = текст.charCodeAt(и)
    а = Math.imul(а ^ код, 0x01000193) >>> 0
    б = Math.imul(б ^ код, 0x85ebca6b) >>> 0
  }
  return а.toString(16).padStart(8, '0') + б.toString(16).padStart(8, '0')
}

/* ── грязные строки ──────────────────────────────────────────────────────── */

/**
 * Строки, распознанное по которым отстало от росчерков.
 *
 * `manual` не грязна никогда: набранное руками росчерки не перезаписывают.
 * Отпечаток у такой строки намеренно остаётся прежним — расхождение с текущим и
 * есть пометка «росчерки изменились, набранное могло устареть» (`FairLine.behind`).
 */
export function dirtyLines(lines: readonly SceneLine[], cache: RecognizedCache): SceneLine[] {
  return lines.filter((строка) => {
    const запись = cache[строка.id]
    if (!запись) return true
    if (запись.state === LINE_STATES.manual) return false
    return запись.fingerprint !== строка.fingerprint
  })
}

/* ── тело запроса ────────────────────────────────────────────────────────── */

/** Равномерно проредить точки до потолка, сохранив первую и последнюю. */
function проредить(точки: readonly [number, number][]): [number, number][] {
  if (точки.length <= POINTS_PER_LINE) return [...точки]
  const шаг = Math.ceil(точки.length / POINTS_PER_LINE)
  const взято: [number, number][] = []
  for (let и = 0; и < точки.length; и += шаг) взято.push(точки[и] as [number, number])
  const последняя = точки[точки.length - 1] as [number, number]
  if (взято[взято.length - 1] !== последняя) взято.push(последняя)
  return взято
}

function округлить(значение: number): number {
  const множитель = 10 ** ЗНАКОВ
  return Math.round(значение * множитель) / множитель
}

/**
 * Тела запросов на список строк — по одному на каждые восемь строк.
 *
 * Обычно тело одно: грязных строк на паузе пера бывает одна-две. Восемь —
 * потолок службы, и разрезает пачку сайт, а не она: иначе правка, задевшая
 * девять строк, получала бы отказ вместо распознавания.
 *
 * **Сдвиг координат — один на всю пачку.** Вся пачка уезжает сервису одним
 * вызовом, и если сдвинуть каждую строку к своему началу, они лягут там одна на
 * другую в одной точке: сервис увидит не пять строк, а пять записей друг поверх
 * друга, и вернёт кашу. Поэтому за начало берётся левый верхний угол габарита
 * **всех** отправляемых строк, и взаимное расположение строк доезжает целым.
 *
 * Времени в сцене нет вовсе, поэтому `t` — номер точки. Так же поступает и
 * библиотека распознавания, когда времени ей не передали: для математики важна
 * форма, а не скорость письма.
 */
export function recognizeBodies(
  elements: readonly SceneElement[],
  lines: readonly SceneLine[],
  dpi = 96,
): RecognizeIn[] {
  const поId = new Map(inkElements(elements).map((э) => [э.id, э]))
  const тела: RecognizeIn[] = []
  for (let и = 0; и < lines.length; и += LINES_PER_CALL) {
    const кусок = lines.slice(и, и + LINES_PER_CALL)
    const общий = кусок.map((с) => с.box).reduce(объединить)
    const пачка: RecognizeLineIn[] = []
    for (const строка of кусок) {
      const штрихи: InkStrokeIn[] = []
      for (const id of строка.strokes) {
        const элемент = поId.get(id)
        if (!элемент) continue
        const точки = проредить(absolutePoints(элемент))
        if (точки.length < 2) continue
        штрихи.push({
          x: точки.map(([x]) => округлить(x - общий.x + ЗАПАС)),
          y: точки.map(([, y]) => округлить(y - общий.y + ЗАПАС)),
          t: точки.map((_, н) => н),
        })
      }
      if (штрихи.length) пачка.push({ id: строка.id, strokes: штрихи })
    }
    if (пачка.length) тела.push({ lines: пачка, dpi })
  }
  return тела
}

/**
 * Точки одной строки по росчеркам, в координатах сцены и уже прорежённые.
 *
 * Нужны живой сессии распознавания: она отдаёт строку целиком одной пачкой
 * точек, и координаты сдвигает уже сама — у неё своя страница, одна на строку.
 * Прореживание общее с пакетным входом намеренно: два предела длины росчерка
 * означали бы, что сокет и пакет читают одну и ту же строку по-разному.
 */
export function linePoints(
  elements: readonly SceneElement[],
  line: SceneLine,
): [number, number][][] {
  const поId = new Map(inkElements(elements).map((э) => [э.id, э]))
  const росчерки: [number, number][][] = []
  for (const id of line.strokes) {
    const элемент = поId.get(id)
    if (!элемент) continue
    const точки = проредить(absolutePoints(элемент))
    if (точки.length >= 2) росчерки.push(точки)
  }
  return росчерки
}

/* ── кэш ─────────────────────────────────────────────────────────────────── */

/**
 * Влить ответ распознавателя в кэш.
 *
 * `lines` — это строки **в том виде, в каком они уехали** в распознавание, а не
 * те, что на сцене сейчас, и подмена здесь была бы худшей из возможных ошибок.
 * Пока пачка шла, человек мог дописать в строке степень: приняв её нынешний
 * отпечаток за отпечаток ответа, доска пометила бы строку разобранной и
 * показала бы под ней вчерашнюю формулу. С отпечатком отправки строка остаётся
 * грязной и уезжает в распознавание ещё раз — то есть врёт не текст, а только
 * лишний запрос.
 *
 * Возвращается новый словарь: старый не трогается, и React видит изменение по
 * ссылке. Стёртые строки отсюда не вычищаются — это дело `pruneRecognized`,
 * которое знает про всю сцену, а не про одну пачку.
 *
 * Строка с `error` в кэш не пишется вовсе: она останется грязной и уйдёт в
 * распознавание снова. Чтобы это не превратилось в запрос на каждой паузе,
 * неудачные отпечатки помнит `ink.ts` и второй раз их не шлёт.
 */
export function mergeRecognized(
  cache: RecognizedCache,
  lines: readonly SceneLine[],
  answer: readonly RecognizeLineOut[],
  at: string,
): RecognizedCache {
  const поId = new Map(lines.map((с) => [с.id, с]))
  const следующий: RecognizedCache = { ...cache }
  for (const строка of answer) {
    const своя = поId.get(строка.id)
    if (!своя || строка.error) continue
    // Набранное руками распознаватель не перебивает: человек уже сказал, что
    // здесь написано.
    if (следующий[строка.id]?.state === LINE_STATES.manual) continue
    следующий[строка.id] = {
      fingerprint: своя.fingerprint,
      latex: строка.latex ?? '',
      jiix: строка.jiix ?? undefined,
      state: LINE_STATES.recognized,
      elements: своя.strokes,
      box: своя.box,
      at,
    }
  }
  return следующий
}

/**
 * Словарь, прочитанный с тома, приведённый к нынешнему виду.
 *
 * Доски, заведённые при подтверждении строк, держат в словаре состояния
 * `confirmed` и `changed` и прежний подтверждённый текст рядом с новым. Ни того,
 * ни другого больше нет: всякая прочитанная строка — просто `recognized`, и
 * показывается последнее прочитанное. Читать такой словарь всё равно нужно —
 * иначе открытие старой доски стоило бы человеку распознавания каждой строки
 * заново, — а вот писать в новом виде.
 *
 * `elements` и `box` у старых записей пусты: их проставит первая же пересборка
 * строк (`syncPlaces`), как только сцена сложится в строки.
 */
export function readCache(raw: unknown): RecognizedCache {
  const словарь = (raw ?? {}) as Record<string, Partial<Recognized> & { confirmedLatex?: string }>
  const следующий: RecognizedCache = {}
  for (const [id, запись] of Object.entries(словарь)) {
    if (!запись || typeof запись !== 'object') continue
    следующий[id] = {
      fingerprint: String(запись.fingerprint ?? ''),
      latex: String(запись.latex ?? ''),
      jiix: запись.jiix ?? undefined,
      state: запись.state === LINE_STATES.manual ? LINE_STATES.manual : LINE_STATES.recognized,
      elements: Array.isArray(запись.elements) ? запись.elements.map(String) : [],
      box: запись.box ?? { x: 0, y: 0, width: 0, height: 0 },
      at: String(запись.at ?? ''),
    }
  }
  return следующий
}

/**
 * Обновить место строк в словаре: росчерки и габарит по нынешней сцене.
 *
 * Место — не часть отпечатка, и это намеренно: строка, перенесённая целиком,
 * распознана верно и заново не спрашивается. Но по её габариту службе строить
 * порядок строк, а по росчеркам — выноски замечаний, и оставить в словаре
 * вчерашние координаты значит однажды получить решение, собранное задом наперёд.
 * Поэтому места обновляются при каждой пересборке строк, отпечатка не касаясь.
 */
export function syncPlaces(cache: RecognizedCache, lines: readonly SceneLine[]): RecognizedCache {
  let менялось = false
  const следующий: RecognizedCache = { ...cache }
  for (const строка of lines) {
    const запись = следующий[строка.id]
    if (!запись) continue
    const тот_же =
      запись.box.x === строка.box.x &&
      запись.box.y === строка.box.y &&
      запись.box.width === строка.box.width &&
      запись.box.height === строка.box.height &&
      запись.elements.length === строка.strokes.length &&
      запись.elements.every((id, и) => id === строка.strokes[и])
    if (тот_же) continue
    следующий[строка.id] = { ...запись, elements: строка.strokes, box: строка.box }
    менялось = true
  }
  return менялось ? следующий : cache
}

/**
 * Распознанное, вычитанное из самой сцены.
 *
 * Доски, заведённые до того, как распознанное стало жить отдельным словарём,
 * держат его в `customData` своих росчерков: у первого росчерка формулы лежит
 * её LaTeX. Читается это ровно один раз, при открытии такой доски, и ровно
 * затем, чтобы не распознавать заново то, что уже прочитано, — то есть чтобы
 * открытие старой доски не стоило человеку запроса на каждую строку. Пометка
 * «подтверждена» из тех записей не читается: подтверждения больше нет.
 *
 * Обратно в `customData` доска больше не пишет: у распознанного одно место, и
 * второе означало бы две правды о том, что написано на доске.
 */
export function recognizedFromScene(
  elements: readonly SceneElement[],
  lines: readonly SceneLine[],
): RecognizedCache {
  const поШтриху = new Map<string, SceneLine>()
  for (const строка of lines) for (const id of строка.strokes) поШтриху.set(id, строка)
  const кэш: RecognizedCache = {}
  for (const формула of sceneFormulas(elements)) {
    const строка = поШтриху.get(формула.carrier.id)
    if (!строка || кэш[строка.id] || !формула.latex) continue
    const набрана = формула.source === SOURCES.mathlive || формула.source === SOURCES.manual
    кэш[строка.id] = {
      fingerprint: строка.fingerprint,
      latex: формула.latex,
      state: набрана ? LINE_STATES.manual : LINE_STATES.recognized,
      elements: строка.strokes,
      box: строка.box,
      at: (формула.carrier.customData as { recognizedAt?: string } | null)?.recognizedAt ?? '',
    }
  }
  return кэш
}

/** Убрать из кэша строки, которых на сцене больше нет. */
export function pruneRecognized(
  cache: RecognizedCache,
  lines: readonly SceneLine[],
): RecognizedCache {
  const живые = new Set(lines.map((с) => с.id))
  const следующий: RecognizedCache = {}
  let менялось = false
  for (const [id, запись] of Object.entries(cache)) {
    if (живые.has(id)) следующий[id] = запись
    else менялось = true
  }
  return менялось ? следующий : cache
}

/**
 * Строка набрана руками.
 *
 * Дальше распознаватель её не трогает: человек уже сказал, что здесь написано.
 * Разбор `jiix` при этом выбрасывается — он описывает не этот текст.
 */
export function typeLine(
  cache: RecognizedCache,
  line: SceneLine,
  latex: string,
  at: string,
): RecognizedCache {
  return {
    ...cache,
    [line.id]: {
      fingerprint: line.fingerprint,
      latex,
      state: LINE_STATES.manual,
      elements: line.strokes,
      box: line.box,
      at,
    },
  }
}

/* ── чистовик ────────────────────────────────────────────────────────────── */

/**
 * Чистовик: одна модель и для панели, и для призраков на холсте.
 *
 * Строка без записи в кэше — ещё не прочитанная: у неё пустой LaTeX и состояние
 * `recognized`. Это законное состояние, а не беда: так выглядит строка в первую
 * секунду своей жизни и на доске без ключей — и показывается она словами «не
 * разобрано», а не пустым местом.
 */
export function fairCopy(lines: readonly SceneLine[], cache: RecognizedCache): FairLine[] {
  return lines.map((строка, и) => {
    const запись = cache[строка.id]
    return {
      n: и + 1,
      id: строка.id,
      step: строка.step,
      latex: запись?.latex ?? '',
      state: запись?.state ?? LINE_STATES.recognized,
      behind: запись?.state === LINE_STATES.manual && запись.fingerprint !== строка.fingerprint,
      strokes: строка.strokes,
      box: строка.box,
    }
  })
}

/**
 * Сколько строк доски уедет репетитору: те, у которых есть текст.
 *
 * Строка, которую никто не прочитал, шагом решения не считается — ни здесь, ни в
 * теле запроса, и это одно и то же правило, написанное один раз.
 */
export function willSee(lines: readonly FairLine[]): number {
  return lines.filter((с) => !!с.latex.trim()).length
}

/**
 * Тело `PUT …/board/steps`: строки сверху вниз так, как их видит агент.
 *
 * Едут строки, у которых есть текст, — прочитанные и набранные руками. Строка,
 * которую распознаватель не прочитал, своего LaTeX не имеет вовсе, и слать её
 * пустой значит отдать репетитору «шаг без содержания»; сколько таких строк на
 * доске, служба считает сама по разнице со сценой.
 *
 * `confirmed` в теле остаётся и всегда истинно: подтверждения на доске нет, а
 * поле служба пока читает. Врать оно не начинает — «человек видит эту строку
 * под своими росчерками и оставил её такой» и есть всё, что оно когда-либо
 * означало.
 *
 * `id` здесь — **короткое** имя строки, а не идентификатор её росчерка. Этим
 * именем строка попадает в файл распознанного и в выжимку, им же репетитор
 * называет её в своих замечаниях, и по нему замечание разрешается обратно в
 * объект на доске. Настоящие идентификаторы едут рядом, в `elements`.
 */
export function stepsBody(lines: readonly SceneLine[], cache: RecognizedCache) {
  return {
    lines: fairCopy(lines, cache)
      .filter((строка) => !!строка.latex.trim())
      .map((строка) => ({
        id: строка.step,
        latex: строка.latex,
        elements: строка.strokes,
        confirmed: true,
        // Откуда взялся текст: набранное руками показывается человеку иначе, чем
        // прочитанное сервисом, и решается этим полем ничего — только показ.
        source: строка.state === LINE_STATES.manual ? SOURCES.manual : SOURCES.myscript,
      })),
  }
}
