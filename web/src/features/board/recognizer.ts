/**
 * recognizer — распознавание **от сцены**: строки, отпечатки, грязные, кэш.
 *
 * ── Почему не от пера ────────────────────────────────────────────────────────
 *
 * Если единицей распознавания считать поток пера, «прошлым» становится момент
 * времени, а не место на холсте: дописанный минус в строке 2 уезжает вместе с
 * тем, что пишется сейчас, и склеивается с чужой формулой. Поэтому единица
 * здесь — **группа росчерков на сцене**, а распознанное — функция от этой
 * группы, которую можно позвать снова, когда группа изменилась.
 *
 * Весь файл — чистые функции над массивом элементов сцены и словарём
 * распознанного. Ни запросов, ни таймеров, ни DOM: запрос делает `ink.ts`,
 * показ — `Ghosts.tsx`. Так правила группировки и отпечатка можно проверить
 * целиком, не открывая браузера, — а ошибка здесь дороже любой другой на доске:
 * она отдаёт распознавателю не то, что написано, и ответ приходит уверенный и
 * не про то.
 *
 * ── Из чего состоит строка ───────────────────────────────────────────────────
 *
 * - **Группа** — росчерки, соседние по геометрии: полосы их габаритов
 *   перекрываются по вертикали не меньше чем на 40 % меньшей высоты, а зазор по
 *   горизонтали не больше полутора высот. Иначе — другая строка.
 * - **Идентификатор** — идентификатор самого раннего росчерка группы (первого в
 *   массиве элементов, то есть первого нарисованного). Он переживает
 *   дорисовывание и перенос строки; исчезает только вместе со своим росчерком.
 * - **Отпечаток** — свёртка точек всех росчерков группы, посчитанных
 *   **относительно габарита группы**. Поэтому перенос строки целиком (панорама
 *   не в счёт — она вида, а не сцены; а вот сдвиг группой) отпечатка не меняет,
 *   а дорисованный штрих, стёртый штрих и правка формы — меняют.
 *
 * ── Чем считается отпечаток ──────────────────────────────────────────────────
 *
 * Не sha256, хотя он тут же рядом (`scene.ts`). Отпечаток считается по **всем**
 * точкам всех росчерков доски и пересчитывается на каждой паузе пера: на строке
 * в тысячу точек криптографическая свёртка стоит заметных миллисекунд, и платит
 * за них планшет посреди письма. Взята FNV-1a — свёртка на сдвигах и умножении,
 * шестнадцать шестнадцатеричных знаков.
 *
 * Стойкость здесь не нужна вовсе, и это не экономия на безопасности: отпечаток
 * никуда не уезжает и ничего не подтверждает, он отвечает на один вопрос — «эти
 * ли самые точки уже распознаны», — а цена совпадения у двух разных строк равна
 * одному непересчитанному призраку. Там, где значение обязано совпасть со
 * службой (короткое имя строки), считается именно sha256, и ничто другое.
 */

import { sceneFormulas, shortId, SOURCES, type Box, type SceneElement } from './scene'
import { absolutePoints } from './strokes'

/* ── состояния строки ────────────────────────────────────────────────────── */

/**
 * Два состояния строки. Подтверждения нет вовсе.
 *
 * - `recognized` — прочитано распознавателем и стои́т призраком под росчерками;
 *   меняется вслед за ними;
 * - `manual` — LaTeX набран руками. Росчерки его **не перезаписывают**: человек
 *   уже сказал, что здесь написано, и распознаватель спорить с ним не вправе.
 *
 * Третьего состояния — «человек принял» — нет намеренно. Подтверждение стоило
 * движения на каждую написанную строку и не решало ничего: неверно прочитанное
 * человек видит **под своей строкой** и правит либо росчерки, либо текст руками.
 * Зато строка, которую забыли подтвердить, молча не доезжала до репетитора, то
 * есть цена забывчивости была выше цены ошибки.
 */
export const LINE_STATES = {
  recognized: 'recognized',
  manual: 'manual',
} as const

export type LineState = (typeof LINE_STATES)[keyof typeof LINE_STATES]

