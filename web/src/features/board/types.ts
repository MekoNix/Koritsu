/**
 * types — формы, которыми область говорит со службой.
 *
 * Маршруты доски объявлены в документе OpenAPI, и путь, метод и тело проверяет
 * компилятор (`api/schema.d.ts`). Здесь повторены **ответы**: половина их полей
 * нужна экрану под своим смыслом («вердикт», «шаг», «замечание»), и держать эти
 * смыслы в комментариях рядом с формой дешевле, чем искать их в порождённом
 * файле. Имя схемы службы названо у каждой формы — по нему их и сверяют, когда
 * одна из сторон меняется.
 *
 * Форма результата задания (`board_check`) в документе не описана вовсе: тело
 * задания очереди — свободный объект, и его договор живёт в обработчике службы.
 * Поэтому она объявлена здесь целиком.
 *
 * Приведений `as unknown` в области нет: если ответ придёт другой формы, это
 * должно быть видно проверкой типов, а не всплыть пустым экраном.
 *
 * Формы распознавания живут не здесь, а в `recognizer.ts`: там же, где правила,
 * по которым они собираются. Сюда они приходят одним типом — `RecognizedCache`,
 * который едет на том рядом со сценой.
 */

import type { RecognizedCache } from './recognizer'

/** Строка чистовика (`StepOut`): подтверждённая — шаг, иначе догадка. */
export type BoardStep = {
  /** Порядок чтения, считает служба. */
  n: number
  /** Шесть hex от идентификатора первого элемента группы — он же едет модели. */
  id: string
  /** Без долларов; пусто — строку не прочитал никто. */
  latex: string
  /** Откуда взялась строка; пусто — неизвестно. */
  source: 'myscript' | 'manual' | 'mathlive' | ''
  /**
   * Поле совместимости: у всякой уехавшей строки оно истинно.
   *
   * Подтверждения строк на доске нет — человек видит прочитанное призраком под
   * своей записью и правит либо росчерки, либо текст, — но поле служба пока
   * читает, и убрать его с одной стороны раньше, чем с другой, значит получить
   * решение без единого шага.
   */
  confirmed: boolean
  /**
   * Настоящие идентификаторы Excalidraw всех элементов строки — по ним
   * замечание становится выноской. Первый — якорь строки. Координат в шаге нет
   * ни одной: их берут из сцены по этим идентификаторам.
   */
  elements: string[]
  /**
   * Кадр, в который попала строка; `null` — ни в какой. Кадр — подпись над
   * группой строк, а не шаг решения: шаг здесь — строка.
   */
  frame?: string | null
  frame_name?: string
}

/** Карточка доски в списке работы (`BoardOut`). */
export type BoardCard = {
  /** Он же `?run=`: доска — это решение работы модуля. */
  id: string
  project_id: string
  /** Пусто — имени не давали, и зовёт её интерфейс сам. */
  name: string
  /** Которая это доска работы, с единицы. */
  n: number
  user_id?: string | null
  created_at: string | null
  /** Сколько строк прочитало последнее распознавание. */
  steps: number
  /** Когда доску в последний раз доверял репетитор; `null` — ни разу. */
  checked_at?: string | null
}

/**
 * Карточка доски в ленте пространства (`WorkspaceBoardOut`).
 *
 * Та же карточка плюс имя работы, в которой доска лежит. Экран его не
 * показывает — работу человек не выбирал и знать о ней не обязан, — но поиск
 * идёт и по нему: доска, заведённая внутри работы (со страницы работы, а не с
 * этого экрана), иначе не находилась бы ничем, кроме собственного имени.
 */
export type WorkspaceBoardCard = BoardCard & {
  project_name: string
}

/**
 * Сцена Excalidraw так, как её хранит служба.
 *
 * Элементы намеренно не типизированы строго: форма элемента принадлежит
 * Excalidraw, меняется с его версиями, и копия этой формы у нас разошлась бы с
 * оригиналом молча. Область читает у элемента ровно то, что ей нужно
 * (`scene.ts`), и делает это узкими типами там же.
 */
export type ExcalidrawScene = {
  elements?: unknown[]
  appState?: { viewBackgroundColor?: string; gridSize?: number | null }
  [k: string]: unknown
}

/** Сцена и её версия (`SceneOut`). Тот же ответ и у чтения, и у записи. */
export type SceneBody = {
  /** Пусто — на доске ещё не рисовали, и это не беда. */
  scene: ExcalidrawScene
  /** Счётчик с единицы: чужой `version` в `PUT` даёт 409 и текущую сцену. */
  version: number
  /**
   * Распознанное по строкам, снятое со сцены (`SceneIn.recognized`).
   *
   * Едет рядом со сценой, а не внутри неё: `customData` росчерков принадлежит
   * рисунку, а распознанное — разбору рисунка, и подмешивать одно в другое
   * значит терять разбор при любой правке рисунка редактором. Служба принимает
   * этот словарь и отдаёт как есть, не разбирая: смысл полей знает только сайт
   * (`recognizer.ts`), и хранение здесь нужно ровно затем, чтобы после
   * перезагрузки страницы не распознавать заново ничего.
   */
  recognized?: RecognizedCache
  at?: string | null
}

/** Тело `409` у записи сцены (`SceneConflictOut`): отказ плюс победившая сцена. */
export type SceneConflict = SceneBody

/** Строки решения и то, не отстали ли они от доски (`StepsOut`). */
export type StepsBody = {
  steps: BoardStep[]
  /** Версия сцены, по которой строки прочитаны. */
  scene_version: number
  /** Материал `<имя доски>.latex.md` этой доски; пусто — строк ещё не строили. */
  latex_material: string
  /** Сколько строк доски осталось непрочитанными. */
  unrecognized: number
  /** На доске писали после того, как строки прочитали: проверка откажется. */
  stale: boolean
  at?: string | null
}

/** Условие задачи словами (`TaskOut` / `TaskIn`). */
export type TaskBody = { text: string }

/**
 * Готово ли распознавание рукописи (`SessionOut`).
 *
 * Ключи в ответе — постоянные заглушки (`"koritsu"`), а не ключи: настоящие не
 * покидают службу. Сайт их и не спрашивает — распознавание идёт запросом к
 * службе, — но поля остаются в ответе ради моста, который живёт рядом.
 */
export type InkSession = {
  /** Ложь — состояние, а не беда: доска рисует и даёт набрать формулу. */
  ready: boolean
  /** Почему не готово: `no_keys`. Пусто, когда готово. */
  reason: string
  scheme: string
  host: string
  application_key: string
  hmac_key: string
  /**
   * Запросов к распознавателю за месяц: вызовы пачкой плюс открытия сокета.
   * Тариф считает запросы, а не штрихи, — это и есть число, за которым следят.
   */
  requests_this_month: number
  /** Из них открытий сокета: живой сокет тратит и в забытой вкладке. */
  opens_this_month: number
}

/** Вид просьбы к репетитору. Одно задание очереди; экран пользуется `chat`. */
export type BoardMode = 'check' | 'hint' | 'drill' | 'chat'

/** Сообщение переписки с репетитором, как оно лежит на томе. */
export type ChatMessage = {
  role: 'you' | 'tutor'
  /** Текст; формулы — LaTeX между знаками доллара. */
  text: string
  at: string | null
  /** Версия сцены, с которой отправлено сообщение человека. */
  scene_version: number | null
}

/** Ответ маршрута переписки: сообщения старые первыми. */
export type ChatBody = { messages: ChatMessage[] }

/** Глубина ответа. Вторая подсказка идёт глубже первой. */
export type BoardLevel = 'hint' | 'explain' | 'solution'

/**
 * Вердикт проверки. Слова для экрана — `board.answer.verdict.*`.
 *
 * Пусто — вердикта не было вовсе: так отвечает режим `drill`, где сверять
 * нечего и ответ лежит целиком в `drill`.
 */
export type BoardVerdict = 'correct' | 'wrong' | 'unclear' | ''

/** Вид замечания. Слова для экрана — `board.answer.kind.*`. */
export type RemarkKind = 'ok' | 'error' | 'hint' | 'missing'

/** Замечание: текст плюс якоря — идентификаторы элементов сцены. */
export type BoardRemark = {
  kind: RemarkKind
  /** Пусто — замечание общее: выноски у него нет, оно живёт списком в ленте. */
  objects: string[]
  text: string
}

/** Один шаг в ответе модели. `ok` — верен ли переход от предыдущего шага. */
export type StepVerdict = {
  /** Короткий идентификатор шага, не номер. */
  step: string
  /** `null` — «по этой строке не понять»: она не распознана или оборвана. */
  ok: boolean | null
  note: string
}

/** Задача на тренировку. Решение и ответ наружу не возвращаются. */
export type BoardDrill = {
  topic: string
  /** Словесная часть условия. */
  task: string
  /** Формула условия строкой LaTeX; на доску она ложится рендером. */
  hint: string
  answer: string
  /** Почему именно эта задача: какой шаг не сошёлся. */
  why: string
}

/** Подсказка: одна строка и, если есть, якорь на шаг. */
export type BoardHint = { step: string; text: string }

/**
 * `job.result` задания `board_check`.
 *
 * `steps` содержит запись на **каждую** строку доски, а не только на те, что
 * модель назвала: не названная приходит с `ok: null` и пустой заметкой. Иначе
 * «сверено 3 перехода» на решении из пяти строк выглядело бы полным.
 */
export type BoardCheckResult = {
  mode: BoardMode
  verdict: BoardVerdict
  steps: StepVerdict[]
  /** Что именно сверено — переходами между соседними шагами, а не строками. */
  checked: string[]
  remarks: BoardRemark[]
  hint: BoardHint | null
  drill: BoardDrill | null
  /** Ответ в переписке (режим `chat`); в прочих режимах пусто. */
  reply: string
  /** Снимок сцены, по которому проверяли. */
  scene_artifact: string
  digest_sha: string
  /** Метка прогона: с неё начинается каждая служебная строка выжимки. */
  mark: string
  steps_total: number
  unrecognized: number
  key_source: string
  /** Версия сцены на старте прогона: по ней видно, что доску правили после. */
  scene_version?: number
}

/** Тело задания очереди. Вид — `board_check`. */
export type BoardCheckPayload = {
  run_id: string
  endpoint: string
  mode: BoardMode
  level: BoardLevel
  /** Шаг, по которому просят подсказку; для прочих режимов не читается. */
  step: string
  scene_version: number
  /**
   * Необязательная строка от человека: «что именно проверить», «что не так с
   * задачей». Едет отдельным недоверенным куском рядом с условием и уезжает
   * только непустой — просьба без слов ничем не отличается от нажатия кнопки.
   */
  wishes?: string
  /** Сообщение переписки: режим `chat`. */
  message?: string
  /**
   * Какие строки приложить (короткие имена): человек выделил на холсте то, о
   * чём спрашивает. Нет поля — все строки доски.
   */
  lines?: string[]
}

