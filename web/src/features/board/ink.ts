export type InkPenOptions = {
  /** Отдать пачку службе пакетным входом. Возвращает ответ или бросает `ApiError`. */
  send: (body: RecognizeIn) => Promise<RecognizeOut>
  /** Готовность распознавания с ключами-заглушками; `null` — ещё не спросили. */
  session: () => InkSession | null
  /** Элементы сцены на момент паузы — за ними идут точки росчерков. */
  elements: () => readonly SceneElement[]
  /** Строки сцены на момент паузы: считаются один раз, здесь и в призраках. */
  lines: () => SceneLine[]
  /** Кэш распознанного на момент паузы. */
  cache: () => RecognizedCache
  /** Кэш пополнился: сюда уходит новый словарь целиком. */
  onCache: (cache: RecognizedCache) => void
  /** Состояние и человеческий текст к нему. */
  onState: (state: InkState, note: string) => void
  /** Можно ли ходить наружу: без ключей MyScript — нельзя. */
  active: () => boolean
}

/**
 * Перо: пауза на доске — грязные строки — сессия (или, если её нет, пакет).
 *
 * Живёт всё время открытой доски. Между паузами это таймер и, если сессия уже
 * открыта, один спящий сокет.
 */
export class InkPen {
  private options: InkPenOptions
  private таймер: ReturnType<typeof setTimeout> | null = null
  /** Пачка уже в пути: вторая одновременно — это вторая оплаченная работа. */
  private занято = false
  /** Отпечатки, на которых распознаватель отказал. Второй раз их не шлём. */
  private отказы = new Set<string>()
  private сессия = new LiveSession()
  /** Обрывов сессии подряд. Дошло до потолка — доска уходит на пакетный вход. */
  private обрывов = 0
  /** Сессия больше не пробуется: читаем пакетным входом. */
  private пакетом = false

  state: InkState = INK_STATES.off

  constructor(options: InkPenOptions) {
    this.options = options
  }

  /**
   * Сцена изменилась. Таймер заводится заново на каждое изменение, поэтому
   * пауза считается от последнего движения пера, стирания или переноса, а не от
   * первого.
   */
  touch(): void {
    if (this.таймер) clearTimeout(this.таймер)
    this.таймер = setTimeout(() => {
      this.таймер = null
      void this.run()
    }, PAUSE)
  }

  /** Отменить назначенную работу и закрыть сессию: доску закрывают. */
  stop(): void {
    if (this.таймер) clearTimeout(this.таймер)
    this.таймер = null
    void this.сессия.stop()
  }

  private сказать(состояние: InkState, текст = ''): void {
    this.state = состояние
    this.options.onState(состояние, текст)
  }

  /** Спокойное состояние: по какому пути доска читает написанное. */
  private покой(текст = ''): void {
    this.сказать(this.пакетом ? INK_STATES.batch : INK_STATES.live, текст)
  }

  /** Распознать грязные строки прямо сейчас, не дожидаясь паузы. */
  async run(): Promise<void> {
    if (this.занято) return
    if (!this.options.active()) {
      this.сказать(INK_STATES.off)
      return
    }
    const строки = this.options.lines()
    const грязные = dirtyLines(строки, this.options.cache()).filter(
      (с) => !this.отказы.has(метка(с)),
    )
    if (грязные.length === 0) {
      // Ничего не менялось — наружу не идём вовсе. Это и есть главная разница с
      // распознаванием по ходу пера: тишина на доске ничего не стоит.
      this.покой()
      return
    }

    this.занято = true
    try {
      if (!this.пакетом && (await this.сессией(грязные))) return
      // До обрыва сессия могла прочитать часть строк. Пакетным входом
      // дочитываются только оставшиеся: каждая из них — отдельный вызов сервиса,
      // и платить за уже прочитанное не за что.
      const прочитано = this.options.cache()
      await this.пачкой(грязные.filter((с) => прочитано[с.id]?.fingerprint !== с.fingerprint))
    } finally {
      this.занято = false
    }
  }

  /**
   * Прочитать строки живой сессией. Ложь — сессия не годна, читать нечем.
   *
   * Строки идут **по очереди**: у сессии одна страница, и две строки на ней
   * склеились бы в одну запись. Ответ каждой сразу ложится в кэш — призрак под
   * прочитанной строкой встаёт, не дожидаясь остальных.
   */
  private async сессией(грязные: readonly SceneLine[]): Promise<boolean> {
    const session = this.options.session()
    if (!session?.ready) return false
    try {
      if (!this.сессия.open) this.сказать(INK_STATES.connecting)
      await this.сессия.start(session)
    } catch (сбой) {
      return this.обрыв(сбой)
    }
    this.обрывов = 0
    this.сказать(INK_STATES.busy)
    const элементы = this.options.elements()
    let беда = ''
    for (const строка of грязные) {
      const росчерки = linePoints(элементы, строка)
      if (росчерки.length === 0) continue
      try {
        const ответ = await this.сессия.recognize(росчерки)
        // Словарь берётся заново: пока строка читалась, человек мог набрать её
        // руками, и затирать это ответом, собранным до правки, нельзя. А вот
        // строка берётся **отправленная**: отпечаток в кэше обязан описывать те
        // росчерки, которые распознавали, иначе дописанная за это время степень
        // осталась бы непрочитанной навсегда.
        this.options.onCache(
          mergeRecognized(this.options.cache(), [строка], [{ ...ответ, id: строка.id }], now()),
        )
      } catch (сбой) {
        if (!this.сессия.open) return this.обрыв(сбой)
        // Сессия жива, а строка не прочиталась: беда её собственная — слишком
        // длинная запись, неразборчивый росчерк. Остальные строки от этого не
        // страдают, а эта не пойдёт наружу второй раз с теми же точками.
        this.отказы.add(метка(строка))
        беда = describeFailure(сбой, this.сессия.link)
      }
    }
    if (беда) this.сказать(INK_STATES.error, беда)
    else this.покой()
    return true
  }

  /**
   * Обрыв сессии. Два подряд — доска уходит на запасной путь и говорит об этом.
   *
   * Два, а не один: первый обрыв часто означает уснувшую сессию или моргнувшую
   * сеть, и уводить с него доску на путь, где каждая строка стоит вызова
   * сервиса, значило бы платить за чужую икоту.
   */
  private обрыв(сбой: unknown): boolean {
    void this.сессия.stop()
    this.обрывов += 1
    const текст = describeFailure(сбой, this.сессия.link)
    if (this.обрывов < ОБРЫВОВ_ДО_ПАКЕТА) {
      this.сказать(INK_STATES.error, текст)
      return true
    }
    this.пакетом = true
    this.сказать(INK_STATES.batch, текст)
    return false
  }

  /** Прочитать строки пакетным входом: вызов службы на каждые восемь строк. */
  private async пачкой(грязные: readonly SceneLine[]): Promise<void> {
    const тела = recognizeBodies(this.options.elements(), грязные)
    if (тела.length === 0) return
    this.сказать(INK_STATES.busy)
    try {
      let беда = ''
      let лишних = 0
      for (const тело of тела) {
        const ответ = await this.options.send(тело)
        this.options.onCache(mergeRecognized(this.options.cache(), грязные, ответ.lines, now()))
        for (const строка of ответ.lines) {
          if (!строка.error) continue
          const своя = грязные.find((с) => с.id === строка.id)
          if (своя) this.отказы.add(метка(своя))
          беда = строка.error
        }
        лишних += ответ.unmatched?.length ?? 0
      }
      // Лишнее прочитанное — знак, что в одной строке написаны две формулы:
      // сервис разделил запись иначе, чем геометрия на холсте. Сказать об этом
      // надо словами, иначе половина написанного просто не появится под строкой.
      if (беда) this.сказать(INK_STATES.error, беда)
      else this.покой(лишних ? `${EXTRA}${лишних}` : '')
    } catch (сбой) {
      // Вся пачка не дошла: отпечатки не запоминаем — со связью это повторится
      // само, как только человек снова тронет доску.
      this.сказать(INK_STATES.error, describeFailure(сбой))
    }
  }
}

/**
 * Приставка к заметке о лишнем прочитанном: за ней идёт число выражений.
 *
 * Приставкой, а не готовой фразой, потому что слова живут в `board.json`, а
 * перевода сюда не дотянуться: класс не компонент и хука перевода не видит.
 */
export const EXTRA = 'extra:'

/** Строка и её отпечаток вместе: этим и помнится неудача. */
function метка(строка: SceneLine): string {
  return `${строка.id}:${строка.fingerprint}`
}

/** Метка времени в кэше — секундная, как у остальной разметки доски. */
export function now(): string {
  return new Date().toISOString().replace(/\.\d{3}Z$/, 'Z')
}

/**
 * Человеческий текст к отказу распознавания.
 *
 * Коды службы названы вслух: «нет ключей» и «сервис не отвечает» — разные беды
 * с разными действиями человека, и общая фраза «что-то пошло не так» лишила бы
 * его обеих.
 *
 * Второй довод — адрес. Библиотека во всех сетевых бедах называет сервер
 * MyScript, даже когда соединение шло через наш мост и MyScript ни при чём.
 * Поэтому к сетевым сообщениям приписывается тот адрес, по которому мы
 * действительно пошли, и код закрытия, если он уже известен.
 */
export function describeFailure(сбой: unknown, связь?: Partial<InkLink>): string {
  const код = String((сбой as { code?: string })?.code ?? '')
  const текст = String((сбой as { message?: string })?.message ?? сбой ?? '')
  const куда = связь?.address ? ` (${связь.address})` : ''
  const закрытие = связь?.code
    ? ` Код закрытия ${связь.code}: ${связь.reason || 'без причины'}.`
    : ''
  if (связь?.code === CLOSE_NO_KEYS) return 'Ключи MyScript не введены.'
  if (код === 'ink_no_keys' || /ink_no_keys|no_keys/.test(текст)) {
    return 'Ключи MyScript не введены.'
  }
  if (код === 'ink_unreachable') return 'Распознаватель не отвечает.'
  if (код === 'rate_limited' || код === 'too_many_requests') {
    return 'Распознавание просят слишком часто: подождите минуту.'
  }
  if (
    /access not granted|access\.not\.granted|WRONG_CREDENTIALS|credentials are invalid/i.test(текст)
  ) {
    return 'Распознаватель отклонил ключи MyScript.'
  }
  if (/no\.activity|NO_ACTIVITY|no activity/i.test(текст)) {
    return 'Сессия закрыта за бездействие: соединимся заново.'
  }
  if (/session\.too\.old|TOO_OLD|Session is too old/i.test(текст)) {
    return 'Сессия устарела: соединимся заново.'
  }
  if (/not reachable|ABNORMAL_CLOSURE/i.test(текст)) {
    return `Распознаватель не отвечает${куда}.${закрытие}`
  }
  if (/CANT_ESTABLISH|Failed to construct|NetworkError|network|Unable to establish/i.test(текст)) {
    return `Не удалось соединиться${куда}.${закрытие}`
  }
  return текст || 'Распознаватель отказал без объяснения.'
}
