/**
 * Коды закрытия по-русски.
 *
 * Библиотека переводит их в одну общую фразу («MyScript recognition server is
 * not reachable»), из которой не видно ни кода, ни того, до кого не достучались.
 * Здесь код называется вслух — именно он отличает «сеть не пускает» (1006) от
 * «сервис отказал» (1008), «мост упал» (1011) и «ключей нет» (4401).
 */
const ПРИЧИНЫ_ЗАКРЫТИЯ: Record<number, string> = {
  1000: 'закрыт штатно',
  1001: 'сторона уходит: сервер перезапускается или вкладку закрывают',
  1002: 'нарушен протокол WebSocket',
  1003: 'данные такого вида не принимаются',
  1005: 'код закрытия не назван',
  1006: 'оборвано без рукопожатия: до сокета никто не ответил',
  1007: 'негодные данные в кадре',
  1008: 'закрыто политикой сервера, часто — отказ в доступе',
  1009: 'сообщение слишком велико',
  1011: 'внутренняя ошибка на той стороне',
  1012: 'сервис перезапускается',
  1013: 'сервис просит повторить позже',
  1014: 'шлюз не дождался ответа сервиса',
  1015: 'не установлено TLS-соединение',
  [CLOSE_NO_KEYS]: 'ключи MyScript не введены',
}

export function closeReason(код: number, причина?: string): string {
  const своё = String(причина ?? '').trim()
  const общее = ПРИЧИНЫ_ЗАКРЫТИЯ[код] ?? 'код закрытия неизвестен'
  return своё ? `${общее}: ${своё}` : общее
}

/**
 * Схема и хост для конфигурации библиотеки.
 *
 * Адрес строит браузер, а не служба: путь `/api/v4.0/iink/document` зашит в
 * библиотеку, а префикс, под которым живёт сайт, известен только здесь — в
 * службу он не приходит вовсе (его снимает обратный прокси). Поэтому префикс
 * кладётся **в хост**: `host` подставляется в шаблон адреса строкой, и
 * `<хост>/<префикс>` даёт ровно тот путь, который прокси умеет разобрать.
 *
 * Хост из ответа службы берётся тогда, когда она назвала **другое** имя: так
 * остаётся дорога однажды вынести мост на своё имя, не трогая страницу.
 */
export function inkServer(session: Pick<InkSession, 'scheme' | 'host'>): {
  scheme: 'http' | 'https'
  host: string
} {
  // Служба называет схему сокета (`ws` / `wss`), а библиотека просит схему
  // страницы и сама переводит её в схему сокета. Перевод — здесь, один раз.
  const защищённо = session.scheme === 'wss' || session.scheme === 'https'
  const свой = typeof location !== 'undefined' ? location : null
  const чужой = (session.host ?? '').trim()
  if (чужой && свой && чужой !== свой.host) {
    return { scheme: защищённо ? 'https' : 'http', host: чужой }
  }
  const хост = свой?.host ?? 'localhost'
  const схема: 'http' | 'https' = свой?.protocol === 'https:' ? 'https' : 'http'
  return { scheme: схема, host: `${хост}${BASE_PATH}` }
}

/** Тот же адрес сокета, что построит библиотека, — без query: в ней лежит ключ. */
export function socketAddress(session: Pick<InkSession, 'scheme' | 'host'>): string {
  const { scheme, host } = inkServer(session)
  return `${scheme === 'https' ? 'wss' : 'ws'}://${host}${ПУТЬ_СОКЕТА}document`
}

/* ───────────────────────── наблюдение за сокетом ─────────────────────────
 *
 * Библиотека не отдаёт наружу ни адрес, ни код закрытия: клиент ловит `close`
 * сам и превращает его в ошибку с человеческим текстом, потеряв и код, и
 * причину, а `connectionStatusChanged` в этом виде холста не шлётся вовсе.
 * Поэтому за сокетом наблюдаем снаружи: `window.WebSocket` оборачивается
 * `Proxy` с ловушкой `construct`.
 *
 * `Proxy`, а не подмена классом: так уцелеют прототип, `instanceof` и
 * статические константы, на которые библиотека опирается. Сам сокет остаётся
 * настоящим — мы только вешаем на него ещё трёх слушателей и ничего не
 * перехватываем. Чужие сокеты отсеиваются по пути.
 */

/** Что случилось с сокетом распознавателя. */
export type SocketEvent =
  | { kind: 'open'; url: string }
  | { kind: 'error'; url: string }
  | { kind: 'close'; url: string; code: number; reason: string }

const наблюдатели = new Set<(событие: SocketEvent) => void>()
let обёрнут = false

/** Адрес без query: в ней лежит ровно `applicationKey`, и он не должен всплыть. */
function безКлюча(адрес: string): string {
  return String(адрес ?? '').split('?')[0] ?? ''
}

function обернутьСокет(): void {
  if (обёрнут || typeof window === 'undefined' || typeof Proxy !== 'function') return
  const Родной = window.WebSocket
  if (typeof Родной !== 'function') return
  window.WebSocket = new Proxy(Родной, {
    construct(цель, аргументы: [string | URL, (string | string[])?]) {
      const сокет = Reflect.construct(цель, аргументы, цель) as WebSocket
      const адрес = String(аргументы[0] ?? '')
      if (адрес.includes(ПУТЬ_СОКЕТА)) {
        const url = безКлюча(адрес)
        const разослать = (событие: SocketEvent) => {
          for (const наблюдатель of [...наблюдатели]) {
            try {
              наблюдатель(событие)
            } catch {
              /* один слушатель не должен ронять другого */
            }
          }
        }
        сокет.addEventListener('open', () => разослать({ kind: 'open', url }))
        сокет.addEventListener('close', (со) =>
          разослать({ kind: 'close', url, code: со?.code ?? 1006, reason: со?.reason ?? '' }),
        )
        сокет.addEventListener('error', () => разослать({ kind: 'error', url }))
      }
      return сокет
    },
  })
  обёрнут = true
}

/** Подписаться на события сокета распознавателя. Возвращает отписку. */
export function watchSocket(наблюдатель: (событие: SocketEvent) => void): () => void {
  обернутьСокет()
  наблюдатели.add(наблюдатель)
  return () => {
    наблюдатели.delete(наблюдатель)
  }
}

