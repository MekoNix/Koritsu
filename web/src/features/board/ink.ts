/**
 * ink — распознавание: живая сессия по сокету, пакетный вход как запасной путь.
 *
 * ── Что здесь считается запросом ─────────────────────────────────────────────
 *
 * Сервис распознавания тарифицирует **открытие сессии**, а не штрих и не
 * формулу. Отсюда всё устройство файла: сессия одна на всё время открытой доски,
 * открывается лениво — с первой строки, которую надо прочитать, — и живёт,
 * пока страница открыта. Между строками уходит `clear`: он чистит содержимое
 * сессии, не закрывая её и не попадая в счёт. Сколько бы строк человек ни
 * написал за один заход, наружу это один оплаченный запрос.
 *
 * Пакетный вход (`POST /api/board/recognize`, один вызов сервиса на строку)
 * остаётся **запасным**: им доска живёт, когда сессия не открылась или оборвалась
 * дважды подряд. Он честнее молчания, но дороже: на длинном решении это десятки
 * вызовов вместо одного. Поэтому переход на него виден человеку словами в полосе
 * состояния, а не происходит молча.
 *
 * ── Что и когда уезжает ──────────────────────────────────────────────────────
 *
 * Единица распознавания — строка **сцены**, а не поток пера: иначе «прошлым»
 * становится момент времени, и дописанный минус в строке 2 склеивается с
 * формулой, которую пишут сейчас. После паузы пера в 700 мс сайт смотрит, какие
 * строки разошлись со своим отпечатком, и читает только их — по одной, в одной и
 * той же сессии: `clear` → точки строки целиком → готовый LaTeX. Пока человек
 * пишет строку 5, строки 1–4 не пересылаются ни разу.
 *
 * Отсюда обещание, которое видно глазами: **ничего не менялось — наружу не
 * уходит ничего**. Пауза на доске, где только читают и прокручивают, не стоит
 * ни запроса, ни кадра в сокете.
 *
 * ── Куда уходят ключи ────────────────────────────────────────────────────────
 *
 * Никуда: их здесь нет. Браузер получает заглушки (`applicationKey: "koritsu"`),
 * настоящие ключи лежат на сервере зашифрованными, и на вызов `hmacChallenge`
 * отвечает мост службы. Иначе нельзя: библиотека подписывает сама, и ключ ей
 * нужен в памяти — то есть в браузере. Мост подменяет ключ в адресе и в теле, а
 * остальные кадры гоняет байт в байт.
 *
 * ── Что делается с отказом ───────────────────────────────────────────────────
 *
 * Строка, которую не прочитали, в кэш не пишется — значит, остаётся грязной.
 * Чтобы это не превратилось в запрос на каждой паузе, отпечаток, на котором
 * строка отказала, запоминается, и второй раз тот же самый не отправляется.
 * Изменились росчерки — отпечаток другой, и попытка повторяется сама.
 */

