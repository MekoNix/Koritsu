/** Что видно про связь: куда пошли, чем кончилось. */
export type InkLink = { address: string; code: number | null; reason: string }

/** Один росчерк так, как его ждёт библиотека: точки в её координатах. */
type Штрих = {
  pointerType: string
  pointers: { x: number; y: number; t: number; p: number }[]
}

/** Холст библиотеки в том объёме, в каком его трогает доска. */
type Холст = {
  clear: () => Promise<unknown>
  importPointEvents: (штрихи: Штрих[]) => Promise<{ exports?: Record<string, unknown> }>
  export: (виды: string[]) => Promise<{ exports?: Record<string, unknown> }>
  destroy: () => Promise<unknown>
  event: {
    addErrorListener: (слушатель: (ошибка: unknown) => void) => void
  }
}

const LATEX = 'application/x-latex'
const JIIX = 'application/vnd.myscript.jiix'

/**
 * Живая сессия распознавания: одна на всё время открытой доски.
 *
 * Строки читаются по одной **внутри** сессии: `clear` очищает её содержимое, и
 * следующая строка приходит на чистую страницу, не склеиваясь с предыдущей.
 * Закрывать и открывать сессию между строками нельзя — каждое открытие
 * оплачено, и решение из десяти строк стоило бы десяти открытий.
 */
export class LiveSession {
  /** Страница сессии пуста: после открытия и после очистки. См. `recognize`. */
  private пусто = true

  private холст: Холст | null = null
  private узел: HTMLElement | null = null
  private открытие: Promise<Холст> | null = null
  private отписка: (() => void) | null = null
  /** Сокет закрылся: следующая строка откроет сессию заново. */
  private оборвана = false

  link: InkLink = { address: '', code: null, reason: '' }

  get open(): boolean {
    return this.холст !== null && !this.оборвана
  }

  private наСокете(событие: SocketEvent): void {
    if (событие.kind === 'open') {
      this.link = { address: событие.url, code: null, reason: '' }
      this.оборвана = false
      return
    }
    // У события `error` браузер намеренно не даёт подробностей. Полезно оно
    // ровно одним: сразу после него придёт `close` с кодом.
    if (событие.kind === 'error') return
    this.link = {
      address: событие.url,
      code: событие.code,
      reason: closeReason(событие.code, событие.reason),
    }
    this.оборвана = true
  }

  /**
   * Открыть сессию, если она ещё не открыта. Повторный вызов при живой сессии —
   * пустой: он был бы вторым оплаченным запросом.
   */
  async start(session: InkSession): Promise<void> {
    if (this.оборвана) await this.stop()
    if (this.холст) return
    if (this.открытие) {
      await this.открытие
      return
    }
    const { scheme, host } = inkServer(session)
    this.link = { address: socketAddress(session), code: null, reason: '' }
    this.отписка?.()
    this.отписка = watchSocket((событие) => this.наСокете(событие))

    this.открытие = (async () => {
      // Пакет тяжёлый и нужен не всем: грузится отдельным куском по требованию,
      // чтобы доска без ключей открывалась без него.
      const { Canvas } = await import('iink-ts')
      const узел = document.createElement('div')
      узел.setAttribute('aria-hidden', 'true')
      // Узел уводится за край окна: холсту библиотеки нужен элемент DOM, по
      // которому он меряет размер, но человеку он не показывается никогда —
      // точки мы отдаём сами, а рисует доску редактор.
      Object.assign(узел.style, {
        position: 'fixed',
        left: '-20000px',
        top: '0',
        width: '1600px',
        height: '900px',
        opacity: '0',
        pointerEvents: 'none',
      } satisfies Partial<CSSStyleDeclaration>)
      document.body.appendChild(узел)
      this.узел = узел
      const холст = (await Canvas.load(узел, 'INTERACTIVE_INK_SSR', {
        configuration: {
          // Схема и хост — единственное, чем задаётся адрес: путь и
          // `applicationKey` в query библиотека дописывает сама. Ключи здесь
          // заглушки: настоящие живут на сервере, подпись считает мост.
          server: {
            scheme,
            host,
            applicationKey: session.application_key,
            hmacKey: session.hmac_key,
          },
          recognition: {
            type: 'MATH',
            lang: 'en_US',
            // JIIX по умолчанию приходит без координат. Без рамок разобрать
            // ответ на части нечем — а строка, в которой человек написал две
            // формулы, приезжает именно частями.
            export: { jiix: { 'bounding-box': true } },
            math: {
              // LaTeX — то, что встаёт призраком под строкой; JIIX — разбор
              // целиком, он ложится в кэш рядом. MathML не просим: лишний тип —
              // лишняя работа сервиса и лишний вес каждого ответа.
              mimeTypes: [LATEX, JIIX],
              // Решателя не просим: доска показывает, что написано, а не считает
              // за человека. Решение — дело репетитора, и оно должно быть его.
              solver: { enable: false },
            },
          },
          // Экспорт по отрыву пера и без задержки: точки строки уезжают одной
          // пачкой, и ответ нужен сразу после неё, а не по своему таймеру.
          triggers: { exportContent: 'POINTER_UP', exportContentDelay: 0 },
          rendering: { minHeight: 900, minWidth: 1600 },
        },
      })) as unknown as Холст
      this.холст = холст
      this.оборвана = false
      холст.event.addErrorListener(() => {
        // Текст беды разбирает тот, кто звал распознавание: у него есть строка,
        // к которой беда относится. Здесь важно одно — сессия больше не годна.
        this.оборвана = true
      })
      return холст
    })()

    try {
      await this.открытие
    } catch (сбой) {
      await this.stop()
      throw сбой
    } finally {
      this.открытие = null
    }
  }

  /**
   * Прочитать одну строку: чистая страница, точки строки целиком, готовый LaTeX.
   *
   * Точки сдвигаются так, чтобы строка легла от `(ЗАПАС, ЗАПАС)`: своя страница
   * у каждой строки, и взаимное расположение строк сервису знать незачем — он
   * читает их поодиночке.
   */
  async recognize(росчерки: readonly [number, number][][]): Promise<RecognizeLineOut> {
    const холст = this.холст
    if (!холст) throw new Error('Сессия распознавания не открыта')
    // Пустую страницу не чистят: на `clear` без содержимого сервис не отвечает
    // ничем, и обещание очистки не разрешилось бы никогда — первая же строка
    // после открытия ждала бы вечно. На всякий случай ждём очистку недолго:
    // страница и так будет переписана импортом точек.
    if (!this.пусто) {
      await Promise.race([
        холст.clear(),
        new Promise((готово) => setTimeout(готово, ЖДАТЬ_ОЧИСТКУ)),
      ])
      this.пусто = true
    }
    let минX = Infinity
    let минY = Infinity
    for (const точки of росчерки) {
      for (const [x, y] of точки) {
        if (x < минX) минX = x
        if (y < минY) минY = y
      }
    }
    if (!Number.isFinite(минX)) return { id: '', latex: '' }
    const штрихи: Штрих[] = росчерки.map((точки) => ({
      pointerType: 'PEN',
      pointers: точки.map(([x, y], н) => ({
        x: x - минX + ЗАПАС,
        y: y - минY + ЗАПАС,
        // Времени в сцене нет вовсе, поэтому `t` — номер точки в миллисекундах:
        // для математики важна форма записи, а не скорость письма.
        t: н * 10,
        p: 1,
      })),
    }))
    this.пусто = false
    const модель = await холст.importPointEvents(штрихи)
    const экспорт = модель?.exports ?? (await холст.export([LATEX, JIIX]))?.exports ?? {}
    const latex = экспорт[LATEX]
    return {
      id: '',
      latex: typeof latex === 'string' ? latex : '',
      jiix: экспорт[JIIX],
    }
  }

  /** Закрыть сессию и убрать узел. Следующее открытие — новый оплаченный запрос. */
  async stop(): Promise<void> {
    // Отписка первым делом: своё же закрытие (код 1000) иначе прилетело бы
    // обратно как обрыв, и доска ушла бы на запасной путь там, где человек
    // просто закрыл вкладку.
    this.отписка?.()
    this.отписка = null
    const холст = this.холст
    this.холст = null
    this.оборвана = false
    try {
      await холст?.destroy()
    } catch {
      /* сокет мог уже умереть — тогда закрывать нечего */
    }
    this.узел?.remove()
    this.узел = null
  }
}

