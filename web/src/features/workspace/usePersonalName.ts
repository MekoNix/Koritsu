/**
 * usePersonalName — как называется личное пространство на экране.
 *
 * Правило: вместо «Личного» с именем человека показывается ник. Значит имя
 * личного пространства не хранится нигде: служба зовёт его `Personal`, а экран
 * показывает ник хозяина.
 *
 * Хуком, а не константой, по единственной причине: ник приходит из `me`, а
 * `me` — запрос. Четыре экрана (переключатель, страница пространства, корзина,
 * палитра поиска) обязаны называть его одинаково, и одно место — это одно имя.
 *
 * Пока `me` не загрузился (или ника у аккаунта нет — строка, заведённая до
 * того, как ник стал обязательным), остаётся прежнее «Личное»: пустое место на
 * месте имени пространства читалось бы как сломанный экран.
 */
import { useMe } from '@/api/hooks'
import { useT } from '@/i18n'

export function usePersonalName(): string {
  const t = useT()
  const { data: me } = useMe()
  return me?.nickname || t('workspace.personalName')
}
