"""
_xlsx — разбор таблиц Excel: листы построчно, значения вместо формул.

До этого модуля `.xlsx` уходил в «неизвестный тип», а служба и вовсе отказывала
на приёме (415): человек видел, что таблица с исходными данными не принимается,
хотя ровно те же цифры в `.csv` пакет читает с первого дня.

Единица нумерации — СТРОКА текста, как у обычного текстового материала, а не
строка листа. Почему не строка листа: книга состоит из нескольких листов, и
номер 12 сам по себе ничего не значит — нужен ещё лист. Якорь «таблица.xlsx»,
строки 40–80» указывает на наш текст, и по нему видно, с какого листа кусок:
имя листа напечатано в тексте перед его строками.

Вид материала — `text`, а не свой «таблица». Содержимое здесь такое же, как у
`.csv`: строки со значениями, разделённые знаком. Отдельный вид пришлось бы
завести во всех словарях и в данных службы, а различал бы он две записи одной и
той же таблицы — выгруженную в csv и сохранённую книгой. Заодно `text` — это
пропуск к тем инструментам, которые работают с текстовым материалом (кусок
текста в контекст, чтение по якорю); строить по таблице блок-схему бессмысленно,
но это ровно то же самое, что и для `.csv`, и решается там же, где решается для
`.csv`, — разбором самого исходника, а не видом материала.

Формулы не читаются как формулы: берётся последнее значение, посчитанное и
сохранённое в файле (`data_only=True`). Модели нужны числа, а не `=СУММ(A1:A9)`.
Плата известная: у книги, собранной программой и ни разу не открытой в Excel или
LibreOffice, посчитанных значений в файле нет, и такие ячейки останутся пустыми —
об этом говорит пометка материала.

Старый двоичный `.xls` (до 2007 года) не поддерживается: это не zip с XML, а
формат OLE2, для которого нужна отдельная библиотека. Файл с такой сигнатурой
разбор узнаёт и говорит человеку, что делать, — молчаливая пустая таблица была
бы хуже отказа.
"""
from __future__ import annotations

import datetime as dt
import io

import openpyxl

from ._docx_safe import DocxUnsafe, OLE2_MAGIC, ZIP_MAGIC, check_zip
from ._text import detect_lang
from .model import KIND_TEXT, UNIT_LINE, Parsed

# Главная часть книги: по ней zip опознаётся как таблица, а не как что угодно
# другое в упаковке Office.
WORKBOOK_PART = "xl/workbook.xml"

# Потолок строк на лист. Кусок материала модель запрашивает сама, границами, и
# ничто не мешает ей попросить лист целиком: выгрузка на 20 000 строк — это
# сотни тысяч знаков, то есть весь бюджет разговора на одну таблицу. Пятисот
# строк хватает любой таблице, которую человек читает глазами (ведомость,
# результаты опытов, смета); всё, что длиннее, — это данные для счёта, а не для
# чтения, и модели от них нужны заголовки и начало. Сколько строк не показано,
# сказано в пометке материала — молча обрезать нельзя.
MAX_ROWS_PER_SHEET = 500

# Разделитель ячеек — тот же, что у таблиц Word: одна форма таблицы в тексте
# на весь пакет, чтобы модель не разбирала два разных вида разметки.
CELL_SEP = " | "

OLD_EXCEL_NOTE = ("не читается: это либо старый формат Excel (.xls, до 2007 года), "
                  "либо книга под паролем. Откройте файл в Excel и сохраните как "
                  ".xlsx — иначе содержимое до модели не доедет")


def _cell(value) -> str:
    """Значение ячейки строкой для текста материала.

    Переводы строк внутри ячейки заменяются пробелом намеренно: единица здесь —
    строка текста, и ячейка с абзацем внутри разорвала бы строку таблицы на
    несколько, после чего колонки перестали бы совпадать.
    """
    if value is None:
        return ""
    if value is True or value is False:
        # Так эти значения подписаны в самом Excel — не `True`/`False`.
        return "ИСТИНА" if value else "ЛОЖЬ"
    if isinstance(value, float):
        # Excel хранит целые числами с плавающей точкой: без этого «7 штук»
        # приехало бы как «7.0».
        if value.is_integer() and abs(value) < 1e15:
            return str(int(value))
        return str(value)
    if isinstance(value, dt.datetime):
        # Время суток печатаем, только если оно есть: у даты «01.09.2026 00:00»
        # половина строки — выдуманная точность.
        пусто = (value.hour, value.minute, value.second) == (0, 0, 0)
        return value.strftime("%d.%m.%Y" if пусто else "%d.%m.%Y %H:%M")
    if isinstance(value, dt.date):
        return value.strftime("%d.%m.%Y")
    if isinstance(value, dt.time):
        return value.strftime("%H:%M")
    return " ".join(str(value).split())


def _sheet_rows(ws, out: list[str]) -> tuple[int, int]:
    """Строки одного листа в `out`. → (показано строк, обрезано строк).

    Пустые хвостовые ячейки и пустые строки отбрасываются: Excel считает лист
    занятым до последней ячейки, которую когда-либо трогали, и выгрузка на
    десять колонок легко приезжает с сотней пустых справа и полосой пустых строк
    снизу. В тексте они были бы частоколом из разделителей.
    """
    показано = обрезано = 0
    for values in ws.iter_rows(values_only=True):
        if показано >= MAX_ROWS_PER_SHEET:
            # Обрезанные строки всё равно считаем: пометка «обрезано M» стоит
            # того, чтобы дочитать лист, а значения этих строк уже не собираем.
            if any(v is not None and str(v).strip() for v in values):
                обрезано += 1
            continue
        cells = [_cell(v) for v in values]
        while cells and not cells[-1]:
            cells.pop()
        if not cells:
            continue
        out.append(CELL_SEP.join(cells))
        показано += 1
    return показано, обрезано


def parse_excel(data: bytes) -> Parsed:
    """
    Разобрать книгу Excel из байтов: текст по листам, `Лист: <имя>` перед
    строками каждого.

    Ни один путь отсюда не возвращает «пусто и молча»: не открылось — материал
    сохраняется с пометкой, по которой видно, что делать человеку.
    """
    if data.startswith(OLE2_MAGIC):
        return Parsed(kind=KIND_TEXT, unit=UNIT_LINE, notes=[OLD_EXCEL_NOTE])
    if not data.startswith(ZIP_MAGIC):
        return Parsed(kind=KIND_TEXT, unit=UNIT_LINE,
                      notes=["файл не открывается как XLSX (это не zip); "
                             "возможно, он повреждён или скачан не до конца"])

    # Тот же осмотр упаковки, что у Word: xlsx — такой же zip с XML внутри, и
    # zip-бомба с XXE в нём ровно те же.
    try:
        found = check_zip(data, main=WORKBOOK_PART, kind="XLSX")
    except DocxUnsafe as exc:
        return Parsed(kind=KIND_TEXT, unit=UNIT_LINE, notes=[f"таблица не разобрана: {exc}"])

    notes: list[str] = []
    if found["macros"]:
        # Содержимое читать безопасно — мы разбираем XML и ничего не выполняем.
        # Но файл целиком уедет дальше как есть, поэтому пометка обязана быть
        # видимой: решение отдавать такую книгу принимает тот, кто отдаёт.
        notes.append("книга с макросами (.xlsm): значения прочитаны, макросы не выполнялись")

    try:
        # read_only — книга читается потоком, лист за листом: выгрузка на
        # сто тысяч строк не разворачивается в память объектами ячеек.
        wb = openpyxl.load_workbook(io.BytesIO(data), read_only=True, data_only=True)
    except Exception as exc:                # чужой файл вправе быть каким угодно
        return Parsed(kind=KIND_TEXT, unit=UNIT_LINE,
                      notes=notes + [f"таблица не разобрана: {exc}"])

    units: list[str] = []
    листов = строк = обрезано = 0
    try:
        for ws in wb.worksheets:
            листов += 1
            if units:
                units.append("")            # пустая строка между листами
            units.append(f"Лист: {ws.title}")
            показано, срезано = _sheet_rows(ws, units)
            строк += показано
            обрезано += срезано
            if not показано:
                # Лист без значений не выкидываем: «лист есть, данных нет» —
                # это тоже ответ, особенно если значения формул не сохранены.
                units.append("(пусто)")
    except Exception as exc:                # битый лист посреди целой книги
        notes.append(f"таблица дочитана не до конца: {exc}")
    finally:
        wb.close()

    сказано = [f"листов: {листов}"]
    if обрезано:
        сказано.append(f"строк обрезано: {обрезано} (показаны первые "
                       f"{MAX_ROWS_PER_SHEET} строк каждого листа)")
    notes.append(", ".join(сказано))
    if not строк:
        notes.append("в книге нет значений: она либо пуста, либо собрана программой и "
                     "результаты формул в файле не сохранены — откройте её в Excel и "
                     "сохраните заново")

    return Parsed(kind=KIND_TEXT, unit=UNIT_LINE, units=units,
                  lang=detect_lang("\n".join(units)), notes=notes)
