"""
errors — свой тип ошибки, отдельный тип «сосед ещё не готов» и подсказка «похоже на».

Свой тип по той же причине, что у соседей (`HokokuError`, `LlmError`,
`OrchestratorError`): `kadai` — верхний слой, и без своего типа вызывающий не
отличит «сценарий позван неправильно» от «оркестратор не смог» и от «модель не
ответила». Ловить `Exception` целиком он тогда обязан — то есть проглотит и то,
что должно было упасть.

`NotReady` — отдельный тип, и это главное решение файла. Половина сценария
опирается на то, чего у соседей сегодня нет: разбор Word, построение DOCX без
шаблона, безтеговая дверь к модели, уровень 3, сборка архива. Соблазн —
вернуть на этих местах правдоподобную пустоту: пустую структуру, пустой список
разделов, «архив собран, файлов нет». Так делать нельзя: пустота доедет до
человека под видом результата, и узнает он о ней от того, кто работу примет.
Незаконченное обязано называться незаконченным и падать с адресом того, кого
ждём, — поэтому `NotReady` несёт имя соседа, место в его коде и подпись
ожидаемой функции, а не слова «не реализовано».

Цена ошибки, если не разделять `KadaiError` и `NotReady`: вызывающий не сможет
отличить «ты позвал не так» (чинится в его коде) от «этого ещё не написали»
(чинится в чужом пакете и ждёт), и оба будут одинаково выглядеть как поломка
сценария.
"""
from __future__ import annotations

import difflib


class KadaiError(Exception):
    """Сценарий позван неправильно: нет такой стадии, нет профиля, битая опись."""


class NotReady(KadaiError):
    """Шов к соседу, которого ещё нет. Текст обязан называть, кого и чего ждём.

    Наследник `KadaiError`, а не отдельная ветка: тот, кто ловит ошибки сценария
    целиком, обязан поймать и это — иначе прогон, упёршийся в ненаписанного
    соседа, выглядел бы падением службы.
    """


def hint(name, known) -> str:
    """Хвост «(похоже на "…")» или пустая строка. Форма та же, что в hokoku и orchestrator.

    Почти все такие ошибки — опечатки (свои, чужого скрипта или модели), и цена
    подсказки не в удобстве: `route("схемы")` вместо `"схема"` без неё читается
    как «такого вида замечаний не бывает», и человек уходит писать свою ветку.
    """
    near = difflib.get_close_matches(str(name), sorted(str(k) for k in known), n=1, cutoff=0.6)
    return f' (похоже на "{near[0]}")' if near else ""


def problem(code: str, message: str, *, key=None, level: str = "error") -> dict:
    """Замечание в общей форме `{module, level, code, key, message}`.

    Форма не своя: она уже общая у `hokoku`, `llm` и `orchestrator`, и заводить
    четвёртую значило бы, что интерфейс разбирает четыре вида записи вместо
    одной. `module` здесь всегда `"kadai"` — по нему видно, кто пожаловался.
    """
    return {"module": "kadai", "level": level, "code": code, "key": key, "message": message}


__all__ = ["KadaiError", "NotReady", "hint", "problem"]
