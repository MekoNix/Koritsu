"""
plan — профиль плюс пожелания: какие стадии будут и где прогон покажет сделанное человеку.

Два режима прохода — **один механизм, а не два пути в коде**. Режимов
объявлено два: полная генерация без остановки (умолчание, решение владельца
2026-08-31) и проход с промежуточным показом структуры (по просьбе). Разница
между ними — одно множество: `pause_after`. Пустое — прогон идёт до конца; в нём
имя стадии — машина стадий после её завершения переходит в `waiting_user` и
ждёт. Ветки `if режим == …` нет нигде, и завести её было бы дорого: третий
режим («покажи и разбор, и структуру») тогда стал бы третьей веткой, а он
получается сложением множеств даром.

**Пожелания здесь не разбираются.** Соблазн — просканировать текст пожеланий на
слова «покажи структуру» и включить остановку. Так делать нельзя: «покажи, что
получится по разделам» не содержит ни одного из слов списка, остановка молча не
случится, и человек получит оплаченный до конца прогон вместо экрана с
вопросом — ровно ту самую дорогую ошибку, ради которой остановка и заводилась.
Понять пожелания словами — это стадия «разбор задания», то есть вызов модели
через шов «структура»/«разбор условия». Поэтому здесь поля структурные
(`show_task`, `show_structure`), а заполняет их либо вызывающий (интерфейс,
галочка), либо позже — стадия разбора задания.

Текст пожеланий переносится дословно и остаётся ДАННЫМИ: он едет к модели
кусками роли `files`, где на него ставится рамка. Ни одна ветка кода здесь не
принимает решений по его содержимому.
"""
from __future__ import annotations

from dataclasses import dataclass, field

from .errors import KadaiError, hint
from .profile import Profile

# Просьба человека → после какой стадии остановиться и показать. Таблицей, а не
# условиями: добавить «покажи схемы перед текстами» — это строка здесь.
STOP_AFTER = {
    "show_task": "разбор задания",
    "show_structure": "шаблон",
}


@dataclass(frozen=True)
class Wishes:
    """Пожелания: дословный текст плюс то немногое, что из него уже вынуто.

    Разделение обязательно. `text` — недоверенные данные, он уходит модели и
    больше ни на что не влияет. Флаги — решения, и принимает их человек или
    стадия разбора задания, а не сканер слов (см. заголовок модуля). Пока
    разбора нет, флаги приходят снаружи и по умолчанию выключены — это и есть
    решение владельца «остановки по умолчанию нет».
    """

    text: str = ""
    show_task: bool = False
    show_structure: bool = False


def pauses_of(wishes: Wishes) -> frozenset:
    """Множество стадий, после которых прогон встанет. Пустое — проход без остановок."""
    return frozenset(stage for flag, stage in STOP_AFTER.items() if getattr(wishes, flag, False))


@dataclass(frozen=True)
class Plan:
    """План одной работы: какие стадии нужны этому виду работы и где стоим.

    Неизменяемый: план — это то, о чём договорились до начала. Правка его на
    ходу означала бы, что часть прогона сделана по одному плану, а часть по
    другому, и объяснить готовый архив было бы нечем. Новое пожелание — новый
    план (и, если стадии уже прошли, замечание, см. `rework`).
    """

    profile: Profile
    stages: tuple
    pause_after: frozenset = frozenset()
    wishes: Wishes = field(default_factory=Wishes)

    def needs(self, stage: str) -> bool:
        """Нужна ли стадия этой работе. У реферата не будет «решения» — и это
        должно быть видно как «стадии нет», а не как мгновенно прошедшая стадия:
        полоска хода, показавшая работу, которой не было, врёт."""
        return stage in self.stages

    def stops_after(self, stage: str) -> bool:
        return stage in self.pause_after


def plan_of(profile: Profile, *, wishes: Wishes | None = None, pause_after=()) -> Plan:
    """План по профилю и пожеланиям. `pause_after` складывается с тем, что дали флаги.

    Складывается, а не заменяет: остановку просят из двух мест — галочкой в
    интерфейсе и разбором пожеланий, — и «последний победил» здесь означал бы,
    что просьбу человека тихо отменил разбор.
    """
    wishes = wishes or Wishes()
    pauses = set(pauses_of(wishes)) | {str(s) for s in pause_after}
    unknown = sorted(p for p in pauses if p not in profile.stages)
    if unknown:
        raise KadaiError("остановиться после стадии, которой у этого вида работы нет: "
                         + ", ".join(f'"{u}"{hint(u, profile.stages)}' for u in unknown))
    return Plan(profile=profile, stages=tuple(profile.stages),
                pause_after=frozenset(pauses), wishes=wishes)


__all__ = ["Wishes", "Plan", "STOP_AFTER", "pauses_of", "plan_of"]
