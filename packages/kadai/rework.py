"""
rework — замечание человека → минимальное множество пересчёта. Таблицей, а не цепочкой `if`.

Пять видов замечания разобраны в записке Д.3, и здесь они лежат данными.
Таблицей, потому что у каждой строки есть колонка, которую цепочка `if` не
умеет держать: **где это честно вырождается в полный пересчёт**. Ветвление
кода такую колонку выражает комментарием, комментарий отстаёт от кода, и через
полгода «а почему правка одного абзаца переписала весь отчёт» отвечается
чтением ветки, а не строки таблицы.

Правило, по которому считается минимум, одно: **тег пересчитывается, если
изменился его вход**. Вход тега — стабильный префикс промпта (правила,
манифест, материалы) плюс запись манифеста об этом теге.

Три свойства зависимостей, из которых всё и следует.

1. **Отчёт — детерминированная функция значений.** Пересборка стоит одного
   вызова без модели, поэтому «пересчитать отчёт» не считается тратой никогда.
2. **Текст ссылается на схему через `{ref:ключ}`, а не через номер.** Значит
   замена схемы не делает текст неверным — и правка схемы локальна.
3. **Текстовые теги связаны через соседей.** Значение каждого зависит от
   значений остальных. Текст — противоположность схемы: локального там нет.

Отсюда вывод, который здесь записан данными, а не спрятан: инкрементальность
окупается на схемах, коде и структуре и **не окупается на тексте**. Половина
отчёта, написанная по старому пониманию задачи, и половина по новому — это не
экономия, а дефект, и увидят его при чтении целиком, то есть на кафедре.

Чего здесь нет и почему: своего отпечатка входа. Признак устарелости тега —
второй `prompt_hash` по стабильным кускам (шов «отпечаток входа»); сегодняшний
считается по всем кускам, включая волатильных соседей, и меняется у всех тегов
сразу. Свой отпечаток в `kadai` был бы вторым ответом на тот же вопрос, и
разошёлся бы он с настоящим молча.
"""
from __future__ import annotations

from dataclasses import dataclass

from .errors import KadaiError, hint
