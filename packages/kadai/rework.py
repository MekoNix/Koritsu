def route(kind: str) -> Route:
    """Маршрут по виду замечания. Опечатка — ошибка с подсказкой, а не «такого не бывает»."""
    try:
        return ROUTES[kind]
    except KeyError:
        raise KadaiError(f'вида замечания "{kind}" нет{hint(kind, ROUTES)}; '
                         f"есть: {', '.join(ROUTES)}") from None


