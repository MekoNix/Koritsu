def tags_using_artifact(values: dict, art_id: str) -> list[str]:
    """Ключи тегов, чьи значения ссылаются на артефакт. Обратный индекс не нужен.

    Значения `diagram` и `image` держат идентификатор полем `artifact` прямо в
    JSON, а блоки — вложенно; один проход по десятку тегов отвечает на вопрос
    целиком. Заводить индекс ради этого значило бы платить сложностью за
    незаметную экономию и получить второе место, где записано, кто на что
    ссылается.
    """
    return sorted(key for key, value in (values or {}).items() if _mentions(value, art_id))


def _mentions(value, art_id: str) -> bool:
    if isinstance(value, dict):
        if value.get("artifact") == art_id:
            return True
        return any(_mentions(v, art_id) for v in value.values())
    if isinstance(value, (list, tuple)):
        return any(_mentions(v, art_id) for v in value)
    return False


# Поля записи манифеста, изменение которых меняет вход тега. Список закрытый:
# метка и `guessed` на вход не влияют, а `required` меняет только проверку.
ENTRY_FIELDS = ("type", "prompt", "limits", "depends_on")


def changed_entries(old_tags: dict, new_tags: dict) -> dict:
    """Что изменилось между манифестами: `changed`, `added`, `gone`.

    Утиная типизация вместо импорта `hokoku`: сравниваются объекты с полями
    `type`, `prompt`, `limits`, `depends_on` — ими обладает `hokoku.TagSpec`, и
    больше ничего от него не нужно. Импорт ради четырёх getattr'ов сделал бы
    `kadai` вторым средним слоем.

    Три списка, а не один: «тег добавили» и «тег убрали» требуют от вызывающего
    разного (первый — заполнить, второй — ничего), и сложить их в одно значило
    бы попросить заполнить исчезнувший тег.
    """
    old_tags, new_tags = dict(old_tags or {}), dict(new_tags or {})
    changed = [k for k in new_tags if k in old_tags and _entry(old_tags[k]) != _entry(new_tags[k])]
    return {"changed": sorted(changed),
            "added": sorted(set(new_tags) - set(old_tags)),
            "gone": sorted(set(old_tags) - set(new_tags))}


def _entry(spec) -> tuple:
    return tuple(_frozen(getattr(spec, name, None)) for name in ENTRY_FIELDS)


def _frozen(value):
    if isinstance(value, dict):
        return tuple(sorted((k, _frozen(v)) for k, v in value.items()))
    if isinstance(value, (list, tuple)):
        return tuple(_frozen(v) for v in value)
    return value


def text_tags(tags: dict) -> list[str]:
    """Ключи тегов, которые пишутся текстом (уровень 2), а не производятся инструментом.

    Разделение то же, что между уровнями 3 и 2: петля производит код, схемы,
    картинки и таблицы, поток пишет связный текст, уже видя их соседями. Текст,
    написанный по одному тегу в петле, был бы рассогласован, и это самый дорогой
    способ написать абзац.
    """
    return sorted(key for key, spec in (tags or {}).items()
                  if getattr(spec, "type", "markdown") not in TOOL_TYPES
                  and not getattr(spec, "missing", False))


def inputs_of(project, art_id: str) -> dict:
    """Из чего и чем построен артефакт. Ответ даёт журнал производных — шов.

    Без него по замечанию «схему переделай» неизвестно ни из какого исходника
    она построена, ни не сменился ли исходник под ней; строить заново «как-нибудь»
    значит выдать другую схему за исправленную.
    """
    return method(project, "derived_of", "журнал производных")(art_id)


def plan_rework(kind: str, *, values=None, tags=None, new_tags=None,
                artifact: str | None = None, key: str | None = None) -> dict:
    """Что пересчитать по замечанию. Возвращает маршрут, список тегов и честную оговорку.

    `None` в `tags` значит ровно одно: «пересчитывается всё, перечислять нечего»,
    и бывает это только у маршрутов с `full_text`, когда манифест не передан.
    Пустой список значит другое — «ничего не нашлось». Путать их нельзя: у
    маршрута «кусок» пустой список означал бы «переписать нечего», а `None`
    прочитался бы как «переписать всё» — то есть замечание к одному абзацу
    оплатило бы весь отчёт. Поэтому «кусок» требует ключ тега.
    """
    r = route(kind)
    out = {"route": r, "kind": r.kind, "stages": r.stages, "cost": r.cost,
           "honest": r.honest, "full_text": r.full_text, "tags": None, "note": ""}
    if r.kind == "схема":
        if not artifact:
            raise KadaiError("замечание про схему без идентификатора артефакта: "
                             "неизвестно, какую из схем переделывать")
        out["tags"] = tags_using_artifact(values or {}, artifact)
        if not out["tags"]:
            out["note"] = ("ни одно значение не ссылается на этот артефакт: схема в "
                           "отчёт не попала, и переделывать её без толку")
    elif r.kind == "структура":
        diff = changed_entries(tags or {}, new_tags or {})
        out["tags"] = diff["changed"] + diff["added"]
        out["note"] = (f"убраны из шаблона: {', '.join(diff['gone'])}"
                       if diff["gone"] else "")
    elif r.kind == "кусок":
        if not key:
            raise KadaiError("замечание «этот кусок перепиши» без ключа тега: "
                             "неизвестно, что переписывать. Ключ называет человек")
        out["tags"] = [key]
    elif r.full_text:
        out["tags"] = text_tags(tags) if tags else None
        out["note"] = ("текстовые теги пересчитываются все сразу: точечного пересчёта "
                       "для текста не бывает, см. honest")
    return out


# ── замечание к работе: что переигрывается на самом деле ─────────────────────

# Вид блока → маршрут замечания. Таблицей, а не разбором слов замечания: «тут
# всё не то» не содержит ни одного слова из любого списка, и угаданный по словам
# маршрут переписал бы не то, за что человек платил. Что именно ему не нравится,
# говорит ключ блока; что это за блок — знает работа.
BLOCK_ROUTE = {"markdown": "кусок", "text": "кусок", "heading": "кусок", "toc": "кусок",
               "code": "код",
               "diagram": "схема", "table": "схема", "image": "схема", "formula": "схема"}

# Какие стадии переигрываются по маршруту. Список закрытый и стоит рядом с
# маршрутом: «переделать схему» не должно тянуть за собой текст, а «переделать
# код» — обязано, и оба утверждения обязаны быть видны в одном месте, а не
# собираться из веток кода.
REPLAY = {
    "кусок": ("тексты", "сборка", "архив"),
    "схема": ("решение", "сборка", "архив"),
    "код": ("решение", "тексты", "сборка", "архив"),
    "структура": ("шаблон", "решение", "тексты", "сборка", "архив"),
    "условие": ("разбор задания", "шаблон", "решение", "тексты", "сборка", "архив"),
}


def route_of_block(record) -> str:
    """Маршрут по виду блока, к которому замечание. Опечатка вида — ошибка.

    Вид блока берётся из записи на диске, а не из догадки по значению: вид
    блока и тип значения у движка отчётов — одно утверждение, и второе мнение о
    нём здесь было бы третьим.
    """
    kind = str((record or {}).get("kind") or "")
    try:
        return BLOCK_ROUTE[kind]
    except KeyError:
        raise KadaiError(f'блок вида "{kind}" переделывать нечем'
                         f"{hint(kind, BLOCK_ROUTE)}") from None


def block_of(records, key: str) -> dict:
    """Запись блока по ключу или ошибка с подсказкой. Ключ называет человек."""
    for record in records or ():
        if str(record.get("key")) == str(key):
            return record
    raise KadaiError(f'блока "{key}" в работе нет'
                     f"{hint(key, [str(r.get('key')) for r in records or ()])}")


def redraft(records, keys, *, hint_of=None) -> list:
    """Вернуть названные текстовые блоки в состояние «место под текст». → новые записи.

    Это и есть механика «написать текст заново»: проход текста пишет туда, где
    текста ещё нет (`text_slots`), и команды «перепиши» у него нет вовсе.
    Черновик с подсказкой — единственный способ попросить его написать блок
    второй раз и заодно сказать, что именно не понравилось человеку.

    Блоки, написанные человеком (`source` = `manual` или `file`), не трогаются
    даже по прямой просьбе: пропажу своего абзаца он обнаружит в готовом
    отчёте. Замечание к своему же блоку — это правка в Word, а не прогон модели.
    """
    from . import blocks as blocks_mod          # ленивый: hokoku знает только blocks
    keys = {str(k) for k in keys or ()}
    out = []
    for record in records or ():
        if str(record.get("key")) not in keys or record.get("source") in ("manual", "file"):
            out.append(dict(record))
            continue
        подсказка = ((hint_of(record) if callable(hint_of) else "")
                     or record.get("label") or "")
        out.append({**record, "kind": "markdown", "source": "agent",
                    "value": blocks_mod.draft_json(подсказка)})
    return out


def apply(session, *, note: str, block: str | None = None, kind: str | None = None) -> dict:
    """Замечание человека → минимальный пересчёт. Возвращает, что решено переиграть.

    Вид замечания либо называется прямо (`kind`), либо выводится из вида блока
    (`block`). Угадывать его по словам замечания нельзя и не будем: правило то
    же, что в `plan` про остановки, и цена ошибки та же — «поправь введение» без
    ключа блока переписало бы всю работу, и узнал бы человек об этом по счёту.

    Что делает каждый маршрут, записано в `REPLAY` и в `ROUTES[…].honest`; здесь
    только исполнение. Стадии, которые переигрываются, возвращаются в состояние
    «ждёт», а история работы не переписывается: события остаются, и по ним
    видно, что стадию делали дважды.
    """
    from . import run as run_mod               # ленивый: run про rework не знает
    from .stages import WAITING, reopen
    if not str(note or "").strip():
        raise KadaiError("замечание без текста: переделывать нечего")
    project = session.project
    записи = method(project, "blocks", "список блоков")()
    if block:
        kind = kind or route_of_block(block_of(записи, block))
    if not kind:
        raise KadaiError("не сказано, к чему замечание: назовите блок (--block b-NN) "
                         f"или вид замечания ({', '.join(ROUTES)}). Разбирать слова "
                         "замечания мы не будем: угаданный маршрут переписал бы не то")
    r = route(kind)
    итог = {"kind": r.kind, "block": block, "stages": REPLAY[r.kind],
            "honest": r.honest, "note": ""}

    # Всё, из-за чего замечание не выполнимо, проверяется ДО того, как работа
    # тронута: законченная работа, открытая ради невыполнимого замечания, так и
    # осталась бы `running` — то есть выглядела бы идущей, не идя никуда.
    if r.kind == "кусок":
        if not block:
            raise KadaiError("замечание «этот кусок перепиши» без ключа блока: "
                             "неизвестно, что переписывать. Ключ называет человек")
        if block_of(записи, block).get("source") in ("manual", "file"):
            # Отказ, а не прогон впустую: свой блок дверь не тронет (и правильно
            # сделает), а работа упёрлась бы в «писать нечего» и встала бы
            # `failed` — по замечанию, которое человек мог выполнить сам.
            raise KadaiError(
                f"блок {block} написан человеком (source=manual): проход текста его "
                "не тронет, и просить об этом бессмысленно. Правьте его сами или "
                "снимите пометку, положив блок заново")

    if session.work.state != "running":
        reopen(session.work, note=f"замечание: {note.strip()[:60]}")

    if r.kind == "кусок":
        method(project, "set_blocks", "список блоков")(
            redraft(записи, [block], hint_of=lambda _: note),
            source="agent", note=f"по замечанию: блок {block} пишется заново")
    elif r.kind == "код":
        session.task = _task_for(note, block, "переделай код")
        # Смена кода меняет вход у всех текстовых блоков сразу, и половина
        # отчёта, написанная по старому коду, — дефект, а не экономия. Поэтому
        # текст пересчитывается весь, кроме написанного человеком: тот из
        # прогона выпадает сам.
        свои = [str(x.get("key")) for x in записи
                if str(x.get("kind")) in ("markdown", "text")
                and x.get("source") not in ("manual", "file")]
        method(project, "set_blocks", "список блоков")(
            redraft(записи, свои), source="agent",
            note=f"по замечанию к коду: текст пишется заново ({len(свои)} блоков)")
        итог["note"] = (f"текст пересчитывается весь ({len(свои)} блоков): точечного "
                        "пересчёта для текста не бывает")
    elif r.kind == "схема":
        session.task = _task_for(note, block, "переделай схему")
        итог["note"] = _derived_note(project, записи, block)
    elif r.kind == "структура":
        итог["note"] = _structure_note(project, записи)
        session.work.problems.append(problem("строение_заново", итог["note"],
                                             level="warning"))
    else:                                       # «условие»
        итог["note"] = ("пересчитывается всё, начиная с разбора задания: требование "
                        "стоит в корне зависимостей, и от него зависит вся работа")

    for name in REPLAY[r.kind]:
        st = session.work.stage(name)
        if st.state != "пропущена":
            st.state, st.done = WAITING, None
            st.note = f"переигрывается: {note.strip()[:60]}"
    session.save()
    run_mod.run(session)
    return итог


def _task_for(note: str, block: str | None, что: str) -> str:
    """Задание петле по замечанию: что переделать и чьими словами.

    Замечание человека едет **внутри** задания, а не отдельным недоверенным
    куском, ровно по одной причине: оно и есть указание, которое он оплатил.
    Условие задачи и материалы при этом остаются данными в рамке — их писал не он.
    """
    адрес = f" в блоке {block}" if block else ""
    return (f"{что}{адрес} по замечанию человека: «{str(note).strip()}».\n"
            "Правь только то, о чём замечание: остальные блоки на месте, и "
            "переписывать их не надо. Связный текст не пиши — его пишет "
            "отдельный проход.")


def _derived_note(project, записи, block: str | None) -> str:
    """Из чего построена схема — по журналу производных. Без него правка вслепую."""
    if not block:
        return ""
    art = (block_of(записи, block).get("value") or {}).get("artifact")
    if not art:
        return "в блоке нет артефакта: схему строить не из чего, петля построит её заново"
    запись = inputs_of(project, art) or {}
    if not запись:
        return ("журнал производных про эту схему молчит: из какого исходника она "
                "построена, неизвестно, и петля построит её заново по своему выбору")
    return (f"схема построена {запись.get('tool')} из "
            + (", ".join(запись.get("inputs") or ()) or "неизвестного входа"))


def _structure_note(project, записи) -> str:
    """Честная оговорка про пересборку строения: что при ней может потеряться.

    Переносит правки человека дверь (`make_template(before=…)`), и переносит по
    заголовку раздела — другого имени, общего у старого и нового строения, нет:
    ключи блоков выдаются заново. Отсюда и граница, которую сценарий обязан
    назвать заранее, а не показать счётом: **разделы, которых в новом строении
    не будет — и переименованные тоже, для двери это одно и то же, — своих
    блоков не сохранят на месте**. Такой блок останется в конце списка, и найти
    его человеку придётся глазами.

    Второе, что можно сделать честно, — назвать номер версии, к которой человек
    вернётся сам (`Project.rollback_blocks`): это единственный способ отменить
    пересборку целиком.
    """
    свои = [str(r.get("key")) for r in записи if r.get("source") in ("manual", "file")]
    try:
        versions = method(project, "block_versions", "список блоков")()
    except KadaiError:
        versions = []
    номер = versions[-1].n if versions else None
    хвост = (f" Прежний список — версия {номер}: вернуть его целиком можно "
             f"rollback_blocks({номер})." if номер else "")
    if not свои:
        return "строение собирается заново; правок человека в списке не было." + хвост
    return (f"строение собирается заново; {len(свои)} блоков, написанных человеком "
            f"({', '.join(свои)}), переедут в раздел с тем же заголовком, а из "
            "разделов, которые исчезнут или сменят название, не переедут — они "
            "останутся в конце списка." + хвост)


