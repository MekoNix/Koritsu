"""
models — индекс проектов и журнал запусков. Содержимое проекта лежит на томе.

Значения тегов остаются файлами, база хранит индекс. Поэтому здесь нет ни
тегов, ни версий, ни манифеста — только то,
без чего проект не найти: чей он, в каком пространстве, как называется, каким
модулем делается и не в корзине ли. Рядом — журнал запусков (`ProjectRun`):
список того, что в работе делали, с именами и порядком.

Всё остальное умеет `orchestrator.Project`, и второе описание проекта в базе
разошлось бы с каталогом на первом же переименовании тега.

**`owner_id` — кто создал, а не кто пользуется.** Квота считается на владельца
(«чужие проекты в общем workspace едят место того, кто их создал»), и
каталог на томе лежит у него же: `/data/users/<owner>/projects/<project>/`.
Отсюда важное следствие: `owner_id` не меняется никогда — смена владельца
означала бы переезд каталога, а путь к нему помнят материалы и артефакты.

Пути в базе не хранится. Он вычисляется из двух uuid (`service.project_dir`),
и это не экономия места: путь в строке — это путь, который однажды разойдётся с
диском, и вычислить его заново будет уже неоткуда.
"""
from __future__ import annotations

import datetime

from sqlalchemy import DateTime, ForeignKey, Index, Integer, String
from sqlalchemy.orm import Mapped, mapped_column

from ..db import Row
from ..ids import ID_LEN

NAME_MAX = 200

# Длина идентификатора модуля (`reports`, `flowcharts`). Короткое слово, оно же
# кусок пути маршрутов модуля (`modules/__init__.py`), — с запасом.
MODULE_LEN = 32

# Столько знаков занимает идентификатор артефакта. Тот же запас, что у среза
# хеша шаблона (`templates.models.SHA_LEN`), и по той же причине: числом, а не
# `len(orchestrator.artifact_id(b""))`, — модели читает `migrations/env.py`, и
# тянуть в него движок отчётов ради одной длины значило бы, что миграции
# перестают собираться без него.
ARTIFACT_LEN = 32


class Project(Row):
    """Строка индекса одного проекта. Тёзка `orchestrator.Project` — намеренно:
    это одна и та же вещь с двух сторон, база знает «чей и где», каталог —
    «что внутри». Внутри пакета оркестраторный зовут через модуль
    (`orchestrator.Project`), чтобы имена не путались."""

    __tablename__ = "projects"

    workspace_id: Mapped[str] = mapped_column(
        String(ID_LEN), ForeignKey("workspaces.id", ondelete="CASCADE"),
        index=True)
    owner_id: Mapped[str] = mapped_column(
        String(ID_LEN), ForeignKey("users.id", ondelete="CASCADE"), index=True)
    name: Mapped[str] = mapped_column(String(NAME_MAX))

    # Каким модулем эта работа делается: `reports`, `kadai`, `flowcharts`,
    # `uml` — идентификатор из реестра модулей. Пустая строка значит «не
    # назначен», и это законное состояние: работу заводят раньше, чем решают,
    # чем её делать.
    #
    # **Поле, а не догадка.** До него модуль работы приходилось выводить
    # косвенно — по тому, есть ли у проекта теги шаблона или запись kadai на
    # томе, — и догадка эта врала на любой работе, где сделано и то, и другое.
    # Главная модуля показывает свои работы, а не все подряд, и решать «моя ли
    # это работа» модуль обязан по объявленному полю.
    module: Mapped[str] = mapped_column(String(MODULE_LEN), default="")

    deleted_at: Mapped[datetime.datetime | None] = mapped_column(
        DateTime(timezone=True), default=None, index=True)
    purge_after: Mapped[datetime.datetime | None] = mapped_column(
        DateTime(timezone=True), default=None, index=True)


class ProjectRun(Row):
    """Одна запись журнала запусков: что в этой работе делали и когда.

    **Зачем журнал вообще.** Работа переживает много запусков разных модулей —
    отчёт, задание, две блок-схемы, — и до этой таблицы у проекта не было
    списка сделанного: карточка показывала переходы в модули, то есть «куда
    можно пойти», а не «что тут есть». При двух схемах на проект такой переход
    не отвечал ни на один вопрос человека.

    **Строка в базе, а не обход тома.** Артефакты на томе адресуются
    содержимым и имени не имеют вовсе (`Project.put_artifact` принимает имя
    только для читаемости вызова), а список запусков нужен именно с именами,
    порядком и сортировкой. Поэтому «что и когда запускали» — индекс в базе, как
    и сам проект, а произведённое остаётся файлами.

    `n` — порядковый номер запуска этого модуля в этой работе, с единицы.
    Считает его служба, а не клиент: два браузера, открывшие проект разом,
    придумали бы одно и то же «Схема 2». Из него интерфейс строит имя по
    умолчанию для запуска, которому имени не дали, — и строит **на своём
    языке**, поэтому текста имени служба за него не сочиняет.

    `artifact_id` — то, что запуск произвёл, если произвёл: XML схемы, собранный
    документ. Пусто — законно: у отчёта и задания результат живёт в самой
    работе (значения тегов, блоки), а не отдельным файлом.

    **Удаление записи не трогает артефакт.** Артефакт адресуется содержимым и
    может стоять значением тега — снести его вслед за строкой журнала значило бы
    выбить картинку из готового документа. Место при этом освобождает уборка
    проекта целиком.
    """

    __tablename__ = "project_runs"

    project_id: Mapped[str] = mapped_column(
        String(ID_LEN), ForeignKey("projects.id", ondelete="CASCADE"))

    # Кто запустил. `SET NULL`, а не `CASCADE`: журнал работы — свойство работы,
    # и уход человека из службы не должен стирать историю проекта, которым
    # пользуются другие участники пространства.
    user_id: Mapped[str | None] = mapped_column(
        String(ID_LEN), ForeignKey("users.id", ondelete="SET NULL"),
        default=None)

    module: Mapped[str] = mapped_column(String(MODULE_LEN))
    name: Mapped[str] = mapped_column(String(NAME_MAX), default="")
    n: Mapped[int] = mapped_column(Integer, default=1)
    artifact_id: Mapped[str | None] = mapped_column(
        String(ARTIFACT_LEN), default=None)

    # Единственный запрос к таблице — «журнал этой работы, новые сверху»; он же
    # с отбором по модулю. Пара и есть индекс.
    __table_args__ = (
        Index("ix_project_runs_project_created", "project_id", "created_at"),
    )


__all__ = ["Project", "ProjectRun", "NAME_MAX", "MODULE_LEN", "ARTIFACT_LEN"]
