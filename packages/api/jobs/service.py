"""
service — постановка задания, выборка своих, отмена и уборка старых.

Ни одного `Request`: всё берёт сессию и идентификаторы, как `workspaces.service`
и по той же причине. Задания ставит не только маршрут `POST /api/jobs`: их
поставит загрузка материала (разбор идёт через очередь), поставит кнопка
«собрать отчёт», поставит однажды консольная команда. Функция постановки,
написанная зависимостью FastAPI, пишется во второй раз в первом же из этих
мест — и пишется чуть иначе.

    Как поставить задание из кода
    -----------------------------

        from ..jobs import service as jobs

        задание = jobs.enqueue(s, user, "parse", {"material": mid},
                               project_id=проект.id)

`user` — строка `accounts.User` (нужен только `id`), `payload` — словарь,
форму которого знает обработчик вида. Проверки внутри две и обе обязательные:
вид должен быть в закрытом списке (`registry.check_kind`, иначе `400
unknown_job_kind`) и, если вид объявлен привязанным к проекту, спрашивающий
должен быть в этом проекте не ниже `editor`.

**Отказа «слишком много заданий» здесь нет.** Слоты — 2 на машину и 1 на
пользователя, остальные ждут в очереди. Значит лимит — это
свойство **захвата**, а не постановки: второе задание человека ложится в базу и
ждёт, а не получает 429. Разница видна на кнопке: отказ заставил бы интерфейс
писать «попробуйте позже», очередь позволяет написать «второе в очереди».

    Что видит клиент
    ----------------

`карточка` — единственная форма задания наружу, и в ней нет `worker_id`,
`heartbeat_at` и `attempt`: чьей машиной и с какой попытки сделана работа, —
наше внутреннее дело, а не договор с клиентом (те же поля покажет админка,
у неё другой договор). `payload` отдаётся: его прислал сам клиент.

Коды отказа этого модуля:

    unknown_job_kind    400  вида нет в закрытом списке
    unknown_job_status  400  такого состояния не бывает
    project_required    400  вид задания требует проекта, а его не дали
    limit_exhausted     402  на цену этого вида месячного остатка не хватает
    not_found           404  нет такого задания, или оно чужое
    forbidden           403  проект есть, роли мало
    in_trash            409  проект в корзине
    already_finished    409  отменять нечего: задание уже кончилось
"""
from __future__ import annotations

import datetime

from sqlalchemy import delete, select
from sqlalchemy.orm import Session

from ..db import now
from ..errors import ApiError, NOT_FOUND
from ..ids import check_id
from ..settings import Settings
from ..workspaces.service import EDITOR, iso, require_role
from . import registry
from .models import (CANCELLED, JobEvent, QUEUED, RUNNING, STATUSES, TERMINAL,
                     Job)

PROJECT_REQUIRED = "project_required"
UNKNOWN_JOB_STATUS = "unknown_job_status"
ALREADY_FINISHED = "already_finished"
IN_TRASH = "in_trash"


# ── постановка ───────────────────────────────────────────────────────────────

def enqueue(s: Session, user, kind: str, payload: dict | None = None, *,
            project_id: str | None = None, settings: Settings | None = None) -> Job:
    """Поставить задание в очередь. → строка `Job` (уже с `id`).

    Порядок проверок — вид, проект, роль, корзина, — и он не случаен: отвечать
    «проект в корзине» на неизвестный вид значило бы рассказывать про чужой
    проект тому, кто и вида-то назвать не сумел.

    `settings` нужен одной проверке — месячному лимиту расхода: и потолок
    (`KORITSU_FREE_MONTHLY_UNITS`), и цена вида (`KORITSU_PRICE_<KIND>`)
    считаются из настроек, а сессия про них не знает. Не дали — лимит здесь не
    проверяется, и это законно ровно в одном случае: постановка из кода, где
    вид задания выбрали мы сами. Отказ на постановке — удобство человека, а не
    заслон: настоящий заслон стоит на захвате, где цена и списывается.

    Строка сбрасывается (`flush`), но не коммитится: коммит делает тот, кто
    владеет сессией (зависимость `db.session` на запросе, `session_scope` в
    коде). Иначе постановка задания, случившаяся посреди загрузки материала,
    закрепилась бы даже тогда, когда сама загрузка откатилась, — и воркер взял
    бы задание на файл, которого нет.
    """
    registry.check_kind(kind)
    # Реестр наполняется импортом, а веб-процесс обработчиков не исполняет и
    # потому сам их не импортирует. Без этой строки `needs_project` отвечал бы
    # по умолчанию, а не по объявлению вида, — и задание, которому проект не
    # нужен, требовало бы проект. Вызов идемпотентен и стоит поиска в словаре.
    registry.load_handlers()

    # Месячный лимит. Проверяется **до** записи в очередь и по цене
    # этого вида: платит человек за запуск нашего кода, а не за токены
    # поставщика, значит спрашивать «хватит ли» надо у всякого вида, у которого
    # есть цена, — не только у зовущих модель. Бесплатный `probe` проходит
    # всегда: его цена ноль, и проверка это знает сама, без второго списка.
    #
    # Отказ здесь дешевле отказа в обработчике: тот случился бы через минуту
    # ожидания в очереди и выглядел бы как упавший прогон.
    if settings is not None:
        from ..runs import limits                              # noqa: PLC0415

        limits.проверить(s, settings, user, kind=kind)

    if registry.needs_project(kind):
        if not project_id:
            raise ApiError(PROJECT_REQUIRED,
                           f"Job kind '{kind}' requires a project", 400,
                           where="body.project_id")
        _проверить_проект(s, user, project_id)
    elif project_id:
        # Проект назвали заданию, которому он не нужен: всё равно проверяем
        # доступ. Записать чужой `project_id` в своё задание — это способ
        # показать чужой идентификатор в своей карточке.
        _проверить_проект(s, user, project_id)

    задание = Job(user_id=user.id, project_id=project_id or None, kind=kind,
                  payload=dict(payload or {}), status=QUEUED,
                  last_seen_at=now())
    s.add(задание)
    s.flush()
    return задание


def _проверить_проект(s: Session, user, project_id: str) -> None:
    """Есть ли у этого человека право заводить работу в этом проекте.

    Порядок тот же, что у `projects.routes.доступный`, и повторён он здесь не
    от небрежности: тот живёт в маршруте и берёт `CurrentUser`, а постановку
    зовут и вне запроса. Проверки же — строка проекта, роль в его пространстве,
    корзина — обязаны совпадать, иначе очередь окажется дырой в правах.
    """
    from ..projects.service import get_row                  # noqa: PLC0415

    p = get_row(s, check_id(project_id, where="body.project_id"),
                where="body.project_id")
    require_role(s, user.id, p.workspace_id, EDITOR, where="body.project_id")
    if p.deleted_at is not None:
        raise ApiError(IN_TRASH, "Project is in the trash", 409,
                       where="body.project_id")


# ── выборка ──────────────────────────────────────────────────────────────────

def check_status(status: str, *, where: str = "query.status") -> str:
    """Состояние из запроса или внятный отказ. Список закрыт (`models.STATUSES`)."""
    if status not in STATUSES:
        raise ApiError(UNKNOWN_JOB_STATUS,
                       f"Status must be one of: {', '.join(STATUSES)}",
                       400, where=where)
    return status


def мои(s: Session, user_id: str, *, project_id: str | None = None,
        status: str | None = None, limit: int = 100) -> list[Job]:
    """Задания этого человека, новые сверху.

    Только свои, и это не фильтр удобства, а единственная проверка доступа в
    списке: задание принадлежит тому, кто его поставил, — даже если проект
    общий. Чужое задание в общем проекте не показывается никому, кроме автора,
    потому что в `payload` лежит то, что он написал (наружу уезжает только
    своё).
    """
    запрос = select(Job).where(Job.user_id == user_id)
    if project_id is not None:
        запрос = запрос.where(Job.project_id == check_id(
            project_id, where="query.project_id"))
    if status is not None:
        запрос = запрос.where(Job.status == check_status(status))
    запрос = запрос.order_by(Job.created_at.desc(), Job.id).limit(int(limit))
    return list(s.scalars(запрос))


def в_работе(s: Session, project_id: str, *, kind: str | None = None,
             limit: int = 200) -> list[Job]:
    """Незаконченные задания **проекта**, старые сверху. Не «мои», а «его».

    Отличие от `мои` не в фильтре, а в том, чей это список. `мои` показывает
    работу человека — там `payload` его, и чужого туда попасть не должно. Здесь
    список принадлежит проекту: разбор файла, поставленный соседом по общему
    пространству, кончится материалом **этого проекта**, и не показать его
    участнику значило бы показать ему опись, в которой файлы появляются
    ниоткуда. Доступ к проекту при этом уже проверен маршрутом — своей проверки
    здесь нет намеренно, чтобы не было и второго её описания.

    Только `queued` и `running`: законченное кончилось, и разговор о нём —
    карточка задания с её `result` и `error`, а не список ожидающих, где ему
    пришлось бы жить вечно.

    Порядок обратный `мои` — старые сверху: это очередь, и первым в ней стоит
    тот, кто ждёт дольше.
    """
    запрос = (select(Job)
              .where(Job.project_id == check_id(project_id,
                                                where="path.project_id"),
                     Job.status.in_((QUEUED, RUNNING))))
    if kind is not None:
        запрос = запрос.where(Job.kind == registry.check_kind(kind))
    запрос = запрос.order_by(Job.created_at, Job.id).limit(int(limit))
    return list(s.scalars(запрос))


def получить(s: Session, user_id: str, job_id: str) -> Job:
    """Задание, если оно этого человека. Иначе — 404, а не 403.

    Чужое задание отвечает так же, как несуществующее: 403 сообщил бы, что
    задание с таким идентификатором есть, то есть отвечал бы на вопрос, задавать
    который спрашивающему не позволено (тот же довод, что у чужого проекта).
    """
    задание = s.get(Job, check_id(job_id, where="path.job_id"))
    if задание is None or задание.user_id != user_id:
        raise ApiError(NOT_FOUND, "Job not found", 404, where="path.job_id")
    return задание


def события(s: Session, job_id: str, *, after: int = 0,
            limit: int = 500) -> list[JobEvent]:
    """События задания по порядку, начиная за номером `after`.

    `after`, а не смещение: клиент дочитывает поток с места обрыва, а смещение
    после уборки старых событий указывало бы не туда, куда указывало минуту
    назад.
    """
    запрос = (select(JobEvent).where(JobEvent.job_id == job_id,
                                     JobEvent.seq > int(after))
              .order_by(JobEvent.seq).limit(int(limit)))
    return list(s.scalars(запрос))


# ── отмена ───────────────────────────────────────────────────────────────────

def отменить(s: Session, задание: Job) -> Job:
    """Попросить задание остановиться. → та же строка.

    Два случая, и они разные по существу:

    * задание ещё ждёт (`queued`) — его никто не брал, останавливать нечего:
      сразу `cancelled`, уведомление здесь же, и воркер его уже не увидит;
    * задание работает (`running`) — ставится флаг, и всё. Убить процесс мы
      могли бы, но закрытые теги обязаны остаться, а это возможно только
      если обработчик остановится сам, между шагами (`ctx.cancelled()`).
      Воркер добьёт процесс, если тот не послушался, — но лишь по истечении
      срока, а не сразу.

    Законченное не отменяется: `409 already_finished`. Молча отвечать «хорошо»
    на отмену сделанной работы значило бы врать интерфейсу, который после этого
    показал бы «отменено» на готовом отчёте.
    """
    if задание.terminal:
        raise ApiError(ALREADY_FINISHED,
                       f"Job is already {задание.status}", 409,
                       where="path.job_id")
    задание.cancel_requested = True
    if задание.status == QUEUED:
        задание.status = CANCELLED
        задание.finished_at = now()
        # Колокольчик. Ждущее задание кончается прямо
        # здесь, и воркер его уже не увидит — значит `при_завершении`, которое
        # обычно зовёт он, позвать больше некому. Без этой строки отменённое до
        # захвата задание было бы единственным терминальным состоянием службы
        # без строки в списке уведомлений.
        from ..notifications.service import при_завершении     # noqa: PLC0415

        при_завершении(s, задание)
    s.flush()
    return задание


# ── уборка ───────────────────────────────────────────────────────────────────

def убрать_старые(s: Session, settings: Settings) -> list[str]:
    """Удалить законченные задания, о которых давно не спрашивали.

    Срок хранения — 90 дней с последнего обращения; потом удаляются и запись
    задания, и её артефакты. Отсюда три свойства уборки:

    * считается `last_seen_at`, а не `finished_at`: отчёт, который человек
      открывает раз в месяц, живёт, пока его открывают;
    * убираются **только** законченные. `queued`, не дождавшееся воркера
      девяносто дней, — это беда очереди, и стирать её значило бы прятать;
    * события уходят вместе с заданием. Здесь — явным запросом, хотя внешний
      ключ и объявлен `ON DELETE CASCADE`: каскад делает то же самое, но по
      одной строке за раз, а событий на задание бывают тысячи.

    Артефакты лежат в каталоге проекта и уходят с ним; отдельного хранилища
    у задания нет — см. `models`.
    """
    порог = now() - datetime.timedelta(days=settings.jobs_retention_days)
    старые = list(s.scalars(select(Job).where(Job.status.in_(TERMINAL),
                                              Job.last_seen_at < порог)))
    if not старые:
        return []
    ид = [j.id for j in старые]
    s.execute(delete(JobEvent).where(JobEvent.job_id.in_(ид)))
    s.execute(delete(Job).where(Job.id.in_(ид)))
    s.flush()
    return ид


# ── расход за месяц ──────────────────────────────────────────────────────────
#
# Единственное место службы, где складывается `jobs.spent_units`. Складывают
# его двое: маршрут `GET /api/usage` (сколько человек истратил из своего
# месячного лимита, `runs.limits`) и список людей в админке (`admin.service`).
# Раньше у каждого была своя сумма и свой «первый день месяца», и разойтись
# они могли молча — а расходятся такие пары там, где это дороже всего
# видно: человеку отказали бы по одному числу, а владелец в админке видел бы
# другое. Колонка живёт здесь, значит и сумма живёт здесь.


def начало_месяца(момент: datetime.datetime | None = None) -> datetime.datetime:
    """Первое число этого месяца, 00:00 UTC — граница расчётного периода.

    UTC, а не местное время: месяц, считаемый в часовом поясе сервера, менялся
    бы при переезде контейнера, и человек получал бы отказ на день раньше или
    позже без единого изменения в своей работе.
    """
    м = момент or now()
    return м.replace(day=1, hour=0, minute=0, second=0, microsecond=0)


def расход_за_месяц(s: Session, *, начало: datetime.datetime | None = None,
                    user_id: str | None = None) -> dict[str, int]:
    """Сколько приведённых единиц истрачено за календарный месяц, по людям.

    Одним запросом с группировкой, а не запросом на человека: список людей в
    админке — это N строк, и запрос на строку превращает страницу в N запросов
    к SQLite (та самая беда «N+1», не видная на трёх пользователях и видная на
    трёхстах). `user_id` сужает выборку до одного человека — тогда это тот же
    запрос с одной строкой в ответе, а не второй способ считать.

    **Месяц считается по `jobs.created_at`.** Задание принадлежит месяцу, в
    котором его завели, — иначе прогон, начатый 31-го и кончившийся 1-го, менял
    бы месяц по ходу работы, и остаток прыгал бы у человека на глазах.

    Отменённые и упавшие задания считаются наравне с готовыми: они потратили
    то, что успели, и не считать этого значило бы отдать расход бесплатно ровно
    тем, кто отменяет прогон на последнем теге.

    Человек, не потративший ничего, в ответе не появляется вовсе — у суммы по
    группам нет строки без строк. Читатель обязан спрашивать с умолчанием
    (`.get(user_id, 0)`), а не по ключу.
    """
    from sqlalchemy import func                                # noqa: PLC0415

    порог = начало or начало_месяца()
    запрос = (select(Job.user_id, func.coalesce(func.sum(Job.spent_units), 0))
              .where(Job.created_at >= порог)
              .group_by(Job.user_id))
    if user_id is not None:
        запрос = запрос.where(Job.user_id == user_id)
    return {uid: int(сумма or 0) for uid, сумма in s.execute(запрос).all()}


# ── наружу ───────────────────────────────────────────────────────────────────

def карточка(задание: Job) -> dict:
    """Задание наружу. Без `worker_id`, `heartbeat_at` и `attempt` — см. модуль."""
    return {
        "id": задание.id,
        "kind": задание.kind,
        "status": задание.status,
        "project_id": задание.project_id,
        "payload": задание.payload or {},
        "progress": задание.progress,
        "result": задание.result,
        "error": задание.error,
        "spent_units": int(задание.spent_units or 0),
        "cancel_requested": bool(задание.cancel_requested),
        "created_at": iso(задание.created_at),
        "started_at": iso(задание.started_at),
        "finished_at": iso(задание.finished_at),
    }


def карточка_события(событие: JobEvent) -> dict:
    """Событие наружу. Та же форма, в которой его отдаёт SSE."""
    return {"seq": событие.seq, "kind": событие.kind,
            "data": событие.data or {}, "at": iso(событие.created_at)}


