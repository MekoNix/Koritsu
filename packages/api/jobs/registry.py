"""
registry — какие бывают виды заданий и кто их исполняет.

Реестр, а не `if kind == ...` в воркере, ровно по той причине, по которой у
службы один формат ошибки: ветвление по виду задания, написанное в воркере,
пишется второй раз в постановке (проверить вид), третий — в маршруте отмены
(можно ли отменять), и три списка расходятся молча. Здесь список один.

    Как добавить новый вид задания
    ------------------------------

Три шага, и ни одного из них нельзя пропустить.

1. **Имя вида — в `ВИДЫ`.** Список закрыт (решение владельца §11 перечисляет
   виды поимённо), и постановка неизвестного вида — отказ `400
   unknown_job_kind`, а не строка в базе, которую никто никогда не возьмёт.

2. **Обработчик — в своём модуле, с декоратором.** Не здесь: `registry` знает
   про виды, но не про прогоны модели и не про архивы, иначе очередь начнёт
   импортировать `orchestrator` и `hokoku`.

       # packages/api/runs/handlers.py                (агент B)
       from ..jobs.registry import register

       @register("fill_tag", needs_secret=True)
       def заполнить_тег(ctx) -> dict:
           тег = ctx.job.payload["key"]
           ctx.progress(0, 1, note=тег)
           if ctx.cancelled():
               return {"cancelled_before": тег}
           ctx.emit({"kind": "text", "text": "…"})
           return {"key": тег, "version": 3}

   Обработчик получает **один** аргумент — `JobContext` (`context.py`), и
   возвращает словарь: он ляжет в `job.result` как есть, поэтому в нём место
   идентификаторам, а не содержимому (модель `models.py` объясняет, почему).
   Исключение из обработчика — это `failed`; наружу от него уедет только
   `{code, message}`, трассировка уйдёт в журнал.

3. **Строка импорта — в `load_handlers()`.** Модуль, который никто не
   импортировал, себя не регистрирует, и вид задания окажется известным
   постановке (он в `ВИДЫ`), но не воркеру. Тот же случай, что и с
   `api.models`: метаданные наполняются импортом, а не объявлением.

    Два флага регистрации
    ---------------------

`needs_project=True` (умолчание) — заданию нужен проект: постановка требует
`project_id` и роль `editor` в нём. `False` — задание про человека целиком
(таким будет, например, выгрузка всех проектов).

`needs_secret=False` (умолчание) — **решение главной сессии, вариант C.**
Обработчик исполняется в подпроцессе с вычищенным окружением (`api/subproc.py`,
тот же, в котором строятся схемы), а настройки уезжают туда каналом, JSON на
stdin. `KORITSU_SECRET` из настроек при этом **вырезается**, если вид задания не
объявил `needs_secret=True`. Кому он нужен: `fill_tag`, `fill_report`, `agent`,
`kadai_*` — они зовут `keys.resolve_key`, а расшифровка ключа модели идёт
секретом сервера. Кому не нужен и кто его не получит: `parse` (чужой PDF в
чужом разборщике), `export`, `build`. Смысл флага именно в `parse`: код,
читающий присланный человеком файл, не должен иметь при себе то, чем
расшифровываются ключи всех остальных.

Обработчик с `needs_secret=True` берёт настройки как обычно — `ctx.settings`, —
и зовёт `keys.resolve_key(ctx.settings, сессия, ctx.job.user_id, поставщик)`.
Обработчик без флага получает те же настройки с секретом-заглушкой; попытка
расшифровать чужой ключ ими даст `КлючНеЧитается`, а не тихо неверный ключ.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Callable, Iterable, TYPE_CHECKING

from ..errors import ApiError, ConfigError

if TYPE_CHECKING:                                    # только для подсказки типа
    from .context import JobContext

# Закрытый список видов (§11 записки владельца плюс задания курса `kadai`).
# Строки, а не Enum: они уезжают в JSON и в URL, и лишний слой между строкой и
# строкой стоил бы двух преобразований на каждом маршруте.
FILL_TAG = "fill_tag"
FILL_REPORT = "fill_report"
AGENT = "agent"
BUILD = "build"
PARSE = "parse"
EXPORT = "export"
KADAI_RUN = "kadai_run"
KADAI_REWORK = "kadai_rework"

# Девятый вид, которого нет в записке владельца, и он там не нужен: `probe` —
# проба самой очереди. Обработчик его ничего не делает с проектом и ничем не
# платит; он отвечает тем, что ему дали, и умеет по просьбе поспать, сообщить о
# ходе работы и упасть. Нужен затем, что «воркер жив» — утверждение, которое
# иначе проверяется только настоящей работой человека: админка (агент C) ставит
# пробу и смотрит, дошла ли она до `done`. Он же — единственный вид, на котором
# проверяемы подпроцесс, таймаут и отмена, пока настоящих обработчиков нет.
PROBE = "probe"

ВИДЫ = (FILL_TAG, FILL_REPORT, AGENT, BUILD, PARSE, EXPORT,
        KADAI_RUN, KADAI_REWORK, PROBE)

UNKNOWN_JOB_KIND = "unknown_job_kind"

Обработчик = Callable[["JobContext"], dict]


@dataclass(frozen=True)
class Регистрация:
    """Что известно про один вид задания: кто его делает и что ему нужно."""

    kind: str
    fn: Обработчик
    needs_project: bool = True
    needs_secret: bool = False


# Заполняется декоратором `register`. Один на процесс — и этого достаточно:
# реестр описывает код, а не состояние, и двух разных наборов обработчиков в
# одном процессе быть не может.
_ОБРАБОТЧИКИ: dict[str, Регистрация] = {}


def register(kind: str, *, needs_project: bool = True,
             needs_secret: bool = False) -> Callable[[Обработчик], Обработчик]:
    """Объявить обработчик вида задания. Декоратор.

    Вид обязан быть в `ВИДЫ`: иначе постановка такого задания всё равно
    отказала бы, и обработчик оказался бы кодом, который невозможно позвать.
    Вторая регистрация того же вида — тоже беда настройки, а не «последняя
    побеждает»: два обработчика одного вида означают, что задание делает то
    один, то другой, в зависимости от порядка импорта.

    Функция возвращается неизменной, поэтому её по-прежнему можно позвать прямо
    — тесту обработчика очередь не нужна.
    """
    if kind not in ВИДЫ:
        raise ConfigError(
            f"вид задания {kind!r} не объявлен в registry.ВИДЫ — "
            f"известны: {', '.join(ВИДЫ)}")

    def декоратор(fn: Обработчик) -> Обработчик:
        уже = _ОБРАБОТЧИКИ.get(kind)
        if уже is not None and уже.fn is not fn:
            raise ConfigError(
                f"вид задания {kind!r} уже зарегистрирован за "
                f"{уже.fn.__module__}.{уже.fn.__qualname__}")
        _ОБРАБОТЧИКИ[kind] = Регистрация(kind=kind, fn=fn,
                                         needs_project=needs_project,
                                         needs_secret=needs_secret)
        return fn

    return декоратор


def load_handlers() -> None:
    """Импортировать модули, которые регистрируют обработчики. Идемпотентно.

    Зовут её двое: воркер перед первым захватом и подпроцесс перед вызовом
    обработчика. Оба — а не только воркер: подпроцесс импортирует пакет заново,
    с нуля, и реестр в нём пуст.

    Строк здесь ровно столько, сколько модулей с обработчиками: проба очереди,
    прогоны (B), разбор и выгрузка (D). Место для них одно — это, и новый вид
    задания без строки здесь окажется известным постановке (он в `ВИДЫ`), но не
    воркеру.

    Регистрация вызовом, а не декоратором на импорте, — у всех и по одной
    причине (`probe._зарегистрировать` объясняет её подробно): импорт случается
    один раз на процесс, и тест, почистивший реестр, обратно обработчик уже не
    получил бы.
    """
    from . import probe                                    # noqa: PLC0415

    probe._зарегистрировать()                    # проба очереди, см. `probe.py`

    # ── сюда B/D дописывают свои модули с обработчиками ──────────────────────
    from ..export import handlers as экспорт     # D: export
    from ..materials import jobs as разбор       # D: parse
    from ..runs import handlers as прогоны       # B: fill_tag, fill_report, agent,
                                                 #    build, kadai_run, kadai_rework

    прогоны.подключить()                              # прогоны, см. `runs/handlers/`
    разбор._зарегистрировать()                        # `parse`, см. `materials/jobs.py`
    экспорт._зарегистрировать()                       # `export`, см. `export/handlers.py`


def known(kind: str) -> bool:
    """Есть ли такой вид в закрытом списке. Без исключения — для условий."""
    return kind in ВИДЫ


def check_kind(kind: str, *, where: str = "body.kind") -> str:
    """Вид задания из запроса или внятный отказ клиенту.

    Отказывает по списку `ВИДЫ`, а не по наличию обработчика: вид, чей
    обработчик ещё не написан, — это `503` по смыслу, а никак не `400`, и
    путать их значило бы отвечать клиенту «ты ошибся» на нашу незаконченность.
    Проверку «обработчик есть» делает воркер (`worker`), в момент исполнения.
    """
    if not known(kind):
        raise ApiError(UNKNOWN_JOB_KIND,
                       f"Job kind must be one of: {', '.join(ВИДЫ)}",
                       400, where=where)
    return kind


def registration(kind: str) -> Регистрация | None:
    """Что зарегистрировано за этим видом. `None` — обработчика ещё нет."""
    return _ОБРАБОТЧИКИ.get(kind)


def handler_for(kind: str) -> Обработчик | None:
    """Сам обработчик или `None`. Форма для воркера."""
    рег = _ОБРАБОТЧИКИ.get(kind)
    return None if рег is None else рег.fn


def registered() -> Iterable[str]:
    """Виды, у которых обработчик уже есть. Для диагностики и админки (агент C)."""
    return tuple(_ОБРАБОТЧИКИ)


def needs_project(kind: str) -> bool:
    """Нужен ли этому виду проект. Неизвестному обработчику — да.

    Умолчание строгое намеренно: все восемь видов из §11 привязаны к проекту, и
    задание без проекта — исключение, которое обработчик обязан объявить сам.
    Мягкое умолчание («не знаю — значит не нужен») пустило бы задание без
    проверки роли, то есть мимо единственной проверки доступа, какая у очереди
    есть.
    """
    рег = _ОБРАБОТЧИКИ.get(kind)
    return True if рег is None else рег.needs_project


def needs_secret(kind: str) -> bool:
    """Уезжает ли секрет сервера в подпроцесс этого вида. Неизвестному — нет.

    Умолчание здесь обратной строгости, чем у `needs_project`, и по той же
    логике: и там, и тут неизвестность трактуется как «меньше прав». Не знаем
    вида — значит секрет не отдаём.
    """
    рег = _ОБРАБОТЧИКИ.get(kind)
    return False if рег is None else рег.needs_secret


def _забыть_всё() -> None:
    """Очистить реестр. Только для тестов: обработчик, зарегистрированный одним
    тестом, не должен доживать до следующего."""
    _ОБРАБОТЧИКИ.clear()


