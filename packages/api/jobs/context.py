"""
context — то единственное, что обработчик задания видит снаружи себя.

Обработчик получает один аргумент, `JobContext`, и через него делает ровно
шесть вещей: смотрит задание, берёт сессию базы, открывает проект, сообщает о
ходе работы, спрашивает «не отменили ли» и списывает потраченное. Больше ему не
дано ничего — ни `Request`, ни приложения, ни глобального движка. Причина
простая и проверяемая: обработчик исполняется **в другом процессе**, где
приложения нет вовсе, и всякое имя, взятое им не отсюда, там либо не
существует, либо существует другим объектом.

**Один и тот же класс работает в обоих случаях** — и в подпроцессе, и «в том же
процессе» (флаг `inline` воркера, ради тестов). Это и был довод в пользу того,
чтобы ребёнок писал в базу сам, а не слал кадры родителю: у канала к родителю
пришлось бы завести второй `JobContext`
— тот, что пишет в трубу, — и два описания одного договора разошлись бы на
первом же новом методе. Ребёнок и так обязан **читать** из базы (`cancelled()`
без базы не работает), значит соединение у него есть по необходимости, и запись
через него же ничего нового не открывает.

SQLite это переживает: база в WAL (`db.make_engine`), писатель в каждый момент
один, ожидание замка — пять секунд (`PRAGMA busy_timeout`), а транзакции здесь
короткие до предела — одна вставка или одно обновление по первичному ключу.
Долгих транзакций из обработчика быть не должно, и это единственное правило,
которое `JobContext` требует соблюдать снаружи: `with ctx.session_scope() as s`
на всю работу — это удержанный на всю работу замок записи.

**Чего ребёнок не делает: не ставит состояние задания.** `queued → running →
done/failed/cancelled` пишет только родитель (`worker.py`), по результату на
stdout или по таймауту. Иначе убитый по таймауту ребёнок оставлял бы задание в
состоянии, которое сам же не успел досказать, — «running» навсегда либо «done»
при недоделанной работе. Ребёнку принадлежат три вещи: `progress`, события и
`spent_units`. Все три — приращения, и все три осмысленны сами по себе, даже
если процесса больше нет.

    Склейка текста
    --------------

Текст модели идёт кусками по несколько знаков. Писать по строке в базу на
каждый — это тысячи транзакций на один отчёт и такой же поток в SSE, где
клиенту он не нужен: человек читает не быстрее, чем раз в десятую долю
секунды. Поэтому события вида `text` копятся и уходят в базу склеенными, не
чаще чем раз в `СКЛЕЙКА_С` (~100 мс). Склейка — на стороне записи, а не
чтения: сделанная при чтении, она обязывала бы каждого читателя (SSE, простой
список маршрута, экспорт журнала) склеивать одинаково, и один из них склеивал
бы иначе.

Любое **не**текстовое событие сбрасывает буфер до себя: порядок обязан
сохраниться, иначе `tag_closed` окажется раньше текста, которым тег закрыли.

    Потолок событий
    ---------------

`СОБЫТИЙ_НА_ЗАДАНИЕ` строк на задание, и ни одной больше. Обработчик,
зациклившийся в шаге с `emit`, иначе кладёт том: миллион строк в SQLite — это
не «много записей», это база, которую перестаёт открывать сайт. По достижении
потолка пишется одно последнее событие `events_truncated`, и оно честнее
молчания: клиент видит, что поток обрезан нами, а не оборвался сам.
"""
from __future__ import annotations

import time
from typing import Any

from sqlalchemy import func, select

from ..db import Db
from ..settings import Settings
from .models import Job, JobEvent

# Не чаще чем раз в столько секунд текстовые куски уезжают в базу («текст
# модели по мере генерации, события склеиваются раз в ~100 мс»).
СКЛЕЙКА_С = 0.1

# Потолок строк событий на одно задание — см. докстроку модуля.
СОБЫТИЙ_НА_ЗАДАНИЕ = 2000

# Вид события, куски которого склеиваются. Один, а не список: склеивать можно
# только то, у чего склейка осмысленна, — текст. Два числа прогресса, сложенные
# вместе, дали бы бессмыслицу.
ВИД_ТЕКСТА = "text"

# Поле, в котором лежит текст такого события.
ПОЛЕ_ТЕКСТА = "text"

# Что пишется вместо оборванного хвоста.
ВИД_ОБРЕЗАНО = "events_truncated"

# Вид события, которым `progress` дублирует себя в поток.
ВИД_ПРОГРЕССА = "progress"


class JobContext:
    """Задание глазами его обработчика.

    Собирается воркером (или подпроцессом) на одно задание и живёт ровно
    столько, сколько это задание исполняется. Наружу службы не уезжает никогда.
    """

    def __init__(self, db: Db, settings: Settings, job_id: str, *,
                 склейка_с: float = СКЛЕЙКА_С,
                 потолок: int = СОБЫТИЙ_НА_ЗАДАНИЕ):
        self._db = db
        self.settings = settings
        self.job_id = job_id
        self._склейка_с = float(склейка_с)
        self._потолок = int(потолок)

        # Снимок задания: `payload`, `kind`, `user_id`, `project_id`. Читается
        # один раз и не перечитывается — всё это при живом задании неизменно, а
        # перечитывание на каждое обращение означало бы поход в базу из каждой
        # строки обработчика.
        with self._db.session_scope() as s:
            строка = s.get(Job, job_id)
            if строка is None:
                raise LookupError(f"задания {job_id} нет в базе")
            s.expunge(строка)
            self._job = строка
            # Номер следующего события. От максимума, а не с единицы: задание,
            # поднятое после потерянного воркера, продолжает свой поток, а не
            # начинает второй с теми же номерами.
            self._seq = int(s.scalar(
                select(func.coalesce(func.max(JobEvent.seq), 0))
                .where(JobEvent.job_id == job_id)) or 0)

        self._буфер: list[str] = []
        # Отсчёт склейки начинается с рождения контекста, а не с нуля: нулём
        # первый же кусок текста считался бы «просроченным» и уезжал бы в базу
        # отдельной строкой — то есть склейка не работала бы ровно в начале
        # ответа модели, где кусков больше всего.
        self._сброшено = time.monotonic()
        self._обрезано = False
        self._проект = None

    # ── что видно обработчику ───────────────────────────────────────────────

    @property
    def job(self) -> Job:
        """Снимок строки задания: `kind`, `payload`, `user_id`, `project_id`.

        Отвязан от сессии намеренно: живая строка держала бы открытую сессию всё
        время работы обработчика, то есть транзакцию длиной в прогон модели.
        Меняющиеся поля (`spent_units`, `progress`) здесь не смотрят — их пишет
        сам обработчик и знает без базы.
        """
        return self._job

    @property
    def session_scope(self):
        """Сессия базы на кусок работы: `with ctx.session_scope() as s`.

        Держать её открытой всю работу нельзя — см. докстроку модуля.
        """
        return self._db.session_scope

    @property
    def project(self):
        """Каталог проекта как `orchestrator.Project`. Лениво и один раз.

        Лениво, потому что заданию без проекта (`needs_project=False`) он не
        нужен вовсе, а открытие читает манифест с тома. Один раз, потому что
        `orchestrator.Project` — это и есть открытый каталог, и второй объект на
        тот же каталог означал бы два кэша манифеста.

        **Какой документ работы открыт, говорит `payload.report`.** В работе
        несколько отчётов, у каждого свой бланк и свои значения, и задание
        обязано писать в тот, из которого его поставили. Читается это здесь, а
        не в каждом обработчике: пять обработчиков, читающих одно поле
        по-своему, однажды прочтут его по-разному, и один из них молча запишет
        значение в чужой документ. Поля нет — единственный документ работы.

        **Какое решение открыто, говорит `payload.run_id`** — то же самое для
        модуля решений, где в работе несколько задач, у каждой свой ход стадий
        и своя папка файлов контекста. Читается здесь и по той же причине.
        """
        if self._проект is None:
            import orchestrator                              # noqa: PLC0415

            from ..projects.service import project_dir       # noqa: PLC0415

            if not self._job.project_id:
                raise LookupError(
                    f"задание {self.job_id} ({self._job.kind}) не привязано к "
                    "проекту, а обработчик просит его каталог")
            with self._db.session_scope() as s:
                каталог = project_dir(s, self.settings, self._job.project_id)
            self._проект = orchestrator.Project(каталог, report=self.report,
                                                solution=self.solution)
        return self._проект

    @property
    def report(self) -> str:
        """Документ работы, из которого поставлено задание, или пустая строка."""
        payload = self._job.payload or {}
        return str(payload.get("report") or "").strip()

    @property
    def solution(self) -> str:
        """Решение работы, из которого поставлено задание, или пустая строка."""
        payload = self._job.payload or {}
        return str(payload.get("run_id") or "").strip()

    # ── что обработчик пишет ────────────────────────────────────────────────

    def progress(self, step: int, total: int, note: str = "") -> None:
        """Сколько сделано: шаг из скольких и одно слово о том, что идёт.

        Пишет и колонку `progress` (её показывает карточка задания), и событие
        `progress` в поток (его показывает SSE). Оба сразу, а не одно
        на выбор: карточка нужна тому, кто открыл страницу минуту спустя, а
        поток — тому, кто смотрит сейчас, и просить обработчик написать одно и
        то же дважды значило бы однажды получить их разошедшимися.
        """
        тело = {"step": int(step), "total": int(total), "note": str(note or "")}
        with self._db.session_scope() as s:
            задание = s.get(Job, self.job_id)
            if задание is not None:
                # Присваивание целиком, а не правка словаря: за содержимым
                # колонки `JSON` SQLAlchemy не следит (см. `models`).
                задание.progress = тело
        self.emit({"kind": ВИД_ПРОГРЕССА, **тело})

    def emit(self, event: dict) -> None:
        """Событие в поток задания. Обязательный ключ — `kind`, остальное — тело.

            ctx.emit({"kind": "text", "text": "…кусок ответа модели…"})
            ctx.emit({"kind": "tag_closed", "key": "цель", "version": 3})

        Куски `text` склеиваются и уезжают в базу не чаще, чем раз в ~100 мс;
        любое другое событие сбрасывает накопленный текст перед собой, чтобы
        порядок остался тем же, в каком обработчик его писал.
        """
        if not isinstance(event, dict):
            raise TypeError("событие задания — словарь с ключом kind")
        вид = str(event.get("kind") or "").strip()
        if not вид:
            raise ValueError("у события задания нет kind")
        тело = {k: v for k, v in event.items() if k != "kind"}

        if вид == ВИД_ТЕКСТА:
            self._буфер.append(str(тело.get(ПОЛЕ_ТЕКСТА, "")))
            if time.monotonic() - self._сброшено >= self._склейка_с:
                self._сбросить_текст()
            return

        self._сбросить_текст()
        self._записать(вид, тело)

    def charge(self, units: int) -> None:
        """Доплата сверх цены вида: столько-то единиц поверх списанного.

        **Основную плату обработчик не считает**. Цену задания списывает
        воркер при захвате, по виду задания (`runs/limits.ЦЕНЫ`), и токены
        поставщика в неё не входят вовсе — они живут в журнале проекта, потому
        что это другой учёт. Здесь остался шов на случай, когда наш же код
        делает внутри одного задания что-то, чего цена вида не покрывает
        (десять схем в одном прогоне агента, скажем). Сегодня им пользуется
        только проба очереди (`probe`), и ею же он проверяется.

        Приращением в самой базе (`spent_units + :n`), а не «прочитал, сложил,
        записал»: второе теряет чужую прибавку, если списывают из двух мест, —
        а списывают из двух, как только у прогона появится параллельный шаг.
        """
        n = int(units)
        if n <= 0:
            return
        with self._db.session_scope() as s:
            s.query(Job).filter(Job.id == self.job_id).update(
                {Job.spent_units: Job.spent_units + n},
                synchronize_session=False)

    def cancelled(self) -> bool:
        """Просили ли остановиться. Спрашивают между шагами.

        Читает базу каждый раз, без кэша: кэш здесь означал бы, что отмена,
        нажатая человеком, доходит через раз, — а отмена обязана быть сразу.
        Запрос дешёвый: одна колонка по первичному ключу.
        """
        with self._db.session_scope() as s:
            return bool(s.scalar(select(Job.cancel_requested)
                                 .where(Job.id == self.job_id)))

    # ── конец работы ────────────────────────────────────────────────────────

    def close(self) -> None:
        """Дописать то, что осталось в буфере склейки.

        Зовёт подпроцесс (и воркер в режиме `inline`) после обработчика — при
        любом исходе, включая упавший. Несброшенный хвост текста — это последние
        слова модели, потерянные ровно тогда, когда они нужнее всего: в
        отчёте о том, почему прогон упал.
        """
        self._сбросить_текст()

    # ── внутреннее ──────────────────────────────────────────────────────────

    def _сбросить_текст(self) -> None:
        if not self._буфер:
            return
        склеенный = "".join(self._буфер)
        self._буфер.clear()
        self._сброшено = time.monotonic()
        if склеенный:
            self._записать(ВИД_ТЕКСТА, {ПОЛЕ_ТЕКСТА: склеенный})

    def _записать(self, вид: str, тело: dict[str, Any]) -> None:
        if self._обрезано:
            return
        if self._seq >= self._потолок:
            self._обрезано = True
            вид, тело = ВИД_ОБРЕЗАНО, {"limit": self._потолок}
        self._seq += 1
        with self._db.session_scope() as s:
            s.add(JobEvent(job_id=self.job_id, seq=self._seq, kind=вид,
                           data=тело))

    def __repr__(self) -> str:                              # для журнала и бед
        return f"<JobContext {self._job.kind} {self.job_id}>"


__all__ = ["JobContext", "СКЛЕЙКА_С", "СОБЫТИЙ_НА_ЗАДАНИЕ",
           "ВИД_ТЕКСТА", "ВИД_ОБРЕЗАНО", "ВИД_ПРОГРЕССА", "ПОЛЕ_ТЕКСТА"]
