"""
child — то, что происходит в подпроцессе задания, и только там.

Обработчик задания исполняется в отдельном процессе по тем же трём причинам, по
которым в отдельном процессе строятся схемы (`modules/diagrams.py`), — и они
здесь весомее, а не слабее:

* **таймаут исполняется.** Прогон модели ждёт сеть, сборка DOCX ждёт
  LibreOffice; поток, зависший в них, не прерывается ничем, процесс прерывается
  сигналом. Полчаса `job_timeout_s` без права их превысить — это и есть разница
  между «одно задание задумалось» и «очередь встала»;
* **лимит памяти исполняется.** `RLIMIT_AS` действует на процесс целиком:
  отчёт, собираемый из материала на тысячу страниц, упрётся в свой потолок и
  упадёт один, а не унесёт с собой воркер и все прочие задания;
* **окружение вычищено.** Тем же `api.subproc`, что чистит его разборщику
  материалов и построителю схем, — один запуск подпроцесса на всю службу, а не
  третий такой же: копия, где забыли вычистить окружение, работает ровно так
  же, как правильная, — до того дня, когда чужой код прочитает `KORITSU_SECRET`.

    Что уезжает каналом, а не окружением
    ------------------------------------

Настройки службы приходят сюда **JSON на stdin**, и это про одно:
`KORITSU_SECRET` не должен наследоваться дальше.
Обработчик зовёт внешние команды — tesseract у разбора, LibreOffice у сборки, —
и всякая переменная окружения родителя досталась бы им тоже. Канал же уходит
ровно в этот процесс и никуда больше.

Секрет и общие ключи поставщиков (`KORITSU_PROVIDER_KEY_*`) кладутся в канал
**только** видам, объявившим `needs_secret=True` (`registry`). Остальные —
`parse`, `export`, `build` — получают настройки с секретом-заглушкой, и это не
формальность: `parse` читает присланный человеком файл чужим разборщиком, и
секрет, которым расшифровываются ключи всех остальных, рядом с ним лежать не
должен.

    Что этот процесс пишет и чего не пишет
    --------------------------------------

Пишет: `progress`, строки `job_events`, `spent_units` — через `JobContext`,
своим движком базы (довод — в `context.py`).

Не пишет: **состояние задания**. `done`, `failed`, `cancelled` ставит родитель,
прочитав отсюда одну строку JSON. Причина ровно та, ради которой подпроцесс и
заведён: этот процесс могут убить в любой момент — по таймауту, по отмене, по
нехватке памяти, — и состояние, которое он не успел досказать, осталось бы
наполовину поставленным. Убитый процесс не может соврать; он может только
замолчать, и молчание родитель трактует сам.

Ответ — один словарь, который обёртка печатает на stdout строкой JSON
(`subproc.ПРОЛОГ` даёт для этого функцию `ответ`):

    {"ok": true,  "result": {...}, "cancelled": false}
    {"ok": false, "code": "handler_failed", "message": "…"}

Трассировка уходит в stderr и оттуда — в журнал родителя, целиком. Наружу от
неё не попадает ничего: в тексте исключения бывает и путь на томе, и кусок
чужого документа.
"""
from __future__ import annotations

import json
import os
import sys
import traceback

# Коды бед, которые может назвать этот процесс. Родитель добавляет к ним свои
# (`timeout`, `worker_lost`) — те, о которых отсюда сказать уже некому.
HANDLER_FAILED = "handler_failed"
NO_HANDLER = "no_handler"
BAD_RESULT = "bad_result"


def выполнить(задание: dict) -> dict:
    """Позвать обработчик и вернуть один словарь с исходом.

    Отдельной функцией, а не телом модуля: её зовёт крошечная обёртка,
    ставящая лимит памяти до импортов (`worker.ТЕЛО` поверх `subproc.ПРОЛОГ`),
    и никто больше. Импорты службы делаются **внутри**, после того как лимит
    уже стоит: FastAPI, SQLAlchemy и оркестратор импортируются с аппетитом, и
    лимит, поставленный после них, оставил бы без потолка самую дорогую часть.
    """
    from ..db import Db                                     # noqa: PLC0415
    from ..settings import Settings                         # noqa: PLC0415
    from . import registry                                  # noqa: PLC0415
    from .context import JobContext                         # noqa: PLC0415

    # Общие ключи поставщиков читает `keys.common_key` из окружения, и менять
    # его ради подпроцесса значило бы завести второй способ найти общий ключ.
    # Поэтому кладём переданное каналом обратно в окружение — здесь, в уже
    # вычищенном процессе, и только для видов с `needs_secret=True`.
    for имя, значение in (задание.get("ключи_окружения") or {}).items():
        os.environ[str(имя)] = str(значение)

    registry.load_handlers()

    настройки = Settings(**задание["настройки"])
    db = Db(настройки)
    try:
        ctx = JobContext(db, настройки, задание["job_id"])
        return позвать(ctx, registry.handler_for(ctx.job.kind))
    finally:
        db.dispose()


def позвать(ctx, обработчик) -> dict:
    """Позвать обработчик и привести любой исход к одному словарю.

    Живёт здесь, а зовут её из двух мест: этот подпроцесс и воркер в режиме
    `inline` (`worker.run_once(inline=True)`, ради тестов). Два места — но одно
    описание того, что считается успехом, что бедой и как беда выглядит наружу.
    Написанное дважды, оно разошлось бы там, где хуже всего: inline-путь
    отдавал бы клиенту текст исключения, потому что «тут же всё своё».

    `обработчик` может быть `None` — вид известен, а кода под него ещё нет.
    """
    from ..errors import ApiError                           # noqa: PLC0415

    if обработчик is None:
        return {"ok": False, "code": NO_HANDLER,
                "message": "No handler is registered for this job kind"}
    try:
        итог = обработчик(ctx)
    except ApiError as беда:
        # Обработчик отказал внятно и сам назвал код — отдаём как есть:
        # `no_key`, `limit_exhausted` и прочее клиенту полезнее, чем общий
        # `handler_failed`.
        traceback.print_exc(file=sys.stderr)
        ctx.close()
        return {"ok": False, "code": беда.code, "message": беда.message}
    except Exception:                                       # noqa: BLE001
        # Всё остальное — беда без права рассказать о себе наружу. Полный текст
        # в stderr, оттуда в журнал родителя.
        traceback.print_exc(file=sys.stderr)
        ctx.close()
        return {"ok": False, "code": HANDLER_FAILED,
                "message": "The job handler failed"}
    ctx.close()

    if not isinstance(итог, dict):
        return {"ok": False, "code": BAD_RESULT,
                "message": "The job handler returned no result"}
    try:
        json.dumps(итог)
    except (TypeError, ValueError):
        return {"ok": False, "code": BAD_RESULT,
                "message": "The job handler returned no result"}
    # Отмену **не** решаем сами: сообщаем, что просьба остановиться на момент
    # конца работы стояла, а состояние ставит родитель.
    return {"ok": True, "result": итог, "cancelled": bool(ctx.cancelled())}


__all__ = ["выполнить", "позвать", "HANDLER_FAILED", "NO_HANDLER",
           "BAD_RESULT"]
