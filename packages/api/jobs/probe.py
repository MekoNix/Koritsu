"""
probe — проба очереди: единственный обработчик, который служба возит с собой.

Зачем он есть. «Воркер жив» — утверждение, которое иначе проверяется только
чужой работой: человек нажал «собрать отчёт», ничего не произошло, и выясняется
это через полчаса. Проба закрывает этот разрыв: задание вида `probe`
ставится руками (или админкой), проходит ровно тот же путь, что
настоящее, — очередь, захват, подпроцесс, события, результат, — и ничего при
этом не делает. Дошло до `done` — жив весь путь целиком, включая базу,
подпроцесс и лимиты.

Он же — единственное, на чём проверяемы подпроцесс, таймаут и отмена, пока
настоящих обработчиков нет: тесты воркера ставят пробу, а не подсовывают
собственный обработчик в реестр, потому что подсунутый обработчик живёт в
процессе теста и в настоящий подпроцесс не попадает вовсе.

    Что умеет
    ---------

        payload                        что делает
        {"echo": <что угодно>}         вернёт это же в `result.echo`
        {"steps": 3}                   три шага с `progress` и текстом
        {"pause": 0.05}                пауза между шагами, секунды
        {"sleep": 2}                   поспать столько секунд и кончить
        {"charge": 100}                списать столько единиц
        {"fail": true}                 упасть

**Проекта не требует** (`needs_project=False`) и ничего на томе не трогает:
проба, которой нужен проект, была бы непригодна ровно тогда, когда нужнее
всего — когда проверяют службу, у которой ещё нет ни одного проекта.

**Секрет не получает** (`needs_secret=False`): платить ей нечем и незачем.

**Числа ограничены сверху, и это не педантизм.** `sleep` дольше `СОН_МАКС`
означал бы, что двое желающих занимают оба слота машины на полчаса задарма —
проба, ставшая способом остановить очередь. Слотов на машину два, и это
единственный вид задания, который любой может поставить без проекта; потолки
здесь и есть плата за такую доступность.
"""
from __future__ import annotations

import time

# Потолки. Числами в одном месте: `min(..., 5)`, написанный по месту, однажды
# окажется написан как `min(..., 500)`.
СОН_МАКС = 5.0          # секунд на одну пробу
ШАГОВ_МАКС = 20         # шагов прогресса
ПАУЗА_МАКС = 0.5        # секунд между шагами
СПИСАНИЕ_МАКС = 1000    # приведённых единиц


def _число(payload: dict, имя: str, умолчание: float, потолок: float) -> float:
    """Число из `payload`, обрезанное потолком. Мусор — умолчание.

    Мусор здесь именно умолчание, а не отказ: `payload` пробы человек набирает
    руками в админке, и уронить задание из-за `"steps": "три"` значило бы
    отвечать беду на опечатку в диагностическом средстве.
    """
    try:
        значение = float(payload.get(имя, умолчание))
    except (TypeError, ValueError):
        return умолчание
    return max(0.0, min(значение, потолок))


def проба(ctx) -> dict:
    """Пройти весь путь задания и ничего не сделать. → `{"echo": …, "steps": n}`.

    Порядок здесь — образец для настоящих обработчиков, и читать его стоит
    именно так: перед каждым шагом спросить `ctx.cancelled()`, после каждого
    сообщить `ctx.progress(...)`. Отмена, проверяемая раз в начале, — это
    отмена, которая не работает: человек нажимает её тогда, когда работа уже
    идёт.
    """
    payload = ctx.job.payload or {}

    if payload.get("fail"):
        # Нарочная беда. Наружу от неё уедет `{code: handler_failed}` без
        # единого слова отсюда — ровно это и проверяется пробой.
        raise RuntimeError("проба задания: нарочная беда по просьбе payload")

    сон = _число(payload, "sleep", 0.0, СОН_МАКС)
    if сон:
        time.sleep(сон)

    шагов = int(_число(payload, "steps", 0, ШАГОВ_МАКС))
    пауза = _число(payload, "pause", 0.0, ПАУЗА_МАКС)
    сделано = 0
    for шаг in range(1, шагов + 1):
        if ctx.cancelled():
            break
        ctx.progress(шаг, шагов, note=f"step {шаг}")
        ctx.emit({"kind": "text", "text": f"step {шаг} "})
        сделано = шаг
        if пауза:
            time.sleep(пауза)

    единицы = int(_число(payload, "charge", 0, СПИСАНИЕ_МАКС))
    if единицы:
        ctx.charge(единицы)

    return {"echo": payload.get("echo"), "steps": сделано}


def _зарегистрировать() -> None:
    """Поставить пробу в реестр. Зовётся из `registry.load_handlers`.

    Функцией, а не декоратором на уровне модуля, по одной причине: регистрация
    декоратором случается на импорте, то есть **один раз на процесс**, и тест,
    почистивший реестр (`registry._забыть_всё`), обратно её уже не получит —
    модуль-то в `sys.modules` остался. Вызов же идемпотентен: `register`
    молчит, если за видом стоит та же самая функция.

    Прочим обработчикам так делать не обязательно: декоратор на уровне
    модуля — обычная форма, и она правильная для всех, кроме единственного
    обработчика, который зовут тесты самой очереди.
    """
    from .registry import PROBE, register                   # noqa: PLC0415

    register(PROBE, needs_project=False, needs_secret=False)(проба)


