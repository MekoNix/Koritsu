"""
ids — наружу уезжают идентификаторы, а не пути.

Решение владельца §3: «клиент видит только идентификаторы, включая скачивание
результата». Правило звучит скучно, а держит две вещи сразу. Первая — обход
каталогов: пока клиент не называет путь, `../../etc/passwd` ему негде написать.
Вторая, менее очевидная и более дорогая: раскладка тома
(`/data/users/<uuid>/projects/<uuid>/`) остаётся нашим делом. Отдав путь наружу
однажды, мы отдали его навсегда — переезд каталога станет ломающей правкой API,
а он обещан (архив, экспорт, второй сервер).

Форма — канонический uuid4 с дефисами, 36 знаков (подтверждено владельцем
2026-09-03): ровно та, что стоит в путях тома в §2. Hex без дефисов был бы на
четыре знака короче в URL, но тогда путь на диске писался бы иначе, чем
идентификатор в ответе, и сопоставлять их пришлось бы глазами.

**Идентификаторы материалов и артефактов сюда не относятся.** У них своя форма
— 16 hex от sha256 содержимого (`materials.material_id`,
`orchestrator.artifact_id`), и она осмысленная: тот же файл — тот же
идентификатор, разбор второй раз не считается. Переписывать их в uuid значило бы
терять это свойство. Проверять их надо там, где они и заведены (`materials`,
`hokoku.wire`), а не заводить здесь третью копию правила.

Кому это нужно: C (проекты, workspace, корзина) и D (материалы, ключи) —
принимают идентификаторы от клиента и обязаны проверить форму **до** похода в
базу. `check_id` для этого и есть: он бросает `ApiError` с `where`, то есть
клиент получает `{"error": {"code": "invalid_id", "where": "path.project_id"}}`,
а не пятисотку из недр SQLAlchemy.
"""
from __future__ import annotations

import re
import uuid

from .errors import ApiError, INVALID_ID

# Канонический uuid4: 8-4-4-4-12, версия 4, вариант RFC 4122. Версию и вариант
# проверяем не из педантизма: `new_id` выдаёт только такие, и чужая форма в
# запросе означает, что идентификатор пришёл не от нас, — повод отказать сразу,
# а не искать несуществующую строку в базе.
ID_RE = re.compile(
    r"\A[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\Z")

ID_LEN = 36


def new_id() -> str:
    """Новый идентификатор строки. uuid4: случайный, без счётчика и без времени.

    Без счётчика — намеренно: последовательный номер сообщает чужому, сколько у
    нас пользователей и когда завёлся сосед, а угадать соседний идентификатор
    позволяет ещё и до проверки доступа.
    """
    return str(uuid.uuid4())


def is_id(значение: object) -> bool:
    """Похоже ли это на наш идентификатор. Без исключений — для условий."""
    return isinstance(значение, str) and ID_RE.match(значение) is not None


def check_id(значение: object, *, where: str | None = None) -> str:
    """Вернуть идентификатор или отказать клиенту внятно.

    `where` — место в запросе (`"path.project_id"`, `"body.material_id"`), оно
    уезжает в ответ. Текст — по-английски: его читает клиент (§7).
    """
    if not is_id(значение):
        raise ApiError(INVALID_ID, "Identifier must be a UUID", 400, where=where)
    return значение  # type: ignore[return-value]


__all__ = ["new_id", "is_id", "check_id", "ID_RE", "ID_LEN"]
