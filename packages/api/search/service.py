"""
service — где ищем, что считаем совпадением и почему не SQL'ем.

**Совпадение считает Python, а не база.** Напрашивался `ILIKE '%…%'`, и на
Postgres он бы работал; на SQLite — нет. `lower()` там знает только латиницу
(`lower('Ё')` возвращает `'Ё'`), а имена работ у нас русские, то есть поиск
«Сортировки» не нашёл бы «сортировки» ровно на той базе, на которой служба
запускается по умолчанию. Две ветки по виду базы — это два разных поиска,
которые разойдутся молча; одна питонья свёртка по именам — один.

Платим за это тем, что имена проектов человека приезжают в процесс целиком.
Их столько же, сколько у него работ, то есть десятки: квота на владельца — 250
МБ, и работа с материалами в неё влезает штук пятьдесят. Потолок обхода
всё равно стоит (`ПОТОЛОК_ПРОЕКТОВ`): «десятки» — это оценка, а не гарантия.

**Материалы лежат на томе, а не в базе,** и второго списка их нет (`materials.Store`
— единственный, кто знает, что такое разобранный материал). Поэтому по ним
ходим каталогами проектов и останавливаемся, как только набрали потолок:
подсказке в палитре двадцать первая строка не нужна, а обход тома стоит.

**Корзина не ищется.** Ни удалённые пространства, ни удалённые проекты: их
каталоги ещё на диске, но человек их выбросил, и находить их поиском значит
предлагать открыть то, чего он больше не ждёт.
"""
from __future__ import annotations

import orchestrator
from sqlalchemy import select
from sqlalchemy.orm import Session

from ..projects.models import Project
from ..projects.service import dir_for
from ..settings import Settings
from ..workspaces.models import Workspace, WorkspaceMember

# Сколько проектов человека вообще смотрим. Не «сколько отдаём» — сколько
# перебираем: обход тома за каждым материалом стоит, и работа, стоящая
# трёхсотой в списке, подсказки не ждёт.
ПОТОЛОК_ПРОЕКТОВ = 300

# Имя записи о работе `kadai` на томе. Отсюда же берётся ответ на вопрос, каким
# модулем открывать найденную работу: другого признака у проекта нет — модуль
# это не колонка в базе, а то, чем работу делали.
СОСТОЯНИЕ_KADAI = "kadai"


def привести(text: str) -> str:
    """К виду, в котором сравниваются имена: без регистра и без «ё».

    «Ёлка», «елка» и «ЕЛКА» — одно и то же слово, и человек, ищущий работу,
    помнит её название, а не его написание. То же правило, что у отбора в
    палитре на стороне сайта (`web/src/features/search/filter.ts`).
    """
    return str(text or "").lower().replace("ё", "е").strip()


def подходит(имя: str, запрос: str) -> bool:
    """Совпадение по подстроке, а не по началу.

    Работу зовут «Лабораторная 4 — сортировки», а набирают в поиске «сорти»:
    поиск по началу имени не нашёл бы её никогда.
    """
    return привести(запрос) in привести(имя)


def доступные(s: Session, user_id: str) -> list[tuple[Project, Workspace]]:
    """Проекты всех пространств человека — и своих, и чужих, где он участник.

    Участие проверяется по таблице участников, а не по `owner_id`: владелец
    пространства сам записан в неё же (`workspaces.service.create_personal`), и
    второе правило доступа рядом с первым разошлось бы с ним на первом же новом
    виде участия.
    """
    запрос = (select(Project, Workspace)
              .join(Workspace, Workspace.id == Project.workspace_id)
              .join(WorkspaceMember,
                    WorkspaceMember.workspace_id == Workspace.id)
              .where(WorkspaceMember.user_id == user_id,
                     Workspace.deleted_at.is_(None),
                     Project.deleted_at.is_(None))
              .order_by(Project.created_at)
              .limit(ПОТОЛОК_ПРОЕКТОВ))
    return [(p, ws) for p, ws in s.execute(запрос).all()]


def модуль(settings: Settings, p: Project) -> str:
    """Чем открывать найденную работу: `kadai` или `reports`.

    Читается это с тома одной записью состояния: работа `kadai` заводит её на
    первом же прогоне, а у отчёта её нет вовсе. Колонки в базе для этого не
    заводится — модуль не свойство проекта, а то, чем в нём работали, и
    проставленная при создании колонка врала бы про проект, открытый другим
    модулем.

    Каталог, которого нет, — это `reports`: проект, заведённый и ни разу не
    тронутый, открывается отчётом, и отказывать поиску из-за пустого каталога
    незачем.
    """
    try:
        на_томе = orchestrator.Project(dir_for(settings, p.owner_id, p.id))
        return "kadai" if на_томе.state(СОСТОЯНИЕ_KADAI) else "reports"
    except Exception:                                        # noqa: BLE001
        return "reports"


def проекты(строки, settings: Settings, запрос: str, limit: int) -> list[dict]:
    """Работы, в имени которых есть набранное. Не больше `limit`.

    Строки приходят снаружи, а не берутся здесь второй раз: маршрут спрашивает
    базу один раз и отдаёт один и тот же список обоим отборам — иначе поиск
    стоил бы двух одинаковых запросов, а между ними ещё и мог бы разъехаться.
    """
    найдено: list[dict] = []
    for p, ws in строки:
        if not подходит(p.name, запрос):
            continue
        найдено.append({"id": p.id, "name": p.name, "workspace_id": ws.id,
                        "workspace_name": ws.name,
                        "workspace_personal": bool(ws.personal),
                        "module": модуль(settings, p)})
        if len(найдено) >= limit:
            break
    return найдено


def материалы(строки, settings: Settings, запрос: str, limit: int) -> list[dict]:
    """Файлы работ, в имени которых есть набранное. Не больше `limit`.

    Обход останавливается на потолке, а не после полного перебора: каждая
    работа — это чтение каталога материалов, и добирать двадцать первую строку
    подсказки таким способом дорого.
    """
    найдено: list[dict] = []
    for p, _ws in строки:
        for материал in _опись(settings, p):
            имя = str(getattr(материал, "name", "") or "")
            if not подходит(имя, запрос):
                continue
            найдено.append({"id": материал.id, "name": имя,
                            "project_id": p.id, "project_name": p.name})
            if len(найдено) >= limit:
                return найдено
    return найдено


def _опись(settings: Settings, p: Project) -> list:
    """Разобранные материалы одного проекта. Каталога нет — пусто, а не отказ.

    Пусто, потому что проект без единого файла — обычное состояние, а поиск,
    падающий на первом же таком проекте, не находит ничего вовсе.
    """
    try:
        return orchestrator.Project(
            dir_for(settings, p.owner_id, p.id)).store().list()
    except Exception:                                        # noqa: BLE001
        return []


__all__ = ["привести", "подходит", "доступные", "модуль", "проекты",
           "материалы", "ПОТОЛОК_ПРОЕКТОВ"]
