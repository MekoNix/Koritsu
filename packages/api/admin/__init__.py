"""
admin — то, что видит владелец службы, и журнал безопасности в базе.

Админ-API `/api/admin/`: пользователи, смена плана, лимиты, очередь, события
безопасности; флаг `is_admin`; на прокси — белый список IP.

    models.py    таблица `security_events`
    service.py   запись и чтение событий, список людей, состояние очереди
    routes.py    `/api/admin/…`, все за зависимостью `require_admin`

**Белый список IP — на прокси, в коде только флаг.** Это записано и здесь, и в
докстроке `routes`, потому что забывается именно оно: `is_admin` защищает от
вошедшего не того человека, но не от того, кто добрался до порта. Адрес
проверяет Caddy — он единственный видит настоящий адрес соединения; служба за
прокси видит `X-Forwarded-For`, который пишет кто угодно.

**Что берут соседи.** Одно имя — запись события безопасности:

    from api.admin import service as журнал
    журнал.событие(request, "csrf_failed", user=user.id, path=…)

Зовут его те места, которые уже пишут журнал `api.security`
(`accounts.service.событие`), и зовут **вместе** с ним, а не вместо: поток в
stderr забирает сборщик логов, таблицу читает владелец в админке.

**Второе имя — личные лимиты.** `service.лимит(user, ключ, умолчание)` — то,
через что прогоны и материалы читают `users.limits`, поставленные владельцем в
админке. Других читателей у этого поля быть не должно. Плановые числа поверх
этого мешка считает `runs.limits` (`потолок`, `квота`, `квота_человека`) — там
же живёт справочник планов.

Ещё три вещи, и все три — здесь:

* **блокировка аккаунта** — `users.blocked_at`, ставится `PATCH … {"blocked":
  true}`. Отзывает все сессии человека; вход, живая сессия и ключ `/api/v1`
  отвечают ему `403 account_blocked` (проверка одна на три входа —
  `accounts.service.отказать_заблокированному`);
* **заведение человека владельцем** — `POST /api/admin/users`: подтверждённый
  аккаунт без пароля и ссылка сброса в ответе. Писем служба не шлёт, поэтому
  ссылку владелец передаёт сам, и показывается она **один раз**;
* **справочник планов** — `GET /api/admin/plans`; сам справочник живёт в
  `runs.limits.ПЛАНЫ`, а `PATCH` принимает только имена оттуда
  (`400 unknown_plan`).
"""
