"""
crypto — как ключ модели лежит на диске зашифрованным.

Решение владельца §3: свой ключ шифруется на диске секретом сервера
(`KORITSU_SECRET`), расшифровывается в памяти только в момент вызова поставщика,
никогда не пишется в журнал и не отдаётся клиенту — наружу уходят последние
четыре знака.

    ключ шифрования = HKDF-SHA256(ikm = settings.secret,
                                  salt = СОЛЬ,
                                  info = ИНФО,
                                  length = 32)
    шифртекст       = "v1:" + Fernet(ключ).encrypt(ключ поставщика)

**Почему не сам `settings.secret` ключом.** Секрет один, а пользуются им двое:
эти ключи и подпись cookie сессии (§7). Один и тот же байтовый материал в двух
криптографических ролях — классическая ошибка: стойкость каждой начинает
зависеть от другой, и находка в подписи cookie превращается в чтение ключей.
HKDF разводит роли: из одного секрета получаются два независимых ключа, и знание
одного не даёт второго.

**Почему соль — константа пакета, а не столбец в базе.** Соль в HKDF разделяет
*области применения*, а не пользователей; отдельная соль на строку не добавила
бы стойкости (ключ-то один на службу), зато завела бы столбец, потеря которого
означает потерю всех ключей. Разделение по пользователям делает не соль, а то,
что строка привязана к `user_id`.

**Почему у шифртекста версия впереди** (решение главной сессии 2026-09-03).
`v1:` — не украшение: смена соли, длины или алгоритма однажды случится, и без
метки в самой строке пришлось бы угадывать, чем шифровали каждую из них.
С меткой старые строки читаются прежним способом, новые пишутся новым, а «не
расшифровалось» перестаёт быть неотличимым от «расшифровано не тем».

`Fernet` — готовая связка AES-128-CBC + HMAC-SHA256 с меткой времени из
`cryptography`. Своей сборки «шифр плюс имитовставка» здесь нет намеренно: это
ровно тот код, который выглядит правильно и оказывается неправильным.
"""
from __future__ import annotations

import base64

from cryptography.fernet import Fernet, InvalidToken
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

# Область применения ключа. Менять нельзя, не сменив `ВЕРСИЯ`: тем же секретом,
# но другой солью, старые строки не расшифровываются.
СОЛЬ = b"koritsu.api.keys.v1"
ИНФО = b"model-key"

ВЕРСИЯ = "v1"
РАЗДЕЛИТЕЛЬ = ":"

# Сколько знаков ключа показываем человеку. Четыре — столько же, сколько
# показывают сами поставщики: узнать по ним ключ нельзя, а «этот или тот из
# двух» человек различает.
ХВОСТ = 4

# Выведенные ключи держим в памяти по секрету: HKDF дёшев, но зовётся он на
# каждый вызов поставщика, а секретов в процессе один-два (тесты собирают по
# приложению на тест). Сам секрет ключом словаря не становится — только его
# отпечаток, чтобы он не всплыл в дампе структуры при отладке.
_кэш: dict[str, Fernet] = {}


class КлючНеЧитается(Exception):
    """Строка не расшифровывается этим секретом или испорчена.

    Наружу не уезжает: `secret_for` возвращает `None`, а причина — в журнал без
    единого байта шифртекста.
    """


def _отпечаток(secret: str) -> str:
    """Короткий отпечаток секрета для ключа кэша. Не обратим и не секрет."""
    d = hashes.Hash(hashes.SHA256())
    d.update(b"cache-key" + secret.encode("utf-8"))
    return d.finalize()[:8].hex()


def замок(secret: str) -> Fernet:
    """`Fernet` на выведенном из секрета ключе."""
    отпечаток = _отпечаток(secret)
    готовый = _кэш.get(отпечаток)
    if готовый is None:
        сырой = HKDF(algorithm=hashes.SHA256(), length=32, salt=СОЛЬ,
                     info=ИНФО).derive(secret.encode("utf-8"))
        готовый = Fernet(base64.urlsafe_b64encode(сырой))
        _кэш[отпечаток] = готовый
    return готовый


def зашифровать(secret: str, ключ: str) -> str:
    """Ключ поставщика → строка для базы, с версией схемы впереди."""
    токен = замок(secret).encrypt(ключ.encode("utf-8")).decode("ascii")
    return f"{ВЕРСИЯ}{РАЗДЕЛИТЕЛЬ}{токен}"


def расшифровать(secret: str, строка: str) -> str:
    """Строка из базы → ключ поставщика. Не вышло — `КлючНеЧитается`.

    Единственное место, где ключ поставщика снова становится текстом. Возвращать
    его наружу отсюда некому: зовут эту функцию из `service.secret_for`, а её —
    из места вызова поставщика.
    """
    версия, _, токен = (строка or "").partition(РАЗДЕЛИТЕЛЬ)
    if not токен:
        raise КлючНеЧитается("в строке нет версии схемы")
    if версия != ВЕРСИЯ:
        raise КлючНеЧитается(f"схема {версия!r} этой сборке неизвестна")
    try:
        return замок(secret).decrypt(токен.encode("ascii")).decode("utf-8")
    except (InvalidToken, ValueError, UnicodeDecodeError):
        # Что именно не сошлось — подпись, длина или кодировка, — не говорим
        # даже журналу: разница между «не тот секрет» и «испорчено» подсказывает
        # тому, кто подбирает.
        raise КлючНеЧитается("строка не расшифровалась этим секретом") from None


def хвост(ключ: str) -> str:
    """Последние знаки ключа — единственное, что видит человек."""
    очищенный = (ключ or "").strip()
    return очищенный[-ХВОСТ:] if len(очищенный) >= ХВОСТ else очищенный


__all__ = ["замок", "зашифровать", "расшифровать", "хвост", "КлючНеЧитается",
           "СОЛЬ", "ИНФО", "ВЕРСИЯ", "ХВОСТ"]
