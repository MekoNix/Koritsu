"""
service — что можно делать с ключами моделей и где ключ снова становится текстом.

**Ключ только свой.** Прогон идёт на ключе того, кто его завёл, и ни на чьём
другом: общего ключа службы нет вовсе. Это правило, а не настройка, и держится
оно одной функцией — `resolve_key`, за которой стоит ровно один источник.

    resolve_key(settings, session, user_id, provider)
        свой ключ  → secret_for(...)   строка из базы, расшифрованная
        иначе      → None              платить нечем

Так решено потому, что расход за прогон обязан быть виден там, где его можно
проверить, — в кабинете человека у поставщика. Общий ключ прятал бы расход в
чужом кабинете и делал бы «сколько я потратил» вопросом без ответа.

**У ключа есть выбранная модель** (`model`). Пресет говорит, с кем
разговаривать, модель — какой именно. Лежит она строкой рядом с ключом, а не
отдельной таблицей: без ключа поставщик недоступен вовсе, и выбранная для него
модель — это свойство ключа, а не человека. Смена ключа выбор сохраняет
(`add_key` переносит его на новую строку): человек сменил ключ, а не модель.

**Расшифровка живёт ровно в одном месте** — `secret_for`. Ключ расшифровывается
в памяти только в момент вызова поставщика: чтобы вызвать
поставщика, надо позвать эту функцию, и другого пути к тексту ключа в службе
нет. Никакой маршрут её не зовёт: наружу уходит `last4`, и только он.

**В журнал ключ не попадает ни в каком виде** — ни текстом, ни шифртекстом.
Отсюда и правило про сообщения бед: они говорят про поставщика и про
пользователя, но никогда не показывают строку. Это проверяется тестом, а не
обещается.

**Список поставщиков — те пресеты `llm`, у которых объявлен `api_key_env`.**
Не весь `PRESETS`: `claude_cli_proba` зовёт
локальную команду и ключа не имеет, и предлагать человеку завести ключ для него
значило бы предлагать бессмыслицу. Список считается из пресетов, а не пишется
руками, чтобы новый пресет появлялся в настройках сам.

**Ключи бывают двух видов**: `model` — оплата прогона модели, `ink` —
распознавание рукописи на доске. Хранятся они одинаково и различаются только
тем, кто их спрашивает; `kind_of` называет вид, `model_providers()` отдаёт
первый список отдельно, потому что выбор поставщика для задания идёт по нему.
"""
from __future__ import annotations

import re

from sqlalchemy import select
from sqlalchemy.orm import Session

import llm

from ..db import now
from ..errors import ApiError
from ..log import беды
from ..settings import Settings
from . import crypto
from .models import MODEL_MAX, ModelKey

UNKNOWN_PROVIDER = "unknown_provider"
INVALID_KEY = "invalid_key"
NOT_FOUND = "not_found"

# Что вообще может быть ключом поставщика: печатные знаки без пробелов.
# Проверка от опечатки (скопировали вместе с переводом строки), а не от злого
# умысла: настоящую пригодность ключа покажет первый вызов поставщика.
КЛЮЧ_RE = re.compile(r"\A[\x21-\x7e]{8,512}\Z")


# ── два вида ключей ──────────────────────────────────────────────────────────
#
# Ключ модели и ключ распознавания рукописи хранятся одинаково — тот же шифр, та
# же таблица, тот же отзыв прежнего — и различаются одним: где их спрашивают.
# Ключом модели платят за прогон, ключом чернил открывают сокет распознавания.
# Отсюда `kind` в ответе `GET /api/keys/providers`: настройки рисуют
# распознавание отдельным подразделом, а не строкой в списке моделей, где
# человек искал бы у него выбор ступени и цену прогона.
МОДЕЛЬ = "model"
ЧЕРНИЛА = "ink"

# Поставщики вида `ink`. Их два, потому что подпись вызова распознавания
# строится парой: `applicationKey` едет в адресе сокета, `hmacKey` участвует в
# подписи и наружу не уезжает никогда. Две строки в таблице, а не одна с
# разделителем: человек вводит их двумя полями и меняет по одному.
ЧЕРНИЛЬНЫЕ = ("myscript_app", "myscript_hmac")


def model_providers() -> tuple[str, ...]:
    """Имена пресетов моделей, для которых ключ имеет смысл. По алфавиту.

    Отдельно от `providers()` намеренно: этот список — ответ на вопрос «чем
    можно оплатить прогон», и читает его проверка `payload.endpoint`
    (`runs/model.проверить_пресет`). Попади в него чернила, задание с
    `endpoint: "myscript_app"` прошло бы постановку и упало бы уже в воркере —
    на сборке пресета, которого нет.
    """
    годные = []
    for имя, фабрика in llm.presets.PRESETS.items():
        try:
            spec = фабрика()
        except Exception:                                    # noqa: BLE001
            continue                     # сломанный пресет не роняет настройки
        if getattr(spec, "api_key_env", None):
            годные.append(имя)
    return tuple(sorted(годные))


def providers() -> tuple[str, ...]:
    """Все поставщики, для которых ключ имеет смысл: модели и чернила.

    Читает её заведение ключа (`POST /api/keys`): человек заводит здесь и то, и
    другое. Чернила идут после моделей и в объявленном порядке — на экране это
    подраздел из двух полей, а алфавит поставил бы `hmacKey` перед
    `applicationKey`, то есть не в том порядке, в каком их выдают.
    """
    return model_providers() + ЧЕРНИЛЬНЫЕ


def kind_of(provider: str) -> str:
    """Вид поставщика: `model` или `ink`. Неизвестному — `model`.

    Умолчание в сторону модели, потому что чернильные поставщики перечислены
    поимённо, а моделей столько, сколько пресетов, и завтра их станет больше.
    """
    return ЧЕРНИЛА if str(provider or "") in ЧЕРНИЛЬНЫЕ else МОДЕЛЬ


def check_provider(provider: str, *, where: str = "body.provider") -> str:
    """Имя поставщика или отказ `400 unknown_provider`.

    Список в тексте ошибки называется намеренно: это не секрет (пресеты видны
    в настройках аккаунта), а клиенту иначе нечего показать человеку, кроме
    «нет».
    """
    имя = (provider or "").strip().lower()
    годные = providers()
    if имя not in годные:
        raise ApiError(UNKNOWN_PROVIDER,
                       f"Unknown provider; expected one of: {', '.join(годные)}",
                       400, where=where)
    return имя


# ── свои ключи ───────────────────────────────────────────────────────────────

def list_keys(s: Session, user_id: str, *,
              include_revoked: bool = False) -> list[ModelKey]:
    """Ключи человека, новые сверху. Отозванные — по просьбе.

    По умолчанию их нет: список в настройках показывает, чем сейчас можно
    платить, а история отзывов — другой разговор и другой экран.
    """
    запрос = select(ModelKey).where(ModelKey.user_id == user_id)
    if not include_revoked:
        запрос = запрос.where(ModelKey.revoked_at.is_(None))
    return list(s.scalars(запрос.order_by(ModelKey.created_at.desc())))


def add_key(s: Session, settings: Settings, user_id: str, provider: str,
            ключ: str) -> ModelKey:
    """Завести ключ. Прежний живой ключ того же поставщика отзывается.

    Отзыв прежнего, а не два живых рядом: «какой из двух сейчас работает» —
    вопрос, на который у человека нет ответа, а у нас нет причины его задавать.
    Прежний остаётся строкой с `revoked_at`, то есть история сохраняется.

    Сам ключ в объект не кладётся и из этой функции не возвращается: на выходе
    строка базы, у которой есть только шифртекст и `last4`.

    Выбранная модель прежнего ключа переносится на новый: смена ключа — это
    смена ключа, а не отмена всех настроек поставщика.
    """
    имя = check_provider(provider)
    очищенный = (ключ or "").strip()
    if not КЛЮЧ_RE.match(очищенный):
        # Про сам ключ в сообщении ни знака — оно уедет в ответ и в журнал
        # клиента.
        raise ApiError(INVALID_KEY,
                       "Provider key must be 8 to 512 printable characters "
                       "without spaces", 400, where="body.key")

    модель = ""
    for прежний in list_keys(s, user_id):
        if прежний.provider == имя:
            # Выбранная модель переезжает на новую строку: человек сменил ключ,
            # а не модель, и молча вернуть его к умолчанию пресета значило бы
            # поменять ему настройку, о которой он не просил.
            модель = модель or (прежний.model or "")
            прежний.revoked_at = now()

    строка = ModelKey(user_id=user_id, provider=имя,
                      ciphertext=crypto.зашифровать(settings.secret, очищенный),
                      last4=crypto.хвост(очищенный), model=модель)
    s.add(строка)
    s.flush()                    # `id` и `created_at` — до ответа клиенту
    return строка


def revoke(s: Session, user_id: str, key_id: str) -> ModelKey:
    """Отозвать свой ключ. Чужой и несуществующий — одинаково `404`.

    Одинаково намеренно: `403` на чужой идентификатор сообщал бы, что такой ключ
    есть, то есть отвечал бы на вопрос, задавать который не позволено.
    Повторный отзыв — не беда: строка уже отозвана, отвечаем ей же.
    """
    строка = s.get(ModelKey, key_id)
    if строка is None or строка.user_id != user_id:
        raise ApiError(NOT_FOUND, "Key not found", 404, where="path.key_id")
    if строка.revoked_at is None:
        строка.revoked_at = now()
    return строка


# ── расшифровка: одно место на всю службу ────────────────────────────────────

def secret_for(s: Session, settings: Settings, user_id: str,
               provider: str) -> str | None:
    """Ключ этого человека для этого поставщика — текстом. `None`, если нет.

    **Единственное место службы, где ключ снова становится текстом.** Зовут её
    из места вызова поставщика, результат живёт в локальной переменной и
    не кладётся ни в объект, ни в журнал, ни в ответ.

    Отозванный ключ не возвращается никогда — на то он и отозван. Нечитаемый
    (сменили `KORITSU_SECRET`, испортили строку) — тоже `None`, но с записью в
    журнал бед: молчаливое «ключа нет» в этом случае увело бы человека искать
    беду в настройках поставщика вместо настроек службы.

    Порядок аргументов отличается от объявленного в задании (`session, user_id,
    provider`) на один: расшифровка невозможна без `settings.secret`, а читать
    окружение по месту вместо настроек — ровно то, что запрещает `settings.py`.
    """
    строка = _живой(s, user_id, provider)
    if строка is None:
        return None
    try:
        return crypto.расшифровать(settings.secret, строка.ciphertext)
    except crypto.КлючНеЧитается as беда:
        # Идентификатор строки — можно (по нему человек найдёт ключ в настройках
        # и заведёт заново), шифртекст — нельзя ни при каких обстоятельствах.
        беды.error("ключ %s (%s) не расшифровался: %s", строка.id,
                   строка.provider, беда)
        return None


def resolve_key(settings: Settings, s: Session, user_id: str,
                provider: str) -> str | None:
    """Чем платим за этот вызов: своим ключом или ничем.

    `None` — «платить нечем»: вызывающий обязан отказать человеку внятно
    («заведите ключ поставщика»), а не звать поставщика без ключа и показывать
    его `401` как свою беду.
    """
    return secret_for(s, settings, user_id, provider)


def has_key(settings: Settings, s: Session, user_id: str,
            provider: str) -> bool:
    """Есть ли чем платить по этому поставщику. Самого ключа наружу не идёт.

    Спрашивается расшифровкой, а не наличием строки, и это важно: строка,
    которая не читается (сменили `KORITSU_SECRET`, испортили шифртекст), —
    это «ключа нет», а не «ключ есть». Иначе экран обещал бы работающего
    агента там, где первый же прогон откажет.
    """
    return bool(secret_for(s, settings, user_id, provider))


def model_of(s: Session, user_id: str, provider: str) -> str:
    """Выбранная модель поставщика или пусто. Пусто — «как в пресете».

    Пустая строка законна и означает умолчание пресета: человек, не выбиравший
    модель, работает тем же, чем работал до появления выбора.
    """
    строка = _живой(s, user_id, provider)
    return (строка.model or "") if строка is not None else ""


def set_model(s: Session, user_id: str, provider: str, model: str) -> str:
    """Выбрать модель поставщика. Пусто — вернуться к умолчанию пресета.

    Кладётся на строку живого ключа: без ключа поставщик недоступен, и выбор
    модели для него было бы некуда применить. Нет ключа — `404`, тем же словом,
    что и отзыв чужого ключа: «такого у вас нет».

    Имя модели не сверяется со списком поставщика намеренно. Список приходит от
    поставщика и бывает неполным (`deepseek-chat` работает, а в `/v1/models` его
    нет — живая проба 2026-09-03), и отказать по нему значило бы запретить
    рабочее имя. Ошибку в имени покажет первый прогон — отказом `model_not_found`,
    у которого есть свои слова.
    """
    строка = _живой(s, user_id, provider)
    if строка is None:
        raise ApiError(NOT_FOUND, f"No key for provider '{provider}'", 404,
                       where="path.provider")
    строка.model = (model or "").strip()[:MODEL_MAX]
    строка.updated_at = now()
    return строка.model


def _живой(s: Session, user_id: str, provider: str) -> ModelKey | None:
    """Живой ключ человека по поставщику. Один запрос на всех спрашивающих."""
    return s.scalars(
        select(ModelKey)
        .where(ModelKey.user_id == user_id, ModelKey.provider == provider,
               ModelKey.revoked_at.is_(None))
        .order_by(ModelKey.created_at.desc())).first()


