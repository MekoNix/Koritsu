"""
subproc — чужой ввод жуётся в отдельном процессе. Один запуск на всю службу.

Решение владельца §3 («разборщик чужих файлов в подпроцессе») родилось про
материалы, но касается всего, куда попадают чужие байты: разбор PDF, построение
блок-схемы по чужому коду, трассировка чужих классов. Три вещи, которые даёт
отдельный процесс и не даёт поток:

* **таймаут исполняется.** Поток, зависший в C-коде pymupdf или tree-sitter, не
  прерывается ничем; процесс прерывается сигналом;
* **лимит памяти исполняется.** `resource.setrlimit(RLIMIT_AS)` действует на
  процесс целиком — в общем процессе он ограничил бы и сайт;
* **окружение вычищено.** Дитя получает `PATH`, `HOME`, `TMPDIR` и языковые
  переменные — и больше ничего. Ни `KORITSU_SECRET`, которым шифруются ключи
  моделей, ни `*_API_KEY`: код, читающий чужой PDF, не должен иметь доступа к
  тому, чем он мог бы за этот PDF расплатиться.

Механизм заведён здесь, а не третьим экземпляром в третьем модуле. Первый жил в
разборе материалов (ночь 1, `materials/parsing.py` — модуль с тех пор удалён,
§12); сегодня им пользуются схемы (`modules/diagrams.py`) и подпроцесс задания
(`jobs/worker.py`).
Скопированный запуск подпроцесса расходится молча и в худшем месте: копия, где
забыли вычистить окружение, работает ровно так же, как правильная, — до того
дня, когда чужой код прочитает `KORITSU_SECRET`.

**Дитя — текст, а не модуль рядом.** Файл, лежащий рядом, однажды импортируют в
общий процесс «просто позвать функцию» — и лимиты, ради которых всё затевалось,
перестанут действовать, ничего при этом не сломав. Здесь импортировать нечего:
это текст для `python -c`.

**Наружу не уезжает ничего, кроме факта.** Текст исключения из дитяти содержит и
путь на томе, и кусок содержимого; клиент получает свой код с постоянным
текстом, а подробности уходят в журнал бед (`log.беды`) вместе с меткой запроса.
Поэтому `ПодпроцессНеУдался` — беда для журнала, а не для ответа.

**Оба числа — настройки, а не константы** (`KORITSU_PARSE_TIMEOUT_S`,
`KORITSU_PARSE_MEMORY_MB`): машина, где скан на двести страниц не укладывается в
минуту, чинится строкой в `.env`, а не правкой этого файла. Умолчания оставлены
здесь же значениями по умолчанию, чтобы функцию можно было позвать из консоли и
теста, не собирая настройки.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys

import materials

# Умолчания. Те же числа, что стоят в `Settings`, и стоят они здесь для вызова
# без настроек (консоль, тест): служба берёт их из `settings`, а не отсюда.
#
# Шестьдесят секунд — не «сколько не жалко»: скан на полсотни страниц с
# распознаванием текста укладывается, а зациклившийся разборщик нет, и разница
# между ними как раз здесь. Гигабайт адресного пространства — с запасом на
# импорт pymupdf и Pillow (они резервируют его щедро) и всё же на порядок
# меньше, чем нужно zip-бомбе, чтобы уронить машину.
ТАЙМАУТ_С = 60.0
ПАМЯТЬ_БАЙТ = 1024 * 1024 * 1024

# Что подпроцесс получает из окружения. Список закрыт: всё, чего здесь нет, до
# дитяти не доходит. `PATH` нужен ради tesseract (OCR — внешняя команда),
# `TMPDIR` — ради временных файлов pymupdf, языковые — ради сообщений.
ОКРУЖЕНИЕ = ("PATH", "HOME", "TMPDIR", "TMP", "TEMP",
             "LANG", "LC_ALL", "LC_CTYPE", "TESSDATA_PREFIX")


class ПодпроцессНеУдался(Exception):
    """Дитя упало, было убито или не уложилось в таймаут.

    Причина внутри — для журнала. Клиенту достаётся код своего модуля без неё: в
    тексте исключения бывает и путь на томе, и кусок разбираемого содержимого.
    """


# Общее начало любого дитяти. Порядок строк важен и не переставляется: лимит
# ставится ДО первого импорта проекта. pymupdf, Pillow и tree-sitter
# импортируются с аппетитом, и лимит, поставленный после, оставил бы самую
# дорогую часть работы без потолка.
ПРОЛОГ = r"""
import json, resource, sys

задание = json.loads(sys.stdin.read())
предел = int(задание["память"])
resource.setrlimit(resource.RLIMIT_AS, (предел, предел))
sys.path.insert(0, задание["пакеты"])


def ответ(данные):
    sys.stdout.write(json.dumps(данные, ensure_ascii=False))
"""


def каталог_пакетов() -> str:
    """Где лежат `packages/`. Пакеты не устанавливаются (решение владельца),
    поэтому путь дитяти передаём явно, а не надеемся на `PYTHONPATH`."""
    return os.path.dirname(os.path.dirname(os.path.abspath(materials.__file__)))


def окружение() -> dict:
    """Окружение подпроцесса: только перечисленное в `ОКРУЖЕНИЕ`.

    Отдельной функцией, потому что это проверяемое утверждение, а не
    подробность вызова: тест берёт её и смотрит, что `KORITSU_SECRET` в ответе
    нет.
    """
    return {имя: os.environ[имя] for имя in ОКРУЖЕНИЕ if имя in os.environ}


def выполнить(тело: str, задание: dict, *, что: str = "подпроцесс",
              таймаут: float = ТАЙМАУТ_С, память: int = ПАМЯТЬ_БАЙТ,
              беда: type[Exception] = ПодпроцессНеУдался) -> dict:
    """Запустить дитя с этим телом и этим заданием. → словарь из его `ответ()`.

    `тело` — код, дописываемый к `ПРОЛОГ`: в нём уже есть разобранное `задание`,
    поставленный лимит памяти, путь к пакетам и функция `ответ`. `задание` —
    что угодно, лишь бы это был JSON; поля `память` и `пакеты` дописываются
    здесь, чтобы вызывающий не мог их забыть.

    `беда` — какой тип исключения бросать: у каждого вызывающего он свой
    (`РазборНеУдался` у материалов, `СхемаНеПостроилась` у схем), потому что
    ловят их в разных местах и отвечают на них по-разному. Тип, а не флаг:
    `except` пишется по типу.
    """
    полное = {**задание, "память": int(память), "пакеты": каталог_пакетов()}
    try:
        готово = subprocess.run(
            [sys.executable, "-c", ПРОЛОГ + тело],
            input=json.dumps(полное).encode("utf-8"),
            stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            env=окружение(), timeout=таймаут, check=False)
    except subprocess.TimeoutExpired:
        raise беда(f"{что} не уложился в {таймаут:.0f} с и был прерван") from None
    except OSError as ошибка:
        raise беда(f"{что}: подпроцесс не запустился: {ошибка}") from None

    if готово.returncode != 0:
        # Хвост, а не весь stderr: трассировка на битом PDF бывает длиннее
        # самого файла, а в журнал нужна причина, а не роман.
        хвост = готово.stderr.decode("utf-8", "replace").strip()[-2000:]
        raise беда(f"{что}: подпроцесс вышел с кодом {готово.returncode}: {хвост}")

    try:
        готовый = json.loads(готово.stdout.decode("utf-8"))
    except (ValueError, UnicodeDecodeError):
        raise беда(f"{что}: подпроцесс вернул не JSON") from None
    if not isinstance(готовый, dict):
        raise беда(f"{что}: подпроцесс вернул {type(готовый).__name__}, а не словарь")
    return готовый


__all__ = ["выполнить", "ПодпроцессНеУдался", "окружение", "каталог_пакетов",
           "ПРОЛОГ", "ТАЙМАУТ_С", "ПАМЯТЬ_БАЙТ", "ОКРУЖЕНИЕ"]
