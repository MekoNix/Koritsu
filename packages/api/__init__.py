"""
api — HTTP-служба поверх оркестратора.

Что это. Единственное место проекта, которое разговаривает по HTTP: принимает
запрос, проверяет, чей он, зовёт `orchestrator` и отдаёт JSON. Предметной работы
здесь нет и не должно быть — заполнением тегов занят `orchestrator`, отчётами
`hokoku`, материалами `materials`, моделями `llm`. Как только сюда переедет хоть
одно правило про версии значений или про сборку документа, у проекта станет два
места, где живёт это правило, и разойдутся они молча — ровно так, как разошлись
бы четыре формы предупреждения до `kyotsu.Notice`.

**Правило разреза.** `api` — не лист: ему разрешено импортировать
`orchestrator`, `materials`, `kyotsu` и `llm` (пресеты и приведённые единицы
расхода) — и никого больше. Обратное направление запрещено полностью: ни один
пакет, включая `orchestrator`, не импортирует `api`. Проверяется это, а не
обещается, — `tests/kyotsu/test_border.py`.

Почему разрешено четверым, а не одному `orchestrator`. Служба обязана отдавать
материалы по идентификатору (`materials.Store`) и показывать список пресетов
модели (`llm`) там, где никакого проекта ещё нет — при регистрации ключа, в
настройках аккаунта. Тянуть это через оркестратор значило бы завести у него
методы, существующие ради HTTP, то есть протащить службу внутрь предметного
пакета — и отменить причину, по которой `orchestrator` вообще отделён от
`hokoku`.

Почему запрещено обратное. Пакет, который импортирует службу, перестаёт
собираться без FastAPI и SQLAlchemy — и `hokoku`, движок отчётов, начинает
требовать веб-сервер, чтобы построить DOCX.

    Состав пакета

    settings.py   всё, что служба узнаёт снаружи; у тома умолчания нет
    errors.py     один формат ответа на беду: {code, message, where}
    ids.py        uuid4 наружу вместо путей
    db.py         движок, сессии, общая основа таблиц, Alembic
    models.py     одно место, где пакет узнаёт про все свои таблицы
    log.py        технический журнал и метка запроса X-Request-Id
    routes.py     два входа: /api для сайта, /api/v1 для скриптов
    app.py        create_app(settings) — сборка приложения
    subproc.py    чужой ввод жуётся в отдельном процессе; один запуск на всех
    auth.py       кто пришёл: cookie или Bearer, права ключа, куда с ним нельзя
    csrf.py       заслон от чужого сайта: cookie + заголовок на изменяющем
    billing.py    заглушка платёжки: 501, тело не читается
    jobs/         очередь заданий и воркер: всё, что делается не в запросе
    tokens/       внешние ключи `/api/tokens`: выдать раз, отозвать, считать
    admin/        `/api/admin`: люди, очередь, журнал безопасности в базе
    migrations/   Alembic: env.py, alembic.ini, versions/

**Как это расширяют.** Четыре шага, и все четыре — дописывание, а не правка
каркаса:

1. **Свой подпакет**: `packages/api/accounts/` с `models.py` и `routes.py`.
   Свой, а не общий модуль на всех: один файл, который правят со всех сторон, —
   это конфликты слияния на ровном месте.
2. **Модели** — подклассы `db.Row` (`id`, `created_at`, `updated_at` уже есть).
   Строка импорта дописывается в `models.py` пакета, иначе `Base.metadata` о
   таблице не знает и `--autogenerate` выпишет её удаление.
3. **Миграция** — одна на подпакет, `--autogenerate` (команда в
   `migrations/alembic.ini`). `down_revision` — тот head, что был в момент
   создания; одинаковый `down_revision` у нескольких миграций — это несколько
   голов, их сводит `alembic merge`. Чужой файл миграции не правит никто.
4. **Маршруты** — свой `APIRouter` без префикса `/api` (его несёт вход) и одна
   строка в `routes.collect()`.

Что общее и заводить второй раз нельзя: `Settings` (настройка, прочитанная
из окружения по месту, — это второе умолчание), `ApiError` (второй формат ошибки
— второй разбор в интерфейсе), `db.Base` (вторые метаданные — потерянные
таблицы), `SessionDep` (вторая сессия на запрос — половина записи при беде),
метка запроса (без неё жалобу не найти в журнале).

Три правила, которые каркас держит и за подпакеты:

* **наружу — идентификаторы, а не пути** (`ids.py`);
* **наружу — по-английски**, коды и тексты ошибок; внутрь, оператору и в
  комментариях — по-русски, как у соседей;
* **содержимое тел не попадает в журнал никогда**, включая строку запроса и
  заголовки: в них уезжают cookie сессии и токен подтверждения почты.

**Очередь заданий** (`jobs/`) — второе место, куда дописывают, и правила
там свои: вид задания заводится строкой в `jobs/registry.py`, обработчик пишется
в **своём** модуле под декоратором `@register(...)`, а исполняется в отдельном
процессе (`python -m api worker`). Всё это описано в докстроке `jobs/__init__.py`
и в `jobs/registry.py`; сюда, в каркас, при добавлении вида задания править
нечего.

**Кто пришёл — одно место на два входа** (`auth.py`). `/api` берётся
cookie-сессией и защищён заслоном CSRF (`csrf.py`), `/api/v1` — внешним ключом
(`tokens/`) со своими правами и лимитом 60 запросов в минуту. Обработчик при
этом один: под второй вход выставляется тот же роутер (`routes.зеркало`),
отличаются у него только имена операций — суффикс `_v1`. Куда с ключом нельзя
(аккаунты, ключи моделей, сами ключи, админка) — списком в `auth.ТОЛЬКО_СЕССИЯ`.

**Админка и журнал безопасности** — `admin/`. Там же таблица `security_events`
и единственный способ прочитать личные лимиты человека
(`admin.service.лимит`); события в неё пишет тот же вызов, что пишет журнал
`api.security` (`accounts.service.событие`), — вторым местом их не заводят.

Чего в пакете нет: платёжки — `POST /api/billing/webhook` отвечает `501`
(`billing.py`) и тела не читает, пока её нет.
"""

