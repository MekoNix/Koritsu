"""
workspaces — рабочие пространства, роли и участники.

Проект принадлежит не человеку, а рабочему пространству, и
у каждого человека есть личное по умолчанию. Заложено с первого дня, даже пока
интерфейс показывает только личное: «добавить поле потом дёшево, переписать
владение файлами — нет».

Роли три и список закрыт: `owner` — создатель, может всё, включая
участников и удаление; `editor` — читает и меняет проекты и материалы;
`viewer` — только читает. Что именно видит `viewer`, решится на UI; на уровне
API у него есть все `GET` пространства и ни одного изменяющего запроса.

**Два кода отказа, и они разные не для красоты.**

* **404 `not_found`** — запрашивающий вообще не участник пространства. Ответ
  такой же, как на несуществующий идентификатор, и это прямое следствие
  правила «клиент видит только идентификаторы»: 403 на чужой проект сообщал бы, что
  проект с таким идентификатором есть, то есть отвечал бы на вопрос, который
  спрашивающему задавать не позволено.
* **403 `forbidden`** — участник есть, роли не хватает (`viewer` шлёт `PUT`).
  Прятать здесь нечего: он и так видит объект, а 404 в этом месте выглядел бы
  как пропавшая строка и породил бы жалобу вместо понятного «нет прав».

**Позванный — ещё не участник.** Приглашение заводит строку участия в состоянии
`pending` и кладёт человеку уведомление с «принять» и «отклонить»; роль он
получает только с ответом. До ответа пространство отвечает ему теми же 404, что
и чужое, — `role_of` состояние `pending` за участие не считает. Так и задумано:
чужие работы не появляются у человека в списке без его согласия.

Личное пространство заводит хук `on_user_created` пакета аккаунтов: регистрация
и заведение пространства — одна неделимая работа, и «пользователь без личного
пространства» не должен существовать даже на миллисекунду. Зовётся оно
`<ник>-workspace`: имя человек видит в переключателе рядом с общими
пространствами, и «Личное» там не отвечало бы на вопрос, чьё оно. Хук ставится в
`routes.collect()` (`register_hooks`), то есть на каждой сборке приложения и
идемпотентно.

Кому что отсюда нужно: материалам — `require_role(s, user_id, workspace_id,
role)` перед любой работой с файлами проекта.
"""
