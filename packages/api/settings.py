"""
settings — всё, что служба узнаёт снаружи, и больше ниоткуда.

Один dataclass вместо чтения `os.environ` по месту. Разница видна не в красоте:
переменная, прочитанная в трёх файлах, в четвёртом читается с другим умолчанием,
и узнаётся об этом на живом томе. Здесь список закрыт, умолчания стоят в одном
месте, а `from_env` падает **до** первого запроса, а не на нём.

**У тома умолчания нет** (решение владельца К.2: «путь задаётся снаружи»,
то же правило, что у `orchestrator.Project`). Умолчание вроде `./data` означало
бы, что рабочая машина, CI и боевая расходятся молча: тесты зелёные, а
контейнер пишет в свой слой, и после `docker compose down` чужих работ нет.

**Секрет обязателен и не короче 32 байт.** Им шифруются ключи моделей на диске
(§3) и подписывается cookie сессии (§7). Умолчание здесь — это общий секрет на
всех, кто скачал репозиторий; проверка длины — заслон от `KORITSU_SECRET=test`,
который переживает выкат и обнаруживается кражей ключей.

Переменные (префикс `KORITSU_`):

    DATA_DIR                     том; обязателен, умолчания нет
    SECRET                       обязателен, ≥32 байт
    ENV                          dev | prod (умолч. dev)
    USER_QUOTA_BYTES             250 МБ — квота на владельца (§2)
    FILE_MAX_BYTES               10 МБ — на один файл (§2)
    SESSION_DAYS                 30 — сессия с продлением (§7)
    TRASH_DAYS                   10 — уборка корзины (§2)
    PARSE_TIMEOUT_S              60 — секунд на подпроцесс со схемой (§3)
    PARSE_MEMORY_MB              1024 — потолок памяти такого подпроцесса (§3)
    REGISTRATIONS_PER_IP_PER_DAY 5 — заслон от массовой регистрации (§7)
    JOB_SLOTS                    2 — тяжёлых заданий на машину (§11)
    JOBS_PER_USER                1 — заданий разом на человека (§11)
    WORKER_POLL_S                1.0 — как часто воркер смотрит в очередь
    JOB_TIMEOUT_S                1800 — потолок работы одного задания
    JOB_MEMORY_MB                2048 — потолок памяти обработчика
    JOBS_RETENTION_DAYS          90 — сколько хранить законченные (§7)
    FREE_MONTHLY_UNITS           2 000 000 — месячный потолок плана `free` (§11)
    PRICE_<KIND>                 цена одного задания этого вида в единицах
                                 (§12; цифры временные, см. `runs/limits.ЦЕНЫ`)
    PREVIEW_PER_MINUTE           30 — предпросмотров схем в минуту на человека
    SSE_POLL_S                   0.5 — как часто поток событий смотрит в базу
    SSE_MAX_S                    3600 — сколько живёт одно соединение потока
    DB_URL                       умолч. sqlite в DATA_DIR/koritsu.db (§7)
    TRUST_PROXY                  умолч. «да в prod, нет в dev» — верить ли
                                 `X-Forwarded-For` (§3: сайт за Caddy)
    BASE_URL                     умолч. http://localhost:8000 — из чего
                                 собирается ссылка в письме (§3)

Числа читаются строго: `KORITSU_FILE_MAX_BYTES=10Mb` — это ошибка настройки, а
не десять байт и не умолчание. Тихое умолчание на опечатке означало бы, что
поднятый с опечаткой prod ведёт себя как dev и никто этого не видит.

Что сюда класть **нельзя**: значения, зависящие от строки базы (лимит проекта,
план подписки, роль). Настройки — про машину и том; всё, что про пользователя,
живёт в базе, иначе первое же переопределение на проект (обещанное в §2)
потребует перезапуска контейнера.
"""
from __future__ import annotations

import os
from dataclasses import dataclass

from .errors import ConfigError

ПРЕФИКС = "KORITSU_"

# Длина секрета в байтах. 32 — не круглое число из воздуха: столько занимает
# ключ AES-256, которым шифруются ключи моделей, и столько же берёт HMAC-SHA256
# для подписи cookie.
SECRET_MIN_BYTES = 32

ENVS = ("dev", "prod")

MB = 1024 * 1024

# Куда ведёт ссылка в письме, если снаружи не сказали иного. Localhost, а не
# рабочий домен: умолчание с настоящим доменом означало бы, что забытая
# настройка на dev-машине рассылает людям ссылки на живой сайт с токеном,
# которого там нет.
BASE_URL_DEFAULT = "http://localhost:8000"

# Что считается «да» и «нет» в переменной окружения. Список закрыт по той же
# причине, по которой числа читаются строго: `KORITSU_TRUST_PROXY=maybe` — это
# опечатка, а не «нет», и молчать про неё нельзя (за прокси с ней лимит по IP
# станет общим на весь сайт).
ДА = ("1", "true", "yes", "on", "да")
НЕТ = ("0", "false", "no", "off", "нет")


@dataclass(frozen=True)
class Settings:
    """Настройки одного экземпляра службы. Неизменяемые: настройка, поменянная
    посреди работы, — это два поведения в одном процессе и невоспроизводимый
    отчёт об ошибке."""

    data_dir: str
    secret: str
    env: str = "dev"
    user_quota_bytes: int = 250 * MB
    file_max_bytes: int = 10 * MB
    session_days: int = 30
    trash_days: int = 10
    registrations_per_ip_per_day: int = 5
    # Потолки подпроцесса, который жуёт чужой текст: построение схем
    # (`modules/diagrams.py`) и всё, что позовёт `subproc.выполнить`. Числа
    # живут здесь, а не константами по месту, по той же причине, что и всё
    # остальное в этом файле: тяжёлый исходник на слабой машине лечится строкой
    # в `.env`, а не правкой кода и выкатом. Имя историческое — первым таким
    # подпроцессом был разбор материала.
    parse_timeout_s: int = 60
    parse_memory_mb: int = 1024
    # Очередь заданий и воркер (§11). Слоты — решение владельца дословно: «2
    # тяжёлых задания на машину, 1 на пользователя, остальные ждут в очереди».
    # Оба числа читает только захват задания (`jobs.worker`), и оба обязаны
    # быть настройками: машина вдвое мощнее лечится строкой в `.env`, а не
    # правкой кода, а `jobs_per_user=1` на время расследования — это способ
    # успокоить очередь, не останавливая её.
    job_slots: int = 2
    jobs_per_user: int = 1
    # Как часто воркер заглядывает в таблицу, когда работы нет. Дробное:
    # секунда — потолок задержки перед началом работы, и на живом сайте её
    # захотят уменьшить, а не увеличить.
    worker_poll_s: float = 1.0
    # Полчаса на задание. Не «сколько не жалко»: отчёт на два десятка тегов с
    # медленным поставщиком в них укладывается, а зациклившийся обработчик —
    # нет, и разница между ними как раз здесь. По этому же сроку воркер
    # признаёт чужое задание потерянным (сердцебиение старше — значит воркера
    # больше нет).
    job_timeout_s: int = 1800
    # Вдвое больше, чем у разборщика материалов: обработчику мало собственной
    # памяти — он держит ещё и ответ модели, и собираемый документ.
    job_memory_mb: int = 2048
    # Девяносто дней с последнего обращения (§7). Считается от `last_seen_at`,
    # а не от конца работы, — см. `jobs.models`.
    jobs_retention_days: int = 90
    # Месячный потолок расхода плана `free` во внутренних единицах
    # (§11: «для free — настройка KORITSU_FREE_MONTHLY_UNITS с временным числом
    # 2 000 000, цифры владелец решит вместе с ценами»). Настройкой, а не
    # числом в коде, именно потому, что число временное: правится строкой в
    # `.env`, а не выкатом. Прочие планы сегодня считаются по нему же — таблица
    # планов и оговорка живут в `runs/limits.py`, чтобы «сколько кому положено»
    # объяснялось в одном месте, а не половиной здесь и половиной там.
    free_monthly_units: int = 2_000_000
    # ── цены наших инструментов (решение владельца §12) ─────────────────────
    #
    # Человек платит внутренними единицами **за запуск нашего кода**, а не за
    # токены поставщика: у каждого вида задания своя цена, и она списывается в
    # `jobs.spent_units` при захвате. Токены поставщика при этом по-прежнему
    # считаются в журнале проекта (`llm.journal`) — это другой учёт, про
    # поставщика, а не про плату.
    #
    # **Все цифры ниже — временные заглушки.** Владелец назовёт цены вместе с
    # ценами подписки (§12: «Цифры цен — открыто, до цен подписки»), и до тех
    # пор они правятся строкой в `.env`, а не выкатом. Соотношение между ними —
    # единственное, что здесь осмысленно: разбор дешевле сборки, сборка дешевле
    # прогона модели, прогон сценария дороже всех.
    price_parse: int = 10
    price_export: int = 20
    price_build: int = 50
    price_fill_tag: int = 100
    price_fill_report: int = 1000
    price_agent: int = 2000
    price_kadai_run: int = 5000
    price_kadai_rework: int = 1000
    # Проба очереди не стоит ничего и стоить не должна: ею проверяют, жив ли
    # воркер, и платная проверка живости — это проверка, которую перестают
    # делать.
    price_probe: int = 0
    # Предпросмотров схем в минуту на человека (§12). Единственный тяжёлый
    # маршрут, который любой вошедший дёргает без проекта и без роли, — значит
    # ограничивает его только это число. Считается в памяти процесса, как лимит
    # внешних ключей (`tokens.service`), и с той же оговоркой про два процесса.
    preview_per_minute: int = 30
    # Как часто поток событий (`api/events`) заглядывает в базу, пока ждёт
    # новых. Полсекунды — потолок задержки события у человека на экране;
    # меньше означало бы столько же запросов в базу на каждого смотрящего.
    sse_poll_s: float = 0.5
    # Сколько живёт одно соединение потока, прежде чем служба закроет его сама.
    # Час — больше самого долгого задания (`job_timeout_s` — полчаса), поэтому
    # поток задания успевает дожить до конца работы; потоку на пользователя это
    # просто потолок, после которого браузер переподключится с `Last-Event-ID`
    # и продолжит с того же места. Без потолка забытая вкладка держала бы
    # соединение и его сессии базы сколько угодно.
    sse_max_s: float = 3600.0
    db_url: str = ""
    # `None` — не «нет», а «не сказали»: умолчание считается из режима ниже.
    # Верить `X-Forwarded-For` можно только за своим прокси; открытый порт с
    # этой настройкой означает, что лимит по IP обходится одной строкой
    # заголовка (решение главной сессии 2026-09-03, вариант B).
    trust_proxy: bool | None = None
    base_url: str = ""

    def __post_init__(self) -> None:
        if not self.data_dir:
            raise ConfigError(
                f"{ПРЕФИКС}DATA_DIR не задан: путь тома задаётся снаружи, "
                "умолчания у него нет")
        object.__setattr__(self, "data_dir",
                           os.path.abspath(os.path.expanduser(self.data_dir)))

        if len(self.secret.encode("utf-8")) < SECRET_MIN_BYTES:
            # Длину говорим, сам секрет — никогда: сообщение уедет в журнал.
            raise ConfigError(
                f"{ПРЕФИКС}SECRET короче {SECRET_MIN_BYTES} байт: им шифруются "
                "ключи моделей и подписываются cookie")

        if self.env not in ENVS:
            raise ConfigError(
                f"{ПРЕФИКС}ENV — {' или '.join(ENVS)}, а не {self.env!r}")

        for имя in ("user_quota_bytes", "file_max_bytes", "session_days",
                    "trash_days", "registrations_per_ip_per_day",
                    "parse_timeout_s", "parse_memory_mb",
                    "job_slots", "jobs_per_user", "worker_poll_s",
                    "job_timeout_s", "job_memory_mb", "jobs_retention_days",
                    "free_monthly_units", "sse_poll_s", "sse_max_s",
                    "preview_per_minute"):
            if getattr(self, имя) <= 0:
                # Ноль слотов — это воркер, который никогда ничего не берёт, и
                # очередь, растущая молча. Отказ на старте дешевле.
                raise ConfigError(f"{_env_name(имя)} должен быть больше нуля")

        # Цены проверяются отдельно и мягче: ноль здесь законен (`probe`
        # бесплатен по построению), а вот отрицательная цена — это задание,
        # которым месячный остаток **пополняется**, и такое лечится отказом на
        # старте, а не расследованием по журналу расхода.
        for имя in vars(self):
            if имя.startswith("price_") and getattr(self, имя) < 0:
                raise ConfigError(f"{_env_name(имя)} не может быть меньше нуля")

        if not self.db_url:
            object.__setattr__(self, "db_url", self.default_db_url())

        if self.trust_proxy is None:
            object.__setattr__(self, "trust_proxy", self.env == "prod")

        # Хвостовая косая срезается один раз здесь, а не в каждом месте, где
        # ссылка склеивается: иначе `http://k.ru/` даст `http://k.ru//confirm`.
        object.__setattr__(self, "base_url",
                           (self.base_url or BASE_URL_DEFAULT).rstrip("/"))

    # ------------------------------------------------------------------ пути

    def default_db_url(self) -> str:
        """SQLite в томе (решение §7). Файл рядом с каталогами пользователей,
        чтобы резервная копия тома (restic по cron, §2) забирала базу вместе с
        файлами: снимок из базы без файлов бесполезен ровно так же, как из
        файлов без базы."""
        return "sqlite:///" + os.path.join(self.data_dir, "koritsu.db")

    @property
    def is_sqlite(self) -> bool:
        return self.db_url.startswith("sqlite")

    @property
    def parse_memory_bytes(self) -> int:
        """Потолок памяти разборщика в байтах — `resource.setrlimit` мегабайтов
        не понимает. Умножение живёт здесь, а не у вызывающего: настройка в
        мегабайтах читается человеком, а перевод в байты, сделанный по месту,
        однажды окажется сделанным дважды или не тем множителем."""
        return self.parse_memory_mb * MB

    @property
    def job_memory_bytes(self) -> int:
        """Потолок памяти обработчика задания в байтах. Тот же довод, что у
        `parse_memory_bytes`: перевод мегабайтов в байты сделан один раз."""
        return self.job_memory_mb * MB

    # --------------------------------------------------------------- чтение

    @classmethod
    def from_env(cls, environ=None) -> "Settings":
        """Собрать настройки из окружения. Падает внятно на каждой беде.

        `environ` — подмена для тестов; в работе это `os.environ`. Файл `.env`
        сюда не читается намеренно: его разворачивает docker compose, и второй
        читатель `.env` (наш) разошёлся бы с первым на кавычках и переносах.
        """
        env = os.environ if environ is None else environ
        get = lambda имя: env.get(ПРЕФИКС + имя)                     # noqa: E731

        return cls(
            data_dir=get("DATA_DIR") or "",
            secret=get("SECRET") or "",
            env=(get("ENV") or "dev").strip().lower(),
            user_quota_bytes=_int(env, "USER_QUOTA_BYTES", 250 * MB),
            file_max_bytes=_int(env, "FILE_MAX_BYTES", 10 * MB),
            session_days=_int(env, "SESSION_DAYS", 30),
            trash_days=_int(env, "TRASH_DAYS", 10),
            registrations_per_ip_per_day=_int(
                env, "REGISTRATIONS_PER_IP_PER_DAY", 5),
            parse_timeout_s=_int(env, "PARSE_TIMEOUT_S", 60),
            parse_memory_mb=_int(env, "PARSE_MEMORY_MB", 1024),
            job_slots=_int(env, "JOB_SLOTS", 2),
            jobs_per_user=_int(env, "JOBS_PER_USER", 1),
            worker_poll_s=_float(env, "WORKER_POLL_S", 1.0),
            job_timeout_s=_int(env, "JOB_TIMEOUT_S", 1800),
            job_memory_mb=_int(env, "JOB_MEMORY_MB", 2048),
            jobs_retention_days=_int(env, "JOBS_RETENTION_DAYS", 90),
            free_monthly_units=_int(env, "FREE_MONTHLY_UNITS", 2_000_000),
            price_parse=_int(env, "PRICE_PARSE", 10),
            price_export=_int(env, "PRICE_EXPORT", 20),
            price_build=_int(env, "PRICE_BUILD", 50),
            price_fill_tag=_int(env, "PRICE_FILL_TAG", 100),
            price_fill_report=_int(env, "PRICE_FILL_REPORT", 1000),
            price_agent=_int(env, "PRICE_AGENT", 2000),
            price_kadai_run=_int(env, "PRICE_KADAI_RUN", 5000),
            price_kadai_rework=_int(env, "PRICE_KADAI_REWORK", 1000),
            price_probe=_int(env, "PRICE_PROBE", 0),
            preview_per_minute=_int(env, "PREVIEW_PER_MINUTE", 30),
            sse_poll_s=_float(env, "SSE_POLL_S", 0.5),
            sse_max_s=_float(env, "SSE_MAX_S", 3600.0),
            db_url=(get("DB_URL") or "").strip(),
            trust_proxy=_bool(env, "TRUST_PROXY", None),
            base_url=(get("BASE_URL") or "").strip(),
        )

    @classmethod
    def for_tests(cls, tmp_path, **правки) -> "Settings":
        """Настройки на временном томе. Единственная точка, где у секрета есть
        умолчание, — и она не работает нигде, кроме тестов.

        `tmp_path` — `pathlib.Path` фикстуры pytest или строка. Любое поле
        переопределяется по имени: `Settings.for_tests(tmp, file_max_bytes=64)`.
        """
        поля = dict(
            data_dir=str(tmp_path),
            secret="проба" * 8,          # заведомо длиннее 32 байт
            env="dev",
        )
        поля.update(правки)
        return cls(**поля)


def _env_name(поле: str) -> str:
    return ПРЕФИКС + поле.upper()


def _int(env, имя: str, умолчание: int) -> int:
    """Целое из окружения. Пустая строка — это «не задано», мусор — беда.

    Разница важна: `KORITSU_TRASH_DAYS=` в compose означает «оставь как есть»
    (так compose передаёт незаполненную переменную), а `KORITSU_TRASH_DAYS=ten`
    означает опечатку, и молчать про неё нельзя — корзина убиралась бы через
    десять дней вместо задуманных, и заметили бы это по пропавшим файлам.
    """
    сырое = (env.get(ПРЕФИКС + имя) or "").strip()
    if not сырое:
        return умолчание
    try:
        return int(сырое)
    except ValueError:
        raise ConfigError(
            f"{ПРЕФИКС}{имя} — целое число, а не {сырое!r}") from None


def _float(env, имя: str, умолчание: float) -> float:
    """Дробное из окружения. Та же строгость, что у `_int`, и по той же причине.

    Отдельной функцией, а не `float(...)` внутри `_int`: целое и дробное — два
    разных договора, и настройка, которую можно задать дробью, обязана быть
    видна как дробная в одном месте, а не угадываться по умолчанию.
    """
    сырое = (env.get(ПРЕФИКС + имя) or "").strip()
    if not сырое:
        return умолчание
    try:
        return float(сырое)
    except ValueError:
        raise ConfigError(
            f"{ПРЕФИКС}{имя} — число, а не {сырое!r}") from None


def _bool(env, имя: str, умолчание):
    """Да/нет из окружения. Пустая строка — «не задано», мусор — беда.

    Разница та же, что у `_int`, и цена ошибки выше: `KORITSU_TRUST_PROXY=maybe`,
    понятый как «нет», превращает лимит регистраций по IP в лимит на весь сайт
    (за прокси все запросы приходят с одного адреса).
    """
    сырое = (env.get(ПРЕФИКС + имя) or "").strip().lower()
    if not сырое:
        return умолчание
    if сырое in ДА:
        return True
    if сырое in НЕТ:
        return False
    raise ConfigError(
        f"{ПРЕФИКС}{имя} — да или нет ({'/'.join(ДА[:3])}, {'/'.join(НЕТ[:3])}), "
        f"а не {сырое!r}")


