"""
modules — реестр модулей службы и шаблон, по которому заводится новый.

Решение брифа: **модули, которые ещё не готовы, в интерфейсе не показываются
вовсе** — ни заглушкой «скоро», ни серым пунктом меню. Значит список модулей
нужен интерфейсу как данные, а не как вёрстка: сайдбар и дашборд строятся по
`GET /api/modules`, и добавление модуля не требует правки сайта.

Отсюда и форма реестра. `ModuleInfo` — четыре поля и ни одного лишнего:

    id             короткое слово, оно же кусок пути (`flowcharts`)
    title          как модуль зовут в интерфейсе, по-английски (§7)
    ready          показывать ли его человеку
    routes_prefix  где живут его маршруты

`ready=False` в ответ не попадает никогда. Именно поэтому флаг вообще есть:
заготовку модуля бывает нужно завести в коде раньше, чем её можно показать, и
единственная честная разница между «есть» и «показываем» — одно поле в одном
месте. Пустых заготовок при этом не держим (решение плана): `cards`, `board`,
`asm` появятся строкой, когда появится их код.

    Как завести новый модуль — пять шагов и ни одной правки каркаса

    1. `packages/api/modules/<id>/` — свой подпакет: `routes.py` с `router`
       (`APIRouter` без префикса `/api`, `tags=["<id>"]`) и `__init__.py`,
       который отдаёт наружу `MODULE = ModuleInfo(...)` и этот `router`.
    2. Маршруты — под `/<id>` (без проекта) и `/projects/{project_id}/<id>`
       (в проекте). Другого места у модуля нет: по этим двум формам его
       находит и человек, и тест.
    3. `operation_id` — с префиксом модуля (`flowcharts_preview`): в клиенте
       сайта они лежат в одном пространстве имён, и `preview` там будет ровно
       один.
    4. Строка в `_наполнить()` ниже — `register(MODULE, router)`.
    5. Тест `tests/api/test_<id>.py` — и строка в `test_modules.py`, если
       модуль меняет ответ реестра.

Больше ничего: `routes.collect()` зовёт `modules.routers()` одной строкой, и
она уже написана.

**Реестр наполняется лениво, а не при импорте.** Импорт подпакета модуля тянет
за собой зависимости доступа, те — базу, и на уровне модуля это замкнутый круг
импортов в первый же день (та же причина, по которой `routes.collect()` —
функция). Наполнение при этом идемпотентно: приложений в процессе бывает много
(тесты собирают по штуке на тест), а реестр один на процесс.

**Скачивание артефактов лежит здесь же** (`artifacts.py`), но модулем не
является и в `GET /api/modules` не попадает: артефакт производят и схемы, и
отчёты, и экспорт, а достаётся он одним маршрутом на всех. Модулем его сделать
значило бы приписать общий маршрут одному из трёх владельцев.
"""
from __future__ import annotations

from dataclasses import dataclass

from fastapi import APIRouter


@dataclass(frozen=True)
class ModuleInfo:
    """Что служба знает о модуле. Неизменяемый: это объявление, а не состояние.

    `title` — по-английски (§7: наружу — по-английски): перевод делает интерфейс,
    и вторая таблица переводов в службе разошлась бы с первой молча.

    `routes_prefix` — где искать маршруты модуля. Наружу он уезжает под именем
    `routes`: клиенту важно «куда стучаться», а не то, что внутри это префикс.
    """

    id: str
    title: str
    ready: bool = True
    routes_prefix: str = ""

    def to_dict(self) -> dict:
        """Карточка модуля наружу. Флага `ready` в ней нет намеренно.

        В ответ попадают только готовые, и повторять это полем значило бы
        предложить интерфейсу второй способ узнать то же самое — а второй
        способ однажды покажет человеку неготовый модуль.
        """
        return {"id": self.id, "title": self.title, "routes": self.routes_prefix}


# Пары «модуль — его роутер». Список, а не словарь: порядок задаёт порядок
# пунктов в сайдбаре, и терять его ради поиска по ключу, которого никто не
# делает, незачем.
_РЕЕСТР: list[tuple[ModuleInfo, APIRouter | None]] = []


def register(info: ModuleInfo, router: APIRouter | None = None) -> None:
    """Записать модуль в реестр. Повторная запись того же `id` — ничего.

    Идемпотентность здесь не украшение: наполнение зовётся из `routers()`, а та
    — из `routes.collect()`, то есть на каждое собранное приложение. Без неё в
    тестах к третьему приложению в реестре лежало бы три `flowcharts`.

    `router=None` — законный случай: у модуля бывает карточка и не бывает своих
    маршрутов (`reports` работает существующими маршрутами проектов).
    """
    if any(готовый.id == info.id for готовый, _ in _РЕЕСТР):
        return
    _РЕЕСТР.append((info, router))


def _наполнить() -> None:
    """Все модули службы. Сюда дописывается строка на новый модуль.

    Импорты внутри функции, а не наверху файла: подпакет модуля тянет
    зависимости доступа и базу, и на уровне модуля это круг импортов.
    """
    from .flowcharts import MODULE as блок_схемы, router as блок_схемы_router
    from .kadai import MODULE as задания, router as задания_router
    from .uml import MODULE as uml, router as uml_router

    # `reports` — модуль без своих маршрутов: отчёты собираются существующими
    # маршрутами проектов и значений тегов. Карточка ему нужна, потому что в
    # сайдбаре он первый; заводить ради неё пустой роутер незачем.
    register(ModuleInfo(id="reports", title="Reports", ready=True,
                        routes_prefix="/api/projects"))
    # `kadai` стоит вторым: это второй способ получить работу — не заполнение
    # шаблона, а одна задача условием на входе. Порядок здесь — порядок пунктов
    # сайдбара, и заданиям место рядом с отчётами, а не после схем.
    register(задания, задания_router)
    register(блок_схемы, блок_схемы_router)
    register(uml, uml_router)


def with_routers() -> list[tuple[ModuleInfo, APIRouter | None]]:
    """Реестр целиком, вместе с неготовыми. Читают его тесты и `routers()`."""
    if not _РЕЕСТР:
        _наполнить()
    return list(_РЕЕСТР)


def all_modules() -> list[ModuleInfo]:
    """Все объявленные модули, включая неготовые. Наружу уезжают не все."""
    return [info for info, _ in with_routers()]


def routers() -> list[APIRouter]:
    """Роутеры, которые `routes.collect()` вешает на вход сайта, одной строкой.

    Неготовый модуль маршрутов не получает: показывать его нельзя, а отвечать
    он всё равно отвечал бы — и первый же человек, узнавший путь, работал бы с
    недоделанным модулем в обход интерфейса.
    """
    from . import artifacts

    готовые = [роутер for info, роутер in with_routers()
               if роутер is not None and info.ready]
    return [реестр_router, artifacts.router, *готовые]


# ── сам реестр как маршрут ───────────────────────────────────────────────────

реестр_router = APIRouter(tags=["modules"])


@реестр_router.get("/modules", operation_id="list_modules",
                   summary="Modules the interface may show",
                   description=(
                       "Every module the interface is allowed to show, in "
                       "sidebar order: id, English title and where its routes "
                       "live. Modules that are not ready are absent from the "
                       "list entirely; there is no placeholder for them."))
def список_модулей() -> list[dict]:
    """Готовые модули: `{id, title, routes}` в порядке сайдбара.

    Неготовые не отдаются вовсе (решение брифа), а не помечаются флагом:
    флаг означал бы, что решение «показывать или нет» принимает интерфейс, и
    принял бы он его по-своему в каждом из мест, где строится меню.
    """
    return [info.to_dict() for info in all_modules() if info.ready]


__all__ = ["ModuleInfo", "register", "all_modules", "with_routers", "routers",
           "реестр_router"]
