"""
models — то, что модули схем помнят о построенном: `project_diagrams`.

Схема живёт в работе, а не в браузере: человек строит её, уходит и возвращается
через день — и ждёт увидеть **тот же код и те же параметры**, а не пустое поле
рядом с картинкой. XML в артефакте этого не хранит: артефакт адресуется
содержимым и знает только байты рисунка. Отсюда таблица.

**Строка — индекс, содержимое — на томе.** Здесь лежат только короткие слова:
что за схема (`kind`), на каком языке разбирался исходник, каким режимом или
палитрой рисовалась. Сам исходник — файл, и лежит он там же, где XML, тем же
артефактом (`source_id`): том уже умеет адресовать содержимым, считать место и
отдавать байты, а мегабайт чужого кода в строке базы превратил бы список схем
работы в вычитывание всех исходников разом.

**Запись журнала — она же запись схемы.** Своего `project_id`, имени, номера и
времени у схемы нет: всё это уже есть у записи журнала запусков
(`ProjectRun`), и второй такой набор разошёлся бы с первым на первом же
переименовании. Отсюда `run_id` внешним ключом с `ON DELETE CASCADE`: **удаление
схемы — это удаление записи журнала** (`DELETE …/runs/{run_id}`), и снимает оно
обе строки разом, без второго маршрута и без порядка вызовов, который однажды
переставят местами.

Артефакты при этом остаются на томе: и XML, и исходник адресуются содержимым и
могут стоять значением тега — снести их вслед за строкой значило бы выбить
картинку из готового документа. Место освобождает уборка работы целиком.
"""
from __future__ import annotations

from sqlalchemy import ForeignKey, String
from sqlalchemy.orm import Mapped, mapped_column

from ..db import Row
from ..ids import ID_LEN
from ..projects.models import ARTIFACT_LEN

# Длина короткого слова-параметра: `flowchart`, `classes`, `py`, `dark`,
# `gost_19_701_90`. Все они приходят из перечней строителя схем, и все — слова,
# а не тексты; тридцать два знака с запасом.
PARAM_LEN = 32


class ProjectDiagram(Row):
    """Чем построена одна сохранённая схема: код, язык и параметры отрисовки.

    Заводится вместе с записью журнала и живёт ровно столько же. Отдельного
    списка «мои схемы» у неё нет намеренно: список схем работы — это журнал
    запусков с отбором по модулю (`GET …/runs?module=flowcharts`), а здесь
    лежит то, чего в журнале нет, — чем именно эту схему строили.

    **Модуль здесь не повторяется.** Блок-схема это или UML, знает запись
    журнала (`ProjectRun.module`), и второе поле с тем же смыслом означало бы,
    что однажды они разойдутся и схема окажется в обоих списках сразу. А вот
    `kind` — не модуль: у UML их два (`classes`, `objects`) на один модуль, и
    без него перестроить сохранённую диаграмму нечем.
    """

    __tablename__ = "project_diagrams"

    # Один к одному с записью журнала: у схемы не бывает двух записей, а у
    # записи — двух схем. `unique` здесь не украшение, а то самое, что не даст
    # второму сохранению завести близнеца при повторе запроса.
    run_id: Mapped[str] = mapped_column(
        String(ID_LEN), ForeignKey("project_runs.id", ondelete="CASCADE"),
        unique=True)

    # Что рисовали: `flowchart`, `classes` или `objects`
    # (`api/modules/diagrams.py`).
    kind: Mapped[str] = mapped_column(String(PARAM_LEN))

    lang: Mapped[str] = mapped_column(String(PARAM_LEN), default="")
    # Режим отрисовки — у блок-схем, палитра — у UML. Два поля, а не одно поле
    # «параметр»: перечни у них разные, проверяются разными дверями строителя, и
    # общее поле пришлось бы разбирать по модулю в каждом месте, где его читают.
    mode: Mapped[str] = mapped_column(String(PARAM_LEN), default="")
    theme: Mapped[str] = mapped_column(String(PARAM_LEN), default="")

    # Исходники, из которых схема построена, — артефактом проекта: список
    # `[{name, source}]` в JSON. Кладётся всегда, в том числе когда исходник
    # пришёл материалом работы: материал переименовывают и удаляют, а схема
    # обязана открываться тем же кодом, каким её построили.
    source_id: Mapped[str] = mapped_column(String(ARTIFACT_LEN), default="")


__all__ = ["ProjectDiagram", "PARAM_LEN"]
