"""
cards — модуль «Тренажёр»: наборы карточек вопрос → ответ и заходы по ним.

Человек загружает набор файлом JSON или таблицей CSV (или получает его от
агента), решает его сколько угодно заходами — вопрос, «Показать ответ»,
«Да» / «Нет», — и
видит, какую долю набора знает. «Знаю» — последний ответ «Да».

Файлы:

    routes.py                                  наборы, черновики, заходы, генерация
    models.py                                  заходы, попытки, прогресс, личные настройки
    ../../runs/handlers/cards_generate.py      агент пишет набор в черновик
    ../../../orchestrator/cards.py             ядро разбора, набор и черновики на томе

**Набор — решение работы**, как доска и программа ассемблера: запись журнала
`module: "cards"` и каталог решения в неявной работе «Тренажёр» пространства.
Прогресс, попытки, заходы и личные настройки — в базе и видны только самому
человеку.

`router` отдаётся лениво: таблицы модуля импортирует `api.models` при сборке
метаданных, а маршруты тянут за собой доступ, проекты и оркестратор — на этом
шаге это круг импортов.
"""
from __future__ import annotations

from .. import ModuleInfo

MODULE = ModuleInfo(id="cards", title="Trainer", ready=True,
                    routes_prefix="/api/cards")


def __getattr__(имя: str):
    if имя == "router":
        from .routes import router                            # noqa: PLC0415

        return router
    raise AttributeError(имя)


__all__ = ["MODULE", "router"]
