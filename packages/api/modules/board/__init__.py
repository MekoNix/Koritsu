"""
board — модуль доски: человек решает задачу от руки и тут же спрашивает совета.

Доска — холст, на котором пишут пером или мышью; написанное распознаётся и
становится строками решения, человек их подтверждает, и подтверждённые уезжают
модели текстом, без картинок. Дальше — переписка с репетитором одним видом
задания очереди (`board_check`, режим `chat`): человек пишет словами, что
проверить или что непонятно, репетитор отвечает словами; строки доски приложены
к каждому сообщению. Прочие режимы того же задания (проверка, подсказка, задача)
остаются в договоре для вызова через API.

Три файла и три разные работы:

    routes.py   доски работы, сцена, строки, условие, переписка, состояние ключей
    ink.py      мост распознавания рукописи и проброс версии протокола
    ../../runs/handlers/board_check.py   само задание очереди

**Доска — решение работы, а не своя таблица.** Одна доска — одна запись журнала
запусков (`module: "board"`) и каталог под ней. Всё, ради чего заводилась бы
своя таблица, у решения уже есть: имя, номер и владелец — в журнале; свой
каталог, условие задачи и папка файлов контекста — на томе; журнал проверок с
ценой и отменой — в очереди заданий; неизменный снимок — артефакт. Своя таблица
означала бы вторую систему версий и второй список работ рядом с первыми.

`routes_prefix` — `/api/projects`, как у решений и отчётов: доска живёт в
работе, своего корня у модуля нет. Два маршрута без проекта всё же есть —
состояние ключей распознавания и сам мост, — но они про человека и про его
ключи, а не про работу, и корнем модуля не становятся.

Карточка модуля обязательна сама по себе: сайдбар строится по
`GET /api/modules`, и модуля, которого там нет, на сайте нет вовсе.
"""
