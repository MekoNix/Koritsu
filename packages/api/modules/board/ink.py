def ключи(s, settings, user_id: str) -> tuple[str, str] | None:
    """Пара ключей распознавания этого человека или `None`, если её нет.

    Свои и только свои: общего ключа у распознавания не бывает
    (`keys.service.source_of` объясняет, почему). Пара — обе половины: одна без
    другой подписи не даёт, и работать «наполовину» здесь не с чем.

    Значения живут в локальной переменной вызывающего и не кладутся ни в
    объект, ни в журнал, ни в ответ.
    """
    приложение = keys.secret_for(s, settings, user_id, "myscript_app")
    подпись = keys.secret_for(s, settings, user_id, "myscript_hmac")
    if not приложение or not подпись:
        return None
    return приложение, подпись


def ключи_есть(s, settings, user_id: str) -> bool:
    """Заведена ли у человека пара ключей. Сами ключи наружу не выходят."""
    return ключи(s, settings, user_id) is not None


def подписать(сообщение: str | bytes, приложение: str, подпись: str) -> str:
    """Подпись сообщения: HMAC-SHA-512, ключ — две половины пары подряд.

    Одна на оба входа. Сокету подписывается строка вызова (`hmacChallenge`),
    пакетному запросу — тело целиком, байт в байт то, что уйдёт по проводу:
    подпись по пересобранному JSON разошлась бы с телом на первом же пробеле.
    Отсюда и `bytes` в подписи функции.

    Hex в нижнем регистре — то, чего ждёт собеседник. Порядок половин обратный
    не годится: ключ это склейка `applicationKey + hmacKey`, и перестановка
    даёт другой ключ и молчаливый отказ в доступе.
    """
    ключ = (приложение + подпись).encode("utf-8")
    тело = сообщение.encode("utf-8") if isinstance(сообщение, str) else сообщение
    return _hmac.new(ключ, тело, hashlib.sha512).hexdigest()


