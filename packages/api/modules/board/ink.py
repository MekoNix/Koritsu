def _записать(db, kind: str, user_id: str, ip: str = "", **detail) -> None:
    """Запись в журнал службы своим соединением. Не бросает никогда.

    Своим, а не отложенной очередью запроса: очередь сбрасывает слой, который
    работает только на HTTP, и сокет прошёл бы мимо него молча. Наблюдение при
    этом не имеет права ломать работу — потому и глушится.
    """
    from ...admin.models import SecurityEvent                # noqa: PLC0415

    try:
        with db.session_scope() as s:
            s.add(SecurityEvent(user_id=user_id or None, ip=ip or "",
                                kind=kind[:32], detail=detail))
    except Exception:                                        # noqa: BLE001
        беды.exception("не удалось записать событие моста %s", kind)


