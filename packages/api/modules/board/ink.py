# * `НАСТРОЙКА_РАСПОЗНАВАНИЯ` — что именно просить в ответе. Разные сборки
#   сервиса зовут одно и то же по-разному, и лишнее поле настройки они
#   пропускают молча;
# * `латекс` — каким полем выражения приезжает формула (`latex` или `label`);
# * `ссылки_на_штрихи` и `строка_ссылки` — как выражение называет росчерки, из
#   которых собрано. Разложение ответа по строкам держится на них, а запасным
#   путём — на рамках выражений, и работает, даже когда ссылок нет вовсе.
