# ── адреса ───────────────────────────────────────────────────────────────────

def адрес_моста(request: Request) -> tuple[str, str]:
    """Схема и хост, которыми страница откроет сокет. → `("wss", "хост")`.

    Берётся из самого запроса, а не из настроек: домена у службы может не быть
    вовсе, а за обратным прокси настоящую схему знает только заголовок. Хвост
    адреса — путь площадки — дописывает страница: базовый путь сборки знает она,
    и служба, догадывающаяся о нём, догадалась бы неверно в первой же установке
    под другим префиксом.
    """
    схема = "wss" if request.url.scheme in ("https", "wss") else "ws"
    return схема, str(request.headers.get("host") or request.url.netloc or "")


def адрес_наверх(запрос: str, приложение: str) -> str:
    """Адрес наверху: тот же путь, но с настоящим ключом в строке запроса.

    Разбираем и собираем заново, а не заменяем подстроку: в строке запроса
    бывает не только ключ, а подстановка вслепую испортила бы соседний
    параметр, в котором то же слово оказалось значением.
    """
    поля = urllib.parse.parse_qsl(запрос or "", keep_blank_values=True)
    поля = [(имя, приложение if имя == ПОЛЕ_КЛЮЧА else значение)
            for имя, значение in поля]
    if not any(имя == ПОЛЕ_КЛЮЧА for имя, _ in поля):
        поля.append((ПОЛЕ_КЛЮЧА, приложение))
    строка = urllib.parse.urlencode(поля)
    return f"{СХЕМА_ВЕРХА}://{ВЕРХ}{ПУТЬ_НАВЕРХУ}?{строка}"


def подменить_ключ(сообщение: str, приложение: str) -> str:
    """Подставить настоящий ключ в тело сообщения, если он там есть.

    Ключ едет не только в адресе: он лежит полем в начале сеанса и при его
    восстановлении. Разбираем как JSON и правим поле, а не строку: замена по
    тексту попала бы в чужое значение, в котором случайно оказалось то же слово.

    Сообщение, которое не разбирается как объект JSON, уезжает как есть — мост
    не обязан понимать всё, что говорит библиотека, и не должен ломать то, чего
    не понял.
    """
    try:
        тело = json.loads(сообщение)
    except (ValueError, TypeError):
        return сообщение
    if not isinstance(тело, dict) or ПОЛЕ_КЛЮЧА not in тело:
        return сообщение
    тело[ПОЛЕ_КЛЮЧА] = приложение
    return json.dumps(тело, ensure_ascii=False)


def вызов_подписи(сообщение: str) -> str | None:
    """Строка вызова подписи, если это она. Иначе `None`.

    Отдельной функцией, потому что решение «этот кадр вниз не пойдёт»
    принимается ровно здесь: вызов подписи — единственное, что мост
    перехватывает, и список перехватываемого обязан читаться одной строкой.
    """
    try:
        тело = json.loads(сообщение)
    except (ValueError, TypeError):
        return None
    if not isinstance(тело, dict):
        return None
    строка = тело.get(ВЫЗОВ)
    return str(строка) if строка else None


def код_вниз(код: int | None) -> int:
    """Код закрытия верхнего соединения в виде, который можно послать вниз.

    `1005` и `1006` по правилам протокола на проводе не появляются: это метки
    «кода не было» и «связь оборвалась». Пересказываем их честно, а не молчим:
    страница показывает человеку настоящий код с расшифровкой, и выдуманный
    увёл бы его искать беду не там.
    """
    if код is None or код == 1005:
        return 1000
    if код == 1006:
        return 1011
    if 1000 <= код <= 4999 and код not in (1004, 1005, 1006):
        return код
    return 1011


# ── сокет ────────────────────────────────────────────────────────────────────

async def _отказать(ws: WebSocket, код: int, причина: str) -> None:
    """Принять соединение и тут же закрыть его своим кодом.

    Принять обязательно: код закрытия доезжает до страницы только по открытому
    сокету, а отказ на самом рукопожатии страница видит как «сервер недоступен»
    — то есть как чужую беду вместо нашего внятного ответа.
    """
    await ws.accept()
    await ws.close(code=код, reason=причина)


async def мост(ws: WebSocket) -> None:
    """Сокет распознавания: браузер ↔ служба ↔ облако.

    Порядок шагов единственно возможный, и каждый следующий стоит дороже
    предыдущего: источник запроса, сессия, частота, ключи, внешнее соединение.
    Отказать по первому дешевле, чем по последнему, а человеку понятнее: «слишком
    часто» — состояние, «нет ключей» — настройка.

    Внешнее соединение открывается **до** того, как мы примем сокет у браузера
    в работу: наоборот — значит пообещать страницу сокет и тут же оборвать его
    без объяснения, а именно так и выглядит «сервер распознавания недоступен»,
    от которого мост и заведён.
    """
    app = ws.app
    db = app.state.db
    settings = app.state.settings

    # Сокет не подчиняется правилам, по которым браузер не даёт чужой странице
    # читать наши ответы: заслон подделки запросов работает на HTTP, а сюда не
    # доходит вовсе. Поэтому источник проверяется здесь и по букве: чужая
    # страница, открывшая наш сокет с cookie человека, тратила бы его ключ.
    источник = str(ws.headers.get("origin") or "")
    хост = str(ws.headers.get("host") or "")
    if источник and urllib.parse.urlsplit(источник).netloc != хост:
        await ws.close(code=1008)
        return

    with db.session_scope() as s:
        сессия = текущая_сессия(ws, s)
        человек = None
        if сессия is not None:
            from ...accounts.models import User               # noqa: PLC0415

            человек = s.get(User, сессия.user_id)
            if человек is not None and человек.deleted_at is not None:
                человек = None
        if человек is None:
            # Отказ на самом рукопожатии, а не кодом закрытия: без сессии мы не
            # знаем, кому отвечаем, и открытый сокет был бы открыт неизвестно
            # кому. Слой сервера превращает это в обычный отказ HTTP, который
            # клиент разбирает.
            await ws.close(code=1008)
            return
        кто = человек.id
        часто = открытий_за_минуту(s, кто) >= ОТКРЫТИЙ_В_МИНУТУ
        пара = None if часто else ключи(s, settings, кто)

    адрес_клиента = ws.client.host if ws.client else ""
    if часто:
        await _отказать(ws, КОД_СЛИШКОМ_ЧАСТО, СЛИШКОМ_ЧАСТО)
        return
    if пара is None:
        await _отказать(ws, КОД_БЕЗ_КЛЮЧЕЙ, НЕТ_КЛЮЧЕЙ)
        return
    приложение, подпись = пара

    # Один живой мост на человека: вторая вкладка вытесняет первую. Тариф
    # считает открытия, и забытая вкладка, которая держит сокет сутками, тратит
    # чужие деньги молча.
    прежний = _ЖИВЫЕ.get(кто)
    if прежний is not None:
        try:
            await прежний.close(code=КОД_ВЫТЕСНЕН, reason=ВЫТЕСНЕН)
        except Exception:                                    # noqa: BLE001
            pass

    import logging                                           # noqa: PLC0415
    from websockets.asyncio.client import connect            # noqa: PLC0415
    from websockets.exceptions import ConnectionClosed       # noqa: PLC0415

    # Библиотека на уровне DEBUG печатает строку рукопожатия целиком — вместе с
    # `applicationKey` в адресе. Ключей в журнале не бывает ни на каком уровне,
    # поэтому наружному соединению даётся свой журнал, начинающийся с WARNING:
    # обрыв и отказ в нём останутся, рукопожатие — нет.
    журнал_верха = logging.getLogger("api.board.ink.upstream")
    журнал_верха.setLevel(logging.WARNING)

    просят = [т.strip() for т in
              str(ws.headers.get("sec-websocket-protocol") or "").split(",")
              if т.strip()]
    try:
        наверх = await connect(адрес_наверх(ws.url.query, приложение),
                               logger=журнал_верха,
                               subprotocols=просят or None,
                               open_timeout=ЖДАТЬ_ВЕРХ,
                               close_timeout=5,
                               max_size=ЛИМИТ_СООБЩЕНИЯ,
                               # Свои пинги держат соединение живым, пока
                               # человек думает над задачей и ничего не пишет.
                               ping_interval=ПИНГ_С, ping_timeout=ПИНГ_С)
    except Exception as беда:                                # noqa: BLE001
        # Сюда идёт всё: имя не разрешилось, TLS не сложился, собеседник
        # отказал, время вышло. В журнал — вид беды, но не адрес: в его строке
        # запроса лежит ровно ключ.
        беды.warning("мост распознавания: наверх не достучались — %s",
                     type(беда).__name__)
        _записать(db, ЗАКРЫТИЕ, кто, адрес_клиента,
                  code=КОД_ВЕРХ_НЕ_ОТВЕТИЛ, reason=ВЕРХ_НЕ_ОТВЕТИЛ, seconds=0)
        await _отказать(ws, КОД_ВЕРХ_НЕ_ОТВЕТИЛ, ВЕРХ_НЕ_ОТВЕТИЛ)
        return

    await ws.accept(subprotocol=getattr(наверх, "subprotocol", None))
    _ЖИВЫЕ[кто] = ws
    _записать(db, ОТКРЫТИЕ, кто, адрес_клиента)
    начало = asyncio.get_running_loop().time()
    код, причина = 1000, ""
    try:
        код, причина = await _качать(ws, наверх, приложение, подпись,
                                     ConnectionClosed)
    finally:
        if _ЖИВЫЕ.get(кто) is ws:
            _ЖИВЫЕ.pop(кто, None)
        with _тихо():
            await наверх.close()
        with _тихо():
            await ws.close(code=код, reason=причина[:120])
        _записать(db, ЗАКРЫТИЕ, кто, адрес_клиента, code=int(код),
                  reason=причина[:120],
                  seconds=round(asyncio.get_running_loop().time() - начало, 1))


class _тихо:
    """Закрыть то, что уже может быть закрыто. Беда закрытия — не беда.

    Своим менеджером, а не `contextlib.suppress(Exception)` по месту: закрытие
    зовётся из трёх мест подряд, и три одинаковых `try` рядом читаются хуже
    одного имени, которое говорит, зачем они.
    """

    def __enter__(self) -> "_тихо":
        return self

    def __exit__(self, *беда) -> bool:
        return True


async def _качать(ws: WebSocket, наверх, приложение: str, подпись: str,
                  ConnectionClosed) -> tuple[int, str]:
    """Гонять кадры в обе стороны, пока жива хоть одна. → код и причина ухода.

    Два направления — две задачи: обе ждут своего собеседника, и та из них, что
    кончилась первой, называет код закрытия. Вторая снимается — оставить её
    висеть значило бы держать поток и внешнее соединение после того, как
    браузер ушёл.
    """
    вниз = asyncio.create_task(_сверху_вниз(ws, наверх, приложение, подпись,
                                            ConnectionClosed))
    вверх = asyncio.create_task(_снизу_вверх(ws, наверх, приложение))
    готово, остальные = await asyncio.wait({вниз, вверх},
                                           return_when=asyncio.FIRST_COMPLETED)
    for задача in остальные:
        задача.cancel()
    for задача in остальные:
        with _тихо():
            await задача
    первая = next(iter(готово))
    try:
        return первая.result()
    except Exception as беда:                                # noqa: BLE001
        беды.warning("мост распознавания: %s", type(беда).__name__)
        return 1011, type(беда).__name__


async def _сверху_вниз(ws: WebSocket, наверх, приложение: str, подпись: str,
                       ConnectionClosed) -> tuple[int, str]:
    """Кадры от собеседника к браузеру. Вызов подписи перехватывается здесь."""
    try:
        async for сообщение in наверх:
            if isinstance(сообщение, str):
                вызов = вызов_подписи(сообщение)
                if вызов is not None:
                    # Вниз не пересылаем вовсе: браузер подписать не может, у
                    # него ключей нет и не будет.
                    await наверх.send(json.dumps(
                        {"type": ОТВЕТ_ПОДПИСИ,
                         ОТВЕТ_ПОДПИСИ: подписать(вызов, приложение, подпись)}))
                    continue
                await ws.send_text(сообщение)
            else:
                await ws.send_bytes(сообщение)
    except ConnectionClosed as закрытие:
        пришло = getattr(закрытие, "rcvd", None)
        return (код_вниз(getattr(пришло, "code", None)),
                str(getattr(пришло, "reason", "") or ""))
    пришло = getattr(getattr(наверх, "protocol", None), "close_rcvd", None)
    return (код_вниз(getattr(пришло, "code", None)),
            str(getattr(пришло, "reason", "") or ""))


async def _снизу_вверх(ws: WebSocket, наверх, приложение: str) -> tuple[int, str]:
    """Кадры от браузера к собеседнику. Здесь подставляется настоящий ключ."""
    while True:
        кадр = await ws.receive()
        вид = кадр.get("type")
        if вид == "websocket.disconnect":
            return код_вниз(кадр.get("code")), ""
        текст = кадр.get("text")
        если_байты = кадр.get("bytes")
        if текст is not None:
            if len(текст.encode("utf-8")) > ЛИМИТ_СООБЩЕНИЯ:
                return 1009, "message too large"
            await наверх.send(подменить_ключ(текст, приложение))
        elif если_байты is not None:
            if len(если_байты) > ЛИМИТ_СООБЩЕНИЯ:
                return 1009, "message too large"
            await наверх.send(если_байты)


# ── пакетное распознавание ───────────────────────────────────────────────────

def точек(строка: dict) -> int:
    """Сколько точек в строке записи. Потолок считается по ним, а не по штрихам.

    По точкам, потому что за них платит провод и время сервиса: строка из
    одного росчерка через пол-экрана тяжелее десяти коротких.
    """
    return sum(len(ш.get("x") or ()) for ш in строка.get("strokes") or ())


def ровные_ли(строка: dict) -> bool:
    """Одинаковой ли длины `x`, `y` и `t` у каждого штриха строки.

    Сервис требует этого сам и отказывает **всей** пачке; проверка здесь стоит
    ничего и превращает отказ всей пачки в беду одной строки.
    """
    for ш in строка.get("strokes") or ():
        x, y, t = ш.get("x") or [], ш.get("y") or [], ш.get("t")
        if not x or len(x) != len(y):
            return False
        if t is not None and len(t) != len(x):
            return False
    return True


def габарит(строка: dict) -> tuple[float, float, float, float] | None:
    """Габарит строки в тех координатах, в каких приехали штрихи.

    `(слева, сверху, справа, снизу)`. Нужен запасным путём разложения: когда
    сервис не сказал, какие штрихи чьи, выражения раскладываются по строкам
    вертикальным перекрытием рамок — тем же правилом, каким страница
    раскладывает росчерки по строкам ответа.
    """
    xs = [з for ш in строка.get("strokes") or () for з in (ш.get("x") or ())]
    ys = [з for ш in строка.get("strokes") or () for з in (ш.get("y") or ())]
    if not xs or not ys:
        return None
    return (min(xs), min(ys), max(xs), max(ys))


def габарит_выражения(выражение: dict,
                      dpi: int) -> tuple[float, float, float, float] | None:
    """Рамка выражения JIIX в координатах штрихов. Рамки нет — `None`.

    Рамки JIIX приходят **в миллиметрах**, а штрихи уезжали в пикселях; перевод
    идёт тем самым разрешением, которое мы и объявили в запросе (`xDPI`).
    """
    рамка = выражение.get("bounding-box")
    if not isinstance(рамка, dict):
        return None
    try:
        x, y = float(рамка["x"]), float(рамка["y"])
        ширина = float(рамка.get("width") or 0)
        высота = float(рамка.get("height") or 0)
    except (KeyError, TypeError, ValueError):
        return None
    к = float(dpi or DPI) / ММ
    return (x * к, y * к, (x + ширина) * к, (y + высота) * к)


def тело_пачки(строки: list[dict], dpi: int) -> dict:
    """Строки записи → тело пакетного запроса.

    **Строка — своя группа штрихов.** Группы едут в том порядке, в каком
    пришли, и это единственное, чем запрос говорит сервису, где кончается одна
    строка и начинается следующая; ответ раскладывается обратно по ним
    (`разложить`).

    Один запрос на все строки, а не по запросу на строку: тариф считает
    запросы, и пачка из шести исправленных строк стоит одну единицу тарифа
    вместо шести. Запасной путь на случай, если сервис границы групп не
    удержит и ответит одним выражением на всю пачку, — настройка
    `ink_batch_per_line`.
    """
    группы = []
    for i, строка in enumerate(строки):
        штрихи = []
        for j, ш in enumerate(строка.get("strokes") or ()):
            один = {"x": list(ш.get("x") or ()), "y": list(ш.get("y") or ())}
            if ш.get("t"):
                один["t"] = list(ш["t"])
            if ШЛЁМ_ИД_ШТРИХОВ:
                один["id"] = f"{i}-{j}"
            штрихи.append(один)
        группы.append({"strokes": штрихи})
    return {"configuration": НАСТРОЙКА_РАСПОЗНАВАНИЯ,
            "xDPI": int(dpi or DPI), "yDPI": int(dpi or DPI),
            "contentType": ВИД_ЗАПИСИ, "strokeGroups": группы}


def выражения(корень) -> list[dict]:
    """Выражения верхнего уровня из ответа JIIX. Не разобрали — пустой список.

    Ответ бывает и строкой: тип ответа объявлен нами, но разбирать чужой JSON
    доверчиво нельзя — сервис вправе ответить чем угодно, а падение здесь
    означало бы пятисотку вместо честного «распознать не удалось».
    """
    if isinstance(корень, (str, bytes)):
        try:
            корень = json.loads(корень)
        except (ValueError, TypeError):
            return []
    если = корень.get("expressions") if isinstance(корень, dict) else None
    return [в for в in (если or ()) if isinstance(в, dict)]


# ── JIIX → LaTeX ─────────────────────────────────────────────────────────────
#
# Распознавание математики отвечает **деревом**, а не формулой: у узлов-операций
# (`+`, `=`, `fraction`, `power`) нет ни `latex`, ни `label` — есть только вид и
# операнды, а подписаны лишь листья (`number`, `symbol`). Формулу из этого
# собирают здесь.
#
# Почему здесь, а не на странице: LaTeX строки — то, что ложится в файл
# распознанного, уезжает репетитору и печатается в выжимке, то есть нужен и
# тогда, когда страницы рядом нет вовсе. Перевод при этом — чистая функция над
# словарём: ни сети, ни ключей, ни состояния.
#
# Узел, вида которого здесь нет, не теряется: у него берётся подпись, а нет
# подписи — склейка переводов операндов. Незнакомая скобка так превращается в
# своё содержимое, а не в пустоту, и человек видит формулу без одной детали, а
# не пустую строку.

# Знаки, которые сервис называет по-человечески, а LaTeX — по-своему. Сюда же
# греческие буквы: в ответе они приезжают самими собой.
ЗНАКИ = {
    "±": r"\pm", "∓": r"\mp", "×": r"\times", "·": r"\cdot", "∙": r"\cdot",
    "÷": r"\div", "≠": r"\neq", "≤": r"\leq", "≥": r"\geq",
    "≈": r"\approx", "≃": r"\simeq", "≅": r"\cong", "≡": r"\equiv",
    "≢": r"\not\equiv", "≪": r"\ll", "≫": r"\gg", "∥": r"\parallel",
    "→": r"\rightarrow", "←": r"\leftarrow", "↔": r"\leftrightarrow",
    "⇒": r"\Rightarrow", "⇐": r"\Leftarrow", "⇔": r"\Leftrightarrow",
    "∞": r"\infty", "∈": r"\in", "∉": r"\notin", "⊂": r"\subset",
    "∪": r"\cup", "∩": r"\cap", "∅": r"\emptyset", "∀": r"\forall",
    "∃": r"\exists", "∑": r"\sum", "∏": r"\prod", "∫": r"\int",
    "√": r"\sqrt", "∂": r"\partial", "°": r"^{\circ}", "%": r"\%",
    "α": r"\alpha", "β": r"\beta", "γ": r"\gamma", "δ": r"\delta",
    "ε": r"\varepsilon", "ζ": r"\zeta", "η": r"\eta", "θ": r"\theta",
    "ι": r"\iota", "κ": r"\kappa", "λ": r"\lambda", "μ": r"\mu",
    "ν": r"\nu", "ξ": r"\xi", "π": r"\pi", "ρ": r"\rho", "σ": r"\sigma",
    "τ": r"\tau", "υ": r"\upsilon", "φ": r"\varphi", "χ": r"\chi",
    "ψ": r"\psi", "ω": r"\omega", "Γ": r"\Gamma", "Δ": r"\Delta",
    "Θ": r"\Theta", "Λ": r"\Lambda", "Ξ": r"\Xi", "Π": r"\Pi",
    "Σ": r"\Sigma", "Φ": r"\Phi", "Ψ": r"\Psi", "Ω": r"\Omega",
}

# Имена, у которых в LaTeX есть своя команда: набранные ею, они стоят прямо и с
# правильными отступами, а набранные буквами — читаются как произведение
# переменных s·i·n.
ФУНКЦИИ = frozenset({
    "sin", "cos", "tan", "cot", "sec", "csc", "sinh", "cosh", "tanh", "coth",
    "arcsin", "arccos", "arctan", "log", "ln", "lg", "exp", "lim", "min",
    "max", "inf", "sup", "det", "dim", "gcd", "deg", "arg", "ker", "hom",
})

# Скобки оград. Фигурные в LaTeX защищаются: без защиты они открывают группу.
СКОБКИ = {"{": r"\{", "}": r"\}", "|": r"|", "‖": r"\|",
          "⌊": r"\lfloor", "⌋": r"\rfloor", "⌈": r"\lceil", "⌉": r"\rceil",
          "⟨": r"\langle", "⟩": r"\rangle"}


# Команда LaTeX в конце куска. Нужна склейке: команда кончается там, где
# начинается не-буква, и `\sin` вплотную к `x` читается набором как одно
# неизвестное слово `\sinx`.
КОМАНДА_В_КОНЦЕ = re.compile(r"\\[A-Za-z]+$")


def _знак(текст: str) -> str:
    """Знак так, как его пишет LaTeX. Незнакомый — как есть."""
    return ЗНАКИ.get(текст, текст)


def _склеить(куски) -> str:
    r"""Соединить куски формулы, разняв пробелом там, где иначе слипнется.

    Пробел ставится только между командой LaTeX и следующей за ней буквой или
    цифрой: `\sin x`, а не `\sinx`. Везде больше он был бы мусором в строке,
    которую человек правит руками.
    """
    итог = ""
    for кусок in куски:
        if not кусок:
            continue
        if итог and кусок[0].isalnum() and КОМАНДА_В_КОНЦЕ.search(итог):
            итог += " "
        итог += кусок
    return итог


def _перемежить(части: list[str], знак: str) -> str:
    """Операнды через знак операции: `a`, `b` и `+` → `a+b`."""
    вперемежку: list[str] = []
    for i, часть in enumerate(части):
        if i:
            вперемежку.append(знак)
        вперемежку.append(часть)
    return _склеить(вперемежку)


def _лист(узел: dict) -> str:
    """Подписанный узел: число или знак. Подписи нет — значение."""
    подпись = узел.get("label")
    if not isinstance(подпись, str) or not подпись.strip():
        значение = узел.get("value")
        подпись = "" if значение is None else str(значение)
    подпись = подпись.strip()
    if подпись in ФУНКЦИИ:
        return "\\" + подпись
    return _знак(подпись)


def _группой(текст: str) -> str:
    """Обернуть в фигурные скобки то, что иначе распадётся.

    Один знак в скобках не нуждается: `x^2` и `x^{2}` — одно и то же, а лишние
    скобки в формуле, которую человек будет править руками, только мешают.
    """
    return текст if len(текст) == 1 else "{" + текст + "}"


def _функция(имя: str) -> str:
    """Имя функции командой LaTeX, если она есть, иначе прямым начертанием."""
    голое = имя.strip()
    if голое in ФУНКЦИИ:
        return "\\" + голое
    return r"\operatorname{" + голое + "}" if голое else ""


def _ограда(узел: dict, внутри: str) -> str:
    """Ограда: скобки по краям содержимого, растущие вместе с ним.

    `\\left`/`\\right`, а не голые скобки: внутри бывает дробь в две строки, и
    скобка ростом в одну строку рядом с нею выглядит ошибкой набора.
    """
    слева = СКОБКИ.get(str(узел.get("open symbol") or "("),
                       str(узел.get("open symbol") or "("))
    справа = СКОБКИ.get(str(узел.get("close symbol") or ")"),
                        str(узел.get("close symbol") or ")"))
    return f"\\left{слева} {внутри} \\right{справа}"


def латекс_из_jiix(выражение) -> str:
    """Дерево выражения JIIX → LaTeX. Чистая функция, ничего не трогает.

    Устроена как разбор по виду узла с одним общим правилом на конце: вид, о
    котором здесь не сказано, отдаёт свою подпись, а нет подписи — склейку
    переводов своих операндов. Поэтому новый вид узла у сервиса означает
    формулу без одной детали, а не пустую строку на экране.

    Порядок операндов берётся у сервиса и не переставляется: у дроби это
    числитель и знаменатель, у степени — основание и показатель, у ограды —
    одно содержимое, и переставить их значило бы написать другую формулу.
    """
    if not isinstance(выражение, dict):
        return ""
    вид = str(выражение.get("type") or "").strip()
    операнды = [о for о in (выражение.get("operands") or ())
                if isinstance(о, dict)]
    части = [латекс_из_jiix(о) for о in операнды]
    склейка = _склеить(части)

    if вид in ("number", "symbol"):
        return _лист(выражение)
    if вид == "fraction" and len(части) >= 2:
        return "\\frac{" + части[0] + "}{" + части[1] + "}"
    if вид == "slantedfraction" and len(части) >= 2:
        return _группой(части[0]) + "/" + _группой(части[1])
    if вид == "square root" and части:
        return "\\sqrt{" + части[0] + "}"
    if вид == "root":
        # Корень степени: показатель первым, подкоренное вторым. С одним
        # операндом это обычный квадратный корень.
        if len(части) >= 2:
            return "\\sqrt[" + части[0] + "]{" + части[1] + "}"
        return "\\sqrt{" + склейка + "}"
    if вид in ("power", "superscript"):
        # У одних сборок степень — узел с основанием и показателем, у других —
        # один показатель, стоящий следом за основанием. Оба случая дают одну и
        # ту же формулу, потому что склейка соседей здесь и есть умножение.
        if len(части) >= 2:
            return _группой(части[0]) + "^{" + части[1] + "}"
        return "^{" + склейка + "}"
    if вид == "subscript":
        if len(части) >= 2:
            return _группой(части[0]) + "_{" + части[1] + "}"
        return "_{" + склейка + "}"
    if вид == "subsuperscript" and len(части) >= 3:
        return _группой(части[0]) + "_{" + части[1] + "}^{" + части[2] + "}"
    if вид == "presuperscript" and len(части) >= 2:
        return "{}^{" + части[1] + "}" + _группой(части[0])
    if вид == "underscript" and len(части) >= 2:
        return "\\underset{" + части[1] + "}{" + части[0] + "}"
    if вид == "overscript" and len(части) >= 2:
        return "\\overset{" + части[1] + "}{" + части[0] + "}"
    if вид == "underoverscript" and len(части) >= 3:
        return ("\\underset{" + части[1] + "}{\\overset{" + части[2] + "}{"
                + части[0] + "}}")
    if вид == "fence":
        return _ограда(выражение, склейка)
    if вид == "function":
        подпись = выражение.get("label")
        имя = _функция(подпись) if isinstance(подпись, str) else ""
        return _склеить([имя, склейка]) if имя else склейка
    if вид == "!":
        return склейка + "!"
    if вид == "percentage":
        знак = _знак(str(выражение.get("operator") or ""))
        return _перемежить(части, знак) + "\\%"
    if вид == "system":
        строки = [латекс_из_jiix(в) for в in (выражение.get("expressions") or ())
                  if isinstance(в, dict)]
        внутри = " \\\\ ".join(с for с in строки if с)
        return "\\begin{cases} " + внутри + " \\end{cases}" if внутри else ""
    if вид == "matrix":
        строки = []
        for ряд in выражение.get("rows") or ():
            if not isinstance(ряд, dict):
                continue
            клетки = [латекс_из_jiix(к) for к in (ряд.get("cells") or ())
                      if isinstance(к, dict)]
            строки.append(" & ".join(клетки))
        внутри = " \\\\ ".join(с for с in строки if с)
        return "\\begin{matrix} " + внутри + " \\end{matrix}" if внутри else ""
    if вид in ("group", "partialfractionnumerator",
               "partialfractiondenominator", "mixed"):
        return склейка
    if вид and len(части) >= 2 and not вид[0].isalnum():
        # Двуместная операция: сам вид узла и есть знак между операндами.
        return _перемежить(части, _знак(вид))
    if вид and len(части) == 1 and not вид[0].isalnum():
        # Одноместная: знак впереди — так пишется минус у отрицательного числа.
        return _склеить([_знак(вид), части[0]])

    подпись = выражение.get("label")
    if isinstance(подпись, str) and подпись.strip():
        return подпись.strip()
    return склейка or _лист(выражение)


def латекс(выражение: dict) -> str:
    """LaTeX одного выражения: готовый, собранный из дерева или подпись.

    Три источника по убыванию точности, и первого обычно нет вовсе: поле
    `latex` кладут не все сборки сервиса. Второй — перевод дерева
    (`латекс_из_jiix`), и он же рабочий: у узлов-операций подписи нет, и без
    перевода строка из `1+2` приезжала бы пустой. Третий — собственная подпись
    выражения, если она вдруг есть, а дерево не собралось.

    Что делать, когда выражений у строки вышло несколько, решает страница: ей
    уезжает и `jiix` целиком.
    """
    значение = выражение.get("latex")
    if isinstance(значение, str) and значение.strip():
        return значение.strip()
    собранное = латекс_из_jiix(выражение)
    if собранное:
        return собранное
    подпись = выражение.get("label")
    return подпись.strip() if isinstance(подпись, str) else ""


def ссылки_на_штрихи(выражение) -> list[str]:
    """Все ссылки на штрихи, какие есть в выражении и внутри него.

    Сервис называет штрихи по-разному в разных сборках: списком `strokes`,
    вложенными объектами вида `{"type": "stroke", "id": …}`. Дерево обходится
    целиком и собирается и то, и другое: разбирать по одному имени значило бы
    получить пустой список ровно тогда, когда сборка сменится.
    """
    найдено: list[str] = []

    def обойти(узел) -> None:
        if isinstance(узел, dict):
            если = узел.get("id")
            if "stroke" in str(узел.get("type") or "").lower() and isinstance(
                    если, str):
                найдено.append(если)
            for имя, значение in узел.items():
                if имя == "strokes" and isinstance(значение, list):
                    найдено.extend(з for з in значение if isinstance(з, str))
                обойти(значение)
        elif isinstance(узел, list):
            for з in узел:
                обойти(з)

    обойти(выражение)
    return найдено


def строка_ссылки(ссылка: str, по_штрихам: list[int]) -> int:
    """Какой строке принадлежит названный штрих. Не разобрали — `-1`.

    Ссылка разбирается двумя способами. Первый — как имя, которое мы же и
    послали (`<строка>-<штрих>`); он работает, только если штрихи уезжали с
    именами. Второй — как порядковый номер: сервис нумерует штрихи в том
    порядке, в каком их получил, и хвостовое число ссылки (`stroke-3`, `S3`,
    `3`) — это номер штриха в общем списке пачки.
    """
    текст = str(ссылка or "")
    если = ПАРА_ЧИСЕЛ.fullmatch(текст)
    строк = (max(по_штрихам) + 1) if по_штрихам else 0
    if ШЛЁМ_ИД_ШТРИХОВ and если:
        строка = int(если.group(1))
        return строка if строка < строк else -1
    хвост = ХВОСТОВОЕ_ЧИСЛО.search(текст)
    if not хвост:
        return -1
    номер = int(хвост.group(1))
    return по_штрихам[номер] if 0 <= номер < len(по_штрихам) else -1


def перекрытие(а, б) -> float:
    """Насколько две рамки накладываются по вертикали. Меньше нуля — не задели."""
    return min(а[3], б[3]) - max(а[1], б[1])


def куда_легло(выражение: dict, строки: list[dict], по_штрихам: list[int],
               dpi: int) -> int:
    """Номер строки, к которой относится выражение. Ни к одной — `-1`.

    Три правила по убыванию точности:

    1. **по штрихам** — выражение само называет росчерки, из которых собрано;
       строка, которой принадлежит больше всего названных, и есть его строка.
       Это единственный способ, не зависящий от того, как записано на холсте;
    2. **строка одна** — забирает всё: делить нечего;
    3. **по рамкам** — наибольшее вертикальное перекрытие рамки выражения с
       габаритом строки. Запасной путь на случай, когда ссылок на штрихи в
       ответе нет вовсе.
    """
    голоса: dict[int, int] = {}
    for ссылка in ссылки_на_штрихи(выражение):
        строка = строка_ссылки(ссылка, по_штрихам)
        if строка >= 0:
            голоса[строка] = голоса.get(строка, 0) + 1
    if голоса:
        return max(голоса, key=lambda с: (голоса[с], -с))
    if len(строки) == 1:
        return 0
    рамка = габарит_выражения(выражение, dpi)
    if рамка is None:
        return -1
    лучшая, лучшее = -1, 0.0
    for i, строка in enumerate(строки):
        свой = габарит(строка)
        if свой is None:
            continue
        сколько = перекрытие(свой, рамка)
        if сколько > лучшее:
            лучшая, лучшее = i, сколько
    return лучшая


def разложить(корень, строки: list[dict],
              dpi: int) -> tuple[list[list[dict]], list[dict]]:
    """Ответ пачки → выражения по строкам запроса и то, что не легло никуда.

    Не легло — не выбрасывается, а уезжает страницe отдельным списком: это
    написанное, которого распознавание не отнесло ни к одной известной ей
    строке, и молчаливая пропажа такого читалась бы как «распозналось пусто».
    """
    по_штрихам = [i for i, с in enumerate(строки)
                  for _ in (с.get("strokes") or ())]
    по_строкам: list[list[dict]] = [[] for _ in строки]
    лишние: list[dict] = []
    for выражение in выражения(корень):
        куда = куда_легло(выражение, строки, по_штрихам, dpi)
        (по_строкам[куда] if куда >= 0 else лишние).append(выражение)
    return по_строкам, лишние


def своё_jiix(корень, свои: list[dict]) -> dict | None:
    """Ответ JIIX, в котором остались выражения одной строки. Нет их — `None`.

    Тот же корень, а не голый список: странице приезжает документ той формы, с
    какой она умеет работать, и форма эта одна независимо от того, уехала
    пачка одним запросом или по строке на запрос.
    """
    if not свои:
        return None
    основа = dict(корень) if isinstance(корень, dict) else {}
    основа["expressions"] = свои
    return основа


def беда_сервиса(ответ) -> str:
    """Отказ сервиса одной строкой, которую покажут человеку.

    Сервис отвечает на отказ `{"code": …, "message": …}`; берём оба поля, а
    если ответ не разобрался — код HTTP. Строка чужая: её показывают, но в
    журнал не пишут и ничего по ней не решают.
    """
    try:
        тело = ответ.json()
    except Exception:                                        # noqa: BLE001
        тело = None
    if isinstance(тело, dict):
        код = str(тело.get("code") or "").strip()
        текст = str(тело.get("message") or "").strip()
        вместе = ": ".join(ч for ч in (код, текст) if ч)
        if вместе:
            return вместе[:ДЛИНА_БЕДЫ]
    return f"HTTP {int(ответ.status_code)}"


def спросить(клиент, тело: dict, приложение: str, подпись: str):
    """Один пакетный запрос наверх. → ответ httpx.

    Тело подписывается **байтами, которые уходят**: подпись по пересобранному
    JSON разошлась бы с телом на первом же пробеле, и сервис ответил бы отказом
    в доступе на верных ключах.
    """
    сырое = json.dumps(тело, ensure_ascii=False).encode("utf-8")
    return клиент.post(
        f"{СХЕМА_REST}://{ВЕРХ}{ПУТЬ_ПАЧКИ_НАВЕРХУ}", content=сырое,
        headers={"Content-Type": "application/json", "Accept": ПРИНИМАЕМ,
                 ПОЛЕ_КЛЮЧА: приложение,
                 ОТВЕТ_ПОДПИСИ: подписать(сырое, приложение, подпись)})


def распознать(s, db, settings, user_id: str, строки: list[dict], dpi: int,
               ip: str = "") -> dict:
    """Строки записи → распознанное по строкам. Сердце пакетного входа.

    Порядок шагов тот же, что у сокета, и по той же причине — отказать
    дешёвым раньше дорогого: потолок пачки, ключи, частота, сеть.

    **Беда одной строки не отказ всему вызову.** Строка, которую нельзя
    отправить (слишком много точек, рваные координаты), и ответ сервиса не
    `2xx` кладутся строкой в `error` своей строки: доска не обязана переставать
    работать оттого, что одна строка не далась, а страница показывает беду там,
    где она случилась.

    **Сеть недоступна — беда всего вызова** (`502 ink_unreachable`): это не
    свойство строки, и рисовать её у каждой значило бы сказать человеку, что
    распознавание сломалось шесть раз подряд. Отказ этот наступает, только
    когда наверх не ушёл **ни один** запрос: уже отвеченное не выбрасывается.
    """
    if len(строки) > СТРОК_ЗА_ВЫЗОВ:
        raise ApiError(INVALID_VALUE,
                       f"At most {СТРОК_ЗА_ВЫЗОВ} lines per call", 400,
                       where="body.lines")
    пара = ключи(s, settings, user_id)
    if пара is None:
        raise ApiError(INK_NO_KEYS,
                       "Recognition keys are not set up for this account", 403,
                       where="body.lines")
    if запросов_за_минуту(s, user_id) >= ЗАПРОСОВ_В_МИНУТУ:
        raise ApiError(RATE_LIMITED,
                       f"More than {ЗАПРОСОВ_В_МИНУТУ} recognition requests "
                       "per minute", 429)
    приложение, подпись = пара

    ответы = [{"id": str(с.get("id") or ""), "latex": "", "text": "",
               "jiix": None, "error": None} for с in строки]
    годные = []
    for i, строка in enumerate(строки):
        if точек(строка) > ТОЧЕК_В_СТРОКЕ:
            ответы[i]["error"] = (f"Line is too long: at most "
                                  f"{ТОЧЕК_В_СТРОКЕ} points")
        elif not ровные_ли(строка):
            ответы[i]["error"] = "Stroke coordinates do not line up"
        else:
            годные.append(i)
    if not годные:
        return {"lines": ответы, "requests": 0, "unmatched": []}

    пачки = ([[i] for i in годные] if getattr(settings, "ink_batch_per_line",
                                              False) else [годные])
    послано, не_дошло, лишние = 0, 0, []
    with httpx.Client(timeout=ЖДАТЬ_ПАЧКУ) as клиент:
        for пачка in пачки:
            свои = [строки[i] for i in пачка]
            try:
                ответ = спросить(клиент, тело_пачки(свои, dpi), приложение,
                                 подпись)
            except Exception as беда:                        # noqa: BLE001
                # Сюда идёт всё, что случилось до ответа: имя не разрешилось,
                # TLS не сложился, время вышло. Вид беды — в журнал службы,
                # адрес и тело — нет: в теле почерк, в заголовке подпись.
                беды.warning("распознавание пачкой: наверх не достучались — %s",
                             type(беда).__name__)
                не_дошло += 1
                continue
            послано += 1
            _записать(db, ЗАПРОС, user_id, ip, lines=len(пачка),
                      status=int(ответ.status_code))
            if ответ.status_code // 100 != 2:
                текст = беда_сервиса(ответ)
                for i in пачка:
                    ответы[i]["error"] = текст
                continue
            try:
                корень = ответ.json()
            except Exception:                                # noqa: BLE001
                корень = {}
            по_строкам, чужие = разложить(корень, свои, dpi)
            лишние.extend(чужие)
            # Подпись всего ответа годится строке только тогда, когда строка в
            # запросе была одна: иначе она описывает соседей вместе с нею и
            # сказала бы про каждую строку одно и то же неправдоподобное.
            подпись = (str((корень or {}).get("label") or "")
                       if len(пачка) == 1 and isinstance(корень, dict) else "")
            for место, i in enumerate(пачка):
                выражения_строки = по_строкам[место]
                ответы[i]["jiix"] = своё_jiix(корень, выражения_строки)
                ответы[i]["latex"] = (латекс(выражения_строки[0])
                                      if выражения_строки else "")
                ответы[i]["text"] = подпись

    if послано == 0 and не_дошло:
        raise ApiError(INK_UNREACHABLE,
                       "The recognition service did not answer", 502)
    return {"lines": ответы, "requests": послано,
            "unmatched": [{"latex": латекс(в), "jiix": в} for в in лишние]}


# ── версия протокола ─────────────────────────────────────────────────────────

ОПИСАНИЕ_ВЕРСИИ = (
    "Passes the recognition service's version answer through. The recognition "
    "library asks for it before opening a socket and, without an answer, falls "
    "back to a protocol version of its own choosing, after which the socket "
    "fails in a way that reads on screen as an unreachable server. Carries no "
    "key and reveals none. 401 unauthenticated, 502 ink_unreachable.")


def версия(user: CurrentUser) -> dict:
    """Ответ собеседника про версию протокола, как есть.

    Обычной, а не асинхронной функцией: так её исполняет отдельный поток, а
    запрос наружу идёт тем же клиентом, каким служба ходит в сеть везде — и тем
    же, который в проверках перекрыт, чтобы ни одна из них не ушла в интернет.

    Ключа здесь нет и быть не может: версия протокола — не секрет, а вопрос о
    ней задаётся до того, как у сеанса появляется ключ.
    """
    адрес = f"https://{ВЕРХ}{ПУТЬ_ВЕРСИИ_НАВЕРХУ}"
    try:
        with httpx.Client(timeout=ЖДАТЬ_ВЕРХ) as клиент:
            ответ = клиент.get(адрес)
        return dict(ответ.json())
    except Exception as беда:                                # noqa: BLE001
        беды.warning("мост распознавания: версия не получена — %s",
                     type(беда).__name__)
        raise ApiError(INK_UNREACHABLE,
                       "The recognition service did not answer", 502,
                       where="path") from None


def подключить(router: APIRouter) -> None:
    """Повесить оба маршрута моста на роутер модуля. Зовётся из `routes`.

    Функцией, а не своим роутером с `include_router`: вложенное включение
    непрозрачно для сборки внешнего входа — она перебирает маршруты роутера по
    одному, а включённый роутер выглядит там не маршрутом, и отказ случился бы
    при сборке приложения. Маршрутов два, и висят они прямо на модуле.

    Сокет при этом внешним входом не зеркалится вовсе (`routes.зеркало`): у
    него нет ни имени операции, ни места в документе, и открывают его
    cookie-сессией из браузера, а не ключом из скрипта.
    """
    router.websocket(ПУТЬ_ДОКУМЕНТА, name="board_ink_bridge")(мост)
    router.get(ПУТЬ_ВЕРСИИ, operation_id="board_ink_version",
               summary="Protocol version of the recognition service",
               description=ОПИСАНИЕ_ВЕРСИИ)(версия)


