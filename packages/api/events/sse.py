"""
sse — формат `text/event-stream` и правило «сессию на каждый опрос».

    Формат кадра
    ------------

        id: 12
        event: text
        data: {"seq": 12, "kind": "text", "data": {"text": "…"}, "at": "…"}

Три поля, и каждое отвечает своему читателю. `id:` браузер запоминает сам и
присылает обратно заголовком `Last-Event-ID` при переподключении — поэтому в
нём стоит **курсор**, а не украшение: у потока задания это `seq` события, у
потока человека — время создания уведомления. `event:` — вид, по нему клиент
раскладывает обработчики (`addEventListener("tag_closed", …)`). `data:` — одна
строка JSON: перевод строки внутри `data` означал бы второй кадр, поэтому JSON
пишется без отступов и с `ensure_ascii=False` (utf-8 у нас везде).

**Двоеточие в начале строки — комментарий**, его клиент выбрасывает. Им и
держится соединение живым: прокси (Caddy, Anubis) закрывают молчащий поток по
таймауту, и `: keep-alive` раз в `ЖИЗНЬ_С` дешевле, чем переподключение каждые
полминуты.

    Почему сессия открывается на каждый опрос
    -----------------------------------------

Поток живёт минутами, а транзакция базы — не должна. SQLite в WAL терпит одного
писателя, и сессия, открытая на всё время потока, держала бы снимок базы столько
же: воркер, пишущий события того же задания, ждал бы читателя, который сам ждёт
воркера. Отсюда правило, которое здесь исполняется, а не обещается: сессия
запроса кончается **до** того, как начнётся поток, а генератор открывает свою
сессию на каждый опрос и закрывает её перед сном.

Само собой это не выходит. FastAPI (0.141) закрывает зависимости с `yield`
**после** того, как ответ отдан целиком: их стек обёрнут вокруг
`await response(...)` (`fastapi/routing.py`), и `SessionDep` у потокового
маршрута жил бы столько же, сколько поток. Поэтому обработчик отпускает её сам
— `routes._отпустить`, там же и разобрано, почему это законно.

Из того же правила следует, что доступ проверяется дважды: один раз в
обработчике (там же, где он был бы у обычного маршрута, — иначе `404` уехал бы
серединой потока вместо ответа) и один раз в каждом опросе (иначе поток пережил
бы удаление задания и продолжал бы отдавать чужое).
"""
from __future__ import annotations

import json
import time

# Как часто в молчащий поток уходит комментарий-пульс. Пятнадцать секунд —
# заметно меньше обычного таймаута прокси (60 с) и заметно больше, чем стоит
# один кадр.
ЖИЗНЬ_С = 15.0

# Умолчание потолка жизни соединения, если его не передали. Настоящее число
# приходит настройкой (`KORITSU_SSE_MAX_S`) — там же объяснено, почему час; а
# умолчание здесь нужно затем, чтобы `Часы` можно было завести и в тесте самих
# часов, где настроек нет вовсе.
ПОТОЛОК_С = 3600.0

# Заголовки потока. `no-cache` — чтобы прокси не собирал кадры в буфер;
# `X-Accel-Buffering` понимает nginx, Caddy буферизацию потока не включает, но
# заголовок безвреден и переживёт смену прокси.
ЗАГОЛОВКИ = {
    "Cache-Control": "no-cache",
    "Connection": "keep-alive",
    "X-Accel-Buffering": "no",
}

MEDIA_TYPE = "text/event-stream"


def кадр(*, id: str | int | None, event: str, data) -> str:
    """Одно событие в формате SSE. Возвращает строку, готовую к отправке.

    `data` сериализуется здесь и только здесь: JSON, собранный по месту,
    однажды окажется собран с отступами — и тогда каждый перенос строки внутри
    него станет границей кадра, а клиент получит обрывки.
    """
    строки = []
    if id is not None:
        строки.append(f"id: {id}")
    строки.append(f"event: {event}")
    тело = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    строки.append(f"data: {тело}")
    return "\n".join(строки) + "\n\n"


def пульс() -> str:
    """Комментарий, которым поток говорит прокси «я живой»."""
    return ": keep-alive\n\n"


class Часы:
    """Сколько поток уже живёт и не пора ли послать пульс.

    Классом, а не двумя переменными в каждом генераторе: генераторов два
    (задание и человек), и «когда слать пульс» у них обязано совпадать —
    написанное дважды, оно разошлось бы на первом же изменении таймаута прокси.
    """

    def __init__(self, потолок: float = ПОТОЛОК_С, жизнь: float = ЖИЗНЬ_С):
        self.начало = time.monotonic()
        self._пульс = self.начало
        self._потолок = float(потолок)
        self._жизнь = float(жизнь)

    @property
    def вышло_время(self) -> bool:
        return time.monotonic() - self.начало >= self._потолок

    def пора_пульс(self) -> bool:
        """Пора ли слать пульс. Спрашивать можно часто: время двигает только «да»."""
        сейчас = time.monotonic()
        if сейчас - self._пульс < self._жизнь:
            return False
        self._пульс = сейчас
        return True

    def отметить(self) -> None:
        """Кадр ушёл — значит соединение только что доказало, что живо."""
        self._пульс = time.monotonic()


__all__ = ["кадр", "пульс", "Часы", "ЗАГОЛОВКИ", "MEDIA_TYPE", "ЖИЗНЬ_С",
           "ПОТОЛОК_С"]
