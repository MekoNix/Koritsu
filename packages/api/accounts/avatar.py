"""
avatar — своя картинка человека: приём, санитайзер, место на томе.

Аватар по умолчанию рисует сайт из идентификатора аккаунта, и это остаётся
умолчанием. Здесь живёт вторая возможность — картинка, которую человек принёс
сам. Всё, что делает этот модуль, укладывается в одно правило: **из запроса не
берётся ничего, кроме байтов**.

**Путь строится из `user_id`, и только из него.** Имя файла, пришедшее с
формой, не используется вовсе — ни как имя, ни как расширение, ни как подсказка
о типе. Каталог даёт `projects.service.user_dir`, а он пропускает
идентификатор через `ids.check_id`, то есть через форму uuid4: `..` такой формы
не имеет, и обходу каталогов взяться неоткуда. Файл всегда один и называется
всегда одинаково — `avatar.png`.

**Тип определяется по сигнатуре, а не по расширению.** Расширение — это буквы,
которые набрал клиент; `злое.png` с содержимым HTML остаётся HTML. Поэтому
принимаются ровно три первых набора байтов (PNG, JPEG, WebP), а имя файла в
решении не участвует.

**Санитайзер содержимого — это пересохранение.** Картинка открывается Pillow,
проверяется, обрезается по центру в квадрат, ужимается до 256×256 и
записывается заново в PNG. Наружу уезжают **наши** байты, а не чужие: всё, что
было в исходном файле сверх пикселей — EXIF с координатами съёмки, цветовые
профили, полезная нагрузка в хвосте, SVG со скриптом внутри, — до диска не
доезжает. Проверка «а точно ли это картинка» отдельной строкой не нужна: файл,
который не открылся, не пересохранился.

**Бомба распаковки** отсекается до декодирования: `Image.open` читает только
заголовок, и объявленные размеры сравниваются с потолком раньше, чем Pillow
разложит картинку в память. Мегабайт данных бывает картинкой на сорок тысяч
пикселей в стороне — это гигабайты в оперативной памяти.

Коды отказа:

    file_too_large   413  больше мегабайта
    unsupported_type 400  не PNG, не JPEG, не WebP, или байты не разбираются
"""
from __future__ import annotations

import io
import os

from ..errors import ApiError

# Предел размера файла. Мегабайта хватает картинке 256×256 с запасом в сотню
# раз: всё, что больше, — это не аватар, а фотография, которую всё равно ужмут.
ПРЕДЕЛ = 1024 * 1024

# Сторона квадрата, в который аватар пересохраняется. Больше, чем показывает
# любое место сайта (72 пикселя в профиле), — с запасом на экраны с двойной
# плотностью и на будущее «покажите крупно».
СТОРОНА = 256

# Потолок объявленных размеров исходника. Всё, что больше, — бомба распаковки:
# файл в килобайты, картинка в гигабайты памяти.
ПИКСЕЛЕЙ_МАКС = 12_000

# Имя файла на томе. Одно на всех и без расширения от клиента: содержимое мы
# пересохраняем сами и знаем про него всё.
ФАЙЛ = "avatar.png"

UNSUPPORTED_TYPE = "unsupported_type"
FILE_TOO_LARGE = "file_too_large"

# Сигнатуры принимаемых форматов: начало файла (и, у WebP, четыре байта через
# четыре). Список закрыт намеренно — это три формата, которые умеет показать
# всякий браузер и открыть Pillow.
_СИГНАТУРЫ = (
    (0, b"\x89PNG\r\n\x1a\n"),          # PNG
    (0, b"\xff\xd8\xff"),               # JPEG
    (0, b"RIFF"),                       # WebP — вторая половина проверяется ниже
)


def узнать_тип(данные: bytes) -> str | None:
    """Формат по первым байтам: `png` | `jpeg` | `webp` | `None`.

    Имя файла сюда не приходит и прийти не может — в этом весь смысл функции.
    """
    if данные.startswith(b"\x89PNG\r\n\x1a\n"):
        return "png"
    if данные.startswith(b"\xff\xd8\xff"):
        return "jpeg"
    if данные.startswith(b"RIFF") and данные[8:12] == b"WEBP":
        return "webp"
    return None


def путь(settings, user_id: str) -> str:
    """Где лежит аватар этого человека. Строится только из `user_id`.

    Каталог берётся у пакета проектов: раскладку тома знает он один, и второе
    знание о том, что такое `users/<uuid>/`, разошлось бы с первым при первом
    же переезде каталога.
    """
    from ..projects.service import user_dir                    # noqa: PLC0415

    return os.path.join(user_dir(settings, user_id), ФАЙЛ)


def перерисовать(данные: bytes) -> bytes:
    """Чужие байты → наш PNG 256×256, обрезанный по центру.

    Обрезка по центру, а не сжатие в квадрат: лицо, растянутое по горизонтали,
    человек читает как поломку сайта, а не как свою фотографию.
    """
    from PIL import Image                                      # noqa: PLC0415

    вид = узнать_тип(данные)
    if вид is None:
        raise ApiError(UNSUPPORTED_TYPE,
                       "Avatar must be a PNG, JPEG or WebP image", 400,
                       where="body.file")
    try:
        with Image.open(io.BytesIO(данные)) as картинка:
            # Размеры читаются из заголовка — до того, как Pillow разложит
            # пиксели в память (см. «бомба распаковки» в шапке).
            ширина, высота = картинка.size
            if (ширина <= 0 or высота <= 0
                    or ширина > ПИКСЕЛЕЙ_МАКС or высота > ПИКСЕЛЕЙ_МАКС):
                raise ApiError(UNSUPPORTED_TYPE,
                               "Avatar image dimensions are out of range", 400,
                               where="body.file")
            # `RGBA` для всего: PNG с прозрачностью остаётся прозрачным, а
            # палитровые и одноканальные приводятся к одному виду, и дальше в
            # коде не бывает «а какой тут режим».
            картинка = картинка.convert("RGBA")
            сторона = min(ширина, высота)
            слева = (ширина - сторона) // 2
            сверху = (высота - сторона) // 2
            квадрат = картинка.crop((слева, сверху, слева + сторона,
                                     сверху + сторона))
            малый = квадрат.resize((СТОРОНА, СТОРОНА), Image.LANCZOS)
            буфер = io.BytesIO()
            малый.save(буфер, format="PNG", optimize=True)
            return буфер.getvalue()
    except ApiError:
        raise
    except Exception:                                          # noqa: BLE001
        # Pillow кидает своё на любом непонятном файле, и текст его беды бывает
        # с путём внутри. Наружу — форма запроса, а не подробности.
        raise ApiError(UNSUPPORTED_TYPE,
                       "Avatar image could not be read", 400,
                       where="body.file") from None


def записать(settings, user_id: str, данные: bytes) -> None:
    """Положить пересохранённый PNG на том, заведя каталог человека."""
    файл = путь(settings, user_id)
    os.makedirs(os.path.dirname(файл), exist_ok=True)
    # Через временный файл рядом: обрыв записи не оставляет половину картинки
    # там, откуда её сейчас же попросят.
    временный = файл + ".tmp"
    with open(временный, "wb") as поток:
        поток.write(данные)
    os.replace(временный, файл)


def прочитать(settings, user_id: str) -> bytes | None:
    """Байты аватара или `None`, если своей картинки нет."""
    try:
        with open(путь(settings, user_id), "rb") as поток:
            return поток.read()
    except OSError:
        return None


def снять(settings, user_id: str) -> None:
    """Убрать свою картинку. Отсутствие файла — не беда: итог тот же."""
    try:
        os.remove(путь(settings, user_id))
    except OSError:
        pass


