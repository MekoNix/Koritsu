"""
models — шаблоны отчётов: `templates` (файлы человека) и `project_templates`
(какие из них приложены к работе).

Шаблон здесь — **DOCX человека, лежащий вне проектов**: тот самый файл с
`{{тегами}}`, который на кафедре один на все работы, а в службе до сегодня
приносился заново при каждом создании проекта. Отсюда все поля и ни одного
лишнего.

**Байты лежат на томе, а не в базе.** В строке — только то, чем шаблон
показывается в списке: имя, размер, число тегов. Класть DOCX в SQLite значило
бы возить мегабайты через сессию на каждое чтение списка и обходить квоту,
которая считается по каталогам тома (`projects.service.bytes_used`), а не по
базе.

**`tags` — число тегов, а не их список.** Список тегов есть у манифеста
проекта, заведённого по этому шаблону, и второе его описание разошлось бы с
первым на первой же правке разбора. В списке шаблонов человеку нужно ровно
одно: «это тот файл, где тегов двенадцать, а не тот, где два».

**`sha256` — по содержимому**, той же длины, что идентификатор артефакта
оркестратора. Не для адресации (адрес — `id` строки): по нему видно, что
человек загрузил один и тот же файл дважды, и его же удобно сверять с
`template_sha256` манифеста проекта.

**Внешний ключ на `users.id` с `ON DELETE CASCADE`** — то же, что у
ключей моделей: удалили аккаунт, значит и его файлов нет. Каталог с байтами
сносится отдельно: базе про том знать нечего.

**Шаблоны работы — связка, а не копия строки.** У работы шаблонов бывает много
(их добавляют на её странице отчётов), и один и тот же DOCX человека прикладывают
к нескольким работам. Поэтому `project_templates` держит только пару
«работа — шаблон»: второй список файлов рядом с первым разошёлся бы с ним на
первом же удалении, а копия байтов на каждую работу стоила бы места в квоте за
то, что и так лежит.
"""
from __future__ import annotations

from sqlalchemy import ForeignKey, Index, Integer, String, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column

from ..db import Row
from ..ids import ID_LEN

# Длина имени шаблона. Имя человек пишет сам (или оно берётся из имени файла), и
# в списке оно должно помещаться в строку — тот же довод, что у `ИМЯ_МАКС`
# приёмника материалов.
NAME_LEN = 120

# Столько знаков sha256 хранится. Ровно столько же оставляет идентификатор
# артефакта оркестратора (`orchestrator.ARTIFACT_ID_LEN`), и это не совпадение:
# шаблон, попавший в проект, лежит там артефактом, и два разных среза одного
# хеша нельзя было бы сличить глазами. Числом, а не `len(artifact_id(b""))`:
# модели читает `migrations/env.py`, и тянуть в него движок отчётов ради одной
# длины значило бы, что миграции перестают собираться без него. Длина колонки с
# запасом (32) — на случай, если срез когда-нибудь удлинится.
SHA_LEN = 32


class ReportTemplate(Row):
    """Шаблон отчёта, принадлежащий человеку.

    `id`, `created_at`, `updated_at` — от `Row`; `created_at` показывается как
    дата загрузки. Имя класса не `Template`: словом «шаблон» в питоне слишком
    часто зовут шаблон страницы, а речь про DOCX работы.
    """

    __tablename__ = "templates"

    user_id: Mapped[str] = mapped_column(
        String(ID_LEN), ForeignKey("users.id", ondelete="CASCADE"))

    name: Mapped[str] = mapped_column(String(NAME_LEN))

    # Размер байтов на томе. Хранится, а не считается при чтении списка: список
    # из двух десятков шаблонов означал бы два десятка `stat` на каждый показ, а
    # файл после загрузки не меняется никогда.
    bytes: Mapped[int] = mapped_column(Integer, default=0)

    # Сколько тегов нашёл разбор манифеста (`orchestrator.template_tags`).
    tags: Mapped[int] = mapped_column(Integer, default=0)

    sha256: Mapped[str] = mapped_column(String(SHA_LEN), default="")

    # Свои шаблоны читаются списком и всегда одним человеком — индекс по паре
    # «чей, когда заведён» и есть тот единственный запрос, который к этой
    # таблице ходит.
    __table_args__ = (
        Index("ix_templates_user_created", "user_id", "created_at"),
    )


class ProjectTemplate(Row):
    """Шаблон, приложенный к работе. Только пара идентификаторов и дата.

    **Зачем шаблоны у работы, если они есть у человека.** Шаблон в настройках —
    это личная полка: «мои бланки». Работа же собирается по одному
    определённому, и бланков у неё бывает несколько (титул кафедры, приложение,
    ГОСТ). Добавляют их там, где и пользуются, — на странице отчётов работы, а
    не в профиле; личный шаблон при этом остаётся **источником**: приложить
    можно и его, по `template_id`.

    Пара уникальна: приложить тот же шаблон второй раз — то же состояние, а не
    второй пункт списка. Оба ключа с `CASCADE`: не стало работы или файла —
    связке не на чем держаться.

    **Строка о работе, а не о человеке.** Кто приложил, здесь не хранится
    намеренно: список шаблонов работы читают все участники пространства, и
    вопрос «чей это бланк» решается владением самим шаблоном
    (`ReportTemplate.user_id`), а не второй пометкой, которая с ним разошлась бы.
    """

    __tablename__ = "project_templates"

    project_id: Mapped[str] = mapped_column(
        String(ID_LEN), ForeignKey("projects.id", ondelete="CASCADE"))
    template_id: Mapped[str] = mapped_column(
        String(ID_LEN), ForeignKey("templates.id", ondelete="CASCADE"))

    __table_args__ = (
        UniqueConstraint("project_id", "template_id",
                         name="uq_project_templates_pair"),
        Index("ix_project_templates_project", "project_id", "created_at"),
    )


__all__ = ["ReportTemplate", "ProjectTemplate", "NAME_LEN", "SHA_LEN"]
