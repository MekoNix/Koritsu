"""
limits — цена наших инструментов, месячный потолок человека и его расход.

Расход считается за наши инструменты и мощности, а не за токены поставщика.
Пользователь платит внутренними токенами за запуски нашего кода: у каждого
вида задания — своя цена в единицах (таблица `ЦЕНЫ` в `runs/limits.py`,
читается из конфига `KORITSU_PRICE_<KIND>`), она и списывается в
`jobs.spent_units`. Токены поставщика при своём ключе не считаются вовсе; при
общем ключе их стоимость заложена в цену вида.

Отсюда четыре вещи, и все четыре здесь:

1. **таблица цен** — `ЦЕНЫ`, вид задания → имя поля `Settings`;
2. **справочник планов** — `ПЛАНЫ`: у плана месячный
   потолок единиц и квота места на томе, оба из настроек. Поверх плана ложится
   личный лимит, если владелец поставил его в админке
   (`users.limits["monthly_units"]`, `users.limits["quota_bytes"]`);
3. **расход за календарный месяц** — сумма `jobs.spent_units` этого человека;
4. **две проверки**: до постановки задания (`402 limit_exhausted`, если на его
   цену уже не хватает) и один раз перед стартом обработчика
   (`runs/handlers/common.Прогон`, на случай, если пока задание ждало в
   очереди, остаток съели соседние задания).

    Где списывается цена: при **захвате**, а не при завершении
    ---------------------------------------------------------

Цена пишется в `jobs.spent_units` тем же единственным `UPDATE`, которым воркер
переводит задание в `running` (`jobs.worker.Worker._взять`). Три довода, и все
три про то, что иначе списание разошлось бы с правдой:

* **отменённое посреди работы обязано стоить.** Оно заняло слот, подпроцесс и
  память, сходило к поставщику и вернулось с половиной ответа; списание в конце
  отдало бы всё это бесплатно ровно тем, кто отменяет прогон на последнем теге;
* **убитое таймаутом и потерянное вместе с воркером — тоже.** Их закрывает не
  обработчик, а родитель, и «списать в конце» означало бы «списать там, где
  конца не случилось»;
* **захват атомарен.** Цена и состояние `running` ложатся одним запросом:
  перезапуск между двумя записями не может оставить работающее задание
  неоплаченным или оплаченное — незапущенным.

Списание — **присваивание**, а не приращение (`spent_units = цена`), и это
важно ровно для одного случая: потерянное задание поднимается в очередь и
захватывается второй раз (потерянное задание поднимается один раз). Работа
делается заново, но платит человек за неё один раз — вторая попытка не его вина.

Плата за такое решение названа честно: задание, упавшее сразу после захвата
(нет ключа модели, кривой `payload`), тоже стоит своей цены. Возврат стоил бы
второй бухгалтерии — «за что вернули» — в таблице, у которой нет ни одной
строки про деньги, кроме этой колонки.

    Почему источник правды — `jobs.spent_units`, а не `Project.spent()`
    ------------------------------------------------------------------

Расход знают двое. `Project.spent()` считает по `journal.jsonl` в каталоге
проекта — это правда про **токены поставщика** в этом проекте, включая прогоны
из консоли. `jobs.spent_units` считает по строкам заданий — это правда про
**плату человека**, потому что у задания есть `user_id`, а у каталога проекта
нет (проект лежит в общем workspace, и работают в нём двое).

Эти два счёта разошлись по смыслу окончательно, и сводить их не надо: журнал
проекта отвечает на вопрос «сколько токенов сожгли у поставщика», наша
колонка — «сколько человек должен нам за запуски». Первый по-прежнему пишется
слоем на каждый вызов модели, и по нему по-прежнему видно, во что обходится
общий ключ; второй показывается человеку в `GET /api/usage`.

**Месяц считается по `jobs.created_at`.** Задание принадлежит месяцу, в котором
его завели, — иначе прогон, начатый 31-го и кончившийся 1-го, менял бы месяц по
ходу работы, и остаток прыгал бы у человека на глазах.
"""
from __future__ import annotations

import datetime
from dataclasses import dataclass

from ..errors import ApiError
from ..jobs import service as задания
from ..log import беды
from ..settings import Settings

LIMIT_EXHAUSTED = "limit_exhausted"

# План по умолчанию — тот же, что стоит у `accounts.User.plan`.
ПЛАН_ПО_УМОЛЧАНИЮ = "free"

# Справочник планов: имя плана → откуда берутся его два числа (месячный потолок
# единиц и квота места на томе). Словарь, а не таблица в базе, потому что план —
# это код цены, а не строка данных: новый план появляется вместе с кодом,
# который его обслуживает, и завести его правкой строки в базе нельзя.
#
# **Планы — справочник**, а не свободная строка. Отсюда три следствия, и все
# три держатся на этом словаре:
#
# * `GET /api/admin/plans` показывает ровно его (`справочник`);
# * `PATCH /api/admin/users/{id}` с планом не отсюда отказывает
#   `400 unknown_plan` — до этого решения план вписывался строкой, и опечатка
#   «pro » с пробелом молча делала человеку потолок `free`;
# * потолок и квота человека считаются по нему, а не по одной настройке на
#   всех (`потолок`, `квота`); личный лимит из админки по-прежнему старше плана.
#
# Значения — **имена полей `Settings`**, а не числа: числа временные и правятся
# строкой в `.env`. У `free` квоты своего поля нет: она и есть
# `user_quota_bytes` (250 МБ на владельца) — второе число с тем же смыслом
# однажды разошлось бы с первым.
ПЛАНЫ: dict[str, dict[str, str]] = {
    "free": {"monthly_units": "free_monthly_units",
             "quota_bytes": "user_quota_bytes"},
    "pro": {"monthly_units": "pro_monthly_units",
            "quota_bytes": "pro_quota_bytes"},
    "team": {"monthly_units": "team_monthly_units",
             "quota_bytes": "team_quota_bytes"},
}

# Код отказа на плане, которого в справочнике нет.
UNKNOWN_PLAN = "unknown_plan"

# Таблица цен: вид задания → имя поля `Settings`. Тем же устройством, что
# `ПЛАНЫ`, и по той же причине: цена — это код, а не строка данных, и вид
# задания, у которого цены нет, обязан быть виден глазами здесь, а не
# обнаруживаться бесплатной работой на живом томе.
#
# Список обязан покрывать `jobs.registry.ВИДЫ` целиком — это проверяется
# тестом, а не обещается: новый вид задания без строки здесь ехал бы даром.
#
# **Числа — заглушки до цен подписки**; лежат они в `Settings`, чтобы
# правиться строкой в `.env`, а не выкатом.
ЦЕНЫ: dict[str, str] = {
    "parse": "price_parse",
    "export": "price_export",
    "build": "price_build",
    "fill_tag": "price_fill_tag",
    "fill_report": "price_fill_report",
    "agent": "price_agent",
    "kadai_run": "price_kadai_run",
    "kadai_rework": "price_kadai_rework",
    "probe": "price_probe",
}


def цена(settings: Settings, kind: str | None) -> int:
    """Сколько единиц стоит одно задание этого вида. Неизвестный вид — ноль.

    Ноль, а не отказ: цена спрашивается на пути постановки и на пути захвата, и
    уронить обе дороги из-за вида, которому забыли назначить цену, значило бы
    остановить очередь целиком. Забывчивость при этом не молчит — строка в
    журнал бед, — и ловится она тестом, сверяющим `ЦЕНЫ` с `registry.ВИДЫ`.
    """
    поле = ЦЕНЫ.get(str(kind or ""))
    if поле is None:
        беды.warning("вид задания %r не описан в runs.limits.ЦЕНЫ — считаю "
                     "бесплатным", kind)
        return 0
    return max(0, int(getattr(settings, поле)))


def цены(settings: Settings) -> dict[str, int]:
    """Все цены разом: `{вид: единицы}`. Форма для клиента и для админки.

    Наружу они уезжают затем, что интерфейс обязан назвать цену **до** запуска:
    «сколько это стоит» — вопрос, который человек задаёт перед нажатием кнопки,
    а не после отказа по лимиту.
    """
    return {вид: цена(settings, вид) for вид in ЦЕНЫ}


@dataclass(frozen=True)
class Расход:
    """Сколько положено, сколько потрачено, сколько осталось. Наружу и внутрь.

    Одной записью, а не тремя числами по месту: остаток, посчитанный дважды,
    однажды посчитается по-разному — маршрут `GET /api/usage` покажет одно, а
    отказ при постановке назовёт другое.
    """

    plan: str
    limit_units: int
    spent_units: int
    period_start: str

    @property
    def remaining_units(self) -> int:
        return max(0, self.limit_units - self.spent_units)

    @property
    def exhausted(self) -> bool:
        return self.remaining_units <= 0

    @property
    def перебрал(self) -> bool:
        """Потрачено больше, чем положено, — то есть месяц кончился уже.

        Отличается от `exhausted` ровно на границе, и разница эта не
        придирка: цена задания списывается **при захвате**, значит к первому
        вопросу обработчика «а есть ли ещё деньги» его собственная цена уже
        вычтена. Задание, ровно уложившееся в остаток, обязано работать —
        `exhausted` сказал бы про него «нет», и человек, купивший ровно один
        прогон, не получил бы ни одного.
        """
        return self.spent_units > self.limit_units

    def хватит(self, сколько: int) -> bool:
        """Хватит ли остатка на задание такой цены. Бесплатному хватает всегда."""
        return int(сколько) <= 0 or self.remaining_units >= int(сколько)

    def наружу(self) -> dict:
        """Форма для клиента. Ключи по-английски, как весь договор службы."""
        return {"plan": self.plan, "limit_units": self.limit_units,
                "spent_units": self.spent_units,
                "remaining_units": self.remaining_units,
                "period_start": self.period_start}


# ── месяц ────────────────────────────────────────────────────────────────────

# Граница расчётного периода и сама сумма живут там же, где колонка, из которой
# они складываются, — в `jobs.service`. Здесь только имя:
# второй `начало_месяца` рядом со вторым `SELECT sum(...)` — это два ответа на
# один вопрос, и разошлись бы они молча.
начало_месяца = задания.начало_месяца


def нормальный_план(plan: str | None) -> str:
    """Имя плана в том виде, в каком его знает справочник.

    Одна дверь к приведению, а не `.strip().lower()` по месту: маршрут, который
    привёл имя иначе, чем справочник, отказал бы человеку в плане, который
    справочнику известен.
    """
    return (plan or ПЛАН_ПО_УМОЛЧАНИЮ).strip().lower()


def известен(plan: str | None) -> bool:
    """Есть ли такой план в справочнике. Отсюда `400 unknown_plan` в админке."""
    return нормальный_план(plan) in ПЛАНЫ


def _поле(plan: str | None, ключ: str) -> str:
    """Имя поля `Settings` с этим числом плана.

    Неизвестный план — числа `free` и строка в журнал бед: это состояние
    настройки (план вписан руками в базу или остался от старого справочника), и
    молчать про него нельзя, но и отказывать человеку в работе из-за чужой
    опечатки — тоже. `PATCH` в админке такого плана уже не поставит
    (`400 unknown_plan`), поэтому путь этот — про прошлое, а не про будущее.
    """
    имя = нормальный_план(plan)
    описание = ПЛАНЫ.get(имя)
    if описание is None:
        беды.warning("план %r не описан в runs.limits.ПЛАНЫ — считаю как %r",
                     имя, ПЛАН_ПО_УМОЛЧАНИЮ)
        описание = ПЛАНЫ[ПЛАН_ПО_УМОЛЧАНИЮ]
    return описание[ключ]


def потолок(settings: Settings, plan: str | None) -> int:
    """Месячный потолок этого плана в единицах."""
    return int(getattr(settings, _поле(plan, "monthly_units")))


def квота(settings: Settings, plan: str | None) -> int:
    """Сколько байт на томе положено этому плану.

    Заведена вместе со справочником: до него квота была одна на всех
    (`user_quota_bytes`), и «сменить план» не меняло в месте на томе ничего.
    """
    return int(getattr(settings, _поле(plan, "quota_bytes")))


def справочник(settings: Settings) -> list[dict]:
    """Все планы с их числами — то, что отдаёт `GET /api/admin/plans`.

    Порядок — как в `ПЛАНЫ`, то есть от младшего к старшему: список планов,
    отсортированный по алфавиту, поставил бы `free` между `pro` и `team`.
    """
    return [{"plan": имя,
             "monthly_units": int(getattr(settings, поля["monthly_units"])),
             "quota_bytes": int(getattr(settings, поля["quota_bytes"]))}
            for имя, поля in ПЛАНЫ.items()]


def потрачено_за_месяц(s, user_id: str,
                       начало: datetime.datetime | None = None) -> int:
    """Сумма `jobs.spent_units` этого человека за календарный месяц.

    Считает не этот модуль, а `jobs.service.расход_за_месяц` — то же самое
    место, откуда берёт свои числа список людей в админке. Одна сумма на
    службу, а не две: `GET /api/usage` и `GET /api/admin/users` обязаны
    называть человеку одно число, а два запроса, написанные порознь, однажды
    разъедутся на границе месяца или на отменённом задании (проверяется
    сквозным тестом `test_e2e_stage2`).

    Ноль здесь — законный ответ: у человека без заданий нет и строки в
    группировке.
    """
    return задания.расход_за_месяц(s, начало=начало,
                                   user_id=user_id).get(user_id, 0)


ЛИЧНЫЙ_ПОТОЛОК = "monthly_units"
ЛИЧНАЯ_КВОТА = "quota_bytes"


def квота_человека(settings: Settings, user) -> int:
    """Сколько байт положено **этому** человеку: личный лимит старше плана.

    Единственный ответ на вопрос «сколько ему места», и звать надо его, а не
    `settings.user_quota_bytes` по месту. До справочника отбор материала
    считался по одной настройке на всех, а карточка в админке показывала
    личный лимит — то есть страница обещала одно, а отказ приходил по другому.
    """
    from ..admin.service import лимит as личный                # noqa: PLC0415

    return int(личный(user, ЛИЧНАЯ_КВОТА,
                      квота(settings, getattr(user, "plan", None))))


def расход(s, settings: Settings, user) -> Расход:
    """Полная сводка по человеку: план, потолок, потраченное, остаток.

    Потолок — планов**ый**, поверх которого стоит личный, если владелец его
    поставил в админке (`users.limits["monthly_units"]`). Читаем его одной
    дверью — `admin.service.лимит`, — а не полем `user.limits` по месту: второй
    читатель того же мешка JSON разошёлся бы с первым на умолчании, и человек с
    личным потолком получал бы разный ответ от `GET /api/usage` и от отказа при
    постановке.
    """
    from ..admin.service import лимит as личный                # noqa: PLC0415

    начало = начало_месяца()
    plan = str(getattr(user, "plan", None) or ПЛАН_ПО_УМОЛЧАНИЮ)
    потолок_плана = потолок(settings, plan)
    return Расход(plan=plan,
                  limit_units=int(личный(user, ЛИЧНЫЙ_ПОТОЛОК, потолок_плана)),
                  spent_units=потрачено_за_месяц(s, user.id, начало),
                  period_start=начало.isoformat())


def проверить(s, settings: Settings, user, *, kind: str | None = None,
              where: str = "body.kind") -> Расход:
    """Пустить ли задание такого вида. Не хватает на его цену — `402`.

    `402 Payment Required`, а не `429`: кончился не темп запросов, а месячная
    квота, и лечится это не ожиданием, а сменой плана. Текст называет цифры —
    то же правило, что у остальных отказов службы: отказ без числа отправляет
    человека гадать, сколько ему не хватило.

    Считается по **цене вида**, а не по «есть ли хоть что-нибудь»: иначе
    человек с остатком в единицу ставил бы прогон сценария за пять тысяч и
    узнавал бы о своём положении по упавшему заданию. Бесплатный вид
    (`probe`, цена 0) проходит всегда — потолок про деньги, а не про очередь.
    """
    сводка = расход(s, settings, user)
    нужно = цена(settings, kind)
    if not сводка.хватит(нужно):
        raise ApiError(
            LIMIT_EXHAUSTED,
            f"Job kind '{kind}' costs {нужно} units and only "
            f"{сводка.remaining_units} are left of the monthly "
            f"{сводка.limit_units} ({сводка.spent_units} spent since "
            f"{сводка.period_start})",
            402, where=where)
    return сводка


