"""
board_check — репетитор доски: один вызов модели по снимку сцены.

    payload   {"endpoint": "deepseek", "run_id": "<доска>",
               "mode": "check" | "hint" | "drill" | "chat",
               "level": "hint" | "explain" | "solution",
               "step": "<id строки>", "wishes": "что именно проверить",
               "message": "сообщение в переписке (режим chat)",
               "lines": ["3b24f8", …],
               "scene_version": 17}
    result    {"mode": "check", "verdict": "wrong",
               "steps": [{"step": "3b24f8", "ok": true, "note": ""}, …],
               "checked": ["переход [3b24f8] → [e6cad9]: потенцирование"],
               "remarks": [{"kind": "error", "objects": ["kv-04"], "text": "…"}],
               "hint": null, "drill": null,
               "scene_artifact": "<16hex>", "digest_sha": "<64hex>",
               "mark": "80d0f1", "steps_total": 3, "unrecognized": 1,
               "key_source": "own"}

**Переписка — четвёртый режим того же задания.** `chat` — сообщение человека
по доске и ответ словами: без вердикта, без разбора по строкам. Переписка
лежит записью состояния доски (`доска-чат`): задание читает её, чтобы модель
видела прежние реплики, и дописывает в неё вопрос с ответом. `lines` — какие
строки доски приложить к сообщению: человек выделил на холсте то, о чём
спрашивает, и остальное модели не нужно. Пустой список или незнакомые
идентификаторы означают «все строки»: молча отправить пустой контекст нельзя. Доска без единой
прочитанной строки в переписке не отказывает — спросить «с чего начать» можно
и на пустой доске.

**Одно задание на три просьбы, а не три вида.** «Проверь», «подскажи» и «дай
задачу» — один вызов модели по одному снимку, и различает их поле `mode`. Три
вида задания означали бы три цены за одну и ту же работу и три места, где
правится сборка промпта.

**Почему своё задание, а не `agent`.** Агент заполняет теги бланка и на работе
без манифеста отказывается ещё до вызова модели; возвращает он текст и вызовы
инструментов, которых у доски нет. Сверх того у него петля до двенадцати ходов
и цена под неё, а проверка доски односнимковая: сцена читается один раз, и
вопроса «покажи ещё кусок» не возникает.

**Снимок берётся на старте.** Написанное после нажатия в этот прогон не
попадает — и это не оплошность, а условие воспроизводимости: замечание
указывает на объекты той сцены, которую модель видела, и на доске, уехавшей
вперёд, оно указывало бы в пустоту.

**Версия сцены сверяется дважды.** `payload.scene_version` — та, по которой
человек нажал кнопку: разошлась с записью на томе — `409`, а не проверка чужой
сцены. А строки решения обязаны быть собраны по той же версии: собранные раньше
— это вчерашний текст, и проверять его значило бы отвечать человеку про
решение, которое он уже исправил.

**Отставшие строки собираются заново, а не отказывают.** Дописанная строка —
обычный ход работы, а не беда, и кэш распознанного рядом со сценой к этому
времени описывает уже новые штрихи: строки пересобираются по нему здесь же, до
прогона, и проверка идёт по той доске, которую человек видит. Отказ
`scene_stale` остаётся на случай, когда читать нечего вовсе: с этой сцены не
прочитано ни строки, и собирать проверку не из чего.

**Непрочитанная строка не исчезает.** Она едет модели как «содержимое
недоступно» и остаётся в `steps` с `ok: null`: неверно распознанная формула
синтаксически безупречна, и ни одна проверка ниже по течению её не поймает, а
`false` на нераспознанной строке — ложное обвинение.

**Куски промпта собирает оркестратор.** Служба не строит ни одного куска и не
знает ни слова про выжимку: она называет доску, режим и глубину, а рамку вокруг
недоверенного текста ставит слой моделей. Условие задачи и строка «что именно
проверить» — тоже недоверенный вход: их набирает тот же человек, что рисует
доску, и «забудь предыдущие указания» в них написать так же легко, как на самой
доске.

**События потока.** `progress` в начале и в конце, `step_checked` на каждую
строку доски (включая те, о которых модель ничего не сказала), `text` — только
в `hint` и `drill`, где у ответа есть человеческие слова. В `drill` вердиктов
нет вовсе: задача на тренировку — карточка рядом с доской, а не разбор
решения, и `steps` при ней пуст. Терминальные `done`/`failed`/`cancelled`
пишет воркер.
"""
from __future__ import annotations

import orchestrator

from ...errors import ApiError
from ...jobs.registry import BOARD_CHECK, register
from .common import Прогон, ШАГ_ПРОВЕРЕН, ТЕКСТ, беда_словами, отменено

BOARD_FAILED = "board_failed"
SCENE_CONFLICT = "scene_conflict"
SCENE_STALE = "scene_stale"
UNKNOWN_MODE = "unknown_mode"

# Три просьбы одного задания. Список закрытый: режим уезжает в сборку промпта и
# в выбор схемы ответа, и четвёртое слово здесь означало бы модель, которую
# попросили ответить по схеме, которой нет.
РЕЖИМЫ = ("check", "hint", "drill", "chat")

# Глубина ответа. Умолчание — `explain`: человек, нажавший «проверь», ждёт
# объяснения, а не односложного вердикта.
ГЛУБИНЫ = ("hint", "explain", "solution")
ГЛУБИНА_ПО_УМОЛЧАНИЮ = "explain"

# Потолок строки «что именно проверить». Она едет в промпт недоверенным куском
# и оплачивается человеком; страница на доске — одна строка, а не сочинение.
ПРОСЬБА_МАКС = 2000


def _имена_записей() -> tuple[str, str]:
    """Имена записей состояния доски: сцена и разбор. Берутся у модуля.

    У модуля, а не вторыми строками здесь: сцена, записанная под одним именем и
    прочитанная под другим, — это пустая доска на проверке, и заметить такое
    можно только по вердикту «не разобрал» на решённой задаче.

    Импорт внутри функции — общий приём службы: модуль маршрутов тянет за собой
    зависимости доступа, а этот файл импортируется из реестра обработчиков, то
    есть из середины сборки очереди.
    """
    from ...modules.board.routes import РАЗБОР, СЦЕНА         # noqa: PLC0415

    return СЦЕНА, РАЗБОР


def _переписка(ctx) -> tuple[list[dict], int]:
    """Прежние сообщения переписки для модели и сколько их берётся."""
    from ...modules.board.routes import (СООБЩЕНИЙ_МОДЕЛИ,     # noqa: PLC0415
                                         сообщения_записи)

    return сообщения_записи(ctx.project), СООБЩЕНИЙ_МОДЕЛИ


def проверить(ctx) -> dict:
    """Позвать репетитора по снимку доски и разложить ответ по событиям."""
    payload = ctx.job.payload or {}
    режим = str(payload.get("mode") or "check").strip().lower()
    if режим not in РЕЖИМЫ:
        raise ApiError(UNKNOWN_MODE,
                       f"payload.mode must be one of: {', '.join(РЕЖИМЫ)}",
                       400, where="body.payload.mode")
    глубина = str(payload.get("level") or ГЛУБИНА_ПО_УМОЛЧАНИЮ).strip().lower()
    if глубина not in ГЛУБИНЫ:
        raise ApiError(UNKNOWN_MODE,
                       f"payload.level must be one of: {', '.join(ГЛУБИНЫ)}",
                       400, where="body.payload.level")
    строка = str(payload.get("step") or "").strip()
    сообщение = str(payload.get("message") or "").strip()[:ПРОСЬБА_МАКС]
    if режим == "chat" and not сообщение:
        raise ApiError(UNKNOWN_MODE, "payload.message is the message to answer",
                       400, where="body.payload.message")
    if режим == "hint" and not строка:
        # Подсказка — это подсказка **по строке**: без неё модель получила бы
        # просьбу «подскажи что-нибудь» и ответила бы решением целиком, то есть
        # ровно тем, чего доска не делает.
        raise ApiError(UNKNOWN_MODE, "payload.step names the line to hint at",
                       400, where="body.payload.step")

    # Сцена сверяется ДО открытия прогона: отказ по чужой версии или отставшим
    # строкам не должен стоить ни расшифровки ключа, ни сборки модели — и в
    # журнале расхода не должен выглядеть как прогон, который не состоялся.
    сцена, версия, шаги = _снимок(ctx, payload.get("scene_version"),
                                  пустая_годится=режим == "chat")
    if режим == "chat":
        шаги = _выбранные(шаги, payload.get("lines"))
    история: list[dict] = []
    if режим == "chat":
        было, сколько = _переписка(ctx)
        история = было[-сколько:]
    with Прогон(ctx) as прогон:
        ctx.progress(0, len(шаги) or 1, note="board")
        if ctx.cancelled():
            return отменено(ctx, режим)

        try:
            итог = orchestrator.board.check_board(
                прогон.project, endpoint=прогон.ep, scene=сцена,
                task=прогон.project.condition_text() or "",
                wishes=str(payload.get("wishes") or "")[:ПРОСЬБА_МАКС],
                mode=режим, level=глубина, step=строка, lines=шаги,
                message=сообщение, history=история, cancel=прогон.отмена)
        except Exception as беда:                            # noqa: BLE001
            # Ядро бросает своё, и ловить его по имени значило бы импортировать
            # `kokuban` — ровно то, чего служба не делает. Написанное для
            # человека уезжает как есть, остальное — одной фразой.
            raise ApiError(BOARD_FAILED, беда_словами(беда), 422,
                           where="body.payload") from None

    if режим == "chat":
        _записать_переписку(ctx, сообщение, итог, версия)

    вердикты = {str(ш.get("step") or ""): ш
                for ш in (getattr(итог, "steps", None) or ())}
    сказанное = []
    for шаг in шаги if режим not in ("drill", "chat") else ():
        # Событие на каждую строку доски, а не только на названные моделью:
        # полоска, дошедшая до трёх из шести, отвечает на вопрос «а остальные?»
        # молчанием, и человек читает это как «остальные в порядке».
        #
        # Кроме `drill`: задача на тренировку — это карточка рядом с доской, а
        # не разбор решения, и шесть пустых вердиктов при ней означали бы
        # проверку, которой не было.
        ид = str(шаг.get("id") or "")
        вердикт = вердиктов_запись(вердикты.get(ид), ид)
        сказанное.append(вердикт)
        ctx.emit({"kind": ШАГ_ПРОВЕРЕН, **вердикт})

    текст = _человеческий_текст(итог, режим)
    if режим == "chat":
        текст = str(getattr(итог, "reply", "") or "")
    if текст:
        ctx.emit({"kind": ТЕКСТ, "text": текст})
    ctx.progress(len(шаги), len(шаги) or 1, note="board")

    return {"mode": режим,
            "verdict": str(getattr(итог, "verdict", "") or ""),
            "steps": сказанное,
            "checked": list(getattr(итог, "checked", None) or ()),
            "remarks": list(getattr(итог, "remarks", None) or ()),
            "hint": getattr(итог, "hint", None),
            "drill": getattr(итог, "drill", None),
            "reply": str(getattr(итог, "reply", "") or ""),
            "scene_artifact": str(getattr(итог, "scene_artifact", "") or ""),
            "digest_sha": str(getattr(итог, "digest_sha", "") or ""),
            "mark": str(getattr(итог, "mark", "") or ""),
            "steps_total": len(шаги),
            "unrecognized": sum(1 for ш in шаги
                                if not str(ш.get("latex") or "").strip()),
            "key_source": прогон.источник}


def вердиктов_запись(сказанное, ид: str) -> dict:
    """Вердикт по одной строке в той форме, в какой его читают оба читателя.

    Строка, о которой модель ничего не сказала, получает `ok: null` и пустое
    замечание. Третье состояние обязано быть: `false` означало бы «здесь
    ошибка», а сказано этого не было, и `true` — «здесь верно», чего сказано
    тоже не было.
    """
    если = сказанное or {}
    ok = если.get("ok")
    return {"step": ид,
            "ok": None if ok is None else bool(ok),
            "note": str(если.get("note") or "")}


def _выбранные(шаги: list[dict], названные) -> list[dict]:
    """Строки, которые человек выделил на холсте; не выделил — все.

    Ни одна из названных не нашлась — тоже все: выделение, разошедшееся с
    записью строк (строку пересобрали между выделением и отправкой), не
    должно оставить модель без записей молча.
    """
    if not isinstance(названные, list):
        return шаги
    нужные = {str(н).strip() for н in названные if isinstance(н, str) and н.strip()}
    if not нужные:
        return шаги
    выбранные = [ш for ш in шаги if str(ш.get("id") or "") in нужные]
    return выбранные or шаги


def _записать_переписку(ctx, сообщение: str, итог, версия: int) -> None:
    """Вопрос и ответ — в переписку доски. Пустой ответ — тоже запись.

    Пустой ответ записывается словами о том, что ответа не было: вопрос без
    ответа в переписке читался бы как вопрос, на который ещё отвечают.
    """
    from ...modules.board.routes import дописать_переписку, сейчас  # noqa: PLC0415

    ответ = str(getattr(итог, "reply", "") or "").strip()
    момент = сейчас()
    дописать_переписку(
        ctx.project,
        {"role": "you", "text": сообщение, "at": момент, "scene_version": версия},
        {"role": "tutor", "text": ответ or "Ответа не получилось: модель не ответила.",
         "at": момент})


def _снимок(ctx, названная, *, пустая_годится: bool = False) -> tuple[dict, int, list[dict]]:
    """Сцена, её версия и строки решения — всё, по чему идёт проверка.

    Одной дверью, а не тремя: три проверки версии в трёх местах однажды
    сверятся с разными числами, и прогон пойдёт по сцене, которой человек не
    видел.

    Две сверки, и обе кончаются до вызова модели, то есть до денег:

    * `payload.scene_version` — та, по которой человек нажал кнопку. Разошлась
      с записью на томе — `409`: за секунду между нажатием и захватом задания
      доску мог переписать сосед по вкладке, и человек получил бы вердикт о
      решении, которого не писал. Не названа вовсе — сверять нечего: задание
      поставили не из браузера;
    * строки обязаны быть собраны по той же версии. Собранные по прежней — это
      вчерашний текст. Но отказывать на этом нечему: то, что прочитано с
      сегодняшних штрихов, лежит рядом со сценой, и строки собираются по нему
      здесь же — тем же путём, каким их пишет страница, вместе с файлом
      распознанного. Отказ остаётся ровно на одну доску: ту, с которой не
      прочитано ни строки, — проверять на ней нечего, и платить за это вызовом
      модели незачем.
    """
    сцена_имя, разбор_имя = _имена_записей()
    запись = ctx.project.state(сцена_имя) or {}
    версия = int(запись.get("version") or 0)
    if названная is not None and int(названная) != версия:
        raise ApiError(SCENE_CONFLICT,
                       f"The board has moved on to version {версия}", 409,
                       where="body.payload.scene_version")
    разбор = ctx.project.state(разбор_имя) or {}
    шаги = list(разбор.get("steps") or ())
    if not шаги or int(разбор.get("scene_version") or 0) != версия:
        шаги = _пересобрать(ctx, запись, версия)
    if not шаги and not пустая_годится:
        raise ApiError(SCENE_STALE,
                       "The board changed after the lines were built; "
                       "rebuild the lines",
                       422, where="body.payload.run_id")
    return dict(запись.get("scene") or {}), версия, шаги


def _пересобрать(ctx, запись, версия: int) -> list[dict]:
    """Собрать строки доски по тому, что с этой сцены уже прочитано.

    Прочитано — значит лежит в кэше рядом со сценой: страница дописывает его на
    каждой паузе пера, и строку, дорисованную за секунду до нажатия, он уже
    описывает. Сборка здесь — не второе мнение о доске: она идёт теми же
    функциями модуля, что и запись строк страницей, и кладёт то же самое —
    строки в состоянии решения и файл распознанного в папке доски.

    Читать нечего — пустой список: это единственная доска, на которой проверка
    отказывается, и решает это `_снимок`.

    Импорт внутри функции — см. `_имена_записей`, довод тот же.
    """
    from ...modules.board.routes import (записать_строки,       # noqa: PLC0415
                                         найти_доску,
                                         строки_из_распознанного)

    шаги = строки_из_распознанного(запись.get("recognized") or {})
    if not шаги:
        return []
    with ctx.session_scope() as s:
        запись_доски = найти_доску(s, ctx.job.project_id, ctx.solution,
                                   where="body.payload.run_id")
        записать_строки(ctx.project, запись_доски, шаги, версия)
    return шаги


def _человеческий_текст(итог, режим: str) -> str:
    """Слова ответа, если они есть. Только у подсказки и у задачи.

    У проверки человеческого текста нет вовсе: её ответ — вердикт, перечень
    сверенного и замечания с якорями, и склеивать их в абзац значило бы
    показать человеку то же самое дважды.
    """
    if режим == "hint":
        подсказка = getattr(итог, "hint", None) or {}
        return str(подсказка.get("text") or "")
    if режим == "drill":
        задача = getattr(итог, "drill", None) or {}
        return str(задача.get("task") or "")
    return ""


def _зарегистрировать() -> None:
    """См. `fill_tag._зарегистрировать` — довод тот же."""
    register(BOARD_CHECK, needs_secret=True)(проверить)


