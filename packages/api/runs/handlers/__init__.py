"""
handlers — обработчики заданий, по модулю на вид.

    fill_tag        один тег          нужен ключ модели
    fill_report     весь отчёт        нужен ключ модели
    agent           уровень 3         нужен ключ модели
    build           DOCX/PDF          ключ не нужен и не даётся
    kadai_run       сценарий работы   нужен ключ модели
    kadai_rework    замечание         нужен ключ модели
    board_check     проверка доски    нужен ключ модели
    asm_run         сборка и трасса   ключ не нужен и не даётся
    asm_memory      дамп на шаге      ключ не нужен и не даётся
    asm_chat        агент по трассе   нужен ключ модели
    cards_generate  набор карточек    нужен ключ модели

По модулю на вид, а не одним файлом: обработчик — это место, где служба
разговаривает с оркестратором, и разговоры у них разные. Общее (endpoint с
ключом человека, месячный потолок, события) вынесено в `common.py`;
если общего в двух модулях окажется больше, чем разного, — значит это один вид
задания с параметром, а не два.

`подключить()` зовётся из `jobs.registry.load_handlers` — единственного места,
где реестр наполняется. Регистрация функцией, а не декоратором на уровне модуля:
декоратор срабатывает на импорте, то есть один раз на процесс, и тест,
почистивший реестр, обратно обработчики уже не получил бы (`jobs/probe.py`
объясняет это подробно).
"""
from __future__ import annotations


def подключить() -> None:
    """Поставить все обработчики прогонов в реестр. Идемпотентно."""
    from . import (agent, asm_chat, asm_memory, asm_run,     # noqa: PLC0415
                   board_check, build, cards_generate, fill_report, fill_tag,
                   kadai_rework, kadai_run)

    for модуль in (fill_tag, fill_report, agent, build, kadai_run, kadai_rework,
                   board_check, asm_run, asm_memory, asm_chat, cards_generate):
        модуль._зарегистрировать()


__all__ = ["подключить"]
