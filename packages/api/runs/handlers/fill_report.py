"""
fill_report — заполнить весь отчёт. Уровень 2 оркестратора, обёрнутый в задание.

    payload   {"endpoint": "deepseek", "keys": ["цель", "выводы"],
               "overwrite": false}
    result    {"filled": ["цель", …], "outcome": "done", "problems": N,
               "key_source": "shared"}

Здесь исполняются два обещания §11 сразу, и оба держатся на потоке:

* **текст по мере генерации.** `on_text` зовётся на каждый кусок ответа модели;
  склейку в ~100 мс делает `JobContext.emit`, а не мы, — она общая на всю
  очередь и должна быть одна;
* **отмена: закрытое сохранено.** Тег сохраняется в момент закрытия своего
  объекта (`fill.py`), поэтому остановка между тегами не отбирает ничего из уже
  записанного. Между тегами мы и спрашиваем — в `on_tag`.

Почему отмена спрашивается **и** между тегами, **и** проводом (`cancel=`).
Провод спрашивает часто, но его вопрос ходит в базу не чаще четверти секунды
(`common.Отмена`), а тег бывает и длиннее. Проверка между тегами стоит одного
запроса на тег и даёт точку, в которой остановка ничего не стоит: предыдущее
записано, следующее не начато. Один механизм без другого либо тормозит базу,
либо отвечает на «отмену» через минуту.

`problems` наружу отдаётся **числом**, а не списком: замечания прогона бывают на
каждый тег, и класть их в `job.result` значило бы держать в базе то, что и так
лежит в записи прогона на томе (`runs/<id>.json`).
"""
from __future__ import annotations

import orchestrator

from ...jobs.registry import FILL_REPORT, register
from .common import Прогон, отменено


def заполнить_отчёт(ctx) -> dict:
    """Весь отчёт одним потоковым прогоном; теги уезжают в поток по мере готовности."""
    payload = ctx.job.payload or {}
    ключи = payload.get("keys") or None
    if ключи is not None:
        ключи = [str(k) for k in ключи]

    закрыто: list[str] = []
    with Прогон(ctx) as прогон:
        всего = len(ключи) if ключи else 0
        ctx.progress(0, всего, note="")
        if ctx.cancelled():
            return отменено(ctx, "")

        def на_текст(кусок: str) -> None:
            прогон.текст(кусок)

        def на_тег(fill) -> None:
            # Порядок: сначала рассказать про тег, потом спросить отмену.
            # Обратный порядок оставил бы последний закрытый тег неназванным
            # ровно в том случае, ради которого всё это и делается, — когда
            # человек нажал «отменить».
            закрыто.append(fill.key)
            прогон.тег_закрыт(fill)
            ctx.progress(len(закрыто), всего or len(закрыто), note=fill.key)
            if ctx.cancelled():
                прогон.отмена.попросить()

        итог = orchestrator.fill_report(
            прогон.project, endpoint=прогон.ep, keys=ключи, on_text=на_текст,
            on_tag=на_тег, cancel=прогон.отмена,
            overwrite=bool(payload.get("overwrite")))

    return {"filled": list(итог.filled), "outcome": итог.outcome,
            "ok": bool(итог.ok), "problems": len(итог.problems),
            "stop": итог.stop, "run": getattr(итог.run, "id", None),
            "key_source": прогон.источник}


def _зарегистрировать() -> None:
    """См. `fill_tag._зарегистрировать` — довод тот же."""
    register(FILL_REPORT, needs_secret=True)(заполнить_отчёт)


__all__ = ["заполнить_отчёт", "_зарегистрировать"]
