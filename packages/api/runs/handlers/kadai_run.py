"""
kadai_run — сценарий работы над документом: семь стадий от условия до архива.

    payload   {"endpoint": "deepseek", "run_id": "<решение работы>",
               "wishes": {"text": "…", "show_task": true,
                          "show_structure": false},
               "until": "тексты"}
    result    {"work": "w-…", "state": "running", "stage": "тексты",
               "stages": [{"name": …, "state": …}, …],
               "outputs": {...},
               "artifacts": {"docx": …, "pdf": …, "archive": …,
                             "archive_light": …},
               "preview": "7c4…", "key_source": "shared"}

**Какое решение работы считается, говорит `run_id`.** В работе их несколько, и
у каждого свой ход стадий, своё условие и свой список блоков; читает поле
`JobContext.project`, а не этот обработчик, — иначе пять обработчиков прочли бы
одно поле по-разному. Поля нет — работа целиком, как она выглядела, пока
решение в ней было одно.

**Что модель видит из файлов работы**, решает `Project.context_ids`: файлы
папки самого решения, его условие и те общие файлы работы, которые к решению
подключили (`PUT …/kadai/context`). По умолчанию не входит ни один: методичку
кладут один раз на работу, но подключают к задаче явно — файл соседней темы в
промпте стоит денег и сбивает модель.

**Пожелания без `payload` берутся из проекта** (`PUT …/kadai/wishes`).
Названное в задании старше записанного: прогон «с
другими пожеланиями» иначе повторял бы прежние.

**Условие приходит с тома, а не из задания.** Оно записано решением
(текстом и, если его принесли файлом, идентификатором материала), и стадия
«приём» читает его сама. Текст старше файла: правка условия действует со
следующего прогона, без второй загрузки.

**`artifacts` — то, что можно скачать.** `outputs` сценария это **имена**
файлов, и по имени с сайта не скачивается ничего; идентификаторы кладёт
`orchestrator.kadai` (DOCX и PDF — стадия «сборка», оба ZIP — стадия «архив»), а
поле называется так же, как у `build`, потому что читает его один и тот же
колокольчик.

**Архивов два, и собираются они одним прогоном.** `archive` — полный: работа со
всем, из чего она собрана, вместе с записью о сборке. `archive_light` — то, что
несут на сдачу: отчёт, `исходники/` и `схемы/`. Вида архива в задании нет
намеренно: выбирает человек, когда скачивает, а спросить его до прогона значило
бы гонять решение второй раз ради другого ZIP.

**Сценарий зовётся через `orchestrator.kadai`, а не напрямую.** `api` не
импортирует `kadai` ни одной строкой: соседей знает только оркестратор, и
обработчик задания — последнее место, где эту стрелку стоило бы
разворачивать. Обёртки живут в `orchestrator/kadai.py` и там же объяснены.

**Стадия — единица доклада, ход — единица прозрачности.** После каждой стадии в
поток уезжает событие `stage`, а в `progress` — «сделано N из семи». Этого мало:
стадия идёт минутами, и полоска, стоящая на «решении», выглядит так же, как
зависшая. Поэтому изнутри стадий приходят события `step`:

    {"kind": "step", "stage": "решение", "tool": "insert_block", "ok": true,
     "note": "вставлен блок b-03 «Алгоритм сортировки»", "n": 4, "total": 50}

`tool` пуст у ходов без инструментов («сочиняю строение работы»); `n`/`total`
едут, только если знаменатель есть. Фразу пишет тот, кто сделал ход
(`orchestrator.tools`, `kadai.run`), и здесь она не переписывается.

**Остановка доходит и внутрь стадии.** `common.Отмена` уезжает дверям сценария
(`orchestrator.kadai.work(stop=…)`), и слой моделей спрашивает её перед каждым
куском потока и перед каждым ходом петли — то есть кнопка «Остановить»
срабатывает за секунду, а не за стадию. Остановленная посреди стадии работа не
падает: стадия возвращается в «ждёт», работа — в «остановлена», и повторный
запуск продолжает с неё же. Сделанное сохранено — блоки пишутся версией в
момент вставки, ход работы — после каждой стадии.

**Первая страница остаётся картинкой.** Пройдя стадию «сборка», прогон кладёт
первую страницу собранного PDF отдельным артефактом PNG и записывает его у
записи решения (`project_runs.preview_artifact_id`). Только пройдя её: собранное
живёт на томе и переживает прогон, и остановленный на «текстах» иначе рисовал бы
заново картинку прежнего документа. Рисует её та же функция, что и у
шаблонной сборки (`build.запомнить_превью`), и это не удобство: лента отчётов
показывает карточки обоих видов рядом, и вторая отрисовка отличалась бы от
первой шириной, полем или разрешением — то есть видно было бы, каким путём
сделан документ.

Отрисовка не может сорвать прогон: документ уже собран и уже лежит артефактом.
Беда уходит в журнал, а карточка остаётся без превью — в том же состоянии, в
каком была до сборки.

**Текст беды — одна русская фраза.** Всё, что сценарий и оркестратор пишут для
человека, уезжает как есть (`kadai_failed`, `job.error.message`); текст, ему не
адресованный, — английский ответ поставщика, чужой `TypeError` — заменяется
одной фразой (`common.беда_словами`). Сырой текст на экране человек читает как
поломку неизвестно чего, а разбирать беду по подробностям всё равно не ему:
они в журнале службы.
"""
from __future__ import annotations

from orchestrator import kadai as сценарий

from ...errors import ApiError
from ...jobs.registry import KADAI_RUN, register
from .build import запомнить_превью
from .common import Прогон, беда_словами, отменено

KADAI_FAILED = "kadai_failed"
UNKNOWN_STAGE = "unknown_stage"

# Стадия, после которой у работы появляется собранный документ. Названа здесь
# затем, что первая страница рисуется только вслед за ней: `made` живёт на томе
# и переживает прогон, и прогон, остановленный на «текстах», иначе рисовал бы
# заново картинку позавчерашнего PDF. Имя сверяется со списком стадий
# (`сценарий.stage_names()`) при первом же прогоне — стадии, которой нет, в
# пройденных не окажется никогда.
СБОРКА = "сборка"


def прогнать(ctx) -> dict:
    """Пройти стадии сценария, докладывая о каждой."""
    payload = ctx.job.payload or {}
    до = str(payload.get("until") or "").strip() or None
    имена = сценарий.stage_names()
    if до is not None and до not in имена:
        raise ApiError(UNKNOWN_STAGE,
                       f"payload.until must be one of: {', '.join(имена)}",
                       400, where="body.payload.until")

    сделано = [0]
    пройдено: set = set()
    with Прогон(ctx) as прогон:
        пожелания = _пожелания(payload.get("wishes"), прогон.project)
        ctx.progress(0, len(имена), note="")
        if ctx.cancelled():
            return отменено(ctx, "")

        стадия = [""]

        def на_стадию(имя: str, снимок: dict) -> None:
            сделано[0] += 1
            пройдено.add(имя)
            состояние = _состояние(снимок, имя)
            прогон.стадия(имя, состояние, note=str(снимок.get("current") or ""))
            ctx.progress(сделано[0], len(имена), note=имя)

        def на_ход(ход: dict) -> None:
            # Стадию называет сам сценарий, но ход петли приходит из слоя
            # инструментов, который про стадии не знает вовсе. Помним последнюю
            # названную: «решение» стоит в ней с первого хода стадии, и ходы
            # петли ложатся под неё.
            имя = str(ход.get("stage") or "")
            if имя:
                стадия[0] = имя
            прогон.ход({**ход, "stage": имя or стадия[0]})

        try:
            снимок = сценарий.work(прогон.project, endpoint=прогон.ep,
                                   wishes=пожелания, until=до,
                                   on_stage=на_стадию, on_step=на_ход,
                                   stop=прогон.отмена)
        except Exception as беда:                            # noqa: BLE001
            # Сценарий бросает своё (`KadaiError`, `NotReady`), и ловить его по
            # имени значило бы импортировать `kadai` — ровно то, чего этот
            # модуль не делает. Отсюда и разбор текста по-русски, а не по классу
            # исключения: написанное для человека уезжает наружу как есть,
            # остальное — одной фразой (`common.беда_словами`).
            raise ApiError(KADAI_FAILED, беда_словами(беда), 422,
                           where="body.payload") from None

    собрано = dict(снимок.get("made") or {})
    превью = (запомнить_превью(ctx, ctx.project, собрано.get("pdf"),
                               запуск=ctx.solution)
              if СБОРКА in пройдено else "")
    if превью:
        ctx.emit({"kind": "artifact", "output": "preview", "artifact": превью})
    итог = {"work": снимок.get("work"), "state": снимок.get("state"),
            "stage": снимок.get("stage"),
            "stages": [{"name": st.get("name"), "state": st.get("state")}
                       for st in (снимок.get("stages") or ())],
            "hold": снимок.get("hold"),
            "outputs": dict(снимок.get("outputs") or {}),
            "problems": len(снимок.get("problems") or ()),
            "preview": превью,
            "key_source": прогон.источник}
    if собрано:
        # `artifacts` — то же поле, каким отвечает `build` (`runs/handlers/build.py`),
        # и читает его колокольчик (`notifications.service.артефакты`). Без него
        # ссылка «Скачать» в уведомлении о законченной работе не появилась бы
        # вовсе: `outputs` — это **имена** файлов, а скачивают по идентификатору.
        итог["artifacts"] = собрано
    return итог


def _пожелания(сырое, project) -> dict:
    """Пожелания к работе: из `payload`, а пусто — из проекта.

    Приводим к трём известным полям, а не отдаём словарь как есть: лишний ключ
    уронил бы `Wishes(**...)` беспричинным `TypeError`, а список полей —
    договор сценария, и повторять его в клиенте незачем.

    Пусто в задании — читаем проект (`PUT …/kadai/wishes`). Порядок именно
    такой: названное в задании старше записанного,
    иначе прогон «с другими пожеланиями» повторял бы прежние. Обратный порядок
    к тому же сделал бы запись бесполезной — сайт кладёт пожелания в первый
    прогон, и они всегда были бы непустыми.
    """
    сырое = сырое if isinstance(сырое, dict) else {}
    просьба = {"text": str(сырое.get("text") or ""),
               "show_task": bool(сырое.get("show_task")),
               "show_structure": bool(сырое.get("show_structure"))}
    if any(просьба.values()):
        return просьба
    return сценарий.wishes(project)


def _состояние(снимок: dict, имя: str) -> str:
    for st in снимок.get("stages") or ():
        if st.get("name") == имя:
            return str(st.get("state") or "")
    return ""


def _зарегистрировать() -> None:
    """См. `fill_tag._зарегистрировать` — довод тот же."""
    register(KADAI_RUN, needs_secret=True)(прогнать)


__all__ = ["прогнать", "_зарегистрировать", "KADAI_FAILED", "UNKNOWN_STAGE",
           "СБОРКА"]
