"""
common — то, что одинаково у всех прогонов модели, написанное один раз.

Семь обработчиков (`fill_tag`, `fill_report`, `agent`, `build`, `kadai_run`,
`kadai_rework`, `board_check`) делают разную работу, но обрамление у шести из
них одно и то же:

    endpoint с ключом человека → месячный потолок → прогон → события

Написанное по месту, это обрамление разошлось бы на первом же исправлении: в
одном обработчике проверка потолка оказалась бы после первого вызова модели, в
другом — до, и «закрытое сохранено» держалось бы через раз.

**Денег обработчик больше не считает**. Цену задания
списывает воркер при захвате — одну на прогон, по виду задания
(`runs/limits.ЦЕНЫ`), — а токены поставщика, которые считались здесь раньше, в
плату не входят вовсе: они по-прежнему пишутся в журнал проекта
(`llm.Journal`, `Project.spent()`), потому что это другой учёт — про
поставщика, а не про человека. Отсюда же исчез и `llm.Limit` поверх остатка
плана: остановка по деньгам стоит **до** первого вызова, в `__enter__`, и
считается в единицах нашей цены, а не в чужих токенах, которые к плате
отношения не имеют.

    Виды событий
    ------------

Список открыт (`jobs.models.JobEvent.kind` не перечисляет их), но имена стоят
здесь константами, потому что читателей у них двое: SSE (`api/events`) и
интерфейс. Строка, написанная по месту, однажды окажется написана иначе — и
клиент перестанет узнавать своё событие, ничего не заметив.

    ТЕКСТ            кусок ответа модели; склейку делает `JobContext` (~100 мс)
    ТЕГ_ЗАКРЫТ       тег дописан и сохранён новой версией
    СТАДИЯ           стадия сценария `kadai` сменилась
    ХОД              ход внутри стадии: что агент делает прямо сейчас
    ШАГ_ПРОВЕРЕН     вердикт по одной строке решения на доске
    ЛИМИТ            месяц кончился до старта; задание закрывается `failed`

`progress` пишет сам `JobContext.progress`, `done` / `failed` / `cancelled` —
воркер по терминальному статусу (`jobs/worker.py`). Обработчику их писать
нельзя: он не знает, чем кончится, — его могут убить по таймауту.
"""
from __future__ import annotations

import time

from ...errors import ApiError
from .. import limits, model

# Как часто провод спрашивает базу «не отменили ли». Слой спрашивает `cancel()`
# перед каждым куском потока (`llm/transport.py`), а кусков в одном ответе
# бывают тысячи; запрос в базу на каждый — это тысяча сессий на один прогон.
# Четверть секунды человек не замечает, а база не замечает нас.
ПРОВЕРКА_ОТМЕНЫ_С = 0.25

# ── имена событий ────────────────────────────────────────────────────────────
ТЕКСТ = "text"
ТЕГ_ЗАКРЫТ = "tag_closed"
СТАДИЯ = "stage"
ХОД = "step"
ШАГ_ПРОВЕРЕН = "step_checked"
ЛИМИТ = limits.LIMIT_EXHAUSTED

CANCELLED_BEFORE = "cancelled_before"

# ── беда поставщика, названная так, чтобы её можно было починить ────────────
#
# Прогон, оборвавшийся на стороне поставщика, раньше уезжал наружу одним
# `run_failed` — «прогон модели не удался, попробуйте другой пресет». Совет
# неверен ровно в тех случаях, которые случаются чаще всего: непринятый ключ
# чинится в настройках, молчащий поставщик — ожиданием, несуществующая модель —
# выбором другой. Поэтому вид ошибки слоя (`llm.ErrorKind`, он же
# `AgentResult.error_kind`) превращается здесь в свой код отказа, у которого в
# словаре сайта свои слова.
#
# Виды, которых тут нет (`context_overflow`, `bad_response`, `refused`,
# `limit_exceeded`), остаются `run_failed` намеренно: они про сам разговор с
# моделью, а не про доступ к ней, и «почини ключ» сказало бы человеку неправду.
MODEL_AUTH = "model_auth"
MODEL_UNREACHABLE = "model_unreachable"
MODEL_NOT_FOUND = "model_not_found"
MODEL_RATE_LIMIT = "model_rate_limit"

# Код отказа отдельным словарём, а ответ отдельным, хотя напрашивается один на
# пару: перечень кодов службы собирается разбором исходников
# (`tests/api/test_error_codes.py`), и он умеет читать `ApiError(СЛОВАРЬ[ключ])`,
# но не умеет — код, вынутый из кортежа в локальную переменную. Код отказа
# обязан быть виден снаружи без запуска, поэтому здесь он стоит так, как его
# видно.
_КОД_ПО_ВИДУ = {
    "auth": MODEL_AUTH,
    "not_found": MODEL_NOT_FOUND,
    "rate_limit": MODEL_RATE_LIMIT,
    "transport": MODEL_UNREACHABLE,
    "timeout": MODEL_UNREACHABLE,
}

_ОТВЕТ_ПО_ВИДУ = {
    "auth": (402, "The provider did not accept the key: check it in settings"),
    "not_found": (400, "The provider has no such model: choose another one"),
    "rate_limit": (429, "The provider throttled the request: try again later"),
    "transport": (502, "The provider did not answer"),
    "timeout": (502, "The provider did not answer in time"),
}


def беда_поставщика(вид: str, *, where: str) -> ApiError | None:
    """Вид ошибки слоя → отказ с человеческим кодом. `None` — не наш случай.

    `None`, а не «общий отказ», потому что решение, чем закончить задание,
    принимает обработчик: у него есть ещё и свои исходы (`agent_refused`,
    потолок ходов), и подменять их отсюда значило бы решать за него.
    """
    имя = str(вид or "")
    if имя not in _КОД_ПО_ВИДУ:
        return None
    статус, текст = _ОТВЕТ_ПО_ВИДУ[имя]
    return ApiError(_КОД_ПО_ВИДУ[имя], текст, статус, where=where)


class ЛимитКончился(ApiError):
    """Месяц кончился до первого вызова модели. Закрытое раньше — сохранено.

    Своим классом, а не `ApiError(...)` по месту, потому что бросают её все
    прогоны, а код и текст обязаны совпасть: клиент различает случаи по коду, и
    `limit_exhausted` из одного места против `limit-exhausted` из другого — это
    два случая там, где случай один.
    """

    def __init__(self, остаток: int = 0):
        super().__init__(
            limits.LIMIT_EXHAUSTED,
            "Monthly limit is used up; whatever was finished is saved", 402)
        self.остаток = int(остаток)


class Отмена:
    """«Не просили ли остановиться» в форме, которую понимает слой модели.

    Слой принимает `cancel` вызываемым объектом без аргументов и спрашивает его
    перед каждым куском потока. Отсюда два свойства этого класса:

    * **ответ «нет» кэшируется** на `ПРОВЕРКА_ОТМЕНЫ_С`. Не кэшировать значило
      бы открывать сессию базы на каждый кусок ответа модели;
    * **ответ «да» не кэшируется, а запоминается навсегда.** Отмена — состояние
      без обратного хода: сказав однажды «стой», мы не имеем права через
      четверть секунды сказать «нет, продолжай».

    `попросить()` ставит «да» без похода в базу. Ею пользуется обработчик,
    проверивший отмену между тегами: он уже сходил в базу сам, и повторный
    запрос был бы вторым ответом на тот же вопрос.
    """

    def __init__(self, ctx, ттл: float = ПРОВЕРКА_ОТМЕНЫ_С):
        self._ctx = ctx
        self._ттл = float(ттл)
        self._да = False
        self._спрошено = 0.0

    def попросить(self) -> None:
        self._да = True

    def __call__(self) -> bool:
        if self._да:
            return True
        сейчас = time.monotonic()
        if сейчас - self._спрошено < self._ттл and self._спрошено:
            return False
        self._спрошено = сейчас
        if self._ctx.cancelled():
            self._да = True
        return self._да


