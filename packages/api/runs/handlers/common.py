class Прогон:
    """Endpoint и месячный потолок одного задания. Контекстный менеджер.

        with Прогон(ctx) as прогон:
            итог = orchestrator.fill_report(прогон.project, endpoint=прогон.ep)

    Порядок в `__enter__` не переставляется: сначала месячный остаток (он
    считается по базе и стоит один запрос), потом ключ (он стоит расшифровки).
    Отказать по деньгам дешевле, чем по ключу, и человеку понятнее: «кончился
    месяц» — состояние, а «нет ключа» — настройка, и первое чаще.

    Списания здесь нет вовсе: цену задания списал воркер при захвате.
    """

    def __init__(self, ctx, *, имя_пресета: str | None = None,
                 where: str = "body.payload.endpoint"):
        self.ctx = ctx
        self._имя = имя_пресета if имя_пресета is not None else _пресет_из(ctx)
        self._where = where
        self._вход = None
        self.ep: str = ""
        self.project = None
        self.отмена = Отмена(ctx)

    # ── вход и выход ────────────────────────────────────────────────────────

    def __enter__(self) -> "Прогон":
        """Проверить месяц, открыть проект, достать ключ поставщика.

        Проверка месяца здесь — **вторая** и последняя: первую сделала
        постановка задания (`jobs.service.enqueue`), а между нею и этой минутой
        задание лежало в очереди, и остаток мог съесть сосед по тому же
        аккаунту. Спрашивается при этом не `exhausted`, а `перебрал`: цена
        этого задания уже списана при захвате, и человек, чей план кончился
        ровно им, работать обязан — иначе купивший один прогон не получил бы ни
        одного (`limits.Расход.перебрал` объясняет разницу подробно).
        """
        with self.ctx.session_scope() as s:
            from ...accounts.models import User                # noqa: PLC0415

            человек = s.get(User, self.ctx.job.user_id)
            сводка = (limits.расход(s, self.ctx.settings, человек)
                      if человек is not None else None)
        if сводка is not None and сводка.перебрал:
            self.ctx.emit({"kind": ЛИМИТ, "remaining_units": 0,
                           "limit_units": сводка.limit_units})
            raise ЛимитКончился(0)

        self.project = self.ctx.project
        self._вход = model.endpoint(self.ctx, self._имя, where=self._where)
        self.ep = self._вход.__enter__()
        return self

    def __exit__(self, *беда) -> bool:
        if self._вход is not None:
            self._вход.__exit__(*беда)
        return False

    # ── события ─────────────────────────────────────────────────────────────

    def текст(self, кусок: str) -> None:
        """Кусок ответа модели в поток. Склейку делает `JobContext` (~100 мс)."""
        if кусок:
            self.ctx.emit({"kind": ТЕКСТ, "text": str(кусок)})

    def тег_закрыт(self, fill) -> None:
        """Тег дописан: имя, номер версии, годность, пометки.

        Значения в событие не кладём — только то, чем его найти. То же правило,
        что у `job.result` (`jobs/models.py`): база держит указатель, том держит
        содержимое, и отчёт на сорок страниц не должен ехать строкой в SQLite
        второй раз.
        """
        версия = getattr(fill, "version", None)
        self.ctx.emit({"kind": ТЕГ_ЗАКРЫТ, "key": fill.key,
                       "ok": bool(fill.ok),
                       "version": getattr(версия, "n", None),
                       "flags": list(getattr(fill, "flags", ()) or ())})

    def стадия(self, имя: str, состояние: str = "", note: str = "") -> None:
        """Смена стадии сценария `kadai`."""
        self.ctx.emit({"kind": СТАДИЯ, "name": str(имя),
                       "state": str(состояние or ""), "note": str(note or "")})

    def ход(self, ход: dict) -> None:
        """Ход внутри стадии: что делается прямо сейчас.

        Стадия — единица доклада, но идёт она минутами: полоска, стоящая на
        «решении» десять минут, отвечает на вопрос «работает ли оно» так же,
        как зависшая. Ход отвечает словами: «вставлен блок b-03 «Алгоритм
        сортировки»», «прочитан материал «методичка.pdf»».

        Поля: `stage` — стадия по-русски (как у события `stage`), `tool` — имя
        инструмента или пусто (ход без инструмента: «сочиняю строение работы»),
        `ok` — вышло ли, `note` — фраза для человека, `n`/`total` — ход и
        потолок, если знаменатель есть. Счётчик без знаменателя не едет вовсе:
        полоска с выдуманным знаменателем врёт.

        Фразу пишет тот, кто сделал ход (`orchestrator.tools`, `kadai.run`), и
        переписывать её здесь нельзя: второе описание одного действия разошлось
        бы с первым, а человек читает оба — в потоке и в истории блоков.
        """
        событие = {"kind": ХОД, "stage": str(ход.get("stage") or ""),
                   "tool": str(ход.get("tool") or ""),
                   "ok": bool(ход.get("ok", True)),
                   "note": str(ход.get("note") or "")}
        for поле in ("n", "total"):
            if ход.get(поле) is not None:
                событие[поле] = int(ход[поле])
        self.ctx.emit(событие)


def _пресет_из(ctx) -> str:
    """Имя пресета из `payload`. Пусто — отказ, а не умолчание.

    Умолчания здесь быть не может: поставщика выбирает человек, и молча
    подставленный означал бы прогон, оплаченный не тем ключом, о котором он
    думал.
    """
    имя = str((ctx.job.payload or {}).get("endpoint") or "").strip()
    if not имя:
        raise ApiError("endpoint_required",
                       "payload.endpoint must name a provider preset", 400,
                       where="body.payload.endpoint")
    return имя


# Сколько знаков текста беды доезжает до человека. Дальше — не объяснение, а
# кусок чужого журнала: `job.error.message` показывается карточкой задания
# целиком, и на трёх экранах человек не найдёт в нём первой строки.
ПРЕДЕЛ_БЕДЫ = 400

# Текст, которым отвечает беда, написанная не для человека. Одна фраза и
# ничего больше: подробности лежат в журнале службы, а человеку сказать про них
# нечего — чинить их не ему.
БЕДА_МОЛЧА = ("работа не доделана: служба не справилась с этой стадией. "
              "Попробуйте ещё раз — сделанное сохранено")


def беда_словами(беда: Exception) -> str:
    """Текст беды для человека: одна русская фраза без сырого текста.

    Сценарий (`kadai.errors`) и оркестратор пишут свои отказы по-русски и для
    человека — такие видно как есть. Всё остальное человеку не адресовано:
    `TypeError` из чужого пакета, английский текст поставщика, тело JSON с
    ошибкой API. На экране они читаются как поломка неизвестно чего, и
    единственное, что человек может из них вынести, — испуг.

    Признак — русские буквы в тексте. Грубо, зато честно и без списка классов
    исключений, которого здесь всё равно не составить: `api` не импортирует ни
    `kadai`, ни чужие пакеты и ловить их по имени не может.
    """
    текст = " ".join(str(беда).split())
    if not текст or not any("а" <= c.lower() <= "я" or c == "ё" for c in текст):
        return БЕДА_МОЛЧА
    if len(текст) > ПРЕДЕЛ_БЕДЫ:
        текст = текст[:ПРЕДЕЛ_БЕДЫ - 1].rstrip() + "…"
    return текст


def отменено(ctx, note: str = "") -> dict:
    """Ответ обработчика, остановившегося по просьбе. Форма одна на всех.

    Состояние `cancelled` ставит воркер, увидев `ctx.cancelled()` на конце
    работы (`jobs/child.позвать`); отсюда уезжает только рассказ о том, где
    именно остановились, — он ложится в `job.result`.
    """
    return {CANCELLED_BEFORE: str(note or "")}


