"""
common — то, что одинаково у всех прогонов модели, написанное один раз.

Шесть обработчиков (`fill_tag`, `fill_report`, `agent`, `build`, `kadai_run`,
`kadai_rework`) делают разную работу, но обрамление у пяти из них одно и то же:

    endpoint с ключом человека → месячный потолок → прогон → события

Написанное по месту, это обрамление разошлось бы на первом же исправлении: в
одном обработчике проверка потолка оказалась бы после первого вызова модели, в
другом — до, и «закрытое сохранено» держалось бы через раз.

**Денег обработчик больше не считает** (решение владельца §12). Цену задания
списывает воркер при захвате — одну на прогон, по виду задания
(`runs/limits.ЦЕНЫ`), — а токены поставщика, которые считались здесь раньше, в
плату не входят вовсе: они по-прежнему пишутся в журнал проекта
(`llm.Journal`, `Project.spent()`), потому что это другой учёт — про
поставщика, а не про человека. Отсюда же исчез и `llm.Limit` поверх остатка
плана: остановка по деньгам стоит **до** первого вызова, в `__enter__`, и
считается в единицах нашей цены, а не в чужих токенах, которые к плате
отношения не имеют.

    Виды событий
    ------------

Список открыт (`jobs.models.JobEvent.kind` не перечисляет их), но имена стоят
здесь константами, потому что читателей у них двое: SSE (`api/events`) и
интерфейс. Строка, написанная по месту, однажды окажется написана иначе — и
клиент перестанет узнавать своё событие, ничего не заметив.

    ТЕКСТ            кусок ответа модели; склейку делает `JobContext` (~100 мс)
    ТЕГ_ЗАКРЫТ       тег дописан и сохранён новой версией
    СТАДИЯ           стадия сценария `kadai` сменилась
    ЛИМИТ            месяц кончился до старта; задание закрывается `failed`

`progress` пишет сам `JobContext.progress`, `done` / `failed` / `cancelled` —
воркер по терминальному статусу (`jobs/worker.py`). Обработчику их писать
нельзя: он не знает, чем кончится, — его могут убить по таймауту.
"""
from __future__ import annotations

import time

from ...errors import ApiError
from .. import limits, model

# Как часто провод спрашивает базу «не отменили ли». Слой спрашивает `cancel()`
# перед каждым куском потока (`llm/transport.py`), а кусков в одном ответе
# бывают тысячи; запрос в базу на каждый — это тысяча сессий на один прогон.
# Четверть секунды человек не замечает, а база не замечает нас.
ПРОВЕРКА_ОТМЕНЫ_С = 0.25

# ── имена событий ────────────────────────────────────────────────────────────
ТЕКСТ = "text"
ТЕГ_ЗАКРЫТ = "tag_closed"
СТАДИЯ = "stage"
ЛИМИТ = limits.LIMIT_EXHAUSTED

CANCELLED_BEFORE = "cancelled_before"


class ЛимитКончился(ApiError):
    """Месяц кончился до первого вызова модели. Закрытое раньше — сохранено.

    Своим классом, а не `ApiError(...)` по месту, потому что бросают её все
    прогоны, а код и текст обязаны совпасть: клиент различает случаи по коду, и
    `limit_exhausted` из одного места против `limit-exhausted` из другого — это
    два случая там, где случай один.
    """

    def __init__(self, остаток: int = 0):
        super().__init__(
            limits.LIMIT_EXHAUSTED,
            "Monthly limit is used up; whatever was finished is saved", 402)
        self.остаток = int(остаток)


class Отмена:
    """«Не просили ли остановиться» в форме, которую понимает слой модели.

    Слой принимает `cancel` вызываемым объектом без аргументов и спрашивает его
    перед каждым куском потока. Отсюда два свойства этого класса:

    * **ответ «нет» кэшируется** на `ПРОВЕРКА_ОТМЕНЫ_С`. Не кэшировать значило
      бы открывать сессию базы на каждый кусок ответа модели;
    * **ответ «да» не кэшируется, а запоминается навсегда.** Отмена — состояние
      без обратного хода: сказав однажды «стой», мы не имеем права через
      четверть секунды сказать «нет, продолжай».

    `попросить()` ставит «да» без похода в базу. Ею пользуется обработчик,
    проверивший отмену между тегами: он уже сходил в базу сам, и повторный
    запрос был бы вторым ответом на тот же вопрос.
    """

    def __init__(self, ctx, ттл: float = ПРОВЕРКА_ОТМЕНЫ_С):
        self._ctx = ctx
        self._ттл = float(ттл)
        self._да = False
        self._спрошено = 0.0

    def попросить(self) -> None:
        self._да = True

    def __call__(self) -> bool:
        if self._да:
            return True
        сейчас = time.monotonic()
        if сейчас - self._спрошено < self._ттл and self._спрошено:
            return False
        self._спрошено = сейчас
        if self._ctx.cancelled():
            self._да = True
        return self._да


# ── обрамление прогона ───────────────────────────────────────────────────────

class Прогон:
    """Endpoint и месячный потолок одного задания. Контекстный менеджер.

        with Прогон(ctx) as прогон:
            итог = orchestrator.fill_report(прогон.project, endpoint=прогон.ep)

    Порядок в `__enter__` не переставляется: сначала месячный остаток (он
    считается по базе и стоит один запрос), потом ключ (он стоит расшифровки).
    Отказать по деньгам дешевле, чем по ключу, и человеку понятнее: «кончился
    месяц» — состояние, а «нет ключа» — настройка, и первое чаще.

    Списания здесь нет вовсе (§12): цену задания списал воркер при захвате.
    """

    def __init__(self, ctx, *, имя_пресета: str | None = None,
                 where: str = "body.payload.endpoint"):
        self.ctx = ctx
        self._имя = имя_пресета if имя_пресета is not None else _пресет_из(ctx)
        self._where = where
        self._вход = None
        self.ep: str = ""
        self.источник: str = ""
        self.project = None
        self.отмена = Отмена(ctx)

    # ── вход и выход ────────────────────────────────────────────────────────

    def __enter__(self) -> "Прогон":
        """Проверить месяц, открыть проект, достать ключ поставщика.

        Проверка месяца здесь — **вторая** и последняя: первую сделала
        постановка задания (`jobs.service.enqueue`), а между нею и этой минутой
        задание лежало в очереди, и остаток мог съесть сосед по тому же
        аккаунту. Спрашивается при этом не `exhausted`, а `перебрал`: цена
        этого задания уже списана при захвате, и человек, чей план кончился
        ровно им, работать обязан — иначе купивший один прогон не получил бы ни
        одного (`limits.Расход.перебрал` объясняет разницу подробно).
        """
        with self.ctx.session_scope() as s:
            from ...accounts.models import User                # noqa: PLC0415

            человек = s.get(User, self.ctx.job.user_id)
            сводка = (limits.расход(s, self.ctx.settings, человек)
                      if человек is not None else None)
        if сводка is not None and сводка.перебрал:
            self.ctx.emit({"kind": ЛИМИТ, "remaining_units": 0,
                           "limit_units": сводка.limit_units})
            raise ЛимитКончился(0)

        self.project = self.ctx.project
        self._вход = model.endpoint(self.ctx, self._имя, where=self._where)
        self.ep, self.источник = self._вход.__enter__()
        return self

    def __exit__(self, *беда) -> bool:
        if self._вход is not None:
            self._вход.__exit__(*беда)
        return False

    # ── события ─────────────────────────────────────────────────────────────

    def текст(self, кусок: str) -> None:
        """Кусок ответа модели в поток. Склейку делает `JobContext` (~100 мс)."""
        if кусок:
            self.ctx.emit({"kind": ТЕКСТ, "text": str(кусок)})

    def тег_закрыт(self, fill) -> None:
        """Тег дописан: имя, номер версии, годность, пометки.

        Значения в событие не кладём — только то, чем его найти. То же правило,
        что у `job.result` (`jobs/models.py`): база держит указатель, том держит
        содержимое, и отчёт на сорок страниц не должен ехать строкой в SQLite
        второй раз.
        """
        версия = getattr(fill, "version", None)
        self.ctx.emit({"kind": ТЕГ_ЗАКРЫТ, "key": fill.key,
                       "ok": bool(fill.ok),
                       "version": getattr(версия, "n", None),
                       "flags": list(getattr(fill, "flags", ()) or ())})

    def стадия(self, имя: str, состояние: str = "", note: str = "") -> None:
        """Смена стадии сценария `kadai`."""
        self.ctx.emit({"kind": СТАДИЯ, "name": str(имя),
                       "state": str(состояние or ""), "note": str(note or "")})


def _пресет_из(ctx) -> str:
    """Имя пресета из `payload`. Пусто — отказ, а не умолчание.

    Умолчания здесь быть не может: поставщика выбирает человек (§11), и молча
    подставленный означал бы прогон, оплаченный не тем ключом, о котором он
    думал.
    """
    имя = str((ctx.job.payload or {}).get("endpoint") or "").strip()
    if not имя:
        raise ApiError("endpoint_required",
                       "payload.endpoint must name a provider preset", 400,
                       where="body.payload.endpoint")
    return имя


def отменено(ctx, note: str = "") -> dict:
    """Ответ обработчика, остановившегося по просьбе. Форма одна на всех.

    Состояние `cancelled` ставит воркер, увидев `ctx.cancelled()` на конце
    работы (`jobs/child.позвать`); отсюда уезжает только рассказ о том, где
    именно остановились, — он ложится в `job.result`.
    """
    return {CANCELLED_BEFORE: str(note or "")}


