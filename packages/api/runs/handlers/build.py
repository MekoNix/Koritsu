"""
build — собрать DOCX/PDF из текущих значений проекта. Модель не зовётся.

    payload   {"outputs": ["docx", "pdf"], "keys": [...], "name": "отчёт.docx",
               "report": "<id отчёта>"}
    result    {"ok": true, "artifacts": {"docx": "9f2…", "pdf": "1a0…"},
               "preview": "7c4…", "problems": N, "errors": [...]}

`report` — какой отчёт работы собирается. В работе их несколько, у каждого свой
бланк и свои значения; поле читает `JobContext.project`, а не этот обработчик.

**`needs_secret=False`** — единственный из пяти прогонов, кому секрет сервера не
достаётся, и это не экономия. Сборка зовёт LibreOffice, то есть чужую программу
в подпроцессе; всё, что лежит в окружении рядом с ней, достаётся и ей. Ключей
модели здесь не нужно ни одного: значения уже на диске.

**В результате — идентификаторы, а не файлы.** `store_artifact` кладёт собранное
в хранилище артефактов проекта (`Project.put_artifact`), и наружу уезжает по
шестнадцать знаков на выход. Так собранный отчёт скачивается тем же маршрутом,
что и всё прочее содержимое проекта, а `job.result` остаётся указателем, а не
местом, где лежит сорокастраничный документ (`jobs/models.py`).

`ok` означает ровно одно: DOCX собран. Отчёт с тремя замечаниями и одним пустым
тегом — это `ok: true` и файл, который человек откроет и поправит; отказ отдал бы
ему пустоту за уже потраченные на модель деньги (то же правило, что у
`hokoku.build_report`).

**Первая страница остаётся картинкой.** Собрав PDF, сборка кладёт его первую
страницу отдельным артефактом PNG и записывает его у запуска
(`project_runs.preview_artifact_id`). Смысл в слове «остаётся»: список отчётов
работы показывает страницу и назавтра, и после перезагрузки, не запуская
LibreOffice заново, — а рисовать её на лету значило бы либо ждать сборку на
каждой отрисовке списка, либо показывать вместо документа набросок.

Отрисовка не может сорвать сборку: документ уже собран и уже лежит артефактом,
и отказ ради картинки для списка отдал бы человеку ошибку вместо готового файла.
Беда уходит в журнал, а карточка остаётся без превью — то есть в том же
состоянии, в каком была до сборки.
"""
from __future__ import annotations

import orchestrator

from ...errors import ApiError
from ...jobs.registry import BUILD, register
from ...log import беды
from .common import отменено

BUILD_FAILED = "build_failed"
BAD_OUTPUTS = "bad_outputs"

ВЫХОДЫ = ("docx", "pdf")

# Ширина картинки первой страницы. Карточка отчёта показывает её колонкой в
# пару сотен точек, и хранить страницу в полном разрешении значило бы платить
# мегабайтами квоты человека за то, чего на карточке не видно. Высота считается
# по пропорции страницы: обрезать документ по формату карточки нельзя — по
# обрезанной странице отчёт не узнать.
ШИРИНА_ПРЕВЬЮ = 560


def собрать(ctx) -> dict:
    """Значения проекта → проверка → документ → артефакты."""
    payload = ctx.job.payload or {}
    выходы = [str(o).strip().lower() for o in (payload.get("outputs") or ["docx"])]
    if not выходы or any(o not in ВЫХОДЫ for o in выходы):
        raise ApiError(BAD_OUTPUTS,
                       f"payload.outputs must be a non-empty list of: "
                       f"{', '.join(ВЫХОДЫ)}", 400,
                       where="body.payload.outputs")
    ключи = payload.get("keys") or None
    if ключи is not None:
        ключи = [str(k) for k in ключи]

    ctx.progress(0, 1, note="build")
    if ctx.cancelled():
        return отменено(ctx, "build")

    проект = ctx.project
    итог = orchestrator.build(проект, keys=ключи, outputs=выходы,
                              name=str(payload.get("name") or "") or None,
                              store=True)
    отчёт = итог.get("report") or {}
    if не_собралось(отчёт):
        # Беда самой сборки (шаблон подменён, задание не то) приходит полем
        # `error` результата, а не исключением. Наружу — её код и текст: они уже
        # написаны для человека и путей на томе не содержат.
        беда = отчёт.get("error") or {}
        raise ApiError(BUILD_FAILED,
                       str(беда.get("message") or "The report was not built"),
                       422, where="body.payload")

    артефакты = {вид: тело.get("artifact")
                 for вид, тело in (отчёт.get("outputs") or {}).items()
                 if isinstance(тело, dict) and тело.get("artifact")}
    for вид, art in артефакты.items():
        ctx.emit({"kind": "artifact", "output": вид, "artifact": art})

    превью = запомнить_превью(ctx, проект, артефакты.get("pdf"))
    if превью:
        ctx.emit({"kind": "artifact", "output": "preview", "artifact": превью})
    ctx.progress(1, 1, note="build")

    return {"ok": bool(итог.get("ok")), "artifacts": артефакты,
            "preview": превью,
            "problems": len(итог.get("problems") or ()),
            "errors": list(отчёт.get("errors") or ()),
            "unfilled": list(отчёт.get("unfilled") or ())}


def запомнить_превью(ctx, проект, pdf: str | None) -> str:
    """Первая страница PDF — артефактом, её идентификатор — у записи запуска.

    Пусто, если показывать нечего: PDF не просили, отрисовка не удалась или
    задание поставили не из отчёта. Пустое значение здесь законно и означает
    «карточка остаётся с наброском», а не «сборка не удалась» — см. докстроку
    модуля.

    Запись идёт в ту же запись журнала, из которой задание поставлено
    (`payload.report`): превью принадлежит отчёту, а не работе, и работа с двумя
    отчётами иначе показывала бы одну и ту же страницу на обеих карточках.
    """
    if not pdf or not ctx.report:
        return ""
    try:
        картинка = первая_страница(проект.resolve_artifact(pdf))
        art = проект.put_artifact(картинка, name="первая страница")
    except Exception:                                        # noqa: BLE001
        беды.exception("сборка %s: первая страница не нарисовалась", ctx.job_id)
        return ""
    from ...projects.models import ProjectRun                # noqa: PLC0415

    with ctx.session_scope() as s:
        запись = s.get(ProjectRun, ctx.report)
        if запись is None or запись.project_id != ctx.job.project_id:
            # Отчёт снесли, пока шла сборка. Картинка уже на томе и остаётся
            # там: артефакт адресуется содержимым, и уборка работы её заберёт.
            return ""
        запись.preview_artifact_id = art
    return art


def первая_страница(pdf: bytes) -> bytes:
    """Байты PDF → PNG его первой страницы шириной `ШИРИНА_ПРЕВЬЮ`.

    Отдельной функцией, потому что это единственное место службы, где документ
    превращается в картинку, и проверять его надо тестом, а не глазами по
    карточке. Библиотека та же, которой разбираются PDF в материалах: вторая
    рядом с ней означала бы вторую зависимость ради того же самого.
    """
    import pymupdf                                           # noqa: PLC0415

    документ = pymupdf.open(stream=pdf, filetype="pdf")
    try:
        if документ.page_count < 1:
            raise ValueError("в PDF нет ни одной страницы")
        страница = документ.load_page(0)
        масштаб = ШИРИНА_ПРЕВЬЮ / max(страница.rect.width, 1)
        картинка = страница.get_pixmap(matrix=pymupdf.Matrix(масштаб, масштаб),
                                       alpha=False)
        return картинка.tobytes("png")
    finally:
        документ.close()


def не_собралось(отчёт: dict) -> bool:
    """Отличить «собрано с замечаниями» от «не собрано вовсе».

    Отдельной функцией, потому что различие это — договор с `hokoku`, а не наше
    удобство: `ok=False` вместе с заполненным `error` означает, что документа
    нет; `ok=False` без `error` не бывает, но проверять надо оба, иначе первое
    же изменение формы отчёта превратит «нет файла» в «пустой результат».
    """
    return not отчёт.get("ok") and bool(отчёт.get("error"))


def _зарегистрировать() -> None:
    """См. `fill_tag._зарегистрировать` — довод тот же.

    `needs_secret` здесь **не** ставится: см. докстроку модуля.
    """
    register(BUILD)(собрать)


__all__ = ["собрать", "не_собралось", "запомнить_превью", "первая_страница",
           "_зарегистрировать", "BUILD_FAILED", "BAD_OUTPUTS", "ВЫХОДЫ",
           "ШИРИНА_ПРЕВЬЮ"]
