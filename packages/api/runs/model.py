"""
model — где ключ поставщика на минуту становится текстом и как он уезжает в слой.

`endpoint` в `payload` задания — это **имя пресета** `llm` (`deepseek`,
`anthropic`, …), а не идентификатор зарегистрированного endpoint'а. Так решено
владельцем (§11: «поставщика выбирает пользователь из пресетов»), и разница
существенна: реестр `llm` — состояние процесса, а процесс у задания свой и
живёт минуты. Клиенту нечего было бы назвать, кроме имени пресета.

    Что здесь происходит по шагам
    -----------------------------

1. имя пресета проверяется по списку тех, у кого вообще бывает ключ
   (`keys.providers()` — пресеты с `api_key_env`);
2. ключ достаётся `keys.resolve_key` — свой, иначе общий, иначе `None`;
3. `None` — отказ `no_key` **до** того, как модель позвали хоть раз;
4. пресет собирается заново (`llm.presets.make`), ему ставится **свой**
   идентификатор — по заданию, — и **своё** имя переменной с ключом;
5. ключ кладётся в `os.environ` этого процесса и снимается оттуда в `finally`
   вместе с самим endpoint'ом.

    Почему ключ уезжает переменной окружения, а не полем
    ---------------------------------------------------

Потому что другого шва нет: `EndpointSpec.resolve_key()` читает переменную или
файл, и делает это **на каждый запрос**, намеренно — «ключ не кэшируется в
объекте, потому что EndpointSpec попадает в логи, repr и сохранённые
настройки». Положить ключ полем значило бы отменить ровно эту защиту.

Имя переменной своё (`KORITSU_RUN_KEY`), а не `DEEPSEEK_API_KEY` пресета, и это
не мелочь. Во-первых, общий ключ владельца живёт под своим именем
(`KORITSU_PROVIDER_KEY_DEEPSEEK`, `keys.common_key`), и подмена настоящего имени
поставщика означала бы, что ключ одного человека перекрывает общий для всех
остальных в том же процессе. Во-вторых, имя закрытое: чужой код, читающий
`os.environ['DEEPSEEK_API_KEY']` по привычке, здесь ничего не найдёт.

Процесс, в котором всё это происходит, — подпроцесс задания (`jobs/child.py`) с
вычищенным окружением и `needs_secret=True`. Ключ живёт в его памяти и умирает
вместе с ним; наружу — ни в ответ, ни в событие, ни в журнал — не уезжает
ничего, кроме слова `own` или `shared` (`keys.source_of`).
"""
from __future__ import annotations

import contextlib
import os

import llm

from ..errors import ApiError
from ..keys import service as keys
from ..settings import Settings

NO_KEY = "no_key"

# Имя переменной, под которым ключ прогона живёт в памяти подпроцесса.
# Закрытое и одно: два имени означали бы два места, где ключ можно забыть снять.
ИМЯ_КЛЮЧА = "KORITSU_RUN_KEY"


def проверить_пресет(имя: str, *, where: str = "body.payload.endpoint") -> str:
    """Имя пресета из `payload` или внятный отказ `400 unknown_provider`.

    Проверка та же, что у заведения ключа (`keys.check_provider`), и она обязана
    быть той же: список поставщиков, по которому человек заводит ключ, и список,
    по которому он выбирает поставщика для прогона, — один список. Разойдись
    они, и человек заводил бы ключ туда, куда прогон сходить не может.
    """
    return keys.check_provider(имя, where=where)


@contextlib.contextmanager
def endpoint(ctx, имя_пресета: str, *, where: str = "body.payload.endpoint"):
    """Endpoint с ключом этого человека на время задания. → `(id, источник)`.

        with endpoint(ctx, "deepseek") as (ep, откуда):
            fill = orchestrator.fill_tag(ctx.project, key, endpoint=ep)

    `откуда` — `own` или `shared`: чьим ключом заплачено. Слово безопасное и
    полезное — оно ложится в результат задания, и по нему человек понимает, за
    чей счёт был прогон. Самого ключа отсюда не уезжает никуда.

    Отказ `no_key` — `402`, а не `400`: запрос правильный, платить нечем. Он
    приходит **до** первого обращения к модели, потому что после — это уже
    потраченные деньги.
    """
    пресет = проверить_пресет(имя_пресета, where=where)
    settings: Settings = ctx.settings
    # Сессия открывается на один короткий запрос и закрывается: расшифровка
    # ключа — не повод держать транзакцию всё время прогона (`context.py`).
    with ctx.session_scope() as s:
        ключ = keys.resolve_key(settings, s, ctx.job.user_id, пресет)
        источник = keys.source_of(settings, s, ctx.job.user_id, пресет)
    if not ключ:
        raise ApiError(
            NO_KEY,
            f"No key for provider '{пресет}': add your own key or ask for a "
            "plan with the shared one", 402, where=where)

    spec = llm.presets.make(пресет)
    # Свой идентификатор — по заданию: реестр `llm` один на процесс, а в режиме
    # `inline` (тесты, консоль) в одном процессе проходят несколько заданий, и
    # общее имя означало бы, что второе задание работает ключом первого.
    spec.id = f"job-{ctx.job_id}"
    spec.api_key_env = ИМЯ_КЛЮЧА
    # Запасной путь пресета (`~/.config/koritsu/<поставщик>.key`) снимаем: на
    # сервере такого файла быть не должно, а если он там окажется, прогон
    # человека молча поехал бы на чужом ключе.
    spec.api_key_file = None

    прежний = os.environ.get(ИМЯ_КЛЮЧА)
    os.environ[ИМЯ_КЛЮЧА] = ключ
    try:
        llm.register_endpoint(spec)
        yield spec.id, источник
    finally:
        llm.unregister(spec.id)
        if прежний is None:
            os.environ.pop(ИМЯ_КЛЮЧА, None)
        else:                                            # pragma: no cover
            os.environ[ИМЯ_КЛЮЧА] = прежний


__all__ = ["endpoint", "проверить_пресет", "NO_KEY", "ИМЯ_КЛЮЧА"]
