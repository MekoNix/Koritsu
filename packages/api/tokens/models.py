"""
models — одна таблица: `api_tokens`, внешние ключи службы.

Ключ показывается один раз при создании, отзывается в настройках, срок жизни
не ограничен. Отсюда каждое поле ниже, и ни одного лишнего.

**В базе хеш, а не токен.** `sha256` от строки — ровно как у почтовых токенов
(`accounts.models.EmailToken`), и по той же причине: снимок базы,
попавший не туда, не должен раздавать доступ к чужим проектам. Своей соли тут
нет намеренно — токен не пароль человека, а 32 случайных байта, и словарного
перебора у него не бывает; argon2 на каждый запрос стоил бы сотни миллисекунд
там, где нужны микросекунды.

**`prefix` — первые восемь знаков строки после `kor_`**, и он единственное, что
человек увидит в списке своих ключей. Не «удобство»: без него список ключей
выглядит как три имени и три даты, и человек, отзывающий один из трёх,
угадывает. Восемь знаков url-safe base64 — это 48 бит, столкновений на десятке
ключей одного человека не бывает, а на подбор целого токена восьми знаков не
хватает и близко.

**`scopes` — JSON-список, а не строка через запятую и не таблица.** Список
закрыт (`tokens.service.ПРАВА`) и короток, а таблица связи ради четырёх
возможных значений — это join на каждый запрос внешнего клиента.

**`revoked_at`, а не удаление строки.** Отозванный ключ обязан отличаться от
несуществующего: запрос отозванным ключом — это событие безопасности (кто-то
пользуется тем, что человек уже забрал), а запрос выдуманным — просто мусор.
Пока строки нет, они неотличимы.

**`last_used_at` пишется не чаще раза в минуту** (`tokens.service.ОТМЕТКА_НЕ_ЧАЩЕ`).
Отметка на каждый запрос означала бы запись в SQLite на каждое чтение списка
проектов — то самое, от чего у сессий заведено `ПРОДЛЕВАТЬ_НЕ_ЧАЩЕ`.
Точности «когда ключом пользовались последний раз» минуты хватает с запасом.
"""
from __future__ import annotations

import datetime

from sqlalchemy import JSON, DateTime, ForeignKey, String
from sqlalchemy.orm import Mapped, mapped_column

from ..db import Row
from ..ids import ID_LEN

# Длины строк. Числами в одном месте — тот же довод, что у `jobs.models`.
NAME_LEN = 64          # имя ключа: «ноутбук», «CI», «ночной скрипт»
PREFIX_LEN = 8         # столько знаков токена показывается человеку
TOKEN_HASH_LEN = 64    # sha256 в hex

# Приставка строки токена. Не украшение: по ней ключ узнаётся глазами в чужом
# конфиге и, главное, ищется автоматом — сканеры утечек находят брошенные в
# репозиторий ключи именно по устойчивой приставке.
ПРИСТАВКА = "kor_"


class ApiToken(Row):
    """Внешний ключ доступа: чей, как называется, что им можно.

    `id`, `created_at`, `updated_at` — от `Row`. Наружу `created_at`
    показывается как дата выдачи; самой строки токена в этой таблице нет и
    появиться не может — хранится только её хеш.
    """

    __tablename__ = "api_tokens"

    user_id: Mapped[str] = mapped_column(
        String(ID_LEN), ForeignKey("users.id", ondelete="CASCADE"), index=True)

    name: Mapped[str] = mapped_column(String(NAME_LEN))

    # Первые знаки токена — то, по чему человек узнаёт свой ключ в списке.
    prefix: Mapped[str] = mapped_column(String(PREFIX_LEN), index=True)

    token_hash: Mapped[str] = mapped_column(String(TOKEN_HASH_LEN),
                                            unique=True, index=True)

    # Список прав из закрытого набора. Присваивается целиком — SQLAlchemy не
    # следит за правкой списка внутри колонки `JSON` (тот же довод, что у
    # `jobs.models`: `MutableList` мы не включаем).
    scopes: Mapped[list] = mapped_column(JSON, default=list)

    last_used_at: Mapped[datetime.datetime | None] = mapped_column(
        DateTime(timezone=True), default=None)
    revoked_at: Mapped[datetime.datetime | None] = mapped_column(
        DateTime(timezone=True), default=None)

    @property
    def revoked(self) -> bool:
        """Отозван ли ключ. Свойством, а не сравнением по месту: сравнений
        было бы четыре, и одно из них однажды оказалось бы `is None`."""
        return self.revoked_at is not None


__all__ = ["ApiToken", "NAME_LEN", "PREFIX_LEN", "TOKEN_HASH_LEN", "ПРИСТАВКА"]
