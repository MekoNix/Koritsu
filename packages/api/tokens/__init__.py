"""
tokens — внешние ключи доступа: то, чем в службу ходит скрипт, а не человек.

Ключ показывается один раз при создании, отзывается в настройках, срок жизни
не ограничен; права — закрытым списком, 60 запросов в минуту на ключ.

    models.py    таблица `api_tokens`: хеш, приставка, права, отзыв
    service.py   выдача, поиск по хешу, права, лимит запросов
    routes.py    `/api/tokens`: завести, список, отозвать

**Чем ключ отличается от сессии.** Сессия — это человек в браузере: она живёт
30 дней, продлевается, защищена CSRF и Anubis. Ключ — это конфиг на чужой
машине: он живёт вечно, проходит мимо обеих защит и потому обязан уметь то, что
сессии не нужно, — ограничивать себя правами и считать свои запросы. Отсюда обе
особенности, которых у сессии нет: `scopes` и лимит.

**Что берут соседи.** Проверку ключа зовут не отсюда, а из `api.auth` — там
живёт «кто пришёл» для обоих входов сразу. Отсюда берут только имена прав:

    from api.tokens.service import PROJECTS_READ, RUNS_RUN

Зачем разделение: `auth` знает про оба входа и про маршруты, `tokens` — только
про свою таблицу. Если бы проверка жила здесь, подпакет ключей знал бы про
cookie-сессию, а зависимость «cookie или Bearer» оказалась бы в двух местах.

Маршруты отсюда не выставляются: их берёт `routes.collect()` прямо из
`tokens.routes`. Импорт роутера здесь замкнул бы круг — `api.models` тянет
`tokens.models`, то есть этот файл, а роутер тянет зависимости доступа, которые
тянут `api.models` обратно.
"""
