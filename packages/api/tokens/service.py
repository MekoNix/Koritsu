"""
service — жизнь внешнего ключа: выдать, узнать, посчитать, отозвать.

Коды отказа, которые выдаёт этот модуль:

    invalid_token      401  ключа с таким хешем нет
    token_revoked      401  ключ был, его отозвали
    insufficient_scope 403  ключ есть, но этого права у него нет
    rate_limited       429  больше 60 запросов в минуту одним ключом
    unknown_scope      400  в списке прав слово не из закрытого набора
    not_found          404  чужой (или несуществующий) ключ в отзыве

**Строка ключа существует ровно один раз** — в ответе на создание. Дальше её
негде взять: в базе хеш, в журнал она не пишется, в событие безопасности
уезжает только приставка. Это дословное решение владельца §7 («показать один
раз при создании»), и оно же — единственная причина, по которой сервис вообще
возвращает строку наружу отдельным полем, а не кладёт её в карточку ключа:
карточка отдаётся ещё и в списке, и одинаковая форма ответа означала бы, что
однажды список отдал бы ключи.

**Права — закрытый список** (`ПРАВА`). Не «строка на усмотрение клиента»:
неизвестное слово в scope выглядит как право, но не проверяется нигде, и ключ,
выданный с опечаткой `project:write`, тихо не работает — или, хуже, работает,
если однажды проверка станет «есть хоть какое-то право».

**Лимит 60 запросов в минуту на ключ** (§11) считается в памяти процесса,
скользящим окном. Это осознанный размен, и его границы стоит назвать: счётчик
не переживает перезапуск и не общий на два процесса (`api` и второй `uvicorn`
за прокси считают отдельно, то есть настоящий потолок — 60 × число процессов).
База тут была бы честнее и стоила бы записи на каждый запрос внешнего клиента —
ровно то, чего SQLite не любит больше всего. Когда процессов станет много,
лимит переедет на прокси, где ему и место; пока их один, память точнее и
дешевле. Отдельно от этого стоит лимит регистраций по IP (у него база есть):
там счётчик обязан переживать перезапуск, потому что обходится ожиданием.
"""
from __future__ import annotations

import datetime
import hashlib
import secrets
import threading
import time
from collections import deque

from sqlalchemy import select
from sqlalchemy.orm import Session

from ..db import now
from ..errors import ApiError
from .models import ПРИСТАВКА, ApiToken, NAME_LEN, PREFIX_LEN

# ── коды отказа ──────────────────────────────────────────────────────────────

INVALID_TOKEN = "invalid_token"
TOKEN_REVOKED = "token_revoked"
INSUFFICIENT_SCOPE = "insufficient_scope"
RATE_LIMITED = "rate_limited"
UNKNOWN_SCOPE = "unknown_scope"
NOT_FOUND = "not_found"

# ── права ────────────────────────────────────────────────────────────────────
#
# Закрытый список (§11 дословно). Имена с двоеточием — общепринятая форма
# «предмет : что с ним можно», и она читается в конфиге скрипта без словаря.

PROJECTS_READ = "projects:read"
PROJECTS_WRITE = "projects:write"
MATERIALS_WRITE = "materials:write"
RUNS_RUN = "runs:run"

ПРАВА = (PROJECTS_READ, PROJECTS_WRITE, MATERIALS_WRITE, RUNS_RUN)

# `projects:write` подразумевает `projects:read`: ключ, которым можно завести
# проект, но нельзя посмотреть на него, — это не осторожность, а неработающий
# ключ. Обратное неверно, и в этом весь смысл разделения.
СЛЕДУЕТ_ИЗ: dict[str, tuple[str, ...]] = {
    PROJECTS_READ: (PROJECTS_READ, PROJECTS_WRITE),
    PROJECTS_WRITE: (PROJECTS_WRITE,),
    MATERIALS_WRITE: (MATERIALS_WRITE,),
    RUNS_RUN: (RUNS_RUN,),
}

# ── лимит запросов ───────────────────────────────────────────────────────────

ЛИМИТ_В_МИНУТУ = 60
ОКНО_С = 60.0

# Отметка `last_used_at` пишется не чаще раза в минуту — тот же довод, что у
# `accounts.service.ПРОДЛЕВАТЬ_НЕ_ЧАЩЕ`: иначе чтение списка проектов внешним
# клиентом превращается в запись в базу.
ОТМЕТКА_НЕ_ЧАЩЕ = datetime.timedelta(minutes=1)

_окна: dict[str, deque] = {}
_замок = threading.Lock()


def в_пределах(ключ: str, *, лимит: int = ЛИМИТ_В_МИНУТУ,
               сейчас: float | None = None) -> bool:
    """Учесть запрос под этим ключом; `False` — лимит превышен.

    Скользящее окно, а не «сколько за календарную минуту»: календарная минута
    позволяет 120 запросов подряд на её границе, и заметно это ровно тогда,
    когда лимит нужен.

    `ключ` — что считаем. Обычно это `ApiToken.id`, но не только: тем же окном
    считается предпросмотр схем (§12, 30 в минуту на человека, `api/modules/
    diagrams.не_чаще`) — под своей приставкой и со своим `лимит=`. Второй такой
    же счётчик рядом разошёлся бы с этим на первой же правке уборки окон, а
    считают они одно и то же — «сколько раз за последнюю минуту».

    Побочный расход памяти ограничен: очередь одного ключа не длиннее лимита, а
    ключи, которыми минуту не пользовались, выбрасываются здесь же.
    """
    t = time.monotonic() if сейчас is None else сейчас
    with _замок:
        очередь = _окна.get(ключ)
        if очередь is None:
            очередь = _окна[ключ] = deque()
        while очередь and t - очередь[0] > ОКНО_С:
            очередь.popleft()
        # Заодно уборка чужих пустых очередей: без неё словарь растёт на каждый
        # когда-либо предъявленный ключ и не уменьшается никогда.
        if len(_окна) > 1000:
            _подмести(t)
        if len(очередь) >= лимит:
            return False
        очередь.append(t)
        return True


def _подмести(t: float) -> None:
    """Выбросить окна, в которых за минуту не было ни одного запроса.

    Зовётся под уже взятым замком (`в_пределах`), поэтому своего не берёт:
    второй захват нерекурсивного `Lock` — это остановка процесса намертво.
    """
    мёртвые = [k for k, q in _окна.items() if not q or t - q[-1] > ОКНО_С]
    for k in мёртвые:
        _окна.pop(k, None)


def забыть_лимиты() -> None:
    """Очистить счётчики. Нужно тестам: окно живёт в памяти процесса, а тесты
    идут в одном процессе один за другим."""
    with _замок:
        _окна.clear()


# ── строка ключа ─────────────────────────────────────────────────────────────

def новый_токен() -> str:
    """`kor_` и 32 случайных байта в url-safe виде.

    `secrets`, а не `random`: второй предсказуем по нескольким выданным
    значениям, и ключ доступа, выданный им, — это ключ, который подбирается.
    """
    return ПРИСТАВКА + secrets.token_urlsafe(32)


def хеш(токен: str) -> str:
    """sha256 в hex — то, что лежит в базе вместо строки ключа."""
    return hashlib.sha256(токен.encode("utf-8")).hexdigest()


def приставка_для_показа(токен: str) -> str:
    """Первые знаки случайной части — то, по чему человек узнаёт ключ в списке.

    Именно случайной части, а не строки целиком: `kor_` одинаково у всех, и
    показывать его в поле «чем этот ключ отличается от того» бессмысленно.
    """
    return токен[len(ПРИСТАВКА):][:PREFIX_LEN]


# ── права ────────────────────────────────────────────────────────────────────

def проверить_права(сырые: list[str] | None) -> list[str]:
    """Привести список прав к порядку `ПРАВА`, отвергнув незнакомое.

    Порядок нормализуется, а не сохраняется как пришёл: список прав уезжает в
    ответ и в карточку, и два одинаковых по смыслу ключа, различающиеся
    порядком слов, читались бы человеком как разные.
    """
    выбрано = []
    for право in сырые or []:
        слово = (право or "").strip()
        if слово not in ПРАВА:
            raise ApiError(UNKNOWN_SCOPE,
                           f"Unknown scope; allowed: {', '.join(ПРАВА)}", 400,
                           where="body.scopes")
        if слово not in выбрано:
            выбрано.append(слово)
    if not выбрано:
        raise ApiError(UNKNOWN_SCOPE, "At least one scope is required", 400,
                       where="body.scopes")
    return [право for право in ПРАВА if право in выбрано]


def даёт(scopes, нужное: str) -> bool:
    """Даёт ли этот набор прав вот это право (с учётом `СЛЕДУЕТ_ИЗ`)."""
    годные = СЛЕДУЕТ_ИЗ.get(нужное, (нужное,))
    return any(право in годные for право in scopes or ())


# ── таблица ──────────────────────────────────────────────────────────────────

def выдать(s: Session, user_id: str, name: str,
           scopes: list[str]) -> tuple[ApiToken, str]:
    """Завести ключ. Возвращает строку **один раз** — второго раза не будет."""
    имя = (name or "").strip()
    if not имя:
        raise ApiError("invalid_name", "Token name is required", 400,
                       where="body.name")
    строка = новый_токен()
    ключ = ApiToken(user_id=user_id, name=имя[:NAME_LEN],
                    prefix=приставка_для_показа(строка),
                    token_hash=хеш(строка),
                    scopes=проверить_права(scopes))
    s.add(ключ)
    s.flush()
    return ключ, строка


def мои(s: Session, user_id: str) -> list[ApiToken]:
    """Ключи человека, новые сверху. Отозванные остаются в списке: человек,
    отозвавший ключ, должен видеть, что он отозван, а не что он исчез."""
    return list(s.scalars(
        select(ApiToken).where(ApiToken.user_id == user_id)
        .order_by(ApiToken.created_at.desc())))


def найти(s: Session, строка: str) -> ApiToken | None:
    """Ключ по предъявленной строке. `None` — такого ключа нет."""
    if not строка or not строка.startswith(ПРИСТАВКА):
        return None
    return s.scalar(select(ApiToken).where(ApiToken.token_hash == хеш(строка)))


def отозвать(s: Session, user_id: str, token_id: str) -> ApiToken:
    """Отозвать свой ключ. Чужой — `404`, а не `403`: иначе отказ сообщал бы,
    что ключ с таким идентификатором существует (§3, тот же довод, что у
    чужого проекта)."""
    ключ = s.get(ApiToken, token_id)
    if ключ is None or ключ.user_id != user_id:
        raise ApiError(NOT_FOUND, "Token not found", 404, where="path.token_id")
    if ключ.revoked_at is None:
        ключ.revoked_at = now()
    return ключ


def отметить_использование(ключ: ApiToken) -> None:
    """Двинуть `last_used_at`, но не чаще раза в минуту (`ОТМЕТКА_НЕ_ЧАЩЕ`)."""
    from ..accounts.service import в_utc      # время из базы приходит наивным

    было = в_utc(ключ.last_used_at)
    if было is None or now() - было >= ОТМЕТКА_НЕ_ЧАЩЕ:
        ключ.last_used_at = now()


def карточка(ключ: ApiToken) -> dict:
    """Что видно снаружи. Строки ключа тут нет и быть не может."""
    def iso(момент):
        return момент.isoformat() if момент is not None else None

    return {"id": ключ.id, "name": ключ.name, "prefix": ключ.prefix,
            "scopes": list(ключ.scopes or []),
            "created_at": iso(ключ.created_at),
            "last_used_at": iso(ключ.last_used_at),
            "revoked_at": iso(ключ.revoked_at)}


