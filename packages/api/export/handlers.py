"""
handlers — задание `export`: файлы проекта в один zip, zip — артефактом.

    payload   {} — экспортируется проект задания целиком, выбирать нечего
    result    {"artifact": "<16 hex>", "bytes": 12345, "materials": 3,
               "artifacts": 2}

Внутри архива четыре места и ни одного лишнего:

    materials/…     оригиналы загруженных файлов, байт в байт
    artifacts/…     всё, что произвела служба: схемы, отчёты, прошлые выгрузки
    values.json     текущие значения тегов
    blocks.json     текущий список блоков
    reports/<id>/values.json   значения каждого отчёта работы, если их несколько
    solutions/<id>/blocks.json список блоков каждого решения работы
    README.txt      опись: что здесь лежит и что чем было

**Решения выгружаются все, как и отчёты.** Задач в работе столько, сколько их
задали, и у каждой свой список блоков и свой ход стадий; архив с одним из них
был бы архивом части работы.

**Отчёты выгружаются все.** В работе их бывает несколько, у каждого свой бланк
и свои значения, и архив с одним из них был бы архивом части работы. Первый
отчёт при этом остаётся в `values.json` — там, где он лежит на томе, — а
каждому заведённому позже отвечает свой каталог.

**Оригиналы, а не разбор.** Извлечённый текст, картинки страниц и `units.json` —
наше внутреннее дело: они восстанавливаются из оригинала за секунды и меняются
с каждой версией разборщика. Человеку принадлежат файлы, которые он принёс, и
файлы, которые служба ему построила.

**Прошлые выгрузки в новую не попадают.** Иначе каждый следующий экспорт вдвое
больше предыдущего: архив — тоже артефакт проекта, и включённый в себя же он
растёт на весь свой прежний размер. Что было выгрузкой, помнит состояние
проекта (`Project.state(СОСТОЯНИЕ)`), а не догадка по имени: имени у артефакта
нет вовсе, и «zip — значит выгрузка» ошиблось бы на первом же загруженном
человеком архиве.

**Потолок — квота владельца** (`KORITSU_USER_QUOTA_BYTES`). Считается по
исходным байтам, до сжатия: считать после значило бы сначала собрать в памяти
то, что заведомо не влезет. Отказ — `413 export_too_large`, и он честнее
молчаливо обрезанного архива.

**Секрета сервера тут нет** (`needs_secret=False`): архив складывается из того,
что уже лежит на томе, платить некому и расшифровывать нечего.
"""
from __future__ import annotations

import datetime
import io
import json
import os
import zipfile

import materials as _materials

from ..errors import ApiError

# Имя архива. Только для читаемости вызова `put_artifact` и для описи внутри:
# у артефакта имени нет, скачивается он под своим идентификатором.
ARCHIVE_NAME = "export.zip"

EXPORT_TOO_LARGE = "export_too_large"

# Под каким именем проект помнит, какие артефакты были выгрузками.
СОСТОЯНИЕ = "export"

# Каталоги внутри архива.
ПАПКА_МАТЕРИАЛОВ = "materials"
ПАПКА_АРТЕФАКТОВ = "artifacts"

# Под каким каталогом в архиве лежат отдельные отчёты работы.
ПАПКА_ОТЧЁТОВ = "reports"

# Каталог решений внутри архива и имя записи хода стадий в нём. Имя записи то
# же, каким её знает сценарий (`kadai.status.STATE_KEY`), — копией, а не
# импортом: служба про пакет `kadai` не знает и знать не должна.
ПАПКА_РЕШЕНИЙ = "solutions"
СОСТОЯНИЕ_KADAI = "kadai"
ХОД = "kadai.json"

ОПИСЬ = "README.txt"
ЗНАЧЕНИЯ = "values.json"
БЛОКИ = "blocks.json"


def выгрузить(ctx) -> dict:
    """Собрать архив проекта и положить его артефактом. → `{artifact, …}`.

    Шаги считаются в четырёх: материалы, артефакты, значения, упаковка. Не ради
    красоты — большой проект складывается десятками секунд, и задание без
    единого `progress` выглядит на сайте зависшим.

    Отмена спрашивается между шагами, как у `probe`: собранный наполовину архив
    никому не нужен, поэтому отменённый экспорт не кладёт на том ничего.
    """
    проект = ctx.project
    потолок = int(ctx.settings.user_quota_bytes)

    ctx.progress(0, 4, note="materials")
    if ctx.cancelled():
        return {"cancelled": True}
    записи, описи = _материалы(проект)

    ctx.progress(1, 4, note="artifacts")
    if ctx.cancelled():
        return {"cancelled": True}
    свои = set(проект.state(СОСТОЯНИЕ).get("artifacts") or ())
    арт_записи, арт_опись = _артефакты(проект, пропустить=свои)
    записи.extend(арт_записи)

    ctx.progress(2, 4, note="values")
    if ctx.cancelled():
        return {"cancelled": True}
    записи.append((ЗНАЧЕНИЯ, _json_байты(проект.values())))
    записи.append((БЛОКИ, _json_байты(проект.blocks())))
    записи.extend(_отчёты(проект))
    записи.extend(_решения(проект))
    записи.append((ОПИСЬ, _опись(ctx.job.project_id, описи, арт_опись)))

    ctx.progress(3, 4, note="packing")
    сырых = sum(len(данные) for _, данные in записи)
    if сырых > потолок:
        # До сжатия и до памяти: архив, который заведомо не влезет в квоту, не
        # стоит и собирать — а собранный он ещё и лёг бы на том.
        raise ApiError(EXPORT_TOO_LARGE,
                       "The export does not fit the storage quota", 413,
                       where="path.project_id")

    архив = собрать_архив(записи)
    art = проект.put_artifact(архив, name=ARCHIVE_NAME)
    проект.put_state(СОСТОЯНИЕ, {"artifacts": sorted(свои | {art}),
                                 "at": _сейчас()})

    ctx.progress(4, 4, note="done")
    return {"artifact": art, "bytes": len(архив),
            "materials": len(описи), "artifacts": len(арт_опись)}


def _отчёты(проект) -> list:
    """Значения и блоки каждого отчёта работы, кроме лежащего в корне.

    Корневой уже выгружен `values.json`/`blocks.json`, и второй его копией
    архив стал бы вдвое длиннее без единого нового байта содержимого.

    Отчёт без значений тоже попадает в архив пустым файлом: «отчёт есть, но в
    нём ничего не написано» — состояние работы, и молча пропущенный каталог
    читался бы как «такого отчёта не было».
    """
    import orchestrator                                      # noqa: PLC0415

    записи = []
    for имя in проект.reports():
        документ = orchestrator.Project(проект.path, report=имя)
        записи.append((f"{ПАПКА_ОТЧЁТОВ}/{имя}/{ЗНАЧЕНИЯ}",
                       _json_байты(документ.values())))
        записи.append((f"{ПАПКА_ОТЧЁТОВ}/{имя}/{БЛОКИ}",
                       _json_байты(документ.blocks())))
    return записи


def _решения(проект) -> list:
    """Список блоков и ход стадий каждого решения работы.

    Решений в работе несколько, у каждого свой список блоков и своё условие, и
    архив без них уносил бы работу наполовину: `blocks.json` в корне — это
    решение, лежавшее там до появления второго, а не все.

    Ход стадий кладётся рядом с блоками: по нему видно, чем решение кончилось и
    какое условие решали, — а восстановить это из блоков нельзя.
    """
    import orchestrator                                      # noqa: PLC0415

    записи = []
    for имя in проект.solutions():
        решение = orchestrator.Project(проект.path, solution=имя)
        записи.append((f"{ПАПКА_РЕШЕНИЙ}/{имя}/{БЛОКИ}",
                       _json_байты(решение.blocks())))
        записи.append((f"{ПАПКА_РЕШЕНИЙ}/{имя}/{ХОД}",
                       _json_байты(решение.state(СОСТОЯНИЕ_KADAI))))
    return записи


# ── сборка ───────────────────────────────────────────────────────────────────

def собрать_архив(записи) -> bytes:
    """Опись `(имя в архиве, байты)` → zip в памяти.

    В памяти, а не через `Project.pack`: тот кладёт готовый файл в `out/` и
    отдаёт имя, а нам нужны байты для `put_artifact` — то есть путь на томе не
    нужен вовсе, и заводить его ради того, чтобы сразу прочитать обратно, значит
    оставить на томе второй экземпляр архива.

    Имена внутри архива приводятся здесь и только здесь: `..` и косая в имени
    zip'а — это запись мимо каталога распаковки на машине того, кто его открыл
    (zip-slip), и наш архив такого содержать не должен, даже если имя файла
    сочинил человек.
    """
    буфер = io.BytesIO()
    with zipfile.ZipFile(буфер, "w", zipfile.ZIP_DEFLATED) as zf:
        for имя, данные in записи:
            zf.writestr(безопасное_имя(имя), данные)
    return буфер.getvalue()


def безопасное_имя(имя: str) -> str:
    """Имя внутри архива: одна косая допускается, `..` и корень — никогда."""
    куски = [к for к in str(имя).replace("\\", "/").split("/")
             if к not in ("", ".", "..")]
    return "/".join(куски) or "file"


def _материалы(проект) -> tuple[list, list]:
    """Оригиналы материалов → записи архива и строки описи.

    Имя внутри архива — то, под которым файл загружали, а не идентификатор:
    архив открывает человек, и `0f3a…` в нём не говорит ему ничего. Совпавшие
    имена (тот же файл под тем же именем дважды) разводятся идентификатором
    — терять файл из-за совпадения имён нельзя.
    """
    склад = проект.store()
    записи, опись, занятые = [], [], set()
    for материал in склад.list():
        имя = os.path.basename(str(материал.name or материал.id)) or материал.id
        if имя in занятые:
            имя = f"{материал.id}-{имя}"
        занятые.add(имя)
        try:
            данные = склад.blob(материал.id)
        except _materials.MaterialsError:
            # Материал в описи есть, а исходника нет: полуудалённый каталог,
            # прерванная уборка. Пропускаем и говорим об этом в описи — молча
            # отдать архив без файла хуже.
            опись.append((имя, материал.id, -1, материал.kind))
            continue
        записи.append((f"{ПАПКА_МАТЕРИАЛОВ}/{имя}", данные))
        опись.append((имя, материал.id, len(данные), материал.kind))
    return записи, опись


def _артефакты(проект, *, пропустить) -> tuple[list, list]:
    """Артефакты проекта → записи архива и строки описи.

    Расширение угадывается по содержимому тем же, чем его угадывает скачивание
    (`modules/artifacts.вид`): у артефакта нет имени, и два разных ответа на
    вопрос «что это за файл» означали бы `.pdf` в браузере и `.bin` в архиве.
    """
    from ..modules.artifacts import вид                      # noqa: PLC0415

    записи, опись = [], []
    for art in проект.artifacts():
        if art in пропустить:
            continue                       # прошлая выгрузка: см. докстроку
        данные = проект.resolve_artifact(art)
        _тип, расширение = вид(данные)
        имя = f"{art}{расширение}"
        записи.append((f"{ПАПКА_АРТЕФАКТОВ}/{имя}", данные))
        опись.append((имя, art, len(данные)))
    return записи, опись


# ── опись ────────────────────────────────────────────────────────────────────

def _опись(project_id, материалы, артефакты) -> bytes:
    """README.txt внутри архива. По-английски, как всё, что уезжает наружу.

    Текстом, а не JSON: опись читает человек, распаковавший архив, и второй
    машинный файл рядом с `values.json` ему не нужен. Всё машинное в архиве уже
    есть.
    """
    строки = [
        "Koritsu project export",
        f"Project: {project_id or '-'}",
        f"Created: {_сейчас()}",
        "",
        "  materials/    original files as uploaded",
        "  artifacts/    files produced in the project: diagrams, reports",
        "  values.json   current tag values",
        "  blocks.json   current block list",
        "  reports/      tag values of every report of the work",
        "  solutions/    block list and stage state of every solution",
        "",
        "The parsed text of a material is not here: it is rebuilt from the "
        "original.",
        "",
        f"Materials ({len(материалы)}):",
    ]
    for имя, mid, размер, вид_ in материалы:
        размер_ = "missing" if размер < 0 else f"{размер} bytes"
        строки.append(f"  {имя}  [{вид_}, {размер_}, id {mid}]")
    строки.append("")
    строки.append(f"Artifacts ({len(артефакты)}):")
    for имя, _art, размер in артефакты:
        строки.append(f"  {имя}  [{размер} bytes]")
    строки.append("")
    return "\n".join(строки).encode("utf-8")


def _json_байты(что) -> bytes:
    """JSON для архива: с отступами и без экранирования кириллицы.

    С отступами намеренно: файл в архиве открывают глазами, а однострочный JSON
    на десять килобайт глазами не открывается.
    """
    return json.dumps(что, ensure_ascii=False, indent=2,
                      default=str).encode("utf-8")


def _сейчас() -> str:
    return datetime.datetime.now().isoformat(timespec="seconds")


def _зарегистрировать() -> None:
    """Поставить обработчик в реестр. Зовётся из `registry.load_handlers`.

    Функцией, а не декоратором на уровне модуля, — довод тот же, что в
    `jobs/probe.py` и `materials/jobs.py`: декоратор случается на импорте, то
    есть один раз на процесс, и тест, почистивший реестр, обратно его уже не
    получит.
    """
    from ..jobs.registry import EXPORT, register              # noqa: PLC0415

    register(EXPORT, needs_project=True, needs_secret=False)(выгрузить)


