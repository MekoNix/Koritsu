"""
materials — приём и выдача материалов проекта через HTTP.

Предметной работы здесь нет: всё, что умеет материал, умеет пакет `materials`
(разбор, карточка, куски с якорями, адресация по sha256). Тут — только то, чего
у него нет и быть не должно: **кто спрашивает, сколько ему можно и в каком
процессе считать чужой файл**.

Три правила этого подпакета, и все три — из решений владельца.

1. **Лимит проверяется до чтения в память** (10 МБ на файл). Сначала
   `Content-Length`, потом счётчик на потоке тела: обрыв случается на первом
   лишнем килобайте, а не после того, как файл целиком лёг в память. Поэтому
   маршрут загрузки берёт `Request`, а не `UploadFile`: с `UploadFile` форму
   разбирает FastAPI до входа в обработчик, и «до чтения» становится «после».
2. **Чужой файл разбирается в подпроцессе** («разборщик чужих файлов в
   подпроцессе» с таймаутом и лимитом памяти). С 2.0.0a5.1 этот подпроцесс —
   подпроцесс **задания** (`jobs.py`, вид `parse`): разбор уехал в очередь
   целиком, и синхронного пути не осталось. Подробности падения наружу не
   уезжают: `parse_failed` в `error` задания и постоянный текст, а исключение с
   трассировкой — в журнал бед. Отдельного модуля со своим подпроцессом у
   разбора больше нет (`parsing.py` удалён в 2.0.0a5.2): его никто не
   звал, а второй подпроцесс внутри первого — две бухгалтерии лимитов вместо
   одной защиты.
3. **Наружу — идентификаторы, а не пути** (`ids.py`). Карточка материала
   несёт `id`, `name`, `kind`, `bytes`, `unit`/`units`; ни `root`, ни
   `source.pdf`, ни каталога проекта в ответе нет. Имя файла из запроса —
   только для карточки и заголовка скачивания, путём оно не становится нигде
   (`upload.имя_файла`).

Значения перечислимых полей карточки — коды по-английски, и приходят они прямо
из пакета `materials`, а не переводятся на границе: `kind` — `text`, `pdf`,
`docx`, `image`, `unknown`; `unit` —
`line`, `page`, `paragraph`; `lang` — `cyrillic`, `latin`, `mixed`. Русскими
остаются `notes` и `anchor`: первое человек читает в карточке, второе уезжает
ссылкой в готовый отчёт.

    Коды ошибок, которые выдаёт этот подпакет

    file_too_large    413  файл больше `settings.file_max_bytes`
    quota_exceeded    413  владельцу проекта не хватает `user_quota_bytes`
    unsupported_type  415  `materials.supported` за такой файл не берётся
    parse_failed      422  разборщик упал или не уложился в таймаут
                           (в `error` задания `parse`, а не в ответе загрузки)
    no_file           400  в multipart нет поля `file`
    invalid_id        400  идентификатор материала не 16 hex
    not_found         404  нет такого проекта/материала — или он не наш
    forbidden         403  участник есть, роли мало (нужен `editor`)
    not_ready         503  пакет проектов ещё не собран

    Состав

    deps.py     единственная дверь к соседям: кто пришёл, проект и его роль
    upload.py   приём multipart с обрывом по размеру, имя файла без пути
    jobs.py     обработчик задания `parse`: принятые байты → материал
    service.py  склейка: хранилище проекта, кэш по хешу, карточка, удаление
    routes.py   маршруты `/api/projects/{id}/materials`

Своих таблиц у подпакета нет и не нужно: материал адресуется хешем содержимого
и живёт файлом в каталоге проекта (`orchestrator.Project.store`). Строка в базе
была бы вторым списком материалов, и разошёлся бы он на первом же прерванном
разборе.
"""
