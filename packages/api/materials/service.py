"""
service — склейка: хранилище проекта, кэш по хешу, квота, карточка наружу.

Здесь нет ни разбора (он в обработчике задания, `jobs.py`), ни доступа (он в
`deps`), ни HTTP (он в `routes`). Здесь — три решения, которые не помещаются ни
туда, ни сюда.

**Хранилище берётся у оркестратора, а не собирается из строк.** Каталог
материалов — `orchestrator.Project(dir).store()`, потому что раскладка проекта
(`materials/`, `artifacts/`, `values/`) принадлежит оркестратору. Склей мы путь
сами, служба и прогон разошлись бы каталогами при первом переименовании, и
загруженный через API файл просто не увидел бы отчёт.

**Кэш разбора — по содержимому** («извлечённый текст хранится по
хешу файла»). `materials.Store` уже адресует материал первыми 16 знаками sha256,
и повторное добавление того же файла возвращает существующий без разбора. Мы
идём на шаг раньше: считаем идентификатор в этом процессе и, если материал уже
лежит, **не запускаем подпроцесс вовсе**. Разница видна на загрузке той же
того же файла второй раз — секунды против нуля.

**Квота проверяется после кэша, а не до.** Тот же файл второй раз не занимает ни
байта, и отказывать по квоте за нулевую прибавку значило бы наказывать за
повторную загрузку. Новый файл — прибавка настоящая, и там квота считается
(250 МБ на владельца, `bytes_used` от пакета проектов).

**Разбор идёт через очередь, и приём разрезан надвое** (2.0.0a5.1). `принять`
делает то, что обязано случиться внутри HTTP-запроса, — проверить тип, узнать
кэш по содержимому, посчитать квоту и положить **сырые** байты в `incoming/`
каталога проекта. Всё остальное делает задание `parse` (`jobs.py`): оно и
разбирает, и убирает за собой. Синхронного пути больше нет: путь один, через
очередь — так проще, и код один.

**Ключ сырого файла — тот же идентификатор материала**, то есть 16 hex от
sha256 содержимого. Не путь: `payload` задания уезжает в базу и в JSON наружу
(`jobs.карточка` отдаёт его клиенту), и путь на томе в нём означал бы ровно то,
что наружу отдавать нельзя. Обработчик складывает путь сам, из каталога своего проекта и
этого ключа, — и проверяет форму ключа перед тем, как класть его в `join`.
"""
from __future__ import annotations

import os
import re
import shutil
import time

import materials
import orchestrator
from sqlalchemy.orm import Session

from ..errors import ApiError
from ..settings import Settings
from .deps import Проект, bytes_used
from ..projects.service import dir_for

QUOTA_EXCEEDED = "quota_exceeded"
UNSUPPORTED_TYPE = "unsupported_type"
# Разборщик не справился с файлом. Код живёт здесь, рядом с приёмом байтов и
# уборкой недоразобранного, а не у обработчика задания: обработчиков у разбора
# со временем может стать двое (очередь и, скажем, консольная команда), а слово
# «файл не разобрался» у службы одно. До 2.0.0a5.2 он лежал в `parsing.py`,
# который удалён вместе со вторым подпроцессом.
PARSE_FAILED = "parse_failed"

# Длина идентификатора материала берётся у самого пакета, а не пишется числом:
# `materials.material_id` — единственный, кто знает, сколько знаков sha256 он
# оставляет, и переезд с 16 на 20 не должен требовать правки здесь.
ДЛИНА_ИД = len(materials.material_id(b""))

# Форма идентификатора материала. Одна на модуль: её спрашивает маршрут (проверка
# пути) и она же ищет ссылки на материалы в значениях тегов. Второе описание той
# же формы разошлось бы с первым на первом же изменении `ID_LEN` в `materials`.
ИД_RE = re.compile(r"\A[0-9a-f]{%d}\Z" % ДЛИНА_ИД)


def открыть(проект: Проект) -> orchestrator.Project:
    """Каталог проекта как `orchestrator.Project`.

    Каталог создаётся, если его ещё нет: `orchestrator.Project` отказывается
    открывать несуществующий каталог, а проект, заведённый строкой в базе,
    каталогом обзаводится при первой работе с файлами. Раскладку внутри при этом
    по-прежнему знает только оркестратор.
    """
    os.makedirs(проект.dir, exist_ok=True)
    return orchestrator.Project(проект.dir)


def хранилище(проект: Проект) -> materials.Store:
    """Хранилище материалов этого проекта."""
    return открыть(проект).store()


def карточка(материал) -> dict:
    """Материал → то, что видит клиент. Путей здесь нет и быть не может.

    `unit` и `units` — «чем и сколько нумеруется содержимое»: у PDF `page`, у
    Word `paragraph`, у текста `line`. Одно поле вместо `pages` и `lines` по той
    же причине, по которой у `Material` одна пара полей: три вида счётчиков в
    ответе означали бы три ветки в интерфейсе там, где смысл один.

    Значения `kind`, `unit` и `lang` перекладываются как есть: коды приходят
    английскими из самого пакета `materials` (там же лежат и русские подписи,
    которыми пишутся карточка и якорь). Перевода на границе тут нет намеренно —
    вторая таблица кодов разошлась бы с первой на первом же новом виде файла.
    """
    d = материал if isinstance(материал, dict) else материал.to_dict()
    return {
        "id": d["id"],
        "name": d.get("name", ""),
        "kind": d.get("kind", ""),
        "bytes": int(d.get("size", 0)),
        "unit": d.get("unit", ""),
        "units": int(d.get("count", 0)),
        "lang": d.get("lang", ""),
        "added": d.get("added", ""),
        "notes": list(d.get("notes", ()) or ()),
        "children": list(d.get("children", ()) or ()),
    }


def проверить_тип(имя: str, данные: bytes) -> None:
    """Возьмётся ли разбор за такой файл. Отказ — `415 unsupported_type`.

    Спрашиваем у `materials.supported`, а не у своего списка расширений: второй
    список разошёлся бы с первым на первом же добавленном туда `.f90`, и человек
    получал бы отказ на файл, который пакет отлично читает.
    """
    if not materials.supported(имя, данные):
        raise ApiError(UNSUPPORTED_TYPE,
                       "This file type is not supported", 415, where="body.file")


def проверить_квоту(s: Session, settings: Settings, owner_id: str,
                    прибавка: int) -> None:
    """Влезет ли прибавка в квоту владельца. Отказ — `413 quota_exceeded`.

    Считает `projects` (`bytes_used` обходит каталоги владельца), а решает эта
    строка: держать порог в двух местах — верный способ развести настройку и
    проверку.

    **Порог берётся у плана владельца, а не из одной настройки на всех**
    (справочник планов): до него `pro` и `free` упирались в одно и то же
    число, а карточка в админке показывала личный лимит, которого проверка не
    видела. Считает его `runs.limits.квота_человека` — та же дверь, за которой
    личный лимит старше плана. Владельца, которого в базе нет, здесь быть не
    может (проект без владельца не заводится), но если он всё же исчез, отбор
    считается по `free`: пропускать файл в никуда хуже, чем отказать.
    """
    from ..accounts.models import User                          # noqa: PLC0415
    from ..runs.limits import квота_человека                    # noqa: PLC0415

    владелец = s.get(User, owner_id)
    потолок = (квота_человека(settings, владелец) if владелец is not None
               else int(settings.user_quota_bytes))
    if bytes_used(s, settings, owner_id) + прибавка > потолок:
        raise ApiError(QUOTA_EXCEEDED, "Storage quota exceeded", 413,
                       where="body.file")


def есть_материал(склад: materials.Store, mid: str) -> bool:
    """Лежит ли такой материал в хранилище уже разобранным.

    Хранилищем, а не каталогом проекта: раскладку внутри проекта знает
    оркестратор (`Project.store()`), и складывать путь к `materials/` здесь
    значило бы завести второе такое знание — то самое, которое разойдётся с
    первым при первом переименовании.
    """
    try:
        склад.get(проверить_форму_ид(mid))
        return True
    except materials.MaterialsError:
        return False


def принять(s: Session, settings: Settings, проект: Проект, имя: str,
            данные: bytes) -> tuple[str, bool]:
    """Принять файл в проект **не разбирая**. → `(ключ, уже ли он разобран)`.

    Порядок шагов — он же порядок отказов, и он не случаен: сначала бесплатное
    (тип по расширению и первым байтам), потом бесплатное же (тот же файл уже
    есть?), и только потом дорогое — обход тома ради квоты и запись на том.

    Второй элемент — «уже разобран»: у такого файла нет ни прибавки к квоте, ни
    сырых байтов в `incoming/`, и задание `parse` для него кончится за один
    поход в хранилище. Задание при этом ставится всё равно: два кода ответа на
    одну кнопку означали бы две ветки в интерфейсе там, где для человека
    случилось одно и то же — «файл в проекте».

    Класть **не разобрав** приходится потому, что разбор уехал в очередь, а
    байты запроса живут ровно столько, сколько живёт запрос. Хранилище
    материалов «положить, не разбирая» не умеет и уметь не должно: материал без
    разбора — это материал без `meta.json`, то есть ровно то, что `Store.list`
    обязан считать мусором. Поэтому сырое лежит рядом, в своём каталоге, и
    материалом становится только у обработчика.
    """
    проверить_тип(имя, данные)
    mid = materials.material_id(данные)
    if есть_материал(хранилище(проект), mid):
        return mid, True                         # тот же файл — та же работа

    проверить_квоту(s, settings, проект.owner_id, len(данные))
    положить_сырой(проект.dir, mid, данные)
    return mid, False


# ── сырые байты до разбора ───────────────────────────────────────────────────

# Каталог сырых файлов внутри каталога проекта. Внутри проекта, а не в общем
# `tmp` тома, по двум причинам: байты уже принадлежат проекту (и считаются в
# квоту его владельца, как всё остальное там же), и задание находит их по
# одному лишь `project_id`, без единого пути в `payload`.
ВХОДЯЩИЕ = "incoming"


def проверить_форму_ид(mid: str) -> str:
    """Ключ сырого файла или беда. Форма проверяется **до** любого `join`.

    Ключ приходит из `payload` задания, то есть из базы, — но написали его туда
    мы сами, и проверка здесь стоит ровно на тот случай, когда однажды напишет
    кто-то другой. `..` в имени, попавший в `os.path.join`, — это чтение и
    запись где угодно на томе, и ловить его надо на входе, а не внутри.
    """
    if not ИД_RE.match(str(mid or "")):
        raise materials.MaterialsError(
            f"{mid!r} — не идентификатор материала")
    return str(mid)


def каталог_входящих(каталог_проекта: str) -> str:
    """Где лежат принятые, но ещё не разобранные байты этого проекта."""
    return os.path.join(каталог_проекта, ВХОДЯЩИЕ)


def положить_сырой(каталог_проекта: str, mid: str, данные: bytes) -> str:
    """Записать сырые байты под их ключом. → путь (наружу он не уезжает).

    Повторная запись тех же байтов молчит: два человека, загрузившие одну и ту
    же книгу одновременно, поставят два задания, и второе увидит материал
    уже разобранным — а не беду «файл занят».
    """
    папка = каталог_входящих(каталог_проекта)
    os.makedirs(папка, exist_ok=True)
    путь = os.path.join(папка, проверить_форму_ид(mid))
    with open(путь, "wb") as f:
        f.write(данные)
    return путь


def сырой(каталог_проекта: str, mid: str) -> str | None:
    """Путь к принятым байтам или `None`, если их нет (уже разобраны, убраны)."""
    путь = os.path.join(каталог_входящих(каталог_проекта),
                        проверить_форму_ид(mid))
    return путь if os.path.isfile(путь) else None


def убрать_сырой(каталог_проекта: str, mid: str) -> None:
    """Снести принятые байты. Зовётся при любом исходе разбора.

    При любом — включая упавший: исходник материала кладёт на том сам
    `Store.add`, и сырая копия после разбора занимает вторые те же байты в
    квоте владельца, а после беды — те же байты ни за что.
    """
    путь = сырой(каталог_проекта, mid)
    if путь is not None:
        try:
            os.remove(путь)
        except OSError:
            pass                       # чужая рука убрала раньше — не беда


def убрать_забытые(s: Session, settings: Settings, *,
                   старше_с: float) -> list[str]:
    """Снести сырые байты, за которыми никто не пришёл. → `[project_id/ключ]`.

    Уборщик `incoming/` живёт в часовой уборке воркера
    (`jobs.worker.Worker.уборка`).

    Забытый сырой файл заводится тремя путями, и все три законные: загрузка
    приняла байты, а постановка задания отказала (лимит, корзина, роль) и
    сессия откатилась; воркер убили между приёмом и разбором; задание сняли до
    захвата. Оставленные байты невидимы: в описи материалов их нет, а в квоту
    владельца они считаются — то есть человек платит местом за файл, которого
    ему не показывают.

    Два условия, и оба обязательны:

    * **нет живого задания `parse` на этот ключ** (`jobs.service.в_работе`).
      Ждущее в очереди задание может простоять дольше любого срока, если очередь
      занята, и снести его файл значило бы устроить `parse_failed` работе,
      которая ещё даже не начиналась;
    * **файл старше `старше_с`** — того же `job_timeout_s`, по которому воркер
      признаёт задание потерянным. Более короткий срок отбирал бы байты у
      разбора, который как раз идёт (его задание живое, но между приёмом и
      постановкой есть щель); более длинный — держал бы мусор дольше, чем живёт
      самое долгое задание службы.

    Порядок «сначала живые задания, потом файлы» — а не наоборот: список заданий
    читается один раз на проект, а файлов в `incoming/` бывает много.
    """
    from ..projects.models import Project                     # noqa: PLC0415
    from ..jobs import service as задания                     # noqa: PLC0415
    from .jobs import КЛЮЧ                                     # noqa: PLC0415
    from sqlalchemy import select                              # noqa: PLC0415

    порог = time.time() - float(старше_с)
    убрано: list[str] = []
    for p in s.scalars(select(Project)):
        папка = каталог_входящих(dir_for(settings, p.owner_id, p.id))
        try:
            имена = os.listdir(папка)
        except OSError:
            continue                       # каталога нет — и убирать нечего
        if not имена:
            continue
        ждут = {str((j.payload or {}).get(КЛЮЧ) or "")
                for j in задания.в_работе(s, p.id, kind="parse")}
        for имя in имена:
            if имя in ждут:
                continue
            путь = os.path.join(папка, имя)
            try:
                if not os.path.isfile(путь) or os.path.getmtime(путь) > порог:
                    continue
                os.remove(путь)
            except OSError:
                continue                   # чужая рука убрала раньше — не беда
            убрано.append(f"{p.id}/{имя}")
    return убрано


def убрать_недоразобранное(склад: materials.Store, mid: str) -> None:
    """Снести каталог материала, у которого нет `meta.json`.

    Разбор мог успеть положить исходник и умереть до `meta.json` — такой
    полуматериал невидим для `Store.list`, но байты на томе занимает и в квоту
    владельцу попадает.

    Проверка «нет meta.json» важна: если материал всё-таки собрался (а упал,
    скажем, вывод), сносить его нельзя — это уже полноценный материал, а не
    мусор.
    """
    папка = os.path.join(склад.root, mid)
    if os.path.isdir(папка) and not os.path.isfile(
            os.path.join(папка, "meta.json")):
        shutil.rmtree(папка, ignore_errors=True)


def ссылки_на_материалы(значения) -> set[str]:
    """Идентификаторы материалов, на которые ссылаются значения тегов проекта.

    Обход всего дерева значений, а не одного поля: ссылка живёт в `artifact`
    (`image`, `diagram` — см. `hokoku.wire`), но лежать это поле может на любой
    глубине — внутри `blocks`, внутри вложенного блока. Плюс к `artifact`
    считаются ссылкой любые строки формы идентификатора: поле с байтами
    когда-нибудь заведут второе, и цена ошибки здесь несимметрична — лишняя
    найденная ссылка оставляет на томе картинку, пропущенная **уносит
    картинку из уже собранного отчёта**.
    """
    найдено: set[str] = set()

    def обойти(узел, ключ=""):
        if isinstance(узел, dict):
            for k, v in узел.items():
                обойти(v, str(k))
        elif isinstance(узел, list):
            for v in узел:
                обойти(v, ключ)
        elif isinstance(узел, str) and (ключ == "artifact" or ИД_RE.match(узел)):
            найдено.add(узел)

    обойти(значения)
    return найдено


def удалить(проект: Проект, material_id: str) -> dict:
    """Убрать материал с тома вместе с его производными. Нет такого — `404`
    (переводит маршрут). → `{"removed": [...], "kept": [...]}`.

    Производные — картинки, вынутые со страниц PDF (`material.children`).
    Они уходят вместе с родителем: иначе удалённый PDF оставляет на томе
    полсотни картинок, которых человек в описи уже не видит, а квота
    считает.

    **Ссылки проверяются здесь, а не в `materials`.** Пакет материалов про
    проект ничего не знает — ни про значения тегов, ни про собранные отчёты, — и
    заводить в нём это знание значило бы связать хранилище файлов с
    оркестратором. Поэтому список «этих не трогать» считаем мы и передаём
    хранилищу (`Store.remove(..., keep=...)`), а раскладку каталогов по-прежнему
    знает только оно.

    Ребёнок, на которого ссылается значение тега, остаётся и называется в
    `kept`: молча унести картинку из уже собранного отчёта хуже, чем оставить на
    томе лишний файл, — второе видно в квоте, первое не видно нигде.
    """
    п = открыть(проект)
    склад = п.store()
    материал = склад.get(material_id)
    занятые = ссылки_на_материалы(п.values())
    убрано = склад.remove(material_id, keep=[c for c in материал.children if c in занятые])
    return {"removed": убрано,
            "kept": [c for c in материал.children if c not in убрано]}


