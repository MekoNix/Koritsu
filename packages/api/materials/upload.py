"""
upload — приём multipart с обрывом по размеру и имя файла, которое не путь.

**Почему обработчик берёт `Request`, а не `UploadFile`.** С `UploadFile` форму
разбирает FastAPI до входа в обработчик: к первой нашей строке файл уже принят
целиком (в память до мегабайта, дальше во временный файл на томе). Проверка
размера в такой точке — не заслон, а отчёт о том, что заслон опоздал: 100-мега
байтный файл при лимите в 10 успевает лечь на диск. Поэтому тело считается
здесь, на потоке: счётчик стоит на `receive`, и первый килобайт сверх лимита
рвёт приём.

Проверок размера две, и обе нужны.

* `Content-Length` — самая дешёвая: отказ до единого прочитанного байта.
  Сравнивается с лимитом плюс небольшой запас, потому что длина тела включает
  разделители multipart и заголовки части, а лимит владельца — про файл (§2, 10
  МБ). Без запаса файл ровно в лимит отвергался бы за чужие сто байт.
* счётчик на потоке — на случай, когда `Content-Length` не прислали
  (`Transfer-Encoding: chunked`) или прислали неправду.

**Имя файла из запроса — не путь, никогда.** Оно приходит от клиента, значит в
нём бывает `../../etc/passwd`, `C:\\Windows\\...`, перевод строки (подделка
записи в журнале) и нулевой байт. `имя_файла` оставляет от него последний
сегмент и печатные знаки — и используется результат ровно в двух местах:
карточка материала и заголовок скачивания. Путь на томе строит хранилище, и
строит он его из sha256 содержимого (`materials.material_id`), а не из имени.
"""
from __future__ import annotations

import os
import re
import unicodedata
from urllib.parse import quote

from fastapi import Request

from ..errors import ApiError

# Коды этого модуля (перечислены и в докстроке пакета).
FILE_TOO_LARGE = "file_too_large"
NO_FILE = "no_file"

ПОЛЕ = "file"

# Запас на разделители multipart и заголовки части. Восемь килобайт — с большим
# запасом: сама часть несёт `Content-Disposition` с именем файла и `Content-Type`,
# и даже очень длинное имя в это укладывается.
ЗАПАС_MULTIPART = 8 * 1024

# Сколько знаков оставляем от имени. Не про безопасность (её делает срез пути), а
# про то, что имя уезжает в карточку и в заголовок ответа: имя на четыре тысячи
# знаков ломает и то и другое.
ИМЯ_МАКС = 120

ИМЯ_ПО_УМОЛЧАНИЮ = "file"

# Что вырезаем из имени: управляющие знаки (включая перевод строки — им
# подделывают запись в журнале) и разделители путей обеих систем.
_МУСОР = re.compile(r"[\x00-\x1f\x7f/\\]+")


class _Превышение(Exception):
    """Тело оказалось длиннее позволенного. Не уезжает наружу: обработчик
    переводит её в `413 file_too_large`."""


def имя_файла(сырое: str | None) -> str:
    """Имя из запроса → имя, годное для карточки. Путём не становится нигде.

    Расширение сохраняется намеренно: по нему `materials` выбирает разбор
    (`.pdf` — постранично, `.docx` — по абзацам, `.py` — по строкам). Обрезка
    длины поэтому режет основу, а не хвост: «очень длинное имя.pdf» обязано
    остаться pdf'ом.
    """
    имя = unicodedata.normalize("NFC", (сырое or "").strip())
    # Последний сегмент по обоим разделителям сразу: `a/b\c.txt` — это `c.txt`,
    # и разбирать, чья это система, незачем.
    имя = _МУСОР.sub(" ", имя).strip()
    имя = re.sub(r"\s+", " ", имя)
    # Ведущие точки убираем: `.htaccess` и `..` в имени — приглашение обращаться
    # с ним как с путём, а он не путь.
    имя = имя.lstrip(". ")
    if not имя:
        return ИМЯ_ПО_УМОЛЧАНИЮ
    основа, расширение = os.path.splitext(имя)
    расширение = расширение[:16]
    основа = основа[:max(1, ИМЯ_МАКС - len(расширение))]
    return (основа + расширение) or ИМЯ_ПО_УМОЛЧАНИЮ


def заголовок_имени(имя: str) -> str:
    """Значение `Content-Disposition` для скачивания оригинала.

    Две формы в одном заголовке — так велит RFC 6266: `filename=` из одних
    латинских знаков для старых клиентов и `filename*=UTF-8''…` для всех
    остальных. Русское имя без второй формы приезжает в браузер крокозябрами, а
    без первой — старый клиент не видит имени вовсе.
    """
    latin = "".join(з if 32 <= ord(з) < 127 and з not in '"\\' else "_" for з in имя)
    latin = latin.strip() or ИМЯ_ПО_УМОЛЧАНИЮ
    return f'attachment; filename="{latin}"; filename*=UTF-8\'\'{quote(имя)}'


def проверить_длину(request: Request, предел: int) -> None:
    """Отказать по `Content-Length` — до единого прочитанного байта."""
    сырое = request.headers.get("content-length")
    if not сырое:
        return                       # длины не прислали: поймает счётчик ниже
    try:
        длина = int(сырое)
    except ValueError:
        return                       # мусор в длине — тоже дело счётчика
    if длина > предел + ЗАПАС_MULTIPART:
        raise ApiError(FILE_TOO_LARGE,
                       f"File exceeds the {предел} byte limit", 413,
                       where=f"body.{ПОЛЕ}")


async def принять_файл(request: Request, предел: int) -> tuple[str, bytes]:
    """Разобрать multipart и вернуть `(имя, байты)`. Рвёт приём на превышении.

    Счётчик ставится на `receive` нового `Request` поверх той же области видимости
    (`scope`) и того же источника: разборщик multipart читает тело через него,
    поэтому обрыв случается внутри разбора, а не после него. Прочитанным сверх
    лимита оказывается ровно один кусок потока (около 64 КБ), а не файл.
    """
    проверить_длину(request, предел)

    прочитано = 0

    async def считающий_receive():
        nonlocal прочитано
        сообщение = await request.receive()
        if сообщение.get("type") == "http.request":
            прочитано += len(сообщение.get("body", b"") or b"")
            if прочитано > предел + ЗАПАС_MULTIPART:
                raise _Превышение
        return сообщение

    поток = Request(request.scope, receive=считающий_receive)
    try:
        # `max_files=1` и `max_fields=4`: маршрут принимает один файл, и запрос
        # с тысячей полей — это не наш клиент, а попытка занять память
        # разборщика. `max_part_size` ограничивает только текстовые поля (файл
        # уходит во временный файл мимо этой проверки) — размер файла держит
        # счётчик выше.
        форма = await поток.form(max_files=1, max_fields=4,
                                 max_part_size=64 * 1024)
    except _Превышение:
        raise ApiError(FILE_TOO_LARGE,
                       f"File exceeds the {предел} byte limit", 413,
                       where=f"body.{ПОЛЕ}") from None
    except Exception:                                        # noqa: BLE001
        # Всё остальное — кривой multipart: нет границы, оборвано на середине.
        # Наружу уезжает форма запроса, а не текст исключения (§3).
        raise ApiError(NO_FILE, f"Multipart field '{ПОЛЕ}' with a file is required",
                       400, where=f"body.{ПОЛЕ}") from None

    try:
        часть = форма.get(ПОЛЕ)
        if часть is None or not hasattr(часть, "read"):
            raise ApiError(NO_FILE,
                           f"Multipart field '{ПОЛЕ}' with a file is required",
                           400, where=f"body.{ПОЛЕ}")
        данные = await часть.read()
        if len(данные) > предел:
            # Файл уложился в тело (заголовки заняли меньше запаса), но сам
            # длиннее лимита. Отдельная проверка, потому что запас выше — про
            # multipart, а лимит владельца — про файл.
            raise ApiError(FILE_TOO_LARGE,
                           f"File exceeds the {предел} byte limit", 413,
                           where=f"body.{ПОЛЕ}")
        if not данные:
            raise ApiError(NO_FILE, "Uploaded file is empty", 400,
                           where=f"body.{ПОЛЕ}")
        return имя_файла(getattr(часть, "filename", "")), данные
    finally:
        await форма.close()


