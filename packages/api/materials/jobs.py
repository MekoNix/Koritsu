"""
jobs — обработчик задания `parse`: принятые байты становятся материалом.

Решение владельца §11: «разбор загруженного файла переезжает из синхронной
загрузки» в очередь, и синхронного пути больше нет вовсе. Разрез проходит по
запросу: `POST …/materials` делает то, что обязано случиться, пока человек
ждёт ответа (тип, кэш по содержимому, квота, байты на том), и отвечает `202`;
всё, что стоит секунд, — здесь.

    Почему прямой `Store.add`, а не второй подпроцесс
    ------------------------------------------------

Разбор чужого файла обязан идти в подпроцессе с таймаутом, потолком памяти и
вычищенным окружением (§3). **Этот обработчик уже исполняется в таком
подпроцессе**: воркер запускает задание через `jobs/child.py` — тот же
`api/subproc`, тот же `RLIMIT_AS` (`KORITSU_JOB_MEMORY_MB`), тот же таймаут
(`KORITSU_JOB_TIMEOUT_S`), то же вычищенное окружение, и вдобавок `parse`
объявлен `needs_secret=False`, то есть секрет сервера сюда не приезжает вовсе.

Второй подпроцесс внутри первого дал бы не вторую защиту, а вторую бухгалтерию:
два потолка памяти (внутренний меньше внешнего — падает не тот, кто съел, а тот,
кого ограничили строже; внешний меньше внутреннего — внутренний не значит
ничего) и два таймаута, из которых сработает более короткий, а в журнале
окажется другой. Поэтому здесь — прямой `Store.add`, а лимиты даёт воркер.

Модуль `materials/parsing.py`, заводивший этот второй подпроцесс, удалён
(решение владельца §12: «удалить, если ничем не используется»): после переезда
разбора в очередь его не звал никто, кроме собственных тестов. Общая механика
подпроцесса осталась там, где ею пользуются двое, — в `api/subproc.py`.

    Что уезжает в `payload` и что возвращается
    ------------------------------------------

    payload   {"pending": "<16 hex>", "name": "источник.pdf"}
    result    {"material": "<16 hex>", "card": {…карточка материала…}}

`pending` — тот же идентификатор материала (sha256 содержимого), под которым
сырые байты лежат в `incoming/` каталога проекта. **Не путь**: `payload`
уезжает в базу и наружу в карточке задания, а §3 обещает, что клиент видит
только идентификаторы. Путь обработчик складывает сам, из каталога своего
проекта, проверив форму ключа (`service.проверить_форму_ид`).

`name` — имя, которое дал файлу человек. Оно приходит из `payload`, а не с тома,
по той же причине: на томе сырой файл назван ключом, и имени, кроме
присланного, у него нет.

    Что делается при беде
    ---------------------

Любой исход — сырые байты уходят с тома (`finally`). Оставленные, они заняли бы
у владельца вторые те же байты в квоте: исходник материала кладёт на том сам
`Store.add`, а после беды — те же байты ни за что.

Беда разбора отвечает клиенту тем же кодом, что и раньше отвечал синхронный
путь, — `parse_failed`: код принадлежит `service.py` и берётся оттуда, чтобы
«что такое неудавшийся разбор» осталось сказанным в одном месте. Подробности
(текст исключения, в котором бывает и путь на томе, и кусок чужого документа) в
ответ не попадают никогда — их уносит в журнал `child.позвать`.
"""
from __future__ import annotations

import materials

from ..errors import ApiError
from . import service
from .service import PARSE_FAILED

# Ключи `payload`. Строками в одном месте: их пишет маршрут и читает
# обработчик, и опечатка в одном из двух мест иначе видна только на живом томе.
КЛЮЧ = "pending"
ИМЯ = "name"


def разобрать_принятое(ctx) -> dict:
    """Сырые байты из `incoming/` → материал проекта. → карточка материала.

    Шагов два, и оба сообщаются: разбор большого файла идёт десятками секунд,
    и задание без единого `progress` выглядит на сайте как зависшее.

    Отмена здесь не спрашивается намеренно. Спрашивать её можно только между
    шагами (`probe` — образец), а весь шаг тут один и неделимый: `Store.add`
    либо дописал `meta.json`, либо не дописал, и прерванный посередине он
    оставляет ровно тот полуматериал, который приходится убирать. Отмену
    разбора человек получает тем же, чем и всегда, — воркер добьёт подпроцесс по
    сроку, а `finally` этого процесса не выполнится; недоразобранное уберёт
    следующая попытка того же файла.
    """
    payload = ctx.job.payload or {}
    mid = service.проверить_форму_ид(payload.get(КЛЮЧ))
    имя = str(payload.get(ИМЯ) or "")

    проект = ctx.project
    склад = проект.store()
    ctx.progress(0, 1, note=имя)
    try:
        путь = service.сырой(проект.path, mid)
        if путь is None:
            # Сырых байтов нет: либо файл уже был в проекте (кэш по содержимому,
            # §4 — маршрут такое задание всё равно ставит), либо задание подняли
            # вторым после того, как первое разобрало тот же файл. Оба случая
            # законны, и оба отвечают одним — материалом.
            материал = _взять(склад, mid)
        else:
            try:
                материал = склад.add(путь, name=имя or None)
            except materials.MaterialsError:
                # Разбор мог успеть положить исходник и умереть до `meta.json`:
                # такой полуматериал невидим для описи, а квоту владельцу
                # считает.
                service.убрать_недоразобранное(склад, mid)
                raise ApiError(PARSE_FAILED, "The file could not be parsed",
                               422, where="body.file") from None
    finally:
        service.убрать_сырой(проект.path, mid)

    ctx.progress(1, 1, note=имя)
    return {"material": материал.id, "card": service.карточка(материал)}


def _взять(склад, mid: str):
    """Материал, который обязан уже лежать. Нет — беда разбора, а не пятисотка.

    Случай редкий и всегда одинаковый по смыслу: байтов нет и материала нет —
    значит, между приёмом и разбором кто-то удалил материал (`DELETE …/{mid}`)
    или убрал сырое. Отвечать на это `handler_failed` значило бы называть бедой
    службы то, что случилось по просьбе человека.
    """
    try:
        return склад.get(mid)
    except materials.MaterialsError:
        raise ApiError(PARSE_FAILED,
                       "The uploaded file is no longer available", 422,
                       where="body.file") from None


def _зарегистрировать() -> None:
    """Поставить обработчик в реестр. Зовётся из `registry.load_handlers`.

    Функцией, а не декоратором на уровне модуля, по той же причине, что у
    `jobs/probe.py`: декоратор случается на импорте, то есть **один раз на
    процесс**, и тест, почистивший реестр (`registry._забыть_всё`), обратно его
    уже не получит — модуль-то в `sys.modules` остался. А чистит реестр не наш
    тест, и «мой обработчик пропал после чужого теста» — беда, которую ищут
    полдня.

    Вызов идемпотентен: `register` молчит, если за видом стоит та же функция.
    """
    from ..jobs.registry import PARSE, register              # noqa: PLC0415

    register(PARSE, needs_project=True, needs_secret=False)(разобрать_принятое)


__all__ = ["разобрать_принятое", "_зарегистрировать", "КЛЮЧ", "ИМЯ"]
