"""
stream_parse — разбор потока по закрытым объектам верхнего уровня.

Зачем отдельный накопитель. Поток обрывается — отменой, таймаутом, упавшим
соединением, — и вместе с обрывом сегодня теряется всё, что модель уже успела
написать. Для отчёта на десятки тегов это значит переспросить целиком и
заплатить второй раз за уже полученные значения. Накопитель отдаёт объект
сразу, как только тот закрылся, поэтому обрыв стоит одного недописанного
объекта, а не всего потока.

Счётчик скобок здесь свой, а не `structured._find_balanced`, и это не дубль по
недосмотру. Тот ищет ОДИН сбалансированный кусок в готовом тексте: состояния
между кусками у него нет (разрыв посреди строкового литерала или посреди `\\"`
ему не пережить), текст он пересматривает с начала на каждый вызов (на потоке
из сотен кусков это квадрат) и возвращает разобранное значение, а не границы —
шагнуть по нему к следующему объекту нечем. Разовому поиску состояние вредно,
потоковому — обязательно; это разные задачи, и общего кода у них десяток строк
про кавычки и экраны.
"""
from __future__ import annotations

import codecs
import json


class ObjectStream:
    """Накопитель кусков потока, отдающий закрытые объекты верхнего уровня.

    Цена ошибки в этом счётчике — молча потерянные значения тегов: скобка,
    посчитанная внутри строкового литерала, сдвигает границу объекта, и дальше
    ломается разбор всего остатка потока, а не одного значения. Поэтому строки
    и экраны считаются здесь наравне со скобками.

    Объект верхнего уровня — любой `{...}`, начатый вне другого объекта. Вне
    объекта накопитель ищет только `{`, поэтому обёртка-массив
    (`[{...}, {...}]`), запятые, переводы строк, забор ```json и пояснения
    модели вокруг JSON пропускаются сами собой. Плата за такую снисходительность
    названа честно: `{` в пояснении вне объекта начинает ложный захват, кусок
    не разберётся и уйдёт в `broken` — вызывающий увидит потерю, а не получит
    молча неполный отчёт.

    Один большой объект (`{"тег1": ..., "тег2": ...}`) закроется только в самом
    конце, и спасать при обрыве будет нечего: чтобы обрыв стоил одного тега,
    модель должна писать значения последовательностью объектов.
    """

    def __init__(self):
        self.objects: list = []          # всё разобранное с начала потока
        self.broken: list = []           # закрывшиеся куски, которые не JSON
        self._buf: list = []
        self._depth = 0
        self._in_string = False
        self._escaped = False
        # Инкрементальный декодер держит недодекодированный хвост: кусок может
        # оборваться посреди многобайтового символа, и «ё» приедет двумя
        # порциями байт. errors="replace" — чтобы битый байт стоил одного
        # символа, а не всего остатка потока: смысл накопителя в спасении.
        self._decoder = codecs.getincrementaldecoder("utf-8")("replace")

    def feed(self, piece) -> list:
        """Кусок потока (str или bytes) → объекты, закрывшиеся именно на нём.

        Кусок может оборваться где угодно: посреди ключа, между `}` и `,`,
        посреди `\\"` и посреди многобайтового символа. Всё состояние разбора —
        глубина, «внутри строки», «после обратной косой», недодекодированные
        байты — живёт между вызовами, потому что иначе каждый неудачный разрыв
        превращается в потерянный хвост потока.
        """
        text = piece if isinstance(piece, str) else self._decoder.decode(piece)
        ready: list = []
        for ch in text:
            if self._depth == 0:
                # Вне объекта разбирать нечего: обёртка массива, запятые,
                # забор и пояснения модели до JSON не относятся.
                if ch != "{":
                    continue
                self._buf = []
            self._buf.append(ch)
            if self._in_string:
                if self._escaped:
                    self._escaped = False
                elif ch == "\\":
                    self._escaped = True
                elif ch == '"':
                    self._in_string = False
                continue
            if ch == '"':
                self._in_string = True
            elif ch == "{":
                self._depth += 1
            elif ch == "}":
                self._depth -= 1
                if self._depth == 0:
                    self._close(ready)
        return ready

    def _close(self, ready: list) -> None:
        """Объект закрылся: разобрать и отдать, а неразобранное — не потерять."""
        raw = "".join(self._buf)
        self._buf = []
        try:
            value = json.loads(raw)
        except ValueError:
            # Молча выбросить нельзя: пропавший тег обязан быть видим.
            self.broken.append(raw)
            return
        self.objects.append(value)
        ready.append(value)

    @property
    def pending(self) -> str:
        """Начатый и незакрытый объект — то, что обрыв не дал дописать.

        Отдаётся сырым текстом, а не значением: он заведомо неполный. Годится
        для журнала и разбора «на чём именно оборвалось».
        """
        return "".join(self._buf)

    @property
    def truncated(self) -> bool:
        """Остался ли недописанный объект (проверяется после конца потока)."""
        return bool(self._buf)


def iter_objects(pieces):
    """Куски текста → объекты по мере закрытия. Обёртка на частый случай.

    Накопитель нужен наружу целиком (у него есть `broken` и `pending`), но
    когда вызывающему нужны только значения, ему не должно приходиться заводить
    объект и склеивать списки вручную.
    """
    stream = ObjectStream()
    for piece in pieces:
        for value in stream.feed(piece):
            yield value


__all__ = ["ObjectStream", "iter_objects"]
