"""
zuhyo (図表 — «графики») — график по декларативной спецификации → PNG.

Зачем отдельный пакет. График в отчёте нужен ровно там же, где схема: агент
собрал числа по материалам и хочет показать их картинкой. Обычный способ —
дать модели выполнить нарисованный ею код matplotlib — здесь закрыт несущим
решением проекта: **пользовательский код не выполняется нигде и никогда**. Ни
`exec`, ни подпроцесса с чужим скриптом, ни `eval` над строкой из ответа модели
тут нет. Модель присылает **данные и вид графика**, рисуем мы сами — и потому
множество возможных картинок конечно и описано перечнем `KINDS`, а не
воображением модели.

    render(spec) -> Chart          спецификация (dict) → PNG, предупреждения
    check(spec)  -> (ChartSpec, notes)   только проверка, без рисования
    ChartError                     спецификация не годится; чинится вызывающим
    KINDS, THEMES, SIZES           перечни, которые вызывающий объявляет модели

Чистый пакет: диска не знает (PNG отдаётся байтами — кладёт их тот, у кого есть
хранилище), модели не знает, `orchestrator` не импортирует. Единственный сосед —
matplotlib, и тот берётся **лениво**, внутри рисования: `import zuhyo` из
службы не должен тянуть за собой ни numpy, ни разбор шрифтов.

**Проверка отделена от рисования** (`_spec` и `_render`). Разбор говорит, какое
поле не годится и что с ним не так, — этот текст читает модель и чинит вызов
следующим ходом; matplotlib на кривых данных сказал бы своё, написанное для
того, кто пишет скрипт, и половину бы принял молча (строка вместо числа стала бы
подписью категории, и график вышел бы правдоподобным враньём).

**Потолки не роняют вызов, а обрезают** (серии сверх `MAX_SERIES`, точки сверх
`MAX_POINTS`). Обрезанное названо в `notes` — тем же способом, каким `fragmos`
говорит «в схему не вошло»: решать, годится ли такая картинка для отчёта, будет
тот, кто её заказал, а немой отказ на сотой тысяче точек не даёт ему ничего.
"""
from __future__ import annotations

from dataclasses import dataclass, field

from ._render import DPI, MAX_PNG_BYTES, SMALL_DPI, draw
from ._spec import (CATEGORY_KINDS, KINDS, MAX_BINS, MAX_POINTS, MAX_SERIES,
                    SERIES_KINDS, SIZES, THEMES, ChartError, ChartSpec, Series,
                    check)


@dataclass(frozen=True)
class Chart:
    """Нарисованный график: байты PNG, что при этом обрезано, чем нарисовано.

    Неизменяемый, как `DiagramResult` у схем, и по той же причине: это
    свидетельство о том, что получилось, и дописывать его по дороге к отчёту
    некому.

    `spec` — спецификация после проверки, приведённая к словарю. Она едет в
    журнал производных: у графика нет материала-исходника, его исходник — сами
    числа, и без них замечание «график переделай» упирается в вопрос, что на
    нём было нарисовано.
    """

    png: bytes
    notes: tuple[str, ...] = ()
    spec: dict = field(default_factory=dict)


def render(spec: dict) -> Chart:
    """Спецификация → PNG. Ошибка спецификации — `ChartError`.

    Потолок веса (`MAX_PNG_BYTES`) держится понижением плотности, а не отказом:
    тяжёлым PNG делает не «неправильный» график, а честная россыпь из тысяч
    точек, и рисовать её мельче — лучше, чем не рисовать вовсе. Понижение
    названо в `notes`. Отказ остаётся только на случай, когда и мелкая не влезла.
    """
    готово, notes = check(spec)
    png = draw(готово, dpi=DPI)
    if len(png) > MAX_PNG_BYTES:
        png = draw(готово, dpi=SMALL_DPI)
        notes = (*notes, f"график тяжелее {MAX_PNG_BYTES // 1024} КБ — "
                         f"нарисован с меньшей плотностью точек")
    if len(png) > MAX_PNG_BYTES:
        raise ChartError(
            f"PNG вышел на {len(png) // 1024} КБ при потолке "
            f"{MAX_PNG_BYTES // 1024} КБ: точек слишком много. Проредь данные "
            f"или разбей их на несколько графиков", field="series")
    return Chart(png=png, notes=tuple(notes), spec=готово.to_dict())


