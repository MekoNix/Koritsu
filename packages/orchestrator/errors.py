"""
errors — единственный тип ошибки пакета и подсказка «похоже на».

Свой тип, а не `ValueError`, по той же причине, что у соседей (`HokokuError`,
`LlmError`, `MaterialsError`): оркестратор зовёт четыре чужих пакета, и без
своего типа вызывающий не отличит «служба позвана неправильно» от «hokoku не
собрал документ» и от «модель не ответила». Ловить `Exception` он тогда обязан
целиком — то есть проглотит и то, что должно было упасть.

Подсказка «похоже на» стоит рядом с ошибкой, а не в интерфейсе, потому что почти
все такие ошибки — опечатки (свои, чужого скрипта или модели), и цена ошибки
без подсказки измеряется не удобством: `set_value("цел", …)` вместо `"цель"`
заводит версию тега, которого нет в шаблоне, отчёт собирается без него, и
объяснить это через месяц нечем.
"""
from __future__ import annotations

import difflib


class OrchestratorError(Exception):
    """Служба позвана неправильно: нет тега, нет проекта, нет версии, нет endpoint'а."""


# Беда слоя моделей словами для человека: вид (`llm.ErrorKind`) → одна фраза.
#
# Текста поставщика здесь нет ни в каком виде, и это решение, а не небрежность.
# Приходит он по-английски, а нередко телом JSON или выводом чужой команды, и на
# экране человек читает его как поломку нашей службы: «transport: 400 Bad
# Request {"error": …}» ему ничего не сообщает. Разобрать беду по подробностям
# есть где — вид, код ответа и тело поставщика записаны в журнале расхода
# (`llm.Journal`) и в записи прогона (`runs/<id>.json`), и читает их тот, кто
# чинит службу, а не тот, кто заказал работу.
TROUBLE_WORDS = {
    "auth": "поставщик не принял ключ или на нём кончились деньги",
    "not_found": "у поставщика нет такой модели",
    "rate_limit": "поставщик просит подождать: обращений слишком много",
    "context_overflow": "запрос не поместился в окно модели",
    "timeout": "поставщик не ответил вовремя",
    "refused": "модель отказалась отвечать",
    "bad_response": "модель ответила не по схеме",
    "transport": "связь с поставщиком оборвалась",
    "limit_exceeded": "прогон остановлен вашим лимитом",
    "cancelled": "прогон остановлен",
    "unsupported": "поставщик не умеет того, что нужно этому прогону",
}

# То же для причины остановки (`llm.Stop`), когда ошибки не было вовсе.
STOP_WORDS = {
    "max_tokens": "ответ модели оборвался на потолке длины",
    "refused": "модель отказалась отвечать",
    "cancelled": "прогон остановлен человеком",
}


def trouble_words(error=None, stop: str = "") -> str:
    """Почему вызов модели не дал ответа — одной фразой по-русски.

    Одно место на всю службу, потому что читателей у этой фразы много и все они
    люди: замечание работы, пометка стадии, `job.error.message` и текст на
    экране. Собираемая по месту, в одном из мест она однажды оказалась бы
    `str(беда)` — и человек прочёл бы английский текст поставщика.

    Вид беды спрашивается утиной проверкой (`kind`), а не `isinstance`: сюда
    приезжает `llm.LlmError`, но приехать может и чужое исключение, у которого
    вида нет вовсе, — и тогда честный ответ «модель не ответила», а не имя
    чужого класса.
    """
    if error is not None:
        return TROUBLE_WORDS.get(str(getattr(error, "kind", "")), "модель не ответила")
    return STOP_WORDS.get(str(stop or ""), "модель не ответила")


def hint(name, known) -> str:
    """Хвост «(похоже на "…")» или пустая строка. Форма та же, что в hokoku."""
    near = difflib.get_close_matches(str(name), sorted(str(k) for k in known), n=1, cutoff=0.6)
    return f' (похоже на "{near[0]}")' if near else ""


__all__ = ["OrchestratorError", "hint", "trouble_words", "TROUBLE_WORDS", "STOP_WORDS"]
