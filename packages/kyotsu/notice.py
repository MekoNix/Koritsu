"""
notice.py — одна форма предупреждения на все пакеты.

До 2.0.0a4.2 каналов было четыре, и все разные: `hokoku` отдавал словари
`{module, level, code, key, message}` (плюс `expected`/`got`/`suggest`), причём
собирал их тремя почти одинаковыми функциями (`validate._p`, `manifest._w`,
`template._problem`); `orchestrator` завёл четвёртую (`fill._problem`);
`llm` клал в `Probe.warnings` голые строки, у которых нет ни уровня, ни кода;
`fragmos` не отдавал ничего вовсе — файл, не разобравшийся при многофайловом
входе, молча не попадал в схему. Четыре формы значат четыре разбора в
интерфейсе, и вопрос «покажи всё, что не так с отчётом» отвечался четырежды.

`Notice` — общая часть всех четырёх: кто сказал, насколько это серьёзно, чем это
называется в коде и что показать человеку. Предметной области здесь нет: коды
остаются у пакетов, `Notice` не знает ни одного из них и не проверяет.

`file`/`line` необязательны намеренно. Позиции в исходнике сегодня не даёт ни
один пакет (tree-sitter её знает, но никуда не протаскивает — отдельный пункт
status.md); когда протащит, предупреждение получит привязку к строке, не меняя
формы. Обязательными их сделать нельзя: у «значение тега не нашло тега в
шаблоне» никакого файла нет и не будет.

Расширяется наследованием, а не свободным словарём: `hokoku.Problem` добавляет
`key` (тег, о котором речь) и `expected`/`got`. `to_dict()` при этом переписывать
не надо — он идёт по полям dataclass'а, поэтому поля подкласса попадают в JSON
сами и старые ключи сохраняются.
"""
from __future__ import annotations

from dataclasses import dataclass, fields

LEVELS = ("info", "warning", "error")


@dataclass(frozen=True)
class Notice:
    """Одно замечание: кто, насколько серьёзно, чем называется, что показать.

    Уровни (те же слова, что были у `hokoku.validate`, и значат то же):
      error   — так нельзя: не соберётся или соберётся не то;
      warning — соберётся, но с изъяном, видимым человеку;
      info    — законное состояние, о котором стоит знать.

    Неизменяемый: замечание — свидетельство о том, что было в момент проверки, и
    дописывать его по дороге к интерфейсу некому. Правка на месте у списка,
    который проходит через три пакета, нашлась бы не раньше, чем на готовом
    отчёте.
    """

    module: str
    level: str
    code: str
    message: str
    file: str | None = None
    line: int | None = None

    def __post_init__(self) -> None:
        # Уровень разбирают и человек, и интерфейс (цвет строки), и `fill`
        # («жёсткая беда версии не заводит»). Опечатка в нём — не косметика:
        # `error`, написанный как `err`, тихо становится замечанием, которое
        # никого не остановит.
        if self.level not in LEVELS:
            raise ValueError(f"level — {', '.join(LEVELS)}, а не {self.level!r}")

    def to_dict(self) -> dict:
        """Запись для JSON. Незаданные необязательные поля не занимают места.

        Пустое поле выброшено, а не отдано как `null`: `{"file": null}` в ответе
        читается как «файл спрашивали и его нет», а правда другая — позицию в
        исходнике сюда пока никто не кладёт.
        """
        return {f.name: getattr(self, f.name) for f in fields(self)
                if getattr(self, f.name) is not None}


__all__ = ["Notice", "LEVELS"]
